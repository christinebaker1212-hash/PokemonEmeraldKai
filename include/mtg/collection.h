// Moemon Kai: a save's Magic cards and decks ("<save>.mtg", src/mtg/mtg_integration.c), the starter decks and the
// duelists' decks (src/mtg/mtg_decks.c), boosters. Plain C, no SDL: tools/mtg/test.sh tests it.
#ifndef GUARD_MTG_COLLECTION_H
#define GUARD_MTG_COLLECTION_H

#include "mtg/mtg.h"

#define MTG_COLLECTION_CARDS 6144      // card ids (the pack has 5408)
#define MTG_DECKS 8
#define MTG_DECK_NAME 16
#define MTG_DECK_MIN 40                // the game's decks: 40 cards at least (the starters' size)
#define MTG_COPIES 4                   // copies of a card in a deck, but for basic lands
#define MTG_OWNED_MAX 99
#define MTG_PACK_MAX 15                // a booster's cards at most (most sets: 11 commons, 3 uncommons, a rare)
#define MTG_SETS 28                    // the booster sets (src/mtg/mtg_sets_data.c, tools/mtg/fetch_sets.py)
#define MTG_PACK_COST 12               // CARD POINTS for a booster at the CARD SHOP (the YU-GI-OH! side's price)
#define MTG_PACKS_MAX 99               // boosters of a set held at most

#define MTG_FLAG_CASE_SIDE 1           // the CARD CASE opens on its MAGIC side

typedef struct {
    char name[MTG_DECK_NAME];
    uint16_t count;
    uint16_t cards[MTG_DECK_MAX];
} MtgSavedDeck;

typedef struct {
    uint32_t owner, rng;
    uint8_t optedIn;                   // has a deck: Magic shows in the CARD CASE and NPCs offer it
    uint8_t flags, activeDeck, starter;
    uint16_t wins, losses;
    uint32_t beaten;                   // duelists beaten (bit per MtgDuelist)
    uint8_t owned[MTG_COLLECTION_CARDS];
    MtgSavedDeck decks[MTG_DECKS];
    int16_t ace[MTG_DECKS];            // each deck's ACE CARD (a card id), -1: the game picks one (Mtg_DeckAce)
    uint8_t tray[MTG_DECKS];           // each deck's hand tray color (TCG_TRAY_* of include/tcg/tcg.h: 0 the deck's own)
    uint8_t packs[MTG_SETS];           // unopened boosters of each set (gMtgSets' order; saved by the set's code)
    uint8_t opened[MTG_SETS];          // boosters of each set opened (up to 255)
    uint16_t packsOpened;              // every booster opened
    uint8_t setPrizes[MTG_SETS];       // each set's PRIZES claimed (bits: 25 / 50 / 75 % owned), from format 5
    uint32_t rewards;                  // the CARD SHOP's milestone PRIZES claimed (bits, mtg_ui.c sMilestones' order)
    uint16_t preconsBought;            // structure decks bought
} MtgCollection;

// ---- the CARD SHOP's counter (as the POKeMON CARD CLUB's): spares traded in, cards and decks for CARD POINTS
#define MTG_TRADE_KEEP 4               // copies kept out of TRADE IN (or more, when a deck uses more)
unsigned Mtg_Spare(const MtgCollection *c, int card);   // copies past MTG_TRADE_KEEP and past what any deck uses
unsigned Mtg_PointValue(int card);                      // CARD POINTS a spare trades in for (by rarity; basics 0)
unsigned Mtg_PointCost(int card);                       // CARD POINTS to pick it at the counter (0: not sold)
int Mtg_TradeIn(MtgCollection *c, int card, unsigned count, uint32_t *points);   // 0: not that many spare

// ---- structure decks: real preconstructed decks of the Premodern years (src/mtg/mtg_precons_data.c, generated by
// tools/mtg/fetch_precons.py; a curated few). The shop offers one once every card in it plays (Mtg_PreconPlays).
enum { MTG_PRECON_STARTER, MTG_PRECON_THEME, MTG_PRECON_CHAMPION };
typedef struct {
    const char *name, *about, *set;
    uint16_t year;
    uint8_t kind;                      // MTG_PRECON_*
    const char *const *cards;          // a recipe, as MtgRecipe's
} MtgPrecon;
#define MTG_PRECONS 16
extern const MtgPrecon gMtgPrecons[MTG_PRECONS];
int Mtg_PreconPlays(int k);                                     // every card of it plays (Mtg_CanUse)
unsigned Mtg_PreconCost(int k);                                 // CARD POINTS (by kind and size)
int Mtg_PreconDeck(int k, MtgSavedDeck *out);                   // its cards as a deck; the number not found (0)
int Mtg_PreconMissing(int k, char *first, unsigned cap);        // cards that don't play yet; the first one's name

// ---- the booster sets (src/mtg/mtg_sets.c), Fourth Edition to Scourge, each with the pool's cards printed in it
typedef struct { uint32_t hash; uint8_t rarity; } MtgSetCard;    // a card by Mtg_NameHash, its rarity in the set
typedef struct {
    const char *code, *name;
    uint16_t year;
    uint32_t top, bottom;              // the pack's colors
    uint8_t commons, uncommons, rares; // a booster's slots
    uint16_t first, count;             // its cards in gMtgSetCards
} MtgSet;
extern const MtgSet gMtgSets[MTG_SETS];
extern const MtgSetCard gMtgSetCards[];
// a set's cards (ids) the game can use, and their rarity there; returns how many
int Mtg_SetCards(int set, uint16_t *out, uint8_t *rarity);
int Mtg_SetAvailable(int set);                                  // enough of it plays to fill its boosters
int Mtg_RandomSet(uint32_t *rng);                               // one of the available sets
int Mtg_SetMascot(int set);                                     // the card on its pack (a rare with art)
int Mtg_SetOwned(const MtgCollection *c, int set, int *total);  // its usable cards owned / all of them
int Mtg_SetByCode(const char *code);                            // -1 if none
int Mtg_AwardPack(MtgCollection *c, int set);                   // a booster into the CARD CASE (0: full)
// a booster of the set opened (one of those held): its cards into the collection, in slot order (commons first,
// the rare last); rarity[i] each one's rarity in the set. Returns how many (0: none held).
int Mtg_OpenPack(MtgCollection *c, int set, uint16_t out[MTG_PACK_MAX], uint8_t rarity[MTG_PACK_MAX]);

void Mtg_CollectionInit(MtgCollection *c, uint32_t seed);
int Mtg_CollectionSave(const MtgCollection *c, const char *path);
int Mtg_CollectionLoad(MtgCollection *c, const char *path);    // 0: no file, or not one of ours
// the same in memory (the file's bytes); Write returns the size (0 if it doesn't fit)
uint32_t Mtg_CollectionWrite(const MtgCollection *c, uint8_t *out, uint32_t cap);
int Mtg_CollectionRead(MtgCollection *c, const uint8_t *in, uint32_t size);

int Mtg_IsBasicLand(int card);
int Mtg_CanUse(int card);                                       // playable, not banned
uint32_t Mtg_NameHash(const char *name);
int Mtg_CardByHash(uint32_t hash);
uint32_t Mtg_Rand(uint32_t *rng);

// a deck the game can play: MTG_DECK_MIN+, MTG_COPIES of a card but basic lands, every card usable and owned
// (basic lands are always there). Returns NULL, or what's wrong with it.
const char *Mtg_DeckProblem(const MtgCollection *c, const MtgSavedDeck *d);
int Mtg_DeckCopies(const MtgSavedDeck *d, int card);
void Mtg_DeckAdd(MtgSavedDeck *d, int card);
void Mtg_DeckRemove(MtgSavedDeck *d, int card);
void Mtg_DeckSort(MtgSavedDeck *d);                             // lands last, then by mana value and name
uint8_t Mtg_DeckColors(const MtgSavedDeck *d);
// The card that stands for a deck: its ACE CARD if chosen and still in it, else its rarest, then costliest card (not a
// basic land); -1 for an empty deck
int Mtg_DeckAce(const MtgCollection *c, int deck);
int Mtg_AutoAce(const uint16_t *cards, int count);
void Mtg_DeckToDuel(const MtgSavedDeck *d, MtgDeck *out);

// ---- recipes: the starters and the duelists' decks (src/mtg/mtg_decks.c)
typedef struct {
    const char *name, *about;
    uint8_t colors;
    const char *const *cards;          // "17 Mountain", "2 Raging Goblin"... ending with NULL
} MtgRecipe;
#define MTG_STARTERS 5
extern const MtgRecipe gMtgStarters[MTG_STARTERS];
int Mtg_RecipeDeck(const MtgRecipe *r, MtgSavedDeck *out);     // the number of cards it couldn't find (0)

typedef struct {
    const char *name;                  // "AUGUST" (no description: the user, 2026-11-05)
    const char *const *cards;          // a recipe as above
    const char *hello, *win, *lose;    // their words: offering a duel, when they win, when they lose
    uint8_t level;                     // 0-3 (the shared AI levels, once forge-ai's translation is in)
} MtgDuelist;
#define MTG_DUELISTS 6
extern const MtgDuelist gMtgDuelists[MTG_DUELISTS];

// The first deck: the chosen starter in deck slot 0, its cards owned; optedIn from now on
void Mtg_GiveStarter(MtgCollection *c, unsigned starter);

#endif
