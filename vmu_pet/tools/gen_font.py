def main():
    out = [';; Generated by vmu_pet/tools/gen_font.py: a 3x5 font, ASCII 32-95, 5 bytes a glyph. Do not edit.', 'font_3x5:']
    for code in range(32, 96):
        rows = G.get(chr(code), G['?'])
        vals = []
        for r in rows:
            v = 0
            for i, ch in enumerate(r):
                if ch == '#':
                    v |= 0x80 >> i
            vals.append('$%02x' % v)
        out.append('  .byte %s  ; %r' % (', '.join(vals), chr(code)))
    if sys.argv[1].endswith('.h'):
        rows = []
        for code in range(32, 96):
            g = G.get(chr(code), G['?'])
            rows.append('    {%s},' % ', '.join(str(sum(0x80 >> i for i, ch in enumerate(r) if ch == '#')) for r in g))
        out = ['// Generated by vmu_pet/tools/gen_font.py. Do not edit.', 'static const unsigned char kFont[64][5] = {'] + rows + ['};']
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
