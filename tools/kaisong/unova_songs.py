#!/usr/bin/env python3
"""UNOVA's music (docs/UNOVA_HANDOFF.md "Music"): Black's own soundtrack, every BGM and fanfare sequence of its sound
archive (wb_sound_data.sdat in the user's Black ROM, unpacked by aletheia's tools: not in the repository), as song
slots of their own and music/<slot>.kaisong files made by Moemon Music Studio's SDAT player (as SINNOH's from
Platinum's: tools/kaisong/sinnoh_songs.py).

    python3 -I tools/kaisong/unova_songs.py slots             # the slots into include/constants/songs.h and
                                                              # sound/song_table.inc (between their UNOVA markers),
                                                              # and src/data/unova_songs.h (Black's sequence -> slot)
    python3 -I tools/kaisong/unova_songs.py convert [STUDIO]  # music/<slot>.kaisong, four at a time

A slot is named after Black's own sequence (SEQ_BGM_T_01 -> MUS_UNOVA_T_01, SEQ_ME_ITEM -> MUS_UNOVA_ME_ITEM) and
plays one of Emerald's songs until its .kaisong replaces it. Slots follow SINNOH's (FIRST), in Black's order, so a
song's number never moves.
"""
import os
import struct
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SDAT = os.path.join(os.path.expanduser('~'), '.cache', 'moemon', 'unova', 'extract', 'data', 'wb_sound_data.sdat')
FIRST = 831   # after SINNOH's from Platinum's sound data (include/constants/songs.h)
SKIP = {'SEQ_BGM_DUMMY', 'SEQ_BGM_SILENCE_FIELD', 'SEQ_BGM_SILENCE_DUNGEON', 'SEQ_BGM_END'}

H_BEGIN = '// Moemon Kai: UNOVA\'s songs, Black\'s own (tools/kaisong/unova_songs.py)'
H_END = '// end of UNOVA\'s songs'
T_BEGIN = '@ Moemon Kai: UNOVA\'s songs, Black\'s own (tools/kaisong/unova_songs.py)'
T_END = '@ end of UNOVA\'s songs'


def sequences(path=SDAT):
    """[(Black's sequence number, its name)] of the BGMs and fanfares"""
    d = open(path, 'rb').read()
    symb = struct.unpack_from('<I', d, 0x10)[0]
    seqsym = struct.unpack_from('<I', d, symb + 8)[0]
    out = []
    for i in range(struct.unpack_from('<I', d, symb + seqsym)[0]):
        o = struct.unpack_from('<I', d, symb + seqsym + 4 + 4 * i)[0]
        name = d[symb + o:d.index(b'\0', symb + o)].decode() if o else ''
        if (name.startswith('SEQ_BGM_') or name.startswith('SEQ_ME_')) and name not in SKIP:
            out.append((i, name))
    return out


def slot_name(name):
    return 'mus_unova_' + (name[len('SEQ_BGM_'):] if name.startswith('SEQ_BGM_') else 'me_' + name[len('SEQ_ME_'):]).lower()


def replace_block(text, begin, end, body, anchor):
    if begin in text:
        a = text.index(begin)
        b = text.index(end, a) + len(end)
        return text[:a] + begin + '\n' + body + end + text[b:]
    a = text.index(anchor) + len(anchor)
    return text[:a] + '\n' + begin + '\n' + body + end + text[a:]


def slots():
    seqs = sequences()
    h = os.path.join(ROOT, 'include/constants/songs.h')
    body = ''.join('#define %-40s %d\n' % (slot_name(n).upper(), FIRST + k) for k, (_, n) in enumerate(seqs))
    text = open(h).read()
    open(h, 'w').write(replace_block(text, H_BEGIN, H_END, body, '// end of SINNOH\'s songs from Platinum\'s sound data'))
    t = os.path.join(ROOT, 'sound/song_table.inc')
    body = ''.join('\t.set %s, %s\n' % (slot_name(n), 'mus_level_up' if '_me_' in slot_name(n) else 'mus_route101')
                   for _, n in seqs)
    body += ''.join('\tsong %s, MUSIC_PLAYER_BGM, 0\n' % slot_name(n) for _, n in seqs)
    text = open(t).read()
    open(t, 'w').write(replace_block(text, T_BEGIN, T_END, body, '@ end of SINNOH\'s songs from Platinum\'s sound data'))
    with open(os.path.join(ROOT, 'src/data/unova_songs.h'), 'w') as f:
        f.write('// Generated by tools/kaisong/unova_songs.py: Black\'s sound archive\'s sequences and their song slots\n')
        f.write('static const struct { u16 seq, song; } sUnovaSongs[] = {\n')
        for _, n in seqs:
            pass
        for (i, n) in seqs:
            f.write('    {%d, %s},\n' % (i, slot_name(n).upper()))
        f.write('};\n')
    print('%d UNOVA song slots from %d' % (len(seqs), FIRST))


def convert(studio):
    seqs = sequences()

    def one(item):
        i, n = item
        out = os.path.join(ROOT, 'music', slot_name(n) + '.kaisong')
        r = subprocess.run([studio, '--export', '%s#%d' % (SDAT, i), out, slot_name(n)], capture_output=True, text=True)
        return n, r.returncode == 0 and os.path.exists(out), (r.stderr or r.stdout).strip()[-200:]

    bad = 0
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        for n, ok, msg in pool.map(one, seqs):
            if not ok:
                bad += 1
                print('%s: %s' % (n, msg))
    print('%d songs, %d left out' % (len(seqs), bad))
    return 1 if bad == len(seqs) else 0


def main():
    if sys.argv[1] == 'slots':
        slots()
    elif sys.argv[1] == 'convert':
        studio = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'tools/moemon_music/build/linux/moemon_music_studio')
        sys.exit(convert(studio))


if __name__ == '__main__':
    main()
