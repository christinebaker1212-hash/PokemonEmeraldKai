#!/usr/bin/env python3
"""The Gen 5-9 moves' side effects as data for src/battle_gen59.c, from tools/moemon_gen58/moves.json.

    python3 tools/moemon_gen58/gen_effect_data.py

Writes src/data/battle_moves_gen59_data.h: gGen59Moves[move - FIRST_GEN58_MOVE] = the stat stages the move changes
on its user and on its target (and how likely, 0 = always), its secondary status (a Kai MOVE_EFFECT_*) and how
likely, and its argument (a type, a status, a power...) where expansion gives one.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
STATS = ['attack', 'defense', 'speed', 'spAtk', 'spDef', 'accuracy', 'evasion']
STATUS = {'MOVE_EFFECT_SLEEP': 'MOVE_EFFECT_SLEEP', 'MOVE_EFFECT_POISON': 'MOVE_EFFECT_POISON',
          'MOVE_EFFECT_BURN': 'MOVE_EFFECT_BURN', 'MOVE_EFFECT_FREEZE_OR_FROSTBITE': 'MOVE_EFFECT_FREEZE',
          'MOVE_EFFECT_FREEZE': 'MOVE_EFFECT_FREEZE', 'MOVE_EFFECT_PARALYSIS': 'MOVE_EFFECT_PARALYSIS',
          'MOVE_EFFECT_TOXIC': 'MOVE_EFFECT_TOXIC', 'MOVE_EFFECT_CONFUSION': 'MOVE_EFFECT_CONFUSION',
          'MOVE_EFFECT_FLINCH': 'MOVE_EFFECT_FLINCH', 'MOVE_EFFECT_PREVENT_ESCAPE': 'MOVE_EFFECT_PREVENT_ESCAPE',
          'MOVE_EFFECT_PAYDAY': 'MOVE_EFFECT_PAYDAY'}


def arg_of(m):
    a = m.get('argument', '')
    for pat in (r'\.type = (TYPE_\w+)', r'\.status = (STATUS1_\w+)'):
        x = re.search(pat, a)
        if x:
            return x.group(1)
    x = re.search(r'\.terrainType = B_TERRAIN_(\w+)', a)
    if x:
        return 'G59_TERRAIN_' + x.group(1)
    x = re.search(r'\.overwriteAbility = (ABILITY_\w+)', a)
    if x:
        return x.group(1)
    return '0'


def main():
    moves = json.load(open(os.path.join(HERE, 'moves.json')))
    out = ['// Generated by tools/moemon_gen58/gen_effect_data.py. Do not edit.',
           '// {user stages ATK DEF SPD SPATK SPDEF ACC EVA}, user chance, {target stages}, target chance, status, chance, arg',
           'const struct Gen59Move gGen59Moves[LAST_GEN58_MOVE - FIRST_GEN58_MOVE + 1] = {']
    for m in moves:
        me, tgt = [0] * 7, [0] * 7
        mc = tc = 0
        status, sc = '0', 0
        status_move = m['category'] == 'DAMAGE_CATEGORY_STATUS'
        user_target = m['target'] in ('TARGET_USER', 'TARGET_ALL_BATTLERS', 'TARGET_ALLY', 'TARGET_USER_AND_ALLY',
                                      'TARGET_USER_OR_ALLY')
        for a in m['additionalEffects']:
            k = a.get('moveEffect', '')
            stages = [int(a.get(s, '0')) for s in STATS]
            chance = int(a.get('chance', '0') or 0)
            chance = 0 if chance >= 100 else chance
            if k in ('STAT_CHANGE_EFFECT_PLUS', 'STAT_CHANGE_EFFECT_MINUS', 'MOVE_EFFECT_STAT_PLUS', 'MOVE_EFFECT_STAT_MINUS'):
                sign = 1 if k.endswith('PLUS') else -1
                self_ = a.get('self') == 'TRUE' or (k.startswith('STAT_CHANGE') and user_target)
                if k == 'STAT_CHANGE_EFFECT_PLUS' and not user_target and m['target'] != 'TARGET_SELECTED':
                    self_ = True
                if k == 'STAT_CHANGE_EFFECT_PLUS' and m['effect'] in ('EFFECT_STAT_CHANGE',) and m['target'] == 'TARGET_SELECTED':
                    self_ = False   # raises the target's (DECORATE on a foe in singles)
                dst = me if self_ else tgt
                for i, v in enumerate(stages):
                    if v:
                        dst[i] = sign * v
                if self_:
                    mc = chance
                else:
                    tc = chance
            elif k in STATUS and status == '0':
                status, sc = STATUS[k], chance
        row = '    [%s - FIRST_GEN58_MOVE] = {{%s}, %d, {%s}, %d, %s, %d, %s},' % (
            m['const'], ', '.join(map(str, me)), mc, ', '.join(map(str, tgt)), tc, status, sc, arg_of(m))
        out.append(row)
    out.append('};')
    open(os.path.join(REPO, 'src/data/battle_moves_gen59_data.h'), 'w').write('\n'.join(out) + '\n')
    print('%d moves' % len(moves))


if __name__ == '__main__':
    main()
