#!/usr/bin/env python3
"""The generic duelists' decks into the game (docs/YGO_DECISIONS.md "NPC decks from YGOPRODeck"): the rated pool
(~/.cache/moemon/npc_pool_rated.json, tools/ygo/rate_pool.py) as graphics/ygo/npc_pool.bin, built in by
src/ygo/ygo_npc_pool_pak.c and read by src/ygo/ygo_npc_pool.c.

  "NPCP", u32 version (1), u32 decks, u32 the payload's size inflated, then the payload, raw deflate:
    each deck, weakest first: u16 rating, u8 format (FORMATS below), u16 era (its year), u8 placing (0 none, else
    1 a win .. 9 a top 256), u8 name length, the name (ASCII), u8 distinct Main Deck cards, u8 distinct Extra Deck
    cards, then (u16 catalog id, u8 copies) for each

Also writes src/ygo/ygo_card_ratings.c from tools/ygo/card_power.json (every card's power from its text: the scale
the player's deck is rated on, Ygo_DeckRating), its deck fit A + B * average fitted so a pool deck's cards give its
duel rating, and the AI levels' offsets kept from the file as it was.

  tools/ygo/write_npc_pool.py [RATED.json]
"""
import json, os, re, struct, zlib
from collections import Counter
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RATED = os.path.expanduser('~/.cache/moemon/npc_pool_rated.json')
FORMATS = ['other', 'tournament', 'tournament ocg', 'meta', 'world championship', 'non-meta', 'anime', 'fun/casual',
           'theorycrafting', 'master duel', 'common charity', 'genesys', 'domain', 'edison', 'goat', 'worlds', 'trinity']
PLACINGS = [('winner', 1), ('1st', 1), ('runner', 2), ('2nd', 2), ('top 4', 3), ('top 8', 4), ('top 16', 5),
            ('top 32', 6), ('top 64', 7), ('top 128', 8), ('top 256', 9)]


def fmt_code(f):
    f = (f or '').lower()
    if 'tournament' in f:
        return FORMATS.index('tournament ocg') if 'ocg' in f else FORMATS.index('tournament')
    for i, k in enumerate(FORMATS):
        if i and k in f:
            return i
    return 0


def placing_code(p):
    p = (p or '').lower()
    if not p:
        return 0
    return next((c for k, c in PLACINGS if k in p), 9)


def card_ratings(pool, cat):
    """src/ygo/ygo_card_ratings.c: the text's power for every card, the deck fit to the pool's duel ratings"""
    power = {int(k): v for k, v in json.load(open(os.path.join(ROOT, 'tools/ygo/card_power.json'))).items()}
    rating = {c['id']: power.get(c['password'], 1500) for c in cat}
    xs, ys = [], []
    for d in pool:
        if d.get('games', 0) >= 4:
            xs.append(sum(rating.get(x, 1500) for x in d['main']) / len(d['main']))
            ys.append(d['rating'])
    if len(xs) > 20:
        b, a = np.polyfit(np.array(xs), np.array(ys), 1)
    else:
        b, a = 1.0, 0.0
    old = open(os.path.join(ROOT, 'src/ygo/ygo_card_ratings.c')).read()
    lv = re.search(r'gYgoLevelRating\[4\] = \{([^}]*)\}', old).group(1)
    out = ['/* Generated by tools/ygo/write_npc_pool.py: every card\'s power from its own text, effects and stats',
           ' * (tools/ygo/text_power.py: tools/ygo/card_power.json), what each AI level gives away, and how a deck\'s',
           ' * rating follows from its cards (fitted to the generic duelists\' decks\' duel ratings, tools/ygo/rate_pool.py).',
           ' * Never shown as numbers. Do not edit. */',
           '#include <stdint.h>', '#include "ygo_internal.h"', '',
           'const int16_t gYgoLevelRating[4] = {%s};' % lv.strip(),
           '/* a deck\'s rating = A + B * its main deck\'s average card rating / 1024 */',
           'const int32_t gYgoDeckFitA = %d, gYgoDeckFitB = %d;' % (round(a), round(b * 1024)),
           'const int16_t gYgoCardRating[YGO_CARD_COUNT + 1] = {']
    for c in sorted(cat, key=lambda c: c['id']):
        out.append('    [%d] = %d,' % (c['id'], max(1, min(4000, rating[c['id']]))))
    out.append('};')
    open(os.path.join(ROOT, 'src/ygo/ygo_card_ratings.c'), 'w').write('\n'.join(out) + '\n')
    return a, b, (np.corrcoef(xs, ys)[0, 1] if len(xs) > 2 else 0)


def main():
    import sys
    pool = json.load(open(sys.argv[1] if len(sys.argv) > 1 else RATED))
    cat = json.load(open(os.path.join(ROOT, 'tools/ygo/catalog.json')))['cards']
    pool = [d for d in pool if d.get('crashes', 0) < 2]   # (decks the engine fell over on, twice: left out)
    pool.sort(key=lambda d: (d['rating'], d['num']))
    payload = bytearray()
    for d in pool:
        name = d['name'].encode('ascii', 'replace')[:28]
        main, extra = Counter(d['main']), Counter(d['extra'])
        payload += struct.pack('<HBHBB', max(0, min(65535, d['rating'])), fmt_code(d['format']), int(d['era'][:4]),
                               placing_code(d.get('placing')), len(name))
        payload += name
        payload += struct.pack('<BB', len(main), len(extra))
        for ids in (main, extra):
            for cid in sorted(ids):
                payload += struct.pack('<HB', cid, ids[cid])
    comp = zlib.compressobj(9, zlib.DEFLATED, -15)
    blob = comp.compress(bytes(payload)) + comp.flush()
    path = os.path.join(ROOT, 'graphics/ygo/npc_pool.bin')
    with open(path, 'wb') as f:
        f.write(b'NPCP' + struct.pack('<III', 1, len(pool), len(payload)) + blob)
    a, b, r = card_ratings(pool, cat)
    print('%d decks, %d KB inflated, %d KB in the pack; deck fit A %.0f B %.3f (r %.3f)' % (
        len(pool), len(payload) // 1024, (len(blob) + 16) // 1024, a, b, r))


if __name__ == '__main__':
    main()
