#!/bin/bash
# The opponents' decks (tools/ygo/npc_decks.json, from scrape_npc_decks.py) rated by AI-against-AI duels on EDOPro's
# engine, then written as src/ygo/ygo_npc_decks.c. Rerun after a change to the decks, the AI or the engine.
#   tools/ygo/rate_npc_decks.sh [ROUNDS]
set -e
cd "$(dirname "$0")/../.."
OUT=${OUT:-/tmp/ygo-tests}
ROUNDS=${1:-30}
mkdir -p "$OUT"
tools/ygo/edo/build_core.sh "$OUT"
python3 - "$OUT/npc_decks.txt" <<'PY'
import json, sys
decks = json.load(open('tools/ygo/npc_decks.json'))
open(sys.argv[1], 'w').write(''.join(' '.join(map(str, d['cards'])) + '\n' for d in decks))
PY
gcc -std=gnu99 -O2 -w -iquote include -iquote src/ygo tools/ygo/rate_npc_decks.c src/ygo/ygo_catalog.c \
    src/ygo/ygo_fusions.c src/ygo/ygo_edo.c src/ygo/ygo_edo_data.c src/ygo/ygo_edo_pak.c src/ygo/ygo_edo_codes.c \
    src/ygo/ygo_ai.c tools/ygo/stb_zlib.c -L"$OUT" -locgcore -lstdc++ -lm -o "$OUT/rate_npc_decks"
"$OUT/rate_npc_decks" "$OUT/npc_decks.txt" "$ROUNDS" | grep -v '^\[' > "$OUT/npc_ratings.txt"
python3 - "$OUT/npc_ratings.txt" <<'PY'
import json, sys
decks = json.load(open('tools/ygo/npc_decks.json'))
rates = [l.split() for l in open(sys.argv[1]) if l.strip()]
assert len(rates) == len(decks), (len(rates), len(decks))
games = {'SDD': 'Stairway to the Destined Duel', 'EDS': 'The Eternal Duelist Soul', 'WC4': 'World Championship 2004',
         'ROD': 'Reshef of Destruction', 'TSC': 'The Sacred Cards'}
def cstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['/* Generated by tools/ygo/rate_npc_decks.sh from tools/ygo/npc_decks.json (tools/ygo/scrape_npc_decks.py):',
       ' * the opponents\' decks of the Game Boy Advance Yu-Gi-Oh! games, rated by AI-against-AI duels. Do not edit. */',
       '#include <stdint.h>', '#include "ygo_internal.h"', '']
order = sorted(range(len(decks)), key=lambda i: int(rates[i][0]))
for k, i in enumerate(order):
    out.append('static const uint16_t sDeck%d[] = {%s};' % (k, ', '.join(map(str, decks[i]['cards']))))
out += ['', 'const struct YgoNpcDeck gYgoNpcDecks[] = {']
for k, i in enumerate(order):
    d = decks[i]
    out.append('    {%s, %s, %s, %d, %d, sDeck%d},' % (cstr(d['name']), cstr(d['game']), cstr(games[d['game']]),
                                                    int(rates[i][0]), len(d['cards']), k))
out += ['};', 'const unsigned gYgoNpcDeckCount = %d;' % len(decks), '']
open('src/ygo/ygo_npc_decks.c', 'w').write('\n'.join(out))
for k, i in enumerate(order):
    print('%5s  %-4s %-30s %s/%s' % (rates[i][0], decks[i]['game'], decks[i]['name'][:30], rates[i][1], rates[i][2]))
PY
