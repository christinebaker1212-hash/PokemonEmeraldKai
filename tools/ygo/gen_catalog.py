#!/usr/bin/env python3
"""src/ygo/ygo_catalog.c and include/ygo/card_ids.h from tools/ygo/catalog.json (tools/ygo/build_catalog.py).

usage: tools/ygo/gen_catalog.py

Text is written for the game's font: the bullet becomes the font's own (Latin-1 0xB7), "α" is spelled out, and
line breaks become spaces (the card screens wrap text themselves).
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CAT = json.load(open(ROOT / 'tools/ygo/catalog.json'))
SETS = ['LOB', 'SDY', 'SDK', 'MRD', 'SRL', 'PSV', 'LON', 'SDJ', 'SDP', 'LOD', 'PGD', 'MFC', 'DCR']
RARITY = {'Common': 0, 'Short Print': 1, 'Super Short Print': 2, 'Rare': 3, 'Super Rare': 4, 'Ultra Rare': 5,
          'Secret Rare': 6}
FRAME = {'normal': 'YGO_NORMAL', 'effect': 'YGO_EFFECT', 'fusion': 'YGO_FUSION', 'ritual': 'YGO_RITUAL',
         'spell': 'YGO_SPELL', 'trap': 'YGO_TRAP', 'token': 'YGO_TOKEN'}
ATTR = {None: 'YGO_ATTR_NONE', 'LIGHT': 'YGO_LIGHT', 'DARK': 'YGO_DARK', 'WATER': 'YGO_WATER', 'FIRE': 'YGO_FIRE',
        'EARTH': 'YGO_EARTH', 'WIND': 'YGO_WIND', 'DIVINE': 'YGO_DIVINE'}
PROP = {'Normal': 'YGO_PROP_NORMAL', 'Continuous': 'YGO_PROP_CONTINUOUS', 'Equip': 'YGO_PROP_EQUIP',
        'Field': 'YGO_PROP_FIELD', 'Quick-Play': 'YGO_PROP_QUICK', 'Ritual': 'YGO_PROP_RITUAL',
        'Counter': 'YGO_PROP_COUNTER'}


def race(r):
    return 'YGO_' + re.sub('[^A-Z]', '_', r.upper()) if r else 'YGO_RACE_NONE'


def text(s):
    s = s.replace('\r\n', '\n').replace('\r', '\n')
    s = re.sub(r'\s*\n\s*', ' ', s).replace('●', '\xb7').replace('α', 'Alpha').strip()
    return s


def cstr(s):
    out = '"'
    for ch in s:
        o = ord(ch)
        if ch in '"\\':
            out += '\\' + ch
        elif 32 <= o < 127:
            out += ch
        elif o < 256:
            out += '\\x%02X""' % o
        else:
            raise SystemExit('no game glyph for %r in %r' % (ch, s))
    return out + '"'


def symbol(name, used):
    s = re.sub('[^A-Z0-9]+', '_', text(name).replace('\xb7', '').upper()).strip('_')
    base, n = s, 2
    while s in used:
        s = '%s_%d' % (base, n)
        n += 1
    used.add(s)
    return s


def main():
    cards = CAT['cards']
    assert [c['id'] for c in cards] == list(range(1, len(cards) + 1)), 'card ids must run 1..N'
    used = set()
    ids = ['/* Generated by tools/ygo/gen_catalog.py from tools/ygo/catalog.json: do not edit. */',
           '#ifndef MOEMON_YGO_CARD_IDS_H', '#define MOEMON_YGO_CARD_IDS_H',
           '#define YGO_CARD_COUNT %d' % len(cards)]
    rows = []
    for c in cards:
        sym = symbol(c['name'], used)
        ids.append('#define YGO_CARD_%s %d' % (sym, c['id']))
        abil = []
        tl = c.get('typeline', '')
        for word, flag in (('Flip', 'YGO_ABILITY_FLIP'), ('Toon', 'YGO_ABILITY_TOON'), ('Spirit', 'YGO_ABILITY_SPIRIT'),
                           ('Union', 'YGO_ABILITY_UNION'), ('Gemini', 'YGO_ABILITY_GEMINI')):
            if word in tl:
                abil.append(flag)
        rar = max([RARITY[e[1]] for s in CAT['sets'] for e in s['cards'] if e[0] == c['id']] or [0])
        bits = ' | '.join('(1u << YGO_SET_%s)' % s for s in c['sets']) or '0'
        def stat(v):
            return 'YGO_STAT_UNKNOWN' if v is None or v < 0 else str(v)
        mon = c['frame'] not in ('spell', 'trap')
        rows.append('    [YGO_CARD_%s] = {%s, %s, %d, %d, %s, %s, %s, %s, %s, %d, %s, %s, %d, %d, %d, %s},' % (
            sym, cstr(text(c['name'])), cstr(text(c['text'])), c['password'], c['id'],
            stat(c.get('atk')) if mon else '0', stat(c.get('defense')) if mon else '0', FRAME[c['frame']],
            ATTR[c.get('attribute')] if mon else 'YGO_ATTR_NONE', race(c.get('race')) if mon else 'YGO_RACE_NONE',
            c.get('level') or 0, PROP[c['property']] if not mon else '0', ' | '.join(abil) or '0',
            c['limit'], rar, c['sdd'] or 0, bits))
    ids.append('#endif')
    (ROOT / 'include/ygo/card_ids.h').write_text('\n'.join(ids) + '\n')
    out = ['/* Generated by tools/ygo/gen_catalog.py from tools/ygo/catalog.json: do not edit. */',
           '#include "ygo/ygo.h"', '',
           '/* name, text, password, id, atk, def, frame, attribute, race, level, property, abilities, limit, rarity,',
           ' * Stairway card, sets */',
           'const struct YgoCard gYgoCards[YGO_CARD_COUNT + 1] = {'] + rows + ['};', '']
    for s in CAT['sets']:
        out.append('static const struct YgoSetCard sSet%s[] = {' % s['code'])
        out += ['    {%d, %d, %d},' % (e[0], RARITY[e[1]], e[2]) for e in s['cards']]
        out.append('};')
    out.append('const struct YgoSet gYgoSets[YGO_SET_COUNT] = {')
    for s in CAT['sets']:
        out.append('    [YGO_SET_%s] = {%s, %s, %d, %d, sSet%s},' % (s['code'], cstr(s['code']), cstr(s['name']),
                                                                  s['kind'] == 'starter', len(s['cards']), s['code']))
    out += ['};', '', 'const struct YgoCard *Ygo_Card(unsigned id)', '{',
            '    return id >= 1 && id <= YGO_CARD_COUNT ? &gYgoCards[id] : NULL;', '}', '']
    (ROOT / 'src/ygo/ygo_catalog.c').write_text('\n'.join(out))
    # Fusion materials: every 2003 Fusion Monster names its materials ("A" + "B" [+ "C"])
    byname = {c['name']: c['id'] for c in cards}
    fus = ['/* Generated by tools/ygo/gen_catalog.py from the Fusion Monsters\' text: do not edit. */',
           '#include <stddef.h>', '#include "ygo_internal.h"', '', 'static const struct YgoFusion sFusions[] = {']
    for c in cards:
        if c['frame'] != 'fusion':
            continue
        first = c['text'].replace('\r', '').split('\n')[0]
        names = re.findall(r'"([^"]+)"', first)
        mats = [byname.get(n) for n in names]
        if not names or None in mats:
            print('  no materials for', c['name'], names)
            continue
        fus.append('    {%d, {%s}}, /* %s */' % (c['id'], ', '.join(map(str, mats)), text(c['name'])))
    fus += ['};', '', 'const struct YgoFusion *Ygo_FusionOf(unsigned card)', '{', '    unsigned i;',
            '    for (i = 0; i < sizeof(sFusions) / sizeof(sFusions[0]); i++)',
            '        if (sFusions[i].card == card)', '            return &sFusions[i];', '    return NULL;', '}', '']
    (ROOT / 'src/ygo/ygo_fusions.c').write_text('\n'.join(fus))
    print('%d cards -> src/ygo/ygo_catalog.c, include/ygo/card_ids.h, src/ygo/ygo_fusions.c' % len(cards))


if __name__ == '__main__':
    main()
