#!/usr/bin/env python3
"""src/ygo/ygo_ai_tags.h: the Yu-Gi-Oh! AI's table of what each card does (AT_* bits by password), from Yugipedia's
search tags in tools/ygo/ai_tags.json (tools/ygo/fetch_ai_tags.py). ygo_ai.c's Outcome reads it with the card's own
words: whose cards an effect destroys or removes, what it draws, searches or Summons, what it costs.

usage: tools/ygo/gen_ai_tags.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TAGS = ROOT / 'tools/ygo/ai_tags.json'
OUT = ROOT / 'src/ygo/ygo_ai_tags.h'

POS = r"(?:face-up |face-down |Attack Position |Defense Position )*"
# (bit, the tags that set it); a tag may set several bits
RULES = [
    ('AT_DMON_THEIRS', [r"^Destroys your opponent's %sMonster Cards$" % POS, r'^Destroys (?:Normal|Flip|Special) Summoned monsters$',
                        r'^Destroys the Summoned monster$', r'^Destroys battling monster', r'^Destroys negated Summons$']),
    ('AT_DMON_MINE', [r"^Destroys your %sMonster Cards$" % POS]),
    ('AT_DMON_ANY', [r'^Destroys %sMonster Cards$' % POS]),
    ('AT_DST_THEIRS', [r"^Destroys your opponent's %s(?:Spell|Trap) Cards$" % POS]),
    ('AT_DST_MINE', [r"^Destroys your %s(?:Spell|Trap) Cards$" % POS]),
    ('AT_DST_ANY', [r'^Destroys %s(?:Spell|Trap) Cards$' % POS, r'^Destroys Equip Cards$']),
    ('AT_REMOVE_THEIRS', [r"^Banishes from your opponent's field$", r"^Sends from your opponent's field to your opponent's Graveyard$",
                          r"^Returns from your opponent's field to your (?:opponent's )?(?:hand|Deck|Extra Deck)$",
                          r"^Tributes opponent's monsters$"]),
    ('AT_REMOVE_ANY', [r'^Banishes from field$', r'^Sends from field to Graveyard$', r'^Returns from field to (?:hand|Deck|Extra Deck)$']),
    ('AT_BOUNCE', [r"field to (?:your opponent's |your )?hand$"]),
    ('AT_DRAW', [r'^You draw cards$']),
    ('AT_THEY_DRAW', [r'^Your opponent draws cards$']),
    ('AT_DISCARD_COST', [r'^You discard for cost$', r'^Discards for cost$', r'^Sends from hand to Graveyard for cost$']),
    ('AT_DISCARD_EFFECT', [r'^You discard as an effect$', r'^You discard$']),
    ('AT_THEY_DISCARD', [r'^Your opponent discards', r"^Sends from your opponent's hand to your opponent's Graveyard$"]),
    ('AT_PAY_LP', [r'^Pays Life Points(?: for cost| for effect)?$', r'^You pay Life Points$']),
    ('AT_TRIBUTE_COST', [r'^Tributes for cost$', r'^Tributes from field for cost$']),
    ('AT_SELF_COST', [r'^Tributes itself for cost$', r'^Sends itself from field to Graveyard for cost$',
                      r'^Banishes itself from field for cost$', r'^Returns itself from field to (?:hand|Deck|Extra Deck) for cost$']),
    ('AT_SEARCH', [r'^Adds from Deck to hand$', r'^Adds from your Deck to your hand$', r'^Adds to your hand from your Deck$',
                   r'^Adds random card from Deck to hand$', r'^Adds from the bottom of the Deck to the hand$',
                   r'^Adds excavated cards to the hand$']),
    ('AT_FROM_GY_TO_HAND', [r'^Adds from Graveyard to hand$', r'^Adds from banishment to hand$', r'^Adds banished cards to the hand$',
                            r"^Adds from your opponent's Graveyard to your hand$"]),
    ('AT_SUMMON', [r'^Special Summons from your (?:Deck|Graveyard|hand|Extra Deck|banishment)$',
                   r"^Special Summons from your opponent's Graveyard to your field$",
                   r'^Returns from Graveyard to field$', r'^Returns banished cards to the field$']),
    ('AT_NEGATE', [r"^Negates the (?:activation|effects) of (?:your opponent's|Effect Monster|Spell|Trap|the Summoned|battling)",
                   r'^Negates (?:Normal|Flip|Special) Summons$']),
    ('AT_DAMAGE', [r'^Damages your opponent$', r'^Your opponent loses Life Points$']),
    ('AT_STATS', [r'^Your monsters gain (?:ATK|DEF)$', r"^Your opponent's monsters lose (?:ATK|DEF)$", r'^Equipped gains ATK$']),
]


def main():
    data = json.load(open(TAGS))['cards']
    rules = [(bit, [re.compile(p) for p in pats]) for bit, pats in RULES]
    rows, used = [], {}
    for pw, tags in data.items():
        bits = 0
        for i, (bit, pats) in enumerate(rules):
            for t in tags:
                if any(p.search(t) for p in pats):
                    bits |= 1 << i
                    used[bit] = used.get(bit, 0) + 1
                    break
        if bits:
            rows.append((int(pw), bits))
    rows.sort()
    with open(OUT, 'w') as f:
        f.write('/* Generated by tools/ygo/gen_ai_tags.py from tools/ygo/ai_tags.json (Yugipedia\'s card search tags):\n'
                ' * what each card does, for ygo_ai.c. Don\'t edit. */\n')
        f.write('enum\n{\n')
        for i, (bit, _) in enumerate(RULES):
            f.write('    %s = %d,\n' % (bit, i))
        f.write('};\n')
        f.write('static const struct\n{\n    uint32_t password;\n    uint32_t tags;\n} sAiTags[] = {\n')
        for pw, bits in rows:
            f.write('    {%d, 0x%x},\n' % (pw, bits))
        f.write('};\n')
    print('%d cards -> %s' % (len(rows), OUT))
    for bit, _ in RULES:
        print('  %-20s %d' % (bit, used.get(bit, 0)))


if __name__ == '__main__':
    main()
