#!/usr/bin/env python3
"""Yu-Gi-Oh! power ratings (tools/ygo/rate_cards.sh): each card's measured worth (three copies in a plain deck against
the deck without them, in Elo) blended with its history on the Forbidden & Limited lists (GOAT's 2005 list counts
most; today's TCG, OCG and Traditional lists less), as a rating where a deck is as strong as its cards' average;
then fitted to the Game Boy decks' measured ratings (src/ygo/ygo_npc_decks.c) so a deck's rating can be read from its
cards. Writes src/ygo/ygo_card_ratings.c and docs/audit_ygo.txt.
usage: rate_cards.py CARDS.txt LEVELS.txt LIMITS.txt GOAT.conf"""
import re
import sys

cards_path, levels_path, limits_path, goat_path = sys.argv[1:5]
measured = {}
for line in open(cards_path):
    p = line.split()
    if len(p) == 3 and p[0] == 'card':
        measured[int(p[1])] = float(p[2])
levels = [0, 0, 0, 0]
for line in open(levels_path):
    p = line.split()
    if len(p) == 3 and p[0] == 'level':
        levels[int(p[1])] = int(round(float(p[2])))

names = []
limits = {}
for line in open(limits_path):
    p = line.rstrip('\n').split(' ', 1)
    if p[0] == 'lists':
        names = p[1].split('|')
    elif p[0] == 'limits':
        q = p[1].split()
        limits[int(q[0])] = list(map(int, q[1:]))

# the catalog: names, kinds
cat = {}
src = open('src/ygo/ygo_catalog.c', encoding='utf-8').read()
for m in re.finditer(r'\[(YGO_CARD_\w+)\] = \{"((?:[^"\\]|\\.)*)", "(?:[^"\\]|\\.)*", (\d+), (\d+), (\d+), (\d+), (YGO_\w+)', src):
    pass
ids = {}
for m in re.finditer(r'#define (YGO_CARD_\w+) (\d+)', open('include/ygo/card_ids.h').read()):
    ids[m.group(1)] = int(m.group(2))
for m in re.finditer(r'\[(YGO_CARD_\w+)\] = \{"((?:[^"\\]|\\.)*)", "(?:[^"\\]|\\.)*", \d+, \d+, (\d+), (\d+), (YGO_\w+)', src):
    if m.group(1) in ids:
        cat[ids[m.group(1)]] = (m.group(2), int(m.group(3)), int(m.group(4)), m.group(5))

# GOAT's list names the cards it allows (a whitelist): only the ones it limits count
goat_explicit = {}
for line in open(goat_path, encoding='utf-8', errors='replace'):
    q = line.split()
    if len(q) >= 2 and q[0].isdigit() and q[1] in ('0', '1', '2'):
        goat_explicit[int(q[0])] = int(q[1])
password = {}
stairway = {}
for m in re.finditer(r'\[(YGO_CARD_\w+)\] = \{"(?:[^"\\]|\\.)*", "(?:[^"\\]|\\.)*", (\d+), \d+, \d+, \d+, YGO_\w+, \w+, \w+, \d+, \d+, \d+, (\d+),', src):
    if m.group(1) in ids:
        password[ids[m.group(1)]] = int(m.group(2))
        stairway[ids[m.group(1)]] = int(m.group(3))

def list_index(word):
    for i, n in enumerate(names):
        if word in n:
            return i
    return None
goat, tcg, ocg, trad = (list_index(w) for w in ('GOAT', 'TCG', 'OCG', 'Traditional'))

def history(cid):
    """the card's history on the lists, in the Elo of three copies"""
    lim = limits.get(cid)
    if not lim:
        return 0.0
    score = 0.0
    # the era's own lists: the Game Boy game's (Stairway to the Destined Duel, 2003) and GOAT's (2005)
    score = max(score, {0: 150, 1: 100, 2: 50}.get(stairway.get(cid, 3), 0))
    score = max(score, {0: 150, 1: 100, 2: 50}.get(goat_explicit.get(password.get(cid, 0), 3), 0))
    for i in (tcg, ocg, trad):
        if i is not None:
            score = max(score, {0: 75, 1: 50, 2: 25}.get(lim[i], 0))
    return score

WEIGHT = 0.65   # the measured worth's share; the lists' history the rest
SCALE = 40 / 3 * 0.5   # three copies' Elo -> a card's rating (a deck: the average of 40)
rating = {}
for cid in sorted(cat):
    if cat[cid][3] == 'YGO_TOKEN':
        rating[cid] = 1500   # (tokens: never in a deck)
        continue
    m = measured.get(cid)
    h = history(cid)
    worth = WEIGHT * m + (1 - WEIGHT) * h if m is not None else h
    worth = max(-300.0, min(300.0, worth))
    rating[cid] = int(round(1500 + worth * SCALE))

# the Game Boy decks: their measured ratings against their cards' average
npc = []
text = open('src/ygo/ygo_npc_decks.c').read()
decks = {int(m.group(1)): list(map(int, m.group(2).split(','))) for m in
         re.finditer(r'static const uint16_t sDeck(\d+)\[\] = \{([^}]*)\};', text)}
for k, m in enumerate(re.finditer(r'\{"((?:[^"\\]|\\.)*)", "(\w+)", "[^"]*", (\d+), (\d+), sDeck(\d+)\}', text)):
    cards = [c for c in decks[int(m.group(5))] if c in cat and cat[c][3] != 'YGO_FUSION']
    mean = sum(rating.get(c, 1500) for c in cards) / max(1, len(cards))
    npc.append((m.group(1), m.group(2), int(m.group(3)), mean))
xs = [n[3] for n in npc]
ys = [n[2] for n in npc]
n = len(npc)
mx, my = sum(xs) / n, sum(ys) / n
sxx = sum((x - mx) ** 2 for x in xs)
sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
syy = sum((y - my) ** 2 for y in ys)
b = sxy / sxx if sxx else 0
a = my - b * mx
r = sxy / (sxx * syy) ** 0.5 if sxx and syy else 0
err = (sum((a + b * x - y) ** 2 for x, y in zip(xs, ys)) / n) ** 0.5

out = ['/* Generated by tools/ygo/rate_cards.sh (tools/ygo/rate_cards.c + rate_cards.py): every card\'s power rating',
       ' * (its measured worth blended with its history on the Forbidden & Limited lists), what each AI level gives',
       ' * away, and how a deck\'s rating follows from its cards (fitted to the Game Boy decks). Never shown as numbers.',
       ' * Do not edit. */',
       '#include <stdint.h>', '#include "ygo_internal.h"', '',
       'const int16_t gYgoLevelRating[4] = {%d, %d, %d, 0};' % tuple(levels[:3]),
       '/* a deck\'s rating = A + B * its main deck\'s average card rating / 1024 */',
       'const int32_t gYgoDeckFitA = %d, gYgoDeckFitB = %d;' % (round(a), round(b * 1024)),
       'const int16_t gYgoCardRating[YGO_CARD_COUNT + 1] = {']
for cid in sorted(rating):
    out.append('    [%d] = %d,' % (cid, rating[cid]))
out += ['};', '']
open('src/ygo/ygo_card_ratings.c', 'w').write('\n'.join(out))

rep = ['Yu-Gi-Oh! power audit (tools/ygo/rate_cards.sh)', '',
       'AI levels against the best (Game Boy decks, both seats): beginner %+d, casual %+d, skilled %+d' % tuple(levels[:3]),
       '%d cards measured; ratings blend %d%% measured worth with %d%% list history (Stairway 2003, GOAT 2005 first)' % (
           len(measured), WEIGHT * 100, (1 - WEIGHT) * 100),
       'deck rating from its cards, against the %d Game Boy decks\' measured ratings: r = %.2f, typical error %.0f' % (
           n, r, err), '']
top = sorted((c for c in rating if cat[c][3] != 'YGO_TOKEN'), key=lambda c: -rating[c])
STAPLES = ['Raigeki', 'Pot of Greed', 'Monster Reborn', 'Change of Heart', 'Dark Hole', 'Mirror Force',
           'Graceful Charity', 'Harpie\'s Feather Duster', 'Sangan', 'Witch of the Black Forest', 'Summoned Skull',
           'Blue-Eyes White Dragon', 'Trap Hole', 'Man-Eater Bug', 'Kuriboh', 'Mystical Elf', 'Celtic Guardian']
by_name = {cat[c][0]: c for c in cat}
rep.append('The era\'s staples: rank of %d, rating' % len(top))
for nm in STAPLES:
    if nm in by_name:
        c = by_name[nm]
        rep.append('  %4d  %5d  %-32s measured %+5.0f  lists %+4.0f' % (top.index(c) + 1, rating[c], nm,
                                                                      measured.get(c, 0), history(c)))
rep.append('')
rep.append('Strongest 40:')
for c in top[:40]:
    rep.append('  %5d  %-40s measured %+5.0f  lists %+4.0f' % (rating[c], cat[c][0], measured.get(c, 0), history(c)))
rep.append('')
rep.append('Weakest 20:')
for c in top[-20:]:
    rep.append('  %5d  %-40s measured %+5.0f  lists %+4.0f' % (rating[c], cat[c][0], measured.get(c, 0), history(c)))
rep.append('')
rep.append('Game Boy decks: measured, from cards')
for name, game, elo, mean in sorted(npc, key=lambda t: t[2]):
    rep.append('  %5d %5d  %-4s %s' % (elo, round(a + b * mean), game, name))
open('docs/audit_ygo.txt', 'w').write('\n'.join(rep) + '\n')
print('\n'.join(rep[:6]))
