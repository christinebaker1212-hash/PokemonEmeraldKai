#!/usr/bin/env python3
"""ORRE's rooms' check spots (docs/ORRE_HANDOFF.md "Shops, POKeMON CENTERs, the PC"): Colosseum's floor events of kind 3
(tools/orre/colo_rooms.py `events`: the hero checks the collision object in front of them, hero_move.c -> floor_character.c
heroDispatchEvent: the PCs, signs, machines), each with the ground-plan box of its check triangles (the room's .col:
each collision object's + 0x30 slot, a triangle's id at + 0x30 of its 0x34 bytes: GScolsys2CheckGetEventID) in
Colosseum's units, as src/data/orre_room_checks.h. src/orre/orre_npcs.c finds the one in
front of the player when A is pressed and runs its script with its four arguments, as Colosseum's cmsRunSync does.

    python3 -I tools/orre/gen_checks.py [UNPACKED]     (default ~/.cache/moemon/orre/unpacked)

A row: the room (Colosseum's id), the collision id, the script, its four arguments, and the box (x0, z0, x1, z1).
"""
import os
import struct
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import colo_rooms  # noqa: E402
import grid  # noqa: E402

OUT = os.path.join(ROOT, 'src', 'data', 'orre_room_checks.h')
CHECK, TOUCH = 3, 2
# touch scripts the maps already do: the shared bank's door animation (5) and elevators (6, 12)
TOUCH_DONE = {0x05960005, 0x05960006, 0x0596000C}


def check_triangles(data, slot=0x30, id_at=0x30):
    """{collision id: [triangles (n, 3, 3)]}: a slot of every collision object (+ 0x30 the check spots, a triangle's id
    at + 0x30; + 0x2C the triggers, at + 0x32), in the map's world"""
    off, n = struct.unpack_from('>II', data, 0)
    out = {}
    for i in range(n):
        o = off + i * 0x40
        p = struct.unpack_from('>I', data, o + slot)[0]
        if not p:
            continue
        rot, t = grid._mtx(struct.unpack_from('>9f', data, o))
        tris, cnt = struct.unpack_from('>II', data, p)
        for k in range(cnt):
            r = tris + k * 0x34
            T = np.array(struct.unpack_from('>9f', data, r)).reshape(1, 3, 3) @ rot.T + t
            out.setdefault(struct.unpack_from('>H', data, r + id_at)[0], []).append(T)
    return out


def main():
    unpacked = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/.cache/moemon/orre/unpacked')
    rooms = colo_rooms.rooms(unpacked)
    rooms = list(rooms.values()) if isinstance(rooms, dict) else rooms
    rows, touches, missing = [], [], 0
    for r in sorted(rooms, key=lambda r: r.room):
        evs = [e for e in r.events if e[0] == CHECK or (e[0] == TOUCH and e[2] not in TOUCH_DONE)]
        if not evs or not r.file:
            continue
        p = os.path.join(unpacked, r.file, r.file + '.col')
        if not os.path.exists(p):
            missing += len(evs)
            continue
        data = open(p, 'rb').read()
        tris = {CHECK: check_triangles(data), TOUCH: check_triangles(data, 0x2C, 0x32)}
        for kind, cid, script, args in evs:
            if cid not in tris[kind]:
                missing += 1
                continue
            xs = [float(v) for T in tris[kind][cid] for v in T[:, :, 0].ravel()]
            zs = [float(v) for T in tris[kind][cid] for v in T[:, :, 2].ravel()]
            (rows if kind == CHECK else touches).append(
                '    {%d, %d, 0x%08X, {%d, %d, %d, %d}, %.2ff, %.2ff, %.2ff, %.2ff},   // %s' % (
                    r.room, cid, script, args[0], args[1], args[2], args[3], min(xs), min(zs), max(xs), max(zs), r.file))
    lines = ['// ORRE\'s rooms\' check spots: Colosseum\'s floor events of kind 3 (generated by tools/orre/gen_checks.py from',
             '// the disc\'s tables; do not edit). {room, collision id, script, its arguments, the check triangles\' box x0,',
             '// z0, x1, z1}: src/orre/orre_npcs.c', '',
             '#define ORRE_ROOM_CHECK_COUNT %d' % len(rows), '',
             'static const struct OrreRoomCheck sOrreRoomChecks[ORRE_ROOM_CHECK_COUNT] = {'] + rows + ['};', '',
             '// Touch spots: floor events of kind 2 (stepping into the trigger runs the script), but the doors\' and',
             '// elevators\' (the maps\' own links); the trigger triangles\' box', '',
             '#define ORRE_ROOM_TOUCH_COUNT %d' % len(touches), '',
             'static const struct OrreRoomCheck sOrreRoomTouches[ORRE_ROOM_TOUCH_COUNT] = {'] + touches + ['};', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('%s: %d check spots, %d touch spots%s' % (OUT, len(rows), len(touches), ' (%d without a check triangle)' % missing if missing else ''))


if __name__ == '__main__':
    main()
