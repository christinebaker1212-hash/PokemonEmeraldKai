#!/usr/bin/env python3
"""ORRE's TVs for the game: src/data/orre_tv.h, each room's channels (Colosseum's own table: tools/orre/tv.py): the
room, the channel std171_mapSetTextureChange asks for, the room model's set that is the screen, and the picture in
orre_data.pak ("tv/<name>.bin", drawn by build_pack.py).

    python3 -I tools/orre/gen_tv.py UNPACKED
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tv  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    rows = []
    for room, (num, ents) in sorted(tv.tables(sys.argv[1]).items(), key=lambda kv: kv[1][0]):
        for i, st, model, anim, _cam in ents:
            rows.append('    {%d, %d, %d, "%s_%d"},   // %s' % (num, i, st, model, anim, room))
    out = ["// Generated by tools/orre/gen_tv.py from the disc: don't edit. ORRE's TVs: {Colosseum's room, the channel",
           "// (std171_mapSetTextureChange's id), the room model's set that is the screen, the picture \"tv/<name>.bin\"}",
           "static const struct OrreTv sOrreTv[] =", "{"] + rows + ["};", ""]
    with open(os.path.join(ROOT, "src", "data", "orre_tv.h"), "w") as f:
        f.write("\n".join(out))
    print("%d channels" % len(rows))


if __name__ == "__main__":
    main()
