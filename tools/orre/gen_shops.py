#!/usr/bin/env python3
"""ORRE's shops (docs/ORRE_HANDOFF.md "Shops, POKeMON CENTERs, the PC"): Colosseum's own lists, as the scripts' menuShopOpen(N)
opens them (src/game/menuShop.c shopOpenItemList: the module pocket_menu.rel publishes its tables into main.dol's .sbss,
lbl_80478E54 the shops (4 bytes each: u8 name, u8 kind, u16 the start of its list) and lbl_80478E44 the zero-ended
lists of item numbers, its _prolog storing them: tools/orre/colo_rooms.py rel_prolog_stores), as src/data/orre_shops.h.
src/orre/orre_vm.c opens Kai's POKeMART with the list.

    python3 -I tools/orre/gen_shops.py [UNPACKED]     (default ~/.cache/moemon/orre/unpacked)

Items are Gen 3's numbers, Kai's own, to 348; Colosseum's own past it (its SCENTS) are left out until Kai has them. The
kind: 0 money, 1 a drinks machine (money), 2-4 POKe COUPONS (the coupon counters: not opened yet).
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import colo_rooms  # noqa: E402

OUT = os.path.join(ROOT, 'src', 'data', 'orre_shops.h')
SHOPS, LISTS, COUNT = 0x80478E54, 0x80478E44, 0x80478E50
LAST_ITEM = 348


def main():
    unpacked = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/.cache/moemon/orre/unpacked')
    d = open(os.path.join(unpacked, 'pocket_menu', 'pocket_menu.rel'), 'rb').read()
    secs, st = colo_rooms.rel_sections(d), colo_rooms.rel_prolog_stores(d)

    def at(addr):
        sec, off = st[addr]
        return d[secs[sec][0] + off:]

    count = struct.unpack_from('>I', at(COUNT))[0]
    shops, lists = at(SHOPS), at(LISTS)
    rows, dropped = [], set()
    for i in range(count):
        name, kind, start = struct.unpack_from('>BBH', shops, 4 * i)
        items, p = [], 2 * start
        while True:
            v = struct.unpack_from('>H', lists, p)[0]
            p += 2
            if v == 0:
                break
            if v <= LAST_ITEM:
                items.append(v)
            else:
                dropped.add(v)
        rows.append('    {%d, {%s}},   // shop %d (name %d)' % (kind, ', '.join(map(str, items + [0])), i, name))
    lines = ['// ORRE\'s shops: Colosseum\'s own lists (generated by tools/orre/gen_shops.py from the disc; do not edit).',
             '// {kind (0 money, 1 drinks, 2-4 POKe COUPONS), items (Kai\'s numbers, 0-ended)}: src/orre/orre_vm.c', '',
             '#define ORRE_SHOP_COUNT %d' % count, '',
             'static const struct OrreShop sOrreShops[ORRE_SHOP_COUNT] = {'] + rows + ['};', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('%s: %d shops%s' % (OUT, count, ' (Colosseum\'s own items left out: %s)' % sorted(dropped) if dropped else ''))


if __name__ == '__main__':
    main()
