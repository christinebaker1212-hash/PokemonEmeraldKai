#!/usr/bin/env python3
"""ORRE's rooms' people (docs/ORRE_HANDOFF.md step 5, "People on the maps"): every room's characters from Colosseum's
own tables (tools/orre/colo_rooms.py: the floor record's + 0x14 slot), each with its ORRE person (the LOOK recipe and
picture tools/orre/people.py made for its model), as src/data/orre_room_people.h. src/orre/orre_npcs.c puts them on
the maps as Colosseum's scripts say (shown, hidden, moved, turned) and runs their talk scripts.

    python3 -I tools/orre/gen_people.py [UNPACKED]     (default ~/.cache/moemon/orre/unpacked)

A row: the room (Colosseum's id), the person's index in the room (what its scripts call it), its flags (0x80 shown
from the start), its talk types (>> 6: turns to the one talking to it, 1 its head, 2 itself; >> 4 & 3: turns back
after), its angle (degrees about Y, 0 facing +Z: the grid's south), the ORRE person (0xFFFF: a model that
isn't a person yet: a POKeMON, a truck, a sack), its name (Colosseum's name table row: the speaker's name), its move
and talk scripts, and where it stands (Colosseum's x and z).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import colo_rooms  # noqa: E402
import people  # noqa: E402

OUT = os.path.join(ROOT, 'src', 'data', 'orre_room_people.h')
ALIASES = {'hizuki_b2': 'hizuki_b1'}   # (RUI in her other clothes: RUI)


def main():
    unpacked = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/.cache/moemon/orre/unpacked')
    rooms = colo_rooms.rooms(unpacked)
    rooms = list(rooms.values()) if isinstance(rooms, dict) else rooms
    info = colo_rooms.people_info(unpacked)
    persons = {e[0]: i for i, e in enumerate(people.PEOPLE)}
    rows, missing = [], {}
    for r in sorted(rooms, key=lambda r: r.room):
        for p in r.people:
            model = info[p.info] if p.info < len(info) and info[p.info] else ''
            stem = model[:-4] if model.endswith('.dat') else model
            stem = ALIASES.get(stem, stem)
            person = persons.get(stem, 0xFFFF)
            if person == 0xFFFF and stem:
                missing[stem] = missing.get(stem, 0) + 1
            rows.append('    {%d, %d, 0x%02X, 0x%02X, %d, 0x%04X, %d, 0x%08X, 0x%08X, %.2ff, %.2ff},   // %s %s' % (
                r.room, p.index, p.flags, p.talk_types, p.angle, person, p.name, p.move, p.talk, p.x, p.z, r.file,
                stem))
    lines = ['// ORRE\'s rooms\' people: Colosseum\'s own characters of each room (generated by tools/orre/gen_people.py',
             '// from the disc\'s tables; do not edit). {room, index, flags, talk types, angle, person, name, move script,',
             '// talk script, x, z}: src/orre/orre_npcs.c', '',
             '#define ORRE_ROOM_PEOPLE_COUNT %d' % len(rows), '',
             'static const struct OrreRoomPerson sOrreRoomPeople[ORRE_ROOM_PEOPLE_COUNT] = {'] + rows + ['};', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('%s: %d people in %d rooms' % (OUT, len(rows), len(rooms)))
    if missing:
        print('models with no ORRE person (props / POKeMON): %s' % ', '.join(
            '%s x%d' % kv for kv in sorted(missing.items(), key=lambda kv: -kv[1])))


if __name__ == '__main__':
    main()
