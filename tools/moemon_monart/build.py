#!/usr/bin/env python3
"""OPTIONS > CREATURES: the original POKeMON battle pictures next to Kai's.

usage: build.py POKEEMERALD_CHECKOUT

Reads a pret/pokeemerald checkout (the vanilla game: its pictures are the ones still in
this repo's graphics/pokemon, Kai's live in graphics/moemon) and writes
src/mp/mp_monart_data.c: every front / back picture and palette of the vanilla game under
its own static name, and the vanilla tables that go with them (pictures, palettes,
coordinates, enemy elevation, front animations, the animation ids) as *_Pokemon. The game
picks Kai's tables or these at run time (include/data.h, mp_monart.c)."""
import os, re, sys

ref = sys.argv[1]
repo = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))

def read(path):
    with open(os.path.join(ref, path), encoding='utf-8-sig') as f:
        return f.read()

out = ['// Generated by tools/moemon_monart/build.py from pret/pokeemerald: the original',
       '// POKeMON pictures for OPTIONS > CREATURES (see mp_monart.c). Do not edit.',
       '#include "global.h"', '#include "data.h"', '#include "graphics.h"', '#include "pokemon_animation.h"',
       '#include "constants/species.h"', '',
       '#define SPECIES_SPRITE(species, sprite) [SPECIES_##species] = {sprite, MON_PIC_SIZE, SPECIES_##species}',
       '#define SPECIES_PAL(species, pal) [SPECIES_##species] = {pal, SPECIES_##species}',
       '#define SPECIES_SHINY_PAL(species, pal) [SPECIES_##species] = {pal, SPECIES_##species + SPECIES_SHINY_TAG}', '']

# 1. the pictures and palettes (front, back, normal, shiny)
want = re.compile(r'^const u32 (gMon(?:FrontPic|BackPic|Palette|ShinyPalette)_\w+)\[\] = (INC\w+\(.*\));\s*$')
names = set()
for path in ('src/anim_mon_front_pics.c', 'src/data/graphics/pokemon.h', 'src/graphics.c'):
    for line in read(path).splitlines():
        m = want.match(line)
        if m and m.group(1) not in names:
            names.add(m.group(1))
            out.append('static const u32 %s[] = %s;' % (m.group(1).replace('gMon', 'sPk', 1), m.group(2)))
out.append('')

def rename_refs(text):
    return re.sub(r'\bgMon(FrontPic|BackPic|Palette|ShinyPalette)_(\w+)', lambda m: 'sPk%s_%s' % (m.group(1), m.group(2))
                  if 'gMon%s_%s' % (m.group(1), m.group(2)) in names else m.group(0), text)

# 2. the tables
for f, table in (('front_pic_table.h', 'gMonFrontPicTable'), ('back_pic_table.h', 'gMonBackPicTable'),
                 ('palette_table.h', 'gMonPaletteTable'), ('shiny_palette_table.h', 'gMonShinyPaletteTable'),
                 ('front_pic_coordinates.h', 'gMonFrontPicCoords'), ('back_pic_coordinates.h', 'gMonBackPicCoords'),
                 ('enemy_mon_elevation.h', 'gEnemyMonElevation')):
    text = rename_refs(read('src/data/pokemon_graphics/' + f))
    text = re.sub(r'\b%s\b' % table, table + '_Pokemon', text)
    out.append('// ' + f)
    out.append(text.strip())
    out.append('')

# 3. the front animations (frame tables) and their per-species ids
text = read('src/data/pokemon_graphics/front_pic_anims.h')
text = re.sub(r'\bgMonFrontAnimsPtrTable\b', 'gMonFrontAnimsPtrTable_Pokemon', text)
out.append('// front_pic_anims.h (data.c\'s sAnim_GeneralFrame0 first)')
out.append('static const union AnimCmd sAnim_GeneralFrame0[] =\n{\n    ANIMCMD_FRAME(0, 0),\n    ANIMCMD_END,\n};')
out.append(text.strip())
out.append('')
pk = read('src/pokemon.c')
m = re.search(r'static const u8 sMonFrontAnimIdsTable\[NUM_SPECIES - 1\] =\s*\{.*?\n\};', pk, re.S)
out.append(m.group(0).replace('static const u8 sMonFrontAnimIdsTable', 'const u8 gMonFrontAnimIdsTable_Pokemon'))
out.append('')

with open(os.path.join(repo, 'src/mp/mp_monart_data.c'), 'w') as f:
    f.write('\n'.join(out))
print('%d pictures and palettes' % len(names))
