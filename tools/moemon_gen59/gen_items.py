#!/usr/bin/env python3
"""Gen 5-9 items for Kai (ids from 508, after the Johto / Kanto story items): what the Gen 5-9 Pokémon need to evolve
and hold. Constants, item data, descriptions, icons.

    python3 tools/moemon_gen59/gen_items.py [EXPANSION_DIR]

Names, prices, descriptions and icons are pokeemerald-expansion's (cached in items.json, icons copied to
graphics/items/, so EXPANSION_DIR is only needed to refresh). Evolution items work like stones (ItemUseOutOfBattle_
EvolutionStone), LINKING CORD and the trade items too (gen_species.py makes their trade evolutions item ones).
Held items get their battle effects in the battle code (HOLD_EFFECT_NONE until then).
Generated: the include/constants/items.h block, src/data/items_gen59.h, src/data/text/item_descriptions_gen59.h,
src/data/graphics/items_gen59.h, src/data/item_icons_gen59.h.
"""
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'tools', 'moemon_gen4'))
from kaitext import kai_text  # noqa: E402

FIRST_ID = 508
# Items the newer games sell only for points (price 0 there): what the department stores ask (src/shop.c MP extras)
SHOP_PRICES = {'ITEM_ICE_STONE': 3000, 'ITEM_SCROLL_OF_DARKNESS': 10000, 'ITEM_SCROLL_OF_WATERS': 10000,
               'ITEM_WHIPPED_DREAM': 3000, 'ITEM_SACHET': 3000, 'ITEM_ELECTRIC_SEED': 4000, 'ITEM_PSYCHIC_SEED': 4000,
               'ITEM_MISTY_SEED': 4000, 'ITEM_GRASSY_SEED': 4000, 'ITEM_BOOSTER_ENERGY': 10000,
               'ITEM_ASSAULT_VEST': 50000, 'ITEM_WEAKNESS_POLICY': 20000, 'ITEM_HEAVY_DUTY_BOOTS': 20000}
GEN = '// Generated by tools/moemon_gen59/gen_items.py. Do not edit.\n'
STONES = ['ITEM_ICE_STONE', 'ITEM_SWEET_APPLE', 'ITEM_TART_APPLE', 'ITEM_SYRUPY_APPLE', 'ITEM_CRACKED_POT',
          'ITEM_CHIPPED_POT', 'ITEM_UNREMARKABLE_TEACUP', 'ITEM_MASTERPIECE_TEACUP', 'ITEM_METAL_ALLOY',
          'ITEM_SCROLL_OF_DARKNESS', 'ITEM_SCROLL_OF_WATERS', 'ITEM_AUSPICIOUS_ARMOR', 'ITEM_MALICIOUS_ARMOR',
          'ITEM_WHIPPED_DREAM', 'ITEM_SACHET', 'ITEM_LINKING_CORD', 'ITEM_STRAWBERRY_SWEET', 'ITEM_LOVE_SWEET',
          'ITEM_BERRY_SWEET', 'ITEM_CLOVER_SWEET', 'ITEM_FLOWER_SWEET', 'ITEM_STAR_SWEET', 'ITEM_RIBBON_SWEET']
HELD = ['ITEM_FLOAT_STONE', 'ITEM_ABSORB_BULB', 'ITEM_CELL_BATTERY', 'ITEM_SNOWBALL', 'ITEM_ELECTRIC_SEED',
        'ITEM_PSYCHIC_SEED', 'ITEM_MISTY_SEED', 'ITEM_GRASSY_SEED', 'ITEM_BOOSTER_ENERGY', 'ITEM_RED_NECTAR',
        'ITEM_YELLOW_NECTAR', 'ITEM_PINK_NECTAR', 'ITEM_PURPLE_NECTAR', 'ITEM_ASSAULT_VEST', 'ITEM_ROCKY_HELMET',
        'ITEM_AIR_BALLOON', 'ITEM_WEAKNESS_POLICY', 'ITEM_HEAVY_DUTY_BOOTS', 'ITEM_PIXIE_PLATE', 'ITEM_FAIRY_FEATHER']
OTHER = ['ITEM_GIMMIGHOUL_COIN', 'ITEM_LEADERS_CREST']
ITEMS = [(c, 'stone') for c in STONES] + [(c, 'held') for c in HELD] + [(c, 'other') for c in OTHER]


def parse_expansion(exp):
    src = open(os.path.join(exp, 'src', 'data', 'items.h'), encoding='utf-8').read()
    gfx = open(os.path.join(exp, 'src', 'data', 'graphics', 'items.h'), encoding='utf-8').read()
    paths = dict(re.findall(r'const u(?:16|32) (gItemIcon\w*)\[\] = INCGFX_U(?:16|32)\("([^"]+)"', gfx))
    out = {}
    for const, _ in ITEMS:
        m = re.search(r'\n    \[%s\] =\n    \{(.*?)\n    \},' % const, src, re.S)
        if not m:
            raise SystemExit('expansion has no %s' % const)
        body = m.group(1)
        body = re.sub(r'[ \t]*#if[^\n]*\n(.*?)[ \t]*#else[^\n]*\n.*?[ \t]*#endif[^\n]*\n', r'\1', body, flags=re.S)
        body = re.sub(r'[ \t]*#if[^\n]*\n(.*?)[ \t]*#endif[^\n]*\n', r'\1', body, flags=re.S)
        e = {}
        n = re.search(r'\.name = (?:ITEM_NAME|_|COMPOUND_STRING)\("([^"]*)"\)', body)
        e['name'] = n.group(1) if n else const[5:].replace('_', ' ').title()
        p = re.search(r'\.price = \(?(\d+)', body)
        e['price'] = int(p.group(1)) if p else 0
        d = re.search(r'\.description = COMPOUND_STRING\((.*?)\),\n', body, re.S)
        e['description'] = ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', d.group(1))) if d else ''
        for f in ('iconPic', 'iconPalette'):
            v = re.search(r'\.%s = ([^,\n]+),' % f, body)
            if v:
                e[f] = v.group(1).strip()
        e['icon_png'] = paths.get(e.get('iconPic'))
        e['icon_pal'] = paths.get(e.get('iconPalette'))
        out[const] = e
    return out


def main():
    cache_p = os.path.join(HERE, 'items.json')
    cache = json.load(open(cache_p, encoding='utf-8')) if os.path.exists(cache_p) else {}
    if len(sys.argv) > 1:
        exp = sys.argv[1]
        cache = parse_expansion(exp)
        for const, e in cache.items():
            for k in ('icon_png', 'icon_pal'):
                if e.get(k):
                    dst = os.path.join(REPO, e[k])
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    if not os.path.exists(dst) and os.path.exists(os.path.join(exp, e[k])):
                        shutil.copy(os.path.join(exp, e[k]), dst)
                    if not os.path.exists(dst):
                        e[k] = None
        json.dump(cache, open(cache_p, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    ids = {const: FIRST_ID + i for i, (const, _) in enumerate(ITEMS)}
    body = ''.join('#define %s %d\n' % (c, i) for c, i in ids.items())
    body += '#define FIRST_GEN59_ITEM %s\n#define LAST_GEN59_ITEM %s\n\n#define ITEMS_COUNT %d\n' % (
        ITEMS[0][0], ITEMS[-1][0], FIRST_ID + len(ITEMS))
    p = os.path.join(REPO, 'include/constants/items.h')
    s = open(p, encoding='utf-8').read()
    s = s.replace('\n#define ITEMS_COUNT %d\n// end of Johto / Kanto items\n' % FIRST_ID, '\n// end of Johto / Kanto items\n')
    blk = '// Moemon Kai: Gen 5-9 items (tools/moemon_gen59/gen_items.py)\n' + body + '// end of Gen 5-9 items\n'
    if '// Moemon Kai: Gen 5-9 items' in s:
        s = re.sub(r'// Moemon Kai: Gen 5-9 items.*?// end of Gen 5-9 items\n', lambda m: blk, s, flags=re.S)
    else:
        s = s.replace('// end of Johto / Kanto items\n', '// end of Johto / Kanto items\n' + blk)
    open(p, 'w', encoding='utf-8').write(s)
    data, descs, gfx, icons = [GEN], [GEN], [GEN], []
    for const, kind in ITEMS:
        e = cache[const]
        sym = ''.join(w.capitalize() for w in const[5:].split('_'))
        name = e['name'].upper().replace('’', "'").replace('É', 'é')
        if len(name) > 13:
            name = {'UNREMARKABLE TEACUP': 'PLAIN TEACUP', 'MASTERPIECE TEACUP': 'MASTER TEACUP',
                    'SCROLL OF DARKNESS': 'DARK SCROLL', 'SCROLL OF WATERS': 'WATER SCROLL',
                    'AUSPICIOUS ARMOR': 'AUSPIC.ARMOR', 'MALICIOUS ARMOR': 'MALIC. ARMOR',
                    'STRAWBERRY SWEET': 'STRAWBRY SWT', 'HEAVY-DUTY BOOTS': 'HEAVYDTYBOOTS',
                    'WEAKNESS POLICY': 'WEAKNESS POL.', 'GIMMIGHOUL COIN': 'GIMMI. COIN', 'BOOSTER ENERGY': 'BOOSTER ENRGY',
                    "LEADER'S CREST": "LEADER'SCREST"}.get(name, name[:13])
        price = e['price'] or SHOP_PRICES.get(const, 0)   # (points-only items in the newer games: a shop price here)
        lines = ['        .name = _("%s"),' % name, '        .itemId = %s,' % const, '        .price = %d,' % price,
                 '        .description = s%sDesc,' % sym]
        if kind == 'stone':
            lines += ['        .pocket = POCKET_ITEMS,', '        .type = ITEM_USE_PARTY_MENU,',
                      '        .fieldUseFunc = ItemUseOutOfBattle_EvolutionStone,']
        else:
            lines += ['        .pocket = POCKET_ITEMS,', '        .type = ITEM_USE_BAG_MENU,',
                      '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,']
        data.append('    [%s] =\n    {\n%s\n    },\n\n' % (const, '\n'.join(lines)))
        d = kai_text(e['description'] or name).split('\\n')
        descs.append('static const u8 s%sDesc[] = _(\n%s);\n\n' % (
            sym, '\n'.join('    "%s%s"' % (l, '\\n' if i < len(d) - 1 else '') for i, l in enumerate(d))))
        if e.get('icon_png') and e.get('icon_pal'):
            gfx.append('const u32 gItemIcon_%s[] = INCGFX_U32("%s", ".4bpp.lz");\n' % (sym, e['icon_png']))
            gfx.append('const u32 gItemIconPalette_%s[] = INCGFX_U32("%s", ".gbapal.lz");\n' % (sym, e['icon_pal']))
            icons.append('    [%s] = {gItemIcon_%s, gItemIconPalette_%s},' % (const, sym, sym))
        else:
            icons.append('    [%s] = {gItemIcon_QuestionMark, gItemIconPalette_QuestionMark},' % const)
    w = lambda rel, t: open(os.path.join(REPO, rel), 'w', encoding='utf-8').write(t)
    w('src/data/items_gen59.h', ''.join(data))
    w('src/data/text/item_descriptions_gen59.h', ''.join(descs))
    w('src/data/graphics/items_gen59.h', ''.join(gfx))
    ext = [l.replace('const u32 ', 'extern const u32 ').split(' = ')[0] + ';\n' for l in gfx[1:]]
    w('src/data/item_icons_gen59.h', GEN + ''.join(ext) + '#define ITEM_ICONS_GEN59 \\\n' + ' \\\n'.join(icons) + '\n')
    print('%d items (%d-%d)' % (len(ITEMS), FIRST_ID, FIRST_ID + len(ITEMS) - 1))


if __name__ == '__main__':
    main()
