def key(s):
    return re.sub(r'[^a-z0-9]', '', re.sub(r'^(SPECIES_|ITEM_|MOVE_|ABILITY_|TYPE_)', '', s).lower())


def camel(const):
    return ''.join(w.capitalize() for w in const.split('_', 1)[1].split('_'))


def write(rel, text):
    p = os.path.join(REPO, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    old = open(p, encoding='utf-8').read() if os.path.exists(p) else None
    if old != text:
        open(p, 'w', encoding='utf-8').write(text)


def block(rel, start, end, body):
    p = os.path.join(REPO, rel)
    s = open(p, encoding='utf-8').read()
    if start not in s:
        raise SystemExit('%s: no "%s"' % (rel, start))
    a = s.index(start)
    b = s.index(end, a)
    open(p, 'w', encoding='utf-8').write(s[:a] + start + '\n' + body + s[b:])


def pick(expr):
    """`X >= GEN_n ? a : b`: the newest value."""
    expr = expr.strip()
    m = re.match(r'^\(?\s*\w+\s*(>=|>)\s*GEN_\w+\s*\)?\s*\?\s*(.*?)\s*:\s*(.*)$', expr, re.S)
    return pick(m.group(2)) if m else expr.strip('() ')


