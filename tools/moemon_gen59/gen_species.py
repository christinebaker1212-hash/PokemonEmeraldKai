        if e['const'] == 'SPECIES_FURFROU':
            continue   # (the expansion's macros hand it ESPURR's evolutions: it doesn't evolve)
        for ev in e['evolutions']:
            tgt = target(ev['target'])
            if not tgt or tgt == e['const']:
                continue
            m, prm = ev['method'], ev['param']
            conds = {c: v for c, v in ev['conds']}
            lvl = prm if prm.isdigit() and prm != '0' else '30'
            if m in ('EVO_LEVEL', 'EVO_LEVEL_BATTLE_ONLY'):
                if 'IF_MIN_FRIENDSHIP' in conds:
                    t = conds.get('IF_TIME', '')
                    rows.append(('EVO_FRIENDSHIP_DAY' if 'DAY' in t else 'EVO_FRIENDSHIP_NIGHT' if 'NIGHT' in t else 'EVO_FRIENDSHIP', '0', tgt))
                elif 'IF_HOLD_ITEM' in conds:
                    t = conds.get('IF_TIME', '')
