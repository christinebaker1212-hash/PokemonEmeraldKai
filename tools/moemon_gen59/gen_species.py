def from_expansion(exp):
    src = ''.join(open(f, encoding='utf-8').read() for f in sorted(glob.glob(
        os.path.join(exp, 'src', 'data', 'pokemon', 'species_info', 'gen_*_families.h'))))
    keys = re.findall(r'^    \[(SPECIES_\w+)\] =', src, re.M)
    macros, objmacros = {}, {}
    for m in re.finditer(r'^[ \t]*#define ([A-Z_0-9]+) ([^\n\\]+)$', src, re.M):
        objmacros.setdefault(m.group(1), m.group(2).strip())
    shared = open(os.path.join(exp, 'src', 'data', 'pokemon', 'species_info', 'shared_dex_text.h'), encoding='utf-8').read()
    shared_text = {m.group(1): ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2)))
                   for m in re.finditer(r'const u8 (g\w+)\[\] = _\((.*?)\);', shared, re.S)}
    for m in re.finditer(r'^#define (\w+)\(([^)]*)\)((?:[^\n]*\\\n)*[^\n]*)', src, re.M):
        macros[m.group(1)] = ([x.strip() for x in m.group(2).split(',')], m.group(3).replace('\\\n', '\n'))
    dex = open(os.path.join(exp, 'include', 'constants', 'pokedex.h'), encoding='utf-8').read()
    nat = {}
    for n, name in enumerate(re.findall(r'^\s+(NATIONAL_DEX_\w+),', dex.split('enum NationalDexOrder', 1)[1]
                                        if 'enum NationalDexOrder' in dex else dex, re.M)):
        if name != 'NATIONAL_DEX_NONE' and name not in nat:
            nat[name] = len(nat) + 1
    gfx = open(os.path.join(exp, 'src', 'data', 'graphics', 'pokemon.h'), encoding='utf-8').read()
    paths = dict(re.findall(r'const u\d+ (g\w+)\[\] = INCGFX_\w+\("([^"]+)"', gfx))
    lv_src = {g: open(os.path.join(exp, 'src', 'data', 'pokemon', 'level_up_learnsets', 'gen_%d.h' % g), encoding='utf-8').read()
              for g in range(1, 10)}
    egg_src = open(os.path.join(exp, 'src', 'data', 'pokemon', 'egg_moves.h'), encoding='utf-8').read()
    teach = json.load(open(os.path.join(exp, 'src', 'data', 'pokemon', 'all_learnables.json'), encoding='utf-8'))
    out = []
    for name, n in sorted(nat.items(), key=lambda x: x[1]):
        if n < NAT_FIRST or n > NAT_LAST:
            continue
        const = 'SPECIES_' + name[len('NATIONAL_DEX_'):]
        k = const if const in keys else next((x for x in keys if x.startswith(const + '_') and 'MEGA' not in x
                                              and 'GMAX' not in x), None)
        if k is None:
            raise SystemExit('no expansion species for %s' % const)
        body = src.split('[%s] =' % k, 1)[1].split('\n    },\n', 1)[0] + '\n'   # (the last field ends with ',\n' too)
        body = expand_macros(body, macros)
        body = re.sub(r'[ \t]*#if[^\n]*\n(.*?)[ \t]*#else[^\n]*\n.*?[ \t]*#endif[^\n]*\n', r'\1', body, flags=re.S)
        body = re.sub(r'[ \t]*#if[^\n]*\n(.*?)[ \t]*#endif[^\n]*\n', r'\1', body, flags=re.S)

        def f(field, default=None):
            m = re.search(r'\.%s\s*=\s*(.*?),\n' % re.escape(field), body, re.S)
            if not m:
                return default
            v = m.group(1).strip()
            return pick(objmacros.get(v, v))
        e = {'const': const, 'national': n, 'expansion_key': k}
        for fld in ('baseHP', 'baseAttack', 'baseDefense', 'baseSpeed', 'baseSpAttack', 'baseSpDefense', 'catchRate',
                    'expYield', 'eggCycles', 'height', 'weight', 'pokemonScale', 'pokemonOffset', 'trainerScale',
                    'trainerOffset', 'frontPicYOffset', 'backPicYOffset', 'enemyMonElevation', 'iconPalIndex'):
            v = f(fld)
            e[fld] = int(v) if v is not None and re.match(r'^-?\d+$', v) else 0
        for st in ('HP', 'Attack', 'Defense', 'Speed', 'SpAttack', 'SpDefense'):
            v = f('evYield_' + st)
            e['ev_' + st] = int(v) if v and v.isdigit() else 0
        e['types'] = re.findall(r'TYPE_\w+', f('types', 'MON_TYPES(TYPE_NORMAL)'))
        e['eggGroups'] = re.findall(r'EGG_GROUP_\w+', f('eggGroups', 'MON_EGG_GROUPS(EGG_GROUP_NO_EGGS_DISCOVERED)'))
        e['abilities'] = re.findall(r'ABILITY_\w+', f('abilities', '{ ABILITY_NONE }'))
        g = f('genderRatio', 'PERCENT_FEMALE(50)')
        pm = re.match(r'PERCENT_FEMALE\(([\d.]+)', g)
        if pm:   # Kai has no PERCENT_FEMALE: the byte itself
            g = str(min(254, int(float(pm.group(1)) * 255 / 100)))
        e['genderRatio'] = g
        e['friendship'] = f('friendship', 'STANDARD_FRIENDSHIP')
        e['growthRate'] = f('growthRate', 'GROWTH_MEDIUM_FAST')
        e['bodyColor'] = re.search(r'BODY_COLOR_\w+', f('bodyColor', 'BODY_COLOR_RED') or '').group(0) if re.search(r'BODY_COLOR_\w+', f('bodyColor', '') or '') else 'BODY_COLOR_RED'
        e['itemCommon'] = f('itemCommon', 'ITEM_NONE')
        e['itemRare'] = f('itemRare', 'ITEM_NONE')
        e['noFlip'] = f('noFlip', 'FALSE')
        nm = re.search(r'\.speciesName = _\("([^"]*)"\)', body)
        if not nm:
            raise SystemExit("no name for %s (%s): %r" % (const, k, body[:300]))
        e['name'] = nm.group(1)
        cat = re.search(r'\.categoryName = _\("([^"]*)"\)', body)
        e['category'] = cat.group(1) if cat else ''
        d = re.search(r'\.description = COMPOUND_STRING\((.*?")\s*\),', body, re.S)
        desc = ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', d.group(1))) if d else ''
        if not desc:   # a shared text (shared_dex_text.h)
            d = re.search(r'\.description = (g\w+),', body)
            desc = shared_text.get(d.group(1), '') if d else ''
        e['dex_text'] = desc.replace('\\n', ' ')
        for fld in ('frontPicSize', 'backPicSize'):
            m = re.search(r'\.%s = MON_COORDS_SIZE\((\d+), (\d+)\)' % fld, body)
            e[fld] = [int(m.group(1)), int(m.group(2))] if m else [64, 64]
        for fld in ('frontAnimId', 'cryId', 'frontPic', 'backPic', 'palette', 'shinyPalette', 'iconSprite',
                    'levelUpLearnset', 'eggMoveLearnset'):
            m = re.search(r'\.%s = (\w+),' % fld, body)
            e[fld] = m.group(1) if m else None
        m = re.search(r'\.frontAnimFrames = ANIM_FRAMES\((.*?)\),\n', body, re.S)
        e['frontAnimFrames'] = re.findall(r'ANIMCMD_FRAME\((\d+), (\d+)\)', m.group(1)) if m else [('0', '30')]
        m = re.search(r'FOOTPRINT\((\w+)\)', body)
        e['footprint_png'] = paths.get('gMonFootprint_' + m.group(1)) if m else None
        e['dir'] = paths[e['frontPic']].rsplit('/', 1)[0] if e['frontPic'] in paths else 'graphics/pokemon/' + name[13:].lower()
        e['icon_png'] = paths.get(e['iconSprite'])
        e['cry_wav'] = 'sound/direct_sound_samples/cries/%s.wav' % (e['cryId'] or 'CRY_NONE')[4:].lower()
        m = re.search(r'\.evolutions = EVOLUTION\((.*?)\),\n', body, re.S)
        e['evolutions'] = parse_evos(m.group(1)) if m else []
        # learnsets: the newest generation's list that has it
        e['level'] = []
        for g in range(9, 0, -1):
            m = re.search(r'static const struct LevelUpMove %s\[\] = \{(.*?)\};' % re.escape(e['levelUpLearnset'] or '~'),
                          lv_src[g], re.S)
            if m:
                e['level'] = [(int(a), b) for a, b in re.findall(r'LEVEL_UP_MOVE\(\s*(\d+),\s*(MOVE_\w+)\)', m.group(1))]
                break
        m = re.search(r'static const u16 %s\[\] = \{(.*?)\};' % re.escape(e['eggMoveLearnset'] or '~'), egg_src, re.S)
        e['egg'] = [x for x in re.findall(r'MOVE_\w+', m.group(1)) if x != 'MOVE_UNAVAILABLE'] if m else []
        tk = k[8:]
        e['teach'] = teach.get(tk) or teach.get(const[8:]) or []
        out.append(e)
    return out


def expand_macros(body, macros):
    """A line `NAME(args),` of a #define'd macro (VIVILLON_MISC_INFO...) becomes its fields."""
    def rep(m):
        name, args = m.group(1), [x.strip() for x in m.group(2).split(',')]
        params, text = macros[name]
        for p_, a_ in zip(params, args):
            text = re.sub(r'\b%s\b' % re.escape(p_), a_.replace('\\', '\\\\'), text)
        text = re.sub(r'(\w+)\s*##\s*(\w+)', r'\1\2', text)
        return '\n'.join('        ' + l.strip() for l in text.split('\n') if l.strip()) + '\n'
    pat = re.compile(r'^[ \t]+(%s)\(([^\n]*)\),?[ \t]*$\n?' % '|'.join(map(re.escape, macros)), re.M) if macros else None
    for _ in range(3):
        if pat:
            body = pat.sub(rep, body)
    return body


