#!/usr/bin/env python3
"""Moemon Co-op app icon: graphics/moemon/app_icon.png (the Poke Ball, 256x256) ->
src/platform/win32res/icon.ico (exe icon, all the sizes Windows asks for) and
include/platform/app_icon.h (64x64 RGBA for the SDL window icon).
  build.py [SOURCE_IMAGE]   a new source image is squared, trimmed and saved as app_icon.png first"""
import os
import sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
PNG = os.path.join(ROOT, 'graphics/moemon/app_icon.png')
ICO = os.path.join(ROOT, 'src/platform/win32res/icon.ico')
HDR = os.path.join(ROOT, 'include/platform/app_icon.h')

if len(sys.argv) > 1:
    im = Image.open(sys.argv[1]).convert('RGBA')
    im = im.crop(im.getbbox())
    side = max(im.size)
    sq = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    sq.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    sq.resize((256, 256), Image.LANCZOS).save(PNG)

src = Image.open(PNG).convert('RGBA')
src.save(ICO, sizes=[(s, s) for s in (16, 20, 24, 32, 40, 48, 64, 128, 256)])
small = src.resize((64, 64), Image.LANCZOS)
px = small.tobytes()
with open(HDR, 'w') as f:
    f.write('// Generated by tools/app_icon/build.py from graphics/moemon/app_icon.png\n')
    f.write('// 64x64 RGBA (bytes R, G, B, A), the SDL window icon\n')
    f.write('#define APP_ICON_SIZE 64\n')
    f.write('static const unsigned char sAppIcon[64 * 64 * 4] = {\n')
    for i in range(0, len(px), 16):
        f.write('    ' + ', '.join('%d' % b for b in px[i:i + 16]) + ',\n')
    f.write('};\n')
print('wrote', PNG, ICO, HDR)
