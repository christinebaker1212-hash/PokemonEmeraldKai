#!/usr/bin/env python3
"""A Game Boy song (GBS) with the chip's tricks, for the GB > GBA tests: square 2 plays a C-E-G arpeggio (its
frequency cycling every frame without a retrigger) struck every 64 frames, and square 1 retriggers one note
every other frame for 16 frames (a buzz).
usage: make_test_gbs_arp.py OUT.gbs"""
import struct, sys

init = bytes([
    0x3E, 0x80, 0xE0, 0x26,        # ld a,$80 / ldh (NR52),a
    0x3E, 0x77, 0xE0, 0x24,        # ld a,$77 / ldh (NR50),a
    0x3E, 0xFF, 0xE0, 0x25,        # ld a,$FF / ldh (NR51),a
    0xAF, 0xEA, 0x00, 0xC0,        # xor a / ld ($C000),a
    0xEA, 0x02, 0xC0,              # ld ($C002),a
    0xC9,                          # ret
])
play = bytes([
    0x21, 0x00, 0xC0, 0x34, 0x7E, 0x47,          # counter++ -> b
    0x21, 0x02, 0xC0, 0x7E, 0x3C, 0xFE, 0x03,    # arpeggio step: (hl) = (hl)+1 mod 3
    0x38, 0x01, 0xAF, 0x77,
    0x21, 0x80, 0x04, 0x85, 0x6F, 0x7E,          # its frequency's low byte from the table at $0480
    0xE0, 0x18, 0x3E, 0x06, 0xE0, 0x19,          # NR23, NR24 = $06 (no trigger)
    0x78, 0xE6, 0x3F, 0x20, 0x0C,                # every 64 frames: strike square 2
    0x3E, 0xF0, 0xE0, 0x17, 0x3E, 0x80, 0xE0, 0x16, 0x3E, 0x86, 0xE0, 0x19,
    0x78, 0xE6, 0x3F, 0xFE, 0x20, 0xD8, 0xFE, 0x30, 0xD0, 0xCB, 0x40, 0xC0,   # frames 32-47, even: square 1 again
    0x3E, 0xF0, 0xE0, 0x12, 0x3E, 0x80, 0xE0, 0x11, 0x3E, 0x60, 0xE0, 0x13, 0x3E, 0x86, 0xE0, 0x14,
    0xC9,
])
code = init + play
code += bytes(0x80 - len(code)) + bytes([0x0B, 0x72, 0xB2])     # C4, E4, G4 (high bits 6)
head = b'GBS' + bytes([1, 1, 1]) + struct.pack('<HHHH', 0x0400, 0x0400, 0x0414, 0xFFFE) + bytes([0, 0])
head += b'Studio arpeggio test'.ljust(32, b'\0') + b'Moemon'.ljust(32, b'\0') + b'2026'.ljust(32, b'\0')
open(sys.argv[1], 'wb').write(head + code)
