#!/usr/bin/env python3
"""Moemon Co-op: data for the action sprites of looks without their own (src/mp/mp_hybrid.c).

For each of Brendan's and May's action frames (bikes, surfing, field move, fishing, watering,
decorating) this finds where their walking head sits (the head of the standing frame facing the
same way, matched pixel for pixel) and which pixels belong to that head. At run time those pixels
are cleared and the look's own head is drawn there. Writes src/mp/mp_hybrid_data.h.

    python3 tools/moemon_hybrid/build.py            (from the repository root)
"""
import os, sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
PICS = os.path.join(ROOT, 'graphics/object_events/pics/people')
OUT = os.path.join(ROOT, 'src/mp/mp_hybrid_data.h')

NECK = 23                     # first body row of a 16x32 walking frame
# (ST_* in mp_avatar.c, file, frame width)
STATES = [(1, 'mach_bike', 32), (2, 'acro_bike', 32), (3, 'surfing', 32), (5, 'field_move', 32),
          (6, 'fishing', 32), (7, 'watering', 32), (8, 'decorating', 16)]
DIRS = 'SNWE'
# Hat / hair colors of the walking heads, cleared one pixel around the head (its outline)
HEAD_COLORS = {'brendan': (5, 9, 10, 11, 14, 15), 'may': (5, 8, 10, 11, 14, 15)}
# Body color groups (palette indices, light to dark) that take the look's clothes, biggest first
BODY_GROUPS = {'brendan': [[5, 6, 7, 8], [12, 13], [10, 11]], 'may': [[7, 8], [5, 6], [12, 13], [10, 11]]}


def frames(who, name, fw):
    im = Image.open(os.path.join(PICS, who, name + '.png'))
    assert im.mode == 'P'
    W, H = im.size
    out = []
    for f in range(W // fw):
        fr = [[im.getpixel((f * fw + x, y)) for x in range(fw)] for y in range(H)]
        if fw == 16:
            fr = [[0] * 8 + r + [0] * 8 for r in fr]   # centered in a 32-wide canvas
        out.append(fr)
    return out


def is_arm(x, y, d):
    # Kai sprites hold their arms beside the lower head (front and back views)
    return d in (0, 1) and 16 <= y <= 21 and (x <= 2 or x >= 13)


def walk_heads(who):
    wf = frames(who, 'walking', 16)
    hs = {}
    for d in range(3):
        f = wf[d]
        hs[DIRS[d]] = {(x - 8, y): f[y][x] for y in range(NECK) for x in range(8, 24)
                       if f[y][x] and not (is_arm(x - 8, y, d) and f[y][x] in (1, 2, 3, 4))}
    hs['E'] = {(15 - x, y): c for (x, y), c in hs['W'].items()}
    return hs


def best_match(fr, hs):
    best = None
    for name, h in hs.items():
        for dy in range(-16, 24):
            for dx in range(-4, 20):
                m = 0
                for (x, y), c in h.items():
                    X, Y = x + dx, y + dy
                    if 0 <= X < 32 and 0 <= Y < 32 and fr[Y][X] == c:
                        m += 1
                key = (m / len(h), -DIRS.index(name), -abs(dx - 8), -abs(dy))
                if best is None or key > best[0]:
                    best = (key, name, dx, dy)
    return best[0][0], best[1], best[2], best[3]


def erase_mask(who, fr, d, dx, dy, hs, state):
    def sil(dy2, upper_only=False):
        return {(x + dx, y + dy2) for (x, y) in hs[d] if not upper_only or y < 16}
    out = sil(dy)
    cols = {x for (x, y) in out}
    top = min(y for (x, y) in out)
    t = top
    # A head drawn a row taller than the walking one: its real top too (not when fishing: the rod)
    while t > 0 and any(fr[t - 1][x] for x in cols if 0 <= x < 32):
        t -= 1
    if t < top and state != 'fishing':
        out |= sil(dy - (top - t), True)
    if state != 'fishing':
        for (X, Y) in list(out):
            if Y - dy >= 17:
                continue
            for ox in (-1, 1):
                P = (X + ox, Y)
                if 0 <= P[0] < 32 and 0 <= P[1] < 32 and fr[P[1]][P[0]] in HEAD_COLORS[who]:
                    out.add(P)
    return {p for p in out if 0 <= p[0] < 32 and 0 <= p[1] < 32}


def main():
    lines = ['// Moemon Co-op: where Brendan\'s and May\'s heads sit in their action frames.',
             '// Generated by tools/moemon_hybrid/build.py. Do not edit.', '']
    for g, who in enumerate(('brendan', 'may')):
        hs = walk_heads(who)
        counts = [0] * 16
        tables = []
        for st, name, fw in STATES:
            rows = []
            for i, fr in enumerate(frames(who, name, fw)):
                score, d, dx, dy = best_match(fr, hs)
                er = erase_mask(who, fr, d, dx, dy, hs, name)
                for y in range(32):
                    for x in range(32):
                        if fr[y][x] and (x, y) not in er:
                            counts[fr[y][x]] += 1
                mask = [sum(1 << x for x in range(32) if (x, y) in er) for y in range(32)]
                if score < 0.5:
                    print('%s %s %d: weak match %.2f' % (who, name, i, score), file=sys.stderr)
                rows.append('    {%d, %d, %d, {%s}},' % (DIRS.index(d), dx, dy, ', '.join('0x%x' % m for m in mask)))
            tables.append((st, name, fw, len(rows)))
            lines.append('static const struct MpHyFrame sHy_%s_%s[] = {' % (who, name))
            lines += rows
            lines.append('};')
        lines.append('static const struct MpHyState sHyStates_%s[] = {' % who)
        for st, name, fw, n in tables:
            lines.append('    [%d] = {sHy_%s_%s, %d, %d},' % (st, who, name, n, fw))
        lines.append('};')
        groups = BODY_GROUPS[who]
        base = [max(range(len(gr)), key=lambda i: counts[gr[i]]) for gr in groups]
        lines.append('static const struct MpHyBody sHyBody_%s = {' % who)
        lines.append('    {%s},' % ', '.join('{%s}' % ', '.join(str(c) for c in gr + [0] * (4 - len(gr))) for gr in groups + [[]] * (4 - len(groups))))
        lines.append('    {%s},' % ', '.join(str(len(gr)) for gr in groups + [[]] * (4 - len(groups))))
        lines.append('    {%s},' % ', '.join(str(b) for b in base + [0] * (4 - len(base))))
        lines.append('    %d,' % len(groups))
        lines.append('};')
        lines.append('')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
