#!/usr/bin/env python3
"""Moemon Quetzal's own multichoice menus (quetzal_rip/data/multichoice.json) as Kai menus.

    python3 tools/quetzal_port/gen_multichoice.py

Quetzal's Kanto / Johto scripts name them 0x2C + n; import.py writes those as MULTI_QZ_<id> and this numbers them
after Kai's own (MULTI_QZ_FIRST + n): include/constants/script_menu_qz.h, src/data/script_menu_qz.h (the lists) and
src/data/script_menu_qz_entries.h (their rows in sMultichoiceLists).
"""
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
FIRST = 117   # after MULTI_DANCE_MACHINE


def main():
    d = json.load(open(os.path.join(REPO, 'quetzal_rip/data/multichoice.json')))
    menus = d['menus']
    assert FIRST + len(menus) <= 256
    head = ['// Generated by tools/quetzal_port/gen_multichoice.py: Quetzal\'s menus (its script id 0x2C + n)',
            '#ifndef GUARD_CONSTANTS_SCRIPT_MENU_QZ_H', '#define GUARD_CONSTANTS_SCRIPT_MENU_QZ_H',
            '#define MULTI_QZ_FIRST %d' % FIRST]
    lists, rows = [head[0]], [head[0]]
    # Kai's HOENN boat docks at SLATEPORT (docs/REGIONS_PLAN.md), Quetzal's at LILYCOVE
    for m in menus:
        m['items'] = [t.replace('LILYCOVE (HOENN)', 'SLATEPORT (HOENN)') for t in m['items']]
    for n, m in enumerate(menus):
        head.append('#define MULTI_QZ_0x%02X %d' % (m['id'], FIRST + n))
        lists.append('static const struct MenuAction sQzMulti_%02X[] = {\n%s};' % (
            m['id'], ''.join('    {(const u8 []) _("%s")},\n' % t.replace('"', '\\"') for t in m['items'])))
        rows.append('    [MULTI_QZ_0x%02X] = MULTICHOICE(sQzMulti_%02X),' % (m['id'], m['id']))
    head += ['#endif', '']
    open(os.path.join(REPO, 'include/constants/script_menu_qz.h'), 'w').write('\n'.join(head))
    open(os.path.join(REPO, 'src/data/script_menu_qz.h'), 'w').write('\n'.join(lists) + '\n')
    open(os.path.join(REPO, 'src/data/script_menu_qz_entries.h'), 'w').write('\n'.join(rows) + '\n')
    print('%d menus (%d-%d)' % (len(menus), FIRST, FIRST + len(menus) - 1))


if __name__ == '__main__':
    main()
