#!/usr/bin/env python3
"""Johto's and Kanto's town maps and Fly destinations into the game.

    python3 tools/quetzal_port/gen_regionmap.py

From quetzal_rip/region_map/ (tools/quetzal_rip/region_map.py):
- graphics: graphics/pokenav/region_map/{johto,kanto,sevii1,sevii2,sevii3}/map.png / map.bin / map.pal
  (Emerald's format: 8bpp tiles with pixel values 112+, a 64x64 one-byte tilemap; the 32-color palettes padded to 48)
- src/data/region_map/qz_region_maps.h:
  sQzMapLayouts[map][15][28]   the map section in each cell (Johto's ids as MAPSEC_JOHTO_*, Kanto's are Emerald's own)
  sQzMapPlaces[]               {mapsec, map, x, y, w, h}: each section's box on its map, measured from the grid
  sQzFlyDests[]                {mapsec, map, heal location, unlock flag}: Quetzal's Fly lists
Maps: 1 Johto, 2 Kanto, 3-5 the Sevii Islands (1-3, 4-5, 6-7), as region_map.c's QZMAP_*.
"""
import json
import os
import shutil

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
RIP = os.path.join(REPO, 'quetzal_rip', 'region_map')
MAPS = ['johto', 'kanto', 'kanto_sevii1', 'kanto_sevii2', 'kanto_sevii3']
DIRS = ['johto', 'kanto', 'sevii1', 'sevii2', 'sevii3']
SUBMAP = {'Kanto': 2, 'Sevii 1-3': 3, 'Sevii 4-5': 4, 'Sevii 6-7': 5}
NONE = 213


def main():
    secs = json.load(open(os.path.join(REPO, 'quetzal_rip/data/region_map_sections.json')))
    johto = {}   # Quetzal's raw Johto section byte -> MAPSEC_JOHTO_FIRST + n
    for n, s in enumerate(x for x in secs if x['region'] == 'johto'):
        johto[s['index']] = 0x100 + n
    layouts = json.load(open(os.path.join(RIP, 'layouts.json')))['layouts']
    out = ['// Generated by tools/quetzal_port/gen_regionmap.py: Johto\'s and Kanto\'s town maps and Fly destinations', '']
    grids = []
    for m, d in zip(MAPS, DIRS):
        dst = os.path.join(REPO, 'graphics/pokenav/region_map', d)
        os.makedirs(dst, exist_ok=True)
        shutil.copy(os.path.join(RIP, m, 'map.png'), dst)
        shutil.copy(os.path.join(RIP, m, 'map.bin'), dst)
        cols = [l.strip() for l in open(os.path.join(RIP, m, 'map.pal'))][3:]
        cols = (cols + ['0 0 0'] * 48)[:48]
        with open(os.path.join(dst, 'map.pal'), 'w', newline='\r\n') as f:
            f.write('JASC-PAL\n0100\n48\n' + ''.join(c + '\n' for c in cols))
        V = d.capitalize()
        out.append('static const u16 sQzMap%s_Pal[] = INCGFX_U16("graphics/pokenav/region_map/%s/map.pal", ".gbapal");' % (V, d))
        out.append('static const u32 sQzMap%s_GfxLZ[] = INCGFX_U32("graphics/pokenav/region_map/%s/map.png", ".8bpp.lz");' % (V, d))
        out.append('static const u32 sQzMap%s_TilemapLZ[] = INCGFX_U32("graphics/pokenav/region_map/%s/map.bin", ".lz");' % (V, d))
        rows = layouts[m]['rows']
        if m == 'johto':
            rows = [[johto.get(v, NONE) if v != NONE else NONE for v in r] for r in rows]
        grids.append(rows)
    out.append('')
    out.append('static const struct {const u16 *pal; const u32 *gfx; const u32 *tilemap;} sQzMapGfx[] = {')
    for d in DIRS:
        V = d.capitalize()
        out.append('    {sQzMap%s_Pal, sQzMap%s_GfxLZ, sQzMap%s_TilemapLZ},' % (V, V, V))
    out.append('};')
    out.append('')
    out.append('static const mapsec_u16_t sQzMapLayouts[%d][MAP_HEIGHT][MAP_WIDTH] = {' % len(grids))
    for g in grids:
        out.append('    {')
        for r in g:
            out.append('        {%s},' % ', '.join('0x%X' % v for v in r))
        out.append('    },')
    out.append('};')
    out.append('')
    places = []
    for i, g in enumerate(grids):
        boxes = {}
        for y, r in enumerate(g):
            for x, v in enumerate(r):
                if v == NONE:
                    continue
                b = boxes.setdefault(v, [x, y, x, y])
                b[0], b[1], b[2], b[3] = min(b[0], x), min(b[1], y), max(b[2], x), max(b[3], y)
        for v, b in sorted(boxes.items()):
            places.append((v, i + 1, b[0], b[1], b[2] - b[0] + 1, b[3] - b[1] + 1))
    out.append('static const struct QzMapPlace sQzMapPlaces[] = {')
    for p in places:
        out.append('    {0x%X, %d, %d, %d, %d, %d},' % p)
    out.append('};')
    out.append('')
    fly = json.load(open(os.path.join(RIP, 'fly_heal.json')))['fly_destinations']
    heal = {h['heal_location']: h['map'] for k in ('johto', 'kanto') for h in json.load(open(os.path.join(RIP, 'fly_heal.json')))['heal_locations'][k]}
    import re
    const = lambda n: re.sub(r'(?<=[a-z0-9])([A-Z])', r'_\1', n).upper()
    qz = dict(re.findall(r'#define (FLAG_QZ_\w+)\s+(\S+)', open(os.path.join(REPO, 'include/constants/qz_port.h')).read()))
    flag = lambda f: qz.get(f, f.replace('FLAG_QZ_', ''))   # the flag the scripts set (most keep Quetzal's number)
    out.append('static const struct QzFlyDest sQzFlyDests[] = {')
    for f in fly['johto']:
        out.append('    {0x%X, QZMAP_JOHTO, HEAL_LOCATION_%s, %s},' % (johto[f['mapsec']], const(heal[f['heal_location']]), flag(f['unlock_flag'])))
    for f in fly['kanto']:
        out.append('    {0x%X, %d, HEAL_LOCATION_%s, %s},' % (f['mapsec'], SUBMAP[f['submap']], const(heal[f['heal_location']]), flag(f['unlock_flag'])))
    out.append('};')
    out.append('')
    open(os.path.join(REPO, 'src/data/region_map/qz_region_maps.h'), 'w').write('\n'.join(out))
    print('%d maps, %d places, %d Fly destinations' % (len(grids), len(places), len(fly['johto']) + len(fly['kanto'])))


if __name__ == '__main__':
    main()
