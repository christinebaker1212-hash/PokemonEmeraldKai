#!/usr/bin/env python3
"""Johto / Kanto wild Pokémon (the Gen 4 cap of the rip) into src/data/wild_encounters.json.

    python3 tools/quetzal_port/gen_wild.py

Quetzal's tables are Kai's own format with two differences:
- ROCK SMASH has 3 slots (Kai 5): slots 0, 1, 2 fill Kai's 60 / 30 / 5 / 4 / 1 as 0, 1, 2, 2, 2.
- HEADBUTT (Johto's trees) is a slot of its own: written to src/data/wild_headbutt_qz.h for the HEADBUTT field move.
Re-running replaces the entries it wrote before (base labels gQuetzal_*).
"""
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))


def main():
    rip = json.load(open(os.path.join(REPO, 'quetzal_rip/gen4/data/wild_encounters.json')))['wild_encounter_groups'][0]
    path = os.path.join(REPO, 'src/data/wild_encounters.json')
    kai = json.load(open(path, encoding='utf-8'))
    main_group = next(g for g in kai['wild_encounter_groups'] if g.get('for_maps'))
    main_group['encounters'] = [e for e in main_group['encounters'] if not e['base_label'].startswith('gQuetzal_')]
    species = set(re.findall(r'#define (SPECIES_\w+)', open(os.path.join(REPO, 'include/constants/species.h')).read()))
    bad, headbutt, n = set(), [], 0
    for e in rip['encounters']:
        out = {'map': e['map'], 'base_label': e['base_label']}
        for k in ('land_mons', 'water_mons', 'fishing_mons'):
            if k in e:
                out[k] = e[k]
        if 'rock_smash_mons' in e:
            m = e['rock_smash_mons']['mons']
            out['rock_smash_mons'] = {'encounter_rate': e['rock_smash_mons']['encounter_rate'],
                                      'mons': [m[0], m[1], m[2], m[2], m[2]] if len(m) == 3 else m}
        if 'headbutt_mons' in e:
            headbutt.append((e['map'], e['headbutt_mons']))
        for k, v in out.items():
            if isinstance(v, dict):
                for mon in v['mons']:
                    if mon['species'] not in species:
                        bad.add(mon['species'])
        if len(out) > 2:
            main_group['encounters'].append(out)
            n += 1
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(kai, f, indent=2, ensure_ascii=False)
        f.write('\n')
    lines = ['// Generated by tools/quetzal_port/gen_wild.py: Johto\'s HEADBUTT trees (5 slots, 50 / 15 / 15 / 10 / 10)',
             'static const struct {u16 map; u8 rate; struct WildPokemon mons[5];} sHeadbuttEncounters[] = {']
    for m, h in headbutt:
        lines.append('    {%s, %d, {%s}},' % (m, h['encounter_rate'], ', '.join(
            '{%d, %d, %s}' % (x['min_level'], x['max_level'], x['species']) for x in h['mons'])))
    lines.append('};\n')
    open(os.path.join(REPO, 'src/data/wild_headbutt_qz.h'), 'w').write('\n'.join(lines))
    print('%d maps with wild Pokémon, %d with HEADBUTT trees' % (n, len(headbutt)))
    for b in sorted(bad):
        print('  not in Kai:', b)


if __name__ == '__main__':
    main()
