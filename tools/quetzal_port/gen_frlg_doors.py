#!/usr/bin/env python3
"""KANTO's door animations, FireRed's (pokefirered src/field_door.c sDoorAnimGraphicsTable): KANTO's tilesets are
FireRed's, so its door metatiles are FireRed's numbers (include/constants/metatile_labels.h). The pictures are in
graphics/door_anims/frlg (FireRed's own). Writes src/data/frlg_doors.h for src/mp/mp_frlgdoor.c.

    python3 -I tools/quetzal_port/gen_frlg_doors.py FRLG_DIR   (FRLG_DIR: src/field_door.c, metatile_labels.h)
"""
import os
import re
import sys


def main():
    frlg = sys.argv[1]
    door = open(os.path.join(frlg, 'field_door.c')).read()
    labels = dict(re.findall(r'#define (METATILE_\w+)\s+(0x[0-9A-Fa-f]+)', open(os.path.join(frlg, 'metatile_labels.h')).read()))
    tiles = dict(re.findall(r'static const u8 (sDoorAnimTiles_\w+)\[\] = INCBIN_U8\("graphics/door_anims/(\w+)\.4bpp"\);', door))
    pals = dict(re.findall(r'static const u8 (sDoorAnimPalettes_\w+)\[\] = \{([^}]*)\};', door))
    rows = re.findall(r'\{(METATILE_\w+),\s*DOOR_SOUND_(\w+),\s*DOOR_SIZE_(\w+),\s*(sDoorAnimTiles_\w+),\s*(sDoorAnimPalettes_\w+)\}', door)
    out = ['// Generated by tools/quetzal_port/gen_frlg_doors.py from pokefirered src/field_door.c. Do not edit.']
    used = sorted({t for _, _, _, t, _ in rows})
    for t in used:
        out.append('static const u8 %s[] = INCGFX_U8("graphics/door_anims/frlg/%s.png", ".4bpp");' % (t, tiles[t]))
    for p in sorted({p for _, _, _, _, p in rows}):
        out.append('static const u8 %s[] = {%s};' % (p, pals[p].strip()))
    out.append('static const struct FrlgDoorGraphics sFrlgDoors[] = {')
    for mt, snd, size, t, p in rows:
        out.append('    {%s, FRLG_DOOR_SOUND_%s, FRLG_DOOR_SIZE_%s, %s, %s},   // %s' % (labels[mt], snd, size, t, p, mt))
    out.append('    {0},')
    out.append('};')
    open('src/data/frlg_doors.h', 'w').write('\n'.join(out) + '\n')
    print('%d doors' % len(rows))


if __name__ == '__main__':
    main()
