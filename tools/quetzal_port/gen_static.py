#!/usr/bin/env python3
"""Johto / Kanto static encounters (legendaries and other Pokémon standing on the map) for src/qz_specials.c.

    python3 tools/quetzal_port/gen_static.py

From quetzal_rip/gen4/data/gifts.json (static_encounters, decoded from Quetzal's tables: Johto 32-byte entries with
species / level / item and three flags, Kanto 16-byte ones with species, four flags and the map). The flag the map's
object hides with is the entry's object flag (Johto's first, Kanto's third); the "done" flag (Johto's second,
Kanto's first) marks it caught or beaten. Kanto's table has no level: the scripts' own, else LEVELS below. Forms Kai doesn't have are the
species itself, shown from the form's generation on (gen; 0 = the species').
Writes src/data/qz_static_encounters.h.
"""
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
LEVELS = {'SPECIES_MEWTWO': 70, 'SPECIES_LUGIA': 70, 'SPECIES_HO_OH': 70, 'SPECIES_DEOXYS': 70, 'SPECIES_RAYQUAZA': 70,
          'SPECIES_GROUDON': 70, 'SPECIES_KYOGRE': 70}


def main():
    st = json.load(open(os.path.join(REPO, 'quetzal_rip/gen4/data/gifts.json')))['static_encounters']
    kai = set(re.findall(r'#define (SPECIES_\w+|ITEM_\w+)', open(os.path.join(REPO, 'include/constants/species.h')).read()
                         + open(os.path.join(REPO, 'include/constants/items.h')).read()))
    rows, skipped = [], 0
    for e in st:
        species, gen = e['species'], 0
        if species not in kai and re.sub(r'_\d+$', '', species) in kai:
            # a regional / other form Kai doesn't have (GALARIAN ARTICUNO, HOOPA UNBOUND, ZYGARDE 10%...): the
            # species itself, from the form's generation on
            species, gen = re.sub(r'_\d+$', '', species), (int(e['scrapped'].split()[1]) if e.get('scrapped', '').startswith('Gen ') else 8)   # (GALARIAN birds: Gen 8)
        if species not in kai:
            skipped += 1
            continue
        if e['region'] == 'johto':
            obj, done = e['flags'][0], e['flags'][1]
            level, item = e['level'], e.get('item', 'ITEM_NONE')
        else:
            obj, done = e['flags'][2], e['flags'][0]
            level, item = LEVELS.get(species, 50), 'ITEM_NONE'
        if item not in kai:
            item = 'ITEM_NONE'
        rows.append('    {%d, %d, %d, %s, %d, %s, 0x%X, 0x%X, %d},' % (1 if e['region'] == 'johto' else 2, e['group'], e['num'],
                    species, level, item, int(obj, 16), int(done, 16), gen))
    out = ['// Generated by tools/quetzal_port/gen_static.py: Johto / Kanto static encounters',
           'static const struct QzStatic {u8 region, group, num; u16 species; u8 level; u16 item; u16 objFlag, doneFlag; u8 gen;} sQzStatics[] = {']
    out += rows + ['};', '']
    open(os.path.join(REPO, 'src/data/qz_static_encounters.h'), 'w').write('\n'.join(out))
    print('%d static encounters (%d past the cap left out)' % (len(rows), skipped))


if __name__ == '__main__':
    main()
