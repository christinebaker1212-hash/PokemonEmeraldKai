#!/usr/bin/env python3
"""Johto's and Kanto's wild Pokémon and trainers as Moemon Quetzal has them (Gen 5-9), for the GENERATION setting.

    python3 tools/quetzal_port/gen_modern.py

The game holds the Gen 4 cap of the rip (gen_wild.py, gen_trainers.py; gen_gen2.py for Gen 1-2). From GENERATION 5
on, each wild slot and trainer's Pokémon is Quetzal's own where its species is of an allowed generation, else the
Gen 4 cap's in the same place (mp_region.c MP_Region_WildInfo / MP_Region_TrainerData):
- src/data/wild_qz_modern.h: for each wild table that differs, Quetzal's species slot by slot (sQzModernWild)
- src/data/trainer_parties_qz_modern.h: for each trainer whose team differs, Quetzal's team (species, level, item,
  moves) in one format (sQzModernParties)
Quetzal's regional forms (SPECIES_GEODUDE_2...) are their base species here; a species Kai doesn't have keeps the
Gen 4 cap's.
"""
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
RIP = os.path.join(REPO, 'quetzal_rip')
FIRST_ID = 864   # gen_trainers.py
AREAS = [('land_mons', 'LandMons'), ('water_mons', 'WaterMons'), ('rock_smash_mons', 'RockSmashMons'),
         ('fishing_mons', 'FishingMons')]


def consts(path, prefix):
    return set(re.findall(r'#define (%s\w+)' % prefix, open(os.path.join(REPO, path), encoding='utf-8').read()))


def main():
    species = consts('include/constants/species.h', 'SPECIES_')
    moves = consts('include/constants/moves.h', 'MOVE_')
    items = consts('include/constants/items.h', 'ITEM_')
    missing = set()

    def sp(c):
        c = re.sub(r'_\d+$', '', c)   # Quetzal's forms: their base species
        if c in species:
            return c
        missing.add(c)
        return None

    def mv(c):
        c = {'MOVE_HIGH_JUMP_KICK': 'MOVE_HI_JUMP_KICK'}.get(c, c)
        return c if c in moves else 'MOVE_NONE'

    # wild
    g4 = json.load(open(os.path.join(RIP, 'gen4/data/wild_encounters.json')))['wild_encounter_groups'][0]['encounters']
    mod = {e['base_label']: e for e in json.load(open(os.path.join(RIP, 'data/wild_encounters.json')))
           ['wild_encounter_groups'][0]['encounters']}
    out = ['// Generated by tools/quetzal_port/gen_modern.py: Johto / Kanto wild tables as Quetzal has them', '']
    pairs = []
    for e in g4:
        f = mod.get(e['base_label'], {})
        for k, suffix in AREAS:
            if k not in e or k not in f:
                continue
            a, b = e[k]['mons'], f[k]['mons']
            if k == 'rock_smash_mons' and len(b) == 3:
                b = [b[0], b[1], b[2], b[2], b[2]]   # gen_wild.py: Kai's 5 ROCK SMASH slots
            if k == 'rock_smash_mons' and len(a) == 3:
                a = [a[0], a[1], a[2], a[2], a[2]]
            if len(a) != len(b):
                continue
            new = [sp(m['species']) or x['species'] for m, x in zip(b, a)]
            if new == [x['species'] for x in a]:
                continue
            name = 'sQzM_%s_%s' % (e['base_label'], suffix)
            out.append('extern const struct WildPokemonInfo %s_%sInfo;' % (e['base_label'], suffix))
            out.append('static const u16 %s[] = {%s};' % (name, ', '.join(new)))
            pairs.append('    {&%s_%sInfo, %s, %d},' % (e['base_label'], suffix, name, len(new)))
    out += ['', 'static const struct {const struct WildPokemonInfo *gen4; const u16 *species; u8 count;} sQzModernWild[] = {']
    out += pairs + ['};', '']
    open(os.path.join(REPO, 'src/data/wild_qz_modern.h'), 'w').write('\n'.join(out))

    # trainers
    t4 = sorted(json.load(open(os.path.join(RIP, 'gen4/data/trainers.json')))['trainers'], key=lambda t: t['id'])
    tm = {t['id']: t for t in json.load(open(os.path.join(RIP, 'data/trainers.json')))['trainers']}
    mons, rows, n_tr = '', '', 0
    for n, t in enumerate(t4):
        u = tm.get(t['id'])
        if u is None or len(u['party']) != len(t['party']):
            continue
        party = []
        for m, x in zip(u['party'], t['party']):
            s = sp(m['species'])
            if s is None:
                s, m = x['species'], x
            item = m.get('held_item') or m.get('item') or 'ITEM_NONE'
            party.append((s, m['lvl'], item if item in items else 'ITEM_NONE',
                          [mv(y) for y in (m.get('moves') or [])] + ['MOVE_NONE'] * 4))
        if [p[0] for p in party] == [x['species'] for x in t['party']]:
            continue
        name = 'sQzM_Party_%d' % t['id']
        mons += 'static const struct QzModernMon %s[] = {\n%s};\n' % (name, ''.join(
            '    {%s, %d, %s, {%s}},\n' % (s, lvl, it, ', '.join(mvs[:4])) for s, lvl, it, mvs in party))
        rows += '    {%d, %s, %d},\n' % (FIRST_ID + n, name, len(party))
        n_tr += 1
    open(os.path.join(REPO, 'src/data/trainer_parties_qz_modern.h'), 'w').write(
        '// Generated by tools/quetzal_port/gen_modern.py: Johto / Kanto trainers\' teams as Quetzal has them\n'
        'struct QzModernMon {u16 species; u8 lvl; u16 heldItem; u16 moves[4];};\n' + mons +
        '\nstatic const struct {u16 trainerId; const struct QzModernMon *mons; u8 count;} sQzModernParties[] = {\n'
        + rows + '};\n')
    print('%d wild tables, %d trainers; species Kai lacks (Gen 4 cap kept): %d' % (len(pairs), n_tr, len(missing)))
    for m in sorted(missing)[:40]:
        print('  ', m)


if __name__ == '__main__':
    main()
