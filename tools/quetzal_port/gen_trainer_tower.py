#!/usr/bin/env python3
"""KANTO's TRAINER TOWER as FireRed's (audit case 10): FireRed's own floors (pokefirered src/trainer_tower_sets.c, the
four challenges of eight floors the game carries without an e-Reader card) as src/data/kanto_trainer_tower.h, read by
src/mp/mp_trainer_tower.c.

    python3 -I tools/quetzal_port/gen_trainer_tower.py

FireRed's trainer classes (its facility classes) become the game's through a KANTO trainer of the same class: its
trainer class, picture and encounter music, and the overworld sprite it stands as on its map (FireRed's own table names
the sprite and the gender; a pair's second sprite from the pair's second object).
"""
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fix_move_tutors import fetch   # noqa: E402
import gen_original_teams as orig   # noqa: E402

REPO = orig.REPO
OUT = os.path.join(REPO, 'src/data/kanto_trainer_tower.h')


def main():
    sets = fetch('src/trainer_tower_sets.c').replace('\r', '')
    engine = fetch('src/trainer_tower.c').replace('\r', '')
    fr, _ = orig.firered()
    names = orig.qz_names()
    kp = orig.kanto_pairs(names)          # QZ -> (map, FireRed trainer)
    by_fr = {ft: (qz, mp) for qz, (mp, ft) in kp.items()}
    trainers_h = fetch('src/data/trainers.h').replace('\r', '')
    fr_class = dict(re.findall(r'\[(TRAINER_\w+)\] = \{\s*\.trainerClass = (TRAINER_CLASS_\w+)', trainers_h))
    fr_pic = dict(re.findall(r'\[(TRAINER_\w+)\] = \{[^}]*?\.trainerPic = (TRAINER_PIC_\w+)', trainers_h))
    qz_src = orig.read(os.path.join(REPO, 'src/data/trainers_qz.h'))
    qz = {}
    for m in re.finditer(r'\[(TRAINER_QZ_\d+)\] =\s*\{(.*?)\n    \},', qz_src, re.S):
        b = m.group(2)
        qz[m.group(1)] = (re.search(r'trainerClass = (\w+)', b).group(1), re.search(r'trainerPic = (\w+)', b).group(1),
                          re.search(r'encounterMusic_gender = ([^,]+),', b).group(1))
    # the overworld sprites KANTO's trainers stand as
    gfx = {}
    for d in glob.glob(os.path.join(REPO, 'data/maps/Kanto_*/map.json')):
        mp = os.path.basename(os.path.dirname(d))
        lt = orig.labels_trainers(orig.read(os.path.join(os.path.dirname(d), 'scripts.inc')))
        for o in json.load(open(d))['object_events']:
            tr = [t for k, t in lt.get(o['script'], []) if 'rematch' not in k]
            if tr:
                gfx.setdefault(tr[0], []).append(o['graphics_id'])
    # FireRed's facility class -> its sprite / gender (trainer_tower.c's tables)
    singles = dict((c, (g, s)) for g, c, s in re.findall(r'\{(OBJ_EVENT_GFX_\w+),\s*(FACILITY_CLASS_\w+),\s*(MALE|FEMALE)\}', engine))
    doubles = {c: (g1, g2, s1, s2) for g1, g2, c, s1, s2 in
               re.findall(r'\{(OBJ_EVENT_GFX_\w+),\s*(OBJ_EVENT_GFX_\w+),\s*(FACILITY_CLASS_\w+),\s*(MALE|FEMALE),\s*(MALE|FEMALE)\}', engine)}
    used = []
    for c in re.findall(r'\.facilityClass = (FACILITY_CLASS_\w+)', sets):
        if c not in used:
            used.append(c)
    classes = []
    for c in used:
        nm = c[len('FACILITY_CLASS_'):]
        # (a trainer drawn as the class's picture first: the picture carries the gender, PSYCHIC_F, SWIMMER_M...)
        cands = [t for t, k in fr_pic.items() if k == 'TRAINER_PIC_' + nm.replace('PKMN_', 'POKEMON_') and t in by_fr] or \
            [t for t, k in fr_class.items() if k == 'TRAINER_CLASS_' + nm and t in by_fr] or \
            [t for t, k in fr_class.items() if k == 'TRAINER_CLASS_' + re.sub(r'_[MF]$', '', nm) and t in by_fr]
        if not cands:
            raise SystemExit('no KANTO trainer of class %s' % nm)
        q = by_fr[cands[0]][0]
        g = gfx.get(q, ['OBJ_EVENT_GFX_YOUNGSTER'])
        g2 = g[1] if len(g) > 1 else g[0]
        if c in doubles:
            gender, gender2 = doubles[c][2], doubles[c][3]
        else:
            gender = gender2 = singles.get(c, (None, 'MALE'))[1]
        cls, pic, music = qz[q]
        classes.append((c, cls, pic, music, g[0], g2, gender, gender2, cands[0]))
    out = ['// Generated by tools/quetzal_port/gen_trainer_tower.py from pret/pokefirered (src/trainer_tower_sets.c,',
           '// src/trainer_tower.c). Do not edit. KANTO\'s TRAINER TOWER floors (src/mp/mp_trainer_tower.c; audit case 10).',
           '']
    out.append('enum {%s, KTT_CLASS_COUNT};' % ', '.join('KTT_' + c[len('FACILITY_'):] for c in used))
    out.append('// FireRed\'s class: the game\'s trainer class, picture and music, the sprites and genders (a pair\'s second)')
    out.append('static const struct KttClass { u8 trainerClass; u16 trainerPic; u8 music; u16 objGfx, objGfx2; u8 gender, gender2; } sKttClasses[] = {')
    for c, cls, pic, music, g1, g2, s1, s2, frt in classes:
        out.append('    [KTT_%s] = {%s, %s, (%s) & 0x7F, %s, %s, %s, %s},   // as %s' % (c[len('FACILITY_'):], cls, pic, music, g1, g2, s1, s2, frt))
    out.append('};')
    out.append('')
    # FireRed's empty second / third trainer of a singles floor
    for m in re.finditer(r'^#define DUMMY_TOWER_\w+\(iv\).*$', sets, re.M):
        out.append(m.group(0))
    out.append('')
    body = sets[sets.index('static const struct TrainerTowerFloor'):sets.index('const struct EReaderTrainerTowerSetSubstruct gTrainerTowerLocalHeader')]
    body = body.replace('struct TrainerTowerFloor', 'struct KttFloor')
    body = re.sub(r'\.facilityClass = FACILITY_CLASS_(\w+)', r'.facilityClass = KTT_CLASS_\1', body)
    body = re.sub(r'\.checksum = \w+,?\n', '', body)
    body = re.sub(r'\b(SPECIES_\w+)', lambda m: orig.kai(m.group(1), 'SPECIES_NONE'), body)
    body = re.sub(r'\b(MOVE_\w+)', lambda m: orig.kai({'MOVE_HIGH_JUMP_KICK': 'MOVE_HI_JUMP_KICK'}.get(m.group(1), m.group(1)), 'MOVE_NONE'), body)
    body = re.sub(r'\b(ITEM_\w+)', lambda m: orig.kai(m.group(1), 'ITEM_NONE'), body)
    out.append(body.rstrip())
    out.append('')
    floors = sets[sets.index('gTrainerTowerFloors[NUM_TOWER_CHALLENGE_TYPES]'):]
    floors = floors[floors.index('{'):floors.index('\n};') + 3]
    out.append('static const struct KttFloor *const sKttFloors[NUM_TOWER_CHALLENGE_TYPES][MAX_TRAINER_TOWER_FLOORS] = ' + floors)
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('%d classes, %d floors' % (len(classes), body.count('static const struct KttFloor')))
    if orig.warn:
        print('unknown, dropped:', ' '.join(sorted(orig.warn)))


if __name__ == '__main__':
    main()
