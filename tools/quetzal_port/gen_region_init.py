#!/usr/bin/env python3
"""JOHTO's / KANTO's first-arrival setup (quetzal_rip/data/region_init.json from tools/quetzal_rip/region_init.py) as
src/data/qz_region_init.h, for mp_region.c MP_Region_Arrive.

    python3 tools/quetzal_port/gen_region_init.py
"""
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))


def main():
    d = json.load(open(os.path.join(REPO, 'quetzal_rip/data/region_init.json')))
    have = set(re.findall(r'#define (FLAG_QZ_0x\w+)', open(os.path.join(REPO, 'include/constants/qz_port.h')).read()))

    def flag(f):   # Quetzal's flags past 0x1000 keep their number; lower ones are renumbered by import.py
        name = 'FLAG_QZ_0x%X' % f
        return name if name in have else ('0x%X' % f if f >= 0x1000 else None)
    out = ['// Generated by tools/quetzal_port/gen_region_init.py: Quetzal\'s setup of a region on its first arrival',
           '// (hidden people and objects, story variables), then its guard flag; and a flag set on every arrival']
    for r in ('johto', 'kanto'):
        e = d[r]
        e['flags'] = [flag(f) for f in e['flags'] if flag(f)]   # (a low flag no script names is left out)
        out.append('static const u16 sQzInitFlags_%s[] = {%s};' % (r, ', '.join(e['flags'])))
        out.append('static const u16 sQzInitVars_%s[][2] = {%s};' % (r, ', '.join('{0x%X, %d}' % (v, n) for v, n in e['vars'])))
    out.append('static const struct {u16 guard, arrival; u8 nFlags, nVars; const u16 *flags; const u16 (*vars)[2];} '
               'sQzRegionInit[] = {')
    for r in ('johto', 'kanto'):
        e = d[r]
        out.append('    {0x%X, 0x%X, %d, %d, sQzInitFlags_%s, sQzInitVars_%s},' % (e['guard'], e['arrival'], len(e['flags']),
                   len(e['vars']), r, r))
    out += ['};', '']
    open(os.path.join(REPO, 'src/data/qz_region_init.h'), 'w').write('\n'.join(out))


if __name__ == '__main__':
    main()
