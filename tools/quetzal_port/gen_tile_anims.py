#!/usr/bin/env python3
"""KANTO's and JOHTO's primary tilesets animated as FireRed's General one (pokefirered src/tileset_anims.c
TilesetAnim_General: the sand by the water every 8 frames, the water and the land by it every 16, the flowers every 16;
frames in data/tilesets/primary/kanto_general/anim, FireRed's own). KANTO's General tileset is FireRed's; JOHTO's
(Quetzal's) keep most of its water tiles where FireRed has them: each animation is copied only over the runs of tiles
that are still FireRed's (a tile Quetzal redrew keeps its own picture).

    python3 -I tools/quetzal_port/gen_tile_anims.py      (writes src/data/tilesets/qz_anims.h)
"""
import glob
import os
from PIL import Image

ANIMS = [('Sand', 'sandwatersedge', 464, 18, 8), ('Water', 'water_current_landwatersedge', 416, 48, 8),
         ('Flower', 'flower', 508, 4, 5)]   # (name, folder, first tile, tiles, frames)
REF = 'data/tilesets/primary/kanto_general/tiles.png'


def tiles(path):
    im = Image.open(path)
    w = im.size[0] // 8
    return [im.crop(((n % w) * 8, (n // w) * 8, (n % w) * 8 + 8, (n // w) * 8 + 8)).tobytes()
            for n in range(im.size[0] * im.size[1] // 64)]


def main():
    ref = tiles(REF)
    out = ['// Generated by tools/quetzal_port/gen_tile_anims.py. Do not edit.',
           '// FireRed\'s General tileset animations for KANTO\'s and JOHTO\'s primary tilesets (src/tileset_anims.c)']
    for name, folder, first, count, frames in ANIMS:
        for f in range(frames):
            out.append('static const u16 sQzAnim_%s%d[] = INCGFX_U16("data/tilesets/primary/kanto_general/anim/%s/%d.png", '
                       '".4bpp");' % (name, f, folder, f))
        out.append('static const u16 *const sQzAnim_%s[] = {%s};' % (name, ', '.join('sQzAnim_%s%d' % (name, f) for f in range(frames))))
    sets = []
    for path in sorted(glob.glob('data/tilesets/primary/*/tiles.png')):
        folder = path.split('/')[-2]
        if not (folder.startswith('johto_primary') or folder == 'kanto_general' or folder == 'kanto_primary7'):
            continue
        t = tiles(path)
        runs = {}
        for name, _, first, count, _ in ANIMS:
            r, start = [], None
            for k in range(count + 1):
                ok = k < count and first + k < len(t) and t[first + k] == ref[first + k]
                if ok and start is None:
                    start = k
                elif not ok and start is not None:
                    r.append((first + start, k - start, start))
                    start = None
            runs[name] = r
        if not any(runs.values()):
            continue
        sym = 'gTileset_' + '_'.join(p.capitalize() for p in folder.split('_'))
        sym = sym.replace('Kanto_General', 'Kanto_General').replace('Johto_Primary', 'Johto_Primary')
        for name in runs:
            out.append('static const struct QzAnimRun sQzRuns_%s_%s[] = {%s{0, 0, 0}};' % (
                folder, name, ''.join('{%d, %d, %d}, ' % r for r in runs[name])))
        sets.append((sym, folder))
    out.append('static const struct QzAnimSet sQzAnimSets[] = {')
    for sym, folder in sets:
        out.append('    {&%s, sQzRuns_%s_Sand, sQzRuns_%s_Water, sQzRuns_%s_Flower},' % (sym, folder, folder, folder))
    out.append('};')
    open('src/data/tilesets/qz_anims.h', 'w').write('\n'.join(out) + '\n')
    print('%d tilesets animated' % len(sets))


if __name__ == '__main__':
    main()
