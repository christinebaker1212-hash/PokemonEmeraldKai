#!/usr/bin/env python3
"""Johto's and Kanto's people as card players: each of Quetzal's own people sprites (graphics ids 0x100+,
gen_objects.py) gets a look-alike among Kai's townsfolk, whom the three card games know by look (tcg_field.c
sPeople, ygo_field.c / tt_field.c sTownsfolk).

    python3 tools/quetzal_port/gen_cardlooks.py

A sprite trainers use looks like that trainer class's Kai sprite; other people sprites (16x32) take one of Kai's
everyday townsfolk by their id. Quetzal's Pokémon sprites play nothing. Writes src/data/qz_card_looks.h.
"""
import collections
import glob
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
BY_CLASS = {
    'COOLTRAINER': 'MAN_3', 'TEAM ROCKET': 'MAGMA_MEMBER_M', 'ROCKET ADMIN': 'MAGMA_MEMBER_F', 'SWIMMER♂': 'SWIMMER_M',
    'SWIMMER♀': 'SWIMMER_F', 'FISHERMAN': 'FISHERMAN', 'POKéMANIAC': 'MANIAC', 'BIRD KEEPER': 'MAN_4',
    'YOUNG COUPLE': 'WOMAN_2', 'EXPERT': 'EXPERT_M', 'HEX MANIAC': 'HEX_MANIAC', 'SUPER NERD': 'SCIENTIST_1',
    'PSYCHIC': 'PSYCHIC_M', 'FIREBREATHER': 'MAN_5', 'RIVAL': 'BOY_3', 'POKéFAN': 'POKEFAN_M', 'POLICEMAN': 'MAN_1',
    'BURGLAR': 'FAT_MAN', 'SAGE': 'OLD_MAN', 'COLLECTOR': 'MANIAC', 'JUGGLER': 'BARD', 'YOUNGSTER': 'YOUNGSTER',
    'BLACK BELT': 'BLACK_BELT', 'DRAGON TAMER': 'MAN_5', 'SAILOR': 'SAILOR', 'GENTLEMAN': 'GENTLEMAN',
    'PICNICKER': 'PICNICKER', 'HIKER': 'HIKER', 'CAMPER': 'CAMPER', 'BUG CATCHER': 'BUG_CATCHER', 'LASS': 'LASS',
    'BATTLE GIRL': 'WOMAN_5', 'AROMA LADY': 'WOMAN_4', 'BEAUTY': 'BEAUTY', 'TRIATHLETE': 'RUNNING_TRIATHLETE_M',
    'TWINS': 'TWIN', 'TUBER': 'TUBER_M', 'SIS AND BRO': 'GIRL_3', '{PKMN} TRAINER': 'BOY_3', 'KIMONO GIRL': 'BEAUTY',
    'SCIENTIST': 'SCIENTIST_1', 'GUITARIST': 'MAN_2', 'KINDLER': 'MAN_5', 'BIKER': 'MAN_2', 'CUE BALL': 'FAT_MAN',
}
EVERYDAY = ['BOY_1', 'GIRL_1', 'BOY_3', 'GIRL_2', 'MAN_1', 'MAN_3', 'WOMAN_2', 'WOMAN_4', 'OLD_MAN', 'GENTLEMAN',
            'LASS', 'YOUNGSTER', 'MAN_2', 'WOMAN_5', 'LITTLE_BOY', 'LITTLE_GIRL']


def main():
    tr = {t['const']: t['class_name'] for t in json.load(open(os.path.join(REPO, 'quetzal_rip/gen4/data/trainers.json')))['trainers']}
    objs = json.load(open(os.path.join(REPO, 'tools/quetzal_port/objects.json')))
    sprites = {s['const']: s for s in json.load(open(os.path.join(REPO, 'quetzal_rip/object_events/object_events.json')))}
    use = collections.defaultdict(collections.Counter)
    seen = set()
    for mj in sorted(glob.glob(os.path.join(REPO, 'data/maps/Johto_*/map.json')) + glob.glob(os.path.join(REPO, 'data/maps/Kanto_*/map.json'))):
        d = json.load(open(mj))
        sc = open(mj.replace('map.json', 'scripts.inc'), encoding='utf-8').read()
        for o in d['object_events']:
            g = o['graphics_id']
            if not objs.get(g, '').startswith('0x'):
                continue
            seen.add(g)
            if o['script'] in ('0x0', '0'):
                continue
            m = re.search(re.escape(o['script']) + r'::\n\ttrainerbattle\w* [^\n]*?(TRAINER_QZ_\w+)', sc)
            if m and m.group(1) in tr:
                use[g][tr[m.group(1)]] += 1
    rows = []
    for g in sorted(seen, key=lambda c: int(objs[c], 16)):
        s = sprites.get(g)
        if not s or (s['width'], s['height']) != (16, 32):
            continue
        cls = use[g].most_common(1)[0][0] if use[g] else None
        kai = BY_CLASS.get(cls) if cls else EVERYDAY[int(objs[g], 16) % len(EVERYDAY)]
        if kai:
            rows.append('    {%s, OBJ_EVENT_GFX_%s},   // %s' % (objs[g], kai, cls or 'townsfolk'))
    open(os.path.join(REPO, 'src/data/qz_card_looks.h'), 'w').write(
        '// Generated by tools/quetzal_port/gen_cardlooks.py: Quetzal\'s people sprites -> Kai\'s look-alike townsfolk\n'
        'static const struct {u16 qz, kai;} sQzCardLooks[] = {\n' + '\n'.join(rows) + '\n};\n')
    print('%d people sprites' % len(rows))


if __name__ == '__main__':
    main()
