#!/usr/bin/env python3
"""JOHTO's / KANTO's badge marts (`pokemart 0`) on Kai's items: src/data/qz_badge_marts.h from
quetzal_rip/data/badge_marts.json (tools/quetzal_rip/badge_marts.py). Items Kai doesn't have are left out; shop.c
MP_ShopItems drops the ones past the GENERATION.

    python3 tools/quetzal_port/gen_badge_marts.py
"""
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))


def main():
    lists = json.load(open(os.path.join(REPO, 'quetzal_rip/data/badge_marts.json')))['lists']
    kai = set(re.findall(r'#define (ITEM_\w+)', open(os.path.join(REPO, 'include/constants/items.h')).read()))
    out = ['// Generated by tools/quetzal_port/gen_badge_marts.py: what JOHTO / KANTO marts sell by badge count',
           '// (`pokemart 0`, shop.c CreatePokemartMenu)']
    dropped = set()
    for k, items in enumerate(lists):
        keep = [i for i in items if i in kai]
        dropped |= set(items) - set(keep)
        out.append('static const u16 sQzBadgeMart%d[] = {%s, ITEM_NONE};' % (k, ', '.join(keep)))
    out.append('static const u16 *const sQzBadgeMarts[] = {%s};' % ', '.join('sQzBadgeMart%d' % k for k in range(len(lists))))
    open(os.path.join(REPO, 'src/data/qz_badge_marts.h'), 'w').write('\n'.join(out) + '\n')
    print('%d lists; not in Kai: %s' % (len(lists), sorted(dropped)))


if __name__ == '__main__':
    main()
