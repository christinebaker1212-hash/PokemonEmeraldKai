#!/usr/bin/env python3
"""JOHTO's / KANTO's in-game trades (Quetzal's 17, capped to Gen 4: quetzal_rip/gen4/data/gifts.json in_game_trades)
as src/data/qz_ingame_trades.h; trade.c uses them in place of HOENN's own while the player is in JOHTO or KANTO.

    python3 tools/quetzal_port/gen_trades.py
"""
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))


def cstr(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def main():
    trades = json.load(open(os.path.join(REPO, 'quetzal_rip/gen4/data/gifts.json')))['in_game_trades']
    kai = set(re.findall(r'#define (SPECIES_\w+|ITEM_\w+)', open(os.path.join(REPO, 'include/constants/species.h')).read()
                         + open(os.path.join(REPO, 'include/constants/items.h')).read()))
    out = ['// Generated by tools/quetzal_port/gen_trades.py: JOHTO / KANTO\'s in-game trades (Quetzal\'s, Gen 4 cap)',
           'static const struct InGameTrade sQzIngameTrades[] =', '{']
    for t in sorted(trades, key=lambda t: t['index']):
        item = t['held_item'] if t['held_item'] in kai else 'ITEM_NONE'
        out.append('''    [%d] = {
        .nickname = _("%s"), .species = %s, .ivs = {%s}, .abilityNum = %d, .otId = %d,
        .conditions = {0, 0, 0, 0, 0}, .personality = 0x%X, .heldItem = %s, .mailNum = -1,
        .otName = _("%s"), .otGender = MALE, .sheen = 0, .requestedSpecies = %s,
    },''' % (t['index'], cstr(t['nickname'].upper())[:10], t['species'], ', '.join(str(v) for v in t['ivs']),
             t['ability_num'], t['ot_id'], t['personality'], item, cstr(t['ot_name'].upper())[:7], t['requested_species']))
    out += ['};', '']
    open(os.path.join(REPO, 'src/data/qz_ingame_trades.h'), 'w').write('\n'.join(out))
    print('%d trades' % len(trades))


if __name__ == '__main__':
    main()
