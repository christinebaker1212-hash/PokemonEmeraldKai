def cstr(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def crystal_ivs(atk_def, spe_spc):
    """Crystal's DVs (two bytes: ATK|DEF, SPE|SPC) as Gen 3 IVs (DV * 2 + 1; HP from the low bits, SPC for both)"""
    atk, dfn, spe, spc = atk_def >> 4, atk_def & 15, spe_spc >> 4, spe_spc & 15
    hp = (atk & 1) << 3 | (dfn & 1) << 2 | (spe & 1) << 1 | (spc & 1)
    return [v * 2 + 1 for v in (hp, atk, dfn, spe, spc, spc)]


