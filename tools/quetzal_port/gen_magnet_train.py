#!/usr/bin/env python3
"""The MAGNET TRAIN's ride as Crystal draws it (pokecrystal engine/events/magnet_train.asm): its train station tiles
(gfx/tilesets/train_station.png, the first 96), the scenery's rows (gfx/overworld/magnet_train_bg.tilemap: a pair
of tiles a row, repeated across) and the train (magnet_train_fg.tilemap, 20 x 4), coloured as SetMagnetTrainPals
does with Crystal's map palettes for the time of day (gfx/tilesets/bg_tiles.pal: GRAY, GREEN, YELLOW).

    python3 -I tools/quetzal_port/gen_magnet_train.py POKECRYSTAL_DIR     (writes src/data/qz_magnet_train.h)

The 2bpp shades become colours 1-4 of a 16-colour palette (nothing transparent), so the train's band covers the
scenery behind it. No ROM: the decomp's own pictures.
"""
import os
import sys
from PIL import Image

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
TILES = 96
PALS = ('gray', 'green', 'yellow')   # (bg_tiles.pal's rows 0, 2, 4)
ROWS = {'gray': 0, 'green': 2, 'yellow': 4}


def shades(path):
    im = Image.open(path).convert('L')
    w = im.size[0] // 8
    out = []
    for n in range(TILES):
        t = []
        for y in range(8):
            for x in range(8):
                v = im.getpixel(((n % w) * 8 + x, (n // w) * 8 + y))
                t.append(3 - round(v / 85))   # (white 0 ... black 3, as the GB's shades)
        out.append(t)
    return out


def palettes(path):
    """{time: {name: [4 BGR555]}} from bg_tiles.pal's morn / day / nite blocks"""
    out, cur = {}, None
    for line in open(path):
        line = line.strip()
        if line.startswith(';'):
            cur = line[1:].strip()
            out[cur] = []
        elif line.startswith('RGB') and cur:
            nums = [int(v) for v in line[3:].split(';')[0].replace(',', ' ').split()]
            out[cur].append([nums[i] | nums[i + 1] << 5 | nums[i + 2] << 10 for i in range(0, 12, 3)])
    return {t: {p: out[t][ROWS[p]] for p in PALS} for t in ('morn', 'day', 'nite')}


def main():
    crystal = sys.argv[1]
    tiles = shades(os.path.join(crystal, 'gfx/tilesets/train_station.png'))
    pals = palettes(os.path.join(crystal, 'gfx/tilesets/bg_tiles.pal'))
    bg = open(os.path.join(crystal, 'gfx/overworld/magnet_train_bg.tilemap'), 'rb').read()
    fg = open(os.path.join(crystal, 'gfx/overworld/magnet_train_fg.tilemap'), 'rb').read()
    out = ['// Generated by tools/quetzal_port/gen_magnet_train.py from pret/pokecrystal. Do not edit.',
           '// The MAGNET TRAIN\'s ride (src/mp/mp_magnettrain.c): Crystal\'s train station tiles, its scenery and train']
    words = []
    for t in tiles:
        b = bytearray()
        for i in range(0, 64, 2):
            b.append((t[i] + 1) | (t[i + 1] + 1) << 4)
        words += [b[i] | b[i + 1] << 8 for i in range(0, 32, 2)]
    out.append('static const u16 sMagnetTrainTiles[] = {%s};' % ', '.join('0x%04X' % w for w in words))
    out.append('static const u8 sMagnetTrainBgRows[18][2] = {%s};' % ', '.join(
        '{0x%02X, 0x%02X}' % (bg[2 * r], bg[2 * r + 1]) for r in range(18)))
    out.append('static const u8 sMagnetTrainFg[4][20] = {%s};' % ', '.join(
        '{%s}' % ', '.join('0x%02X' % fg[r * 20 + c] for c in range(20)) for r in range(4)))
    out.append('// morn, day, nite: GRAY, GREEN, YELLOW (colours 1-4)')
    out.append('static const u16 sMagnetTrainPals[3][3][16] = {%s};' % ', '.join(
        '{%s}' % ', '.join('{0, %s}' % ', '.join('0x%04X' % c for c in pals[t][p]) for p in PALS)
        for t in ('morn', 'day', 'nite')))
    open(os.path.join(REPO, 'src/data/qz_magnet_train.h'), 'w').write('\n'.join(out) + '\n')
    print('src/data/qz_magnet_train.h: %d tiles' % TILES)


if __name__ == '__main__':
    main()
