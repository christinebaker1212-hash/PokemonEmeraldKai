#!/usr/bin/env python3
"""Johto's / Kanto's Pokémon of later generations standing on maps, back for the GENERATION setting.

    python3 tools/quetzal_port/gen_later_objects.py

The Gen 4 cap of the rip (tools/quetzal_rip/gencap.py) hid every overworld Pokémon of Gen 5-9 with
FLAG_QZ_GEN_CAPPED. This puts Quetzal's own flag back on each of them in data/maps/*/map.json and writes
src/data/qz_later_objects.h: the map, local id and species of each, which the game hides while the GENERATION
doesn't allow the species (mp_region.c MP_Gen_ObjectHidden). Static encounters among them show and hide with
src/qz_specials.c RefreshStatics as before. Run it again after import.py (which brings the cap's flag back); it defines the flags import.py doesn't
(include/constants/qz_port.h).
"""
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
CAPPED = 'FLAG_QZ_GEN_CAPPED'


def main():
    changes = json.load(open(os.path.join(REPO, 'quetzal_rip/gen4/changes.json')))
    kai = set(re.findall(r'#define (SPECIES_\w+)', open(os.path.join(REPO, 'include/constants/species.h')).read()))
    rows, fixed, skipped, flags = [], 0, [], []
    for c in changes:
        if c['what'] != 'object' or c['why'] != 'hidden: later Pokémon':
            continue
        m = re.match(r'maps/(\w+)/map\.json object (\d+)', c['where'])
        name, local = m.group(1), int(m.group(2))
        species = c['from'] if c['from'] in kai else re.sub(r'_\d+$', '', c['from'])
        rip = json.load(open(os.path.join(REPO, 'quetzal_rip/maps', name, 'map.json')))
        path = os.path.join(REPO, 'data/maps', name, 'map.json')
        if not os.path.exists(path) or species not in kai:
            skipped.append((name, local, c['from']))
            continue
        ours = json.load(open(path))
        flag = rip['object_events'][local - 1]['flag']
        flags.append(flag)
        obj = ours['object_events'][local - 1]
        if obj['flag'] == CAPPED:
            obj['flag'] = flag
            fixed += 1
            with open(path, 'w') as f:
                json.dump(ours, f, indent=2, ensure_ascii=False)
                f.write('\n')
        rows.append('    {MAP_GROUP(%s), MAP_NUM(%s), %d, %s},' % (ours['id'], ours['id'], local, species))
    # their flags, kept at Quetzal's numbers (all past 0x1000, as import.py keeps them)
    hpath = os.path.join(REPO, 'include/constants/qz_port.h')
    h = open(hpath).read()
    have = set(re.findall(r'#define (FLAG_QZ_\w+)', h))
    need = sorted(set(f for f in flags if f not in have))
    if need:
        block = '\n// flags of the later generations\' POKéMON on maps (tools/quetzal_port/gen_later_objects.py)\n'
        block += ''.join('#define %-40s 0x%X\n' % (f, int(f.split('0x')[1], 16)) for f in need)
        i = h.rindex('#endif')
        open(hpath, 'w').write(h[:i] + block.lstrip('\n') + '\n' + h[i:])
    out = ['// Generated by tools/quetzal_port/gen_later_objects.py: Johto / Kanto overworld Pokémon of later generations,',
           '// hidden while the GENERATION doesn\'t allow them (mp_region.c MP_Gen_ObjectHidden)',
           'static const struct QzLaterObject {u8 group, num, localId; u16 species;} sQzLaterObjects[] = {']
    out += sorted(set(rows)) + ['};', '']
    open(os.path.join(REPO, 'src/data/qz_later_objects.h'), 'w').write('\n'.join(out))
    print('%d objects (%d flags put back), %d left hidden: %s' % (len(set(rows)), fixed, len(skipped), skipped))


if __name__ == '__main__':
    main()
