#!/usr/bin/env python3
"""Johto's and Kanto's wild Pokémon and trainers before Gen 4 is open (docs/REGIONS_PLAN.md "Gen 4").

    python3 tools/quetzal_rip/gencap.py --max-gen 3 --out quetzal_rip/gen3     (the rip capped to Gen 3; overlay not kept)
    python3 tools/quetzal_port/gen_gen3.py

The game uses the Gen 4 cap of the rip (gen_wild.py, gen_trainers.py). Until the player has beaten an Elite Four in
another region, Johto and Kanto show the Gen 3 cap instead, where it differs:
- src/data/wild_qz_gen3.h: for each wild table that differs, its Gen 3 version and the pair
  {Gen 4 table, Gen 3 table} (sQzGen3Wild); mp_region.c MP_Region_WildInfo swaps by pointer
- src/data/trainer_parties_qz_gen3.h: each trainer whose team differs, its Gen 3 team (sQzGen3Parties);
  mp_region.c MP_Region_TrainerData gives battles that team
"""
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
RIP = os.path.join(REPO, 'quetzal_rip')
FIRST_ID = 864   # gen_trainers.py
AREAS = [('land_mons', 'LandMons'), ('water_mons', 'WaterMons'), ('rock_smash_mons', 'RockSmashMons'),
         ('fishing_mons', 'FishingMons')]


def consts(path, prefix):
    return set(re.findall(r'#define (%s\w+)' % prefix, open(os.path.join(REPO, path), encoding='utf-8').read()))


def main():
    kai = consts('include/constants/species.h', 'SPECIES_') | consts('include/constants/moves.h', 'MOVE_') | \
        consts('include/constants/items.h', 'ITEM_')
    bad = set()

    def check(c):
        c = {'MOVE_HIGH_JUMP_KICK': 'MOVE_HI_JUMP_KICK'}.get(c, c)
        if c not in kai:
            bad.add(c)
        return c

    # wild
    g4 = json.load(open(os.path.join(RIP, 'gen4/data/wild_encounters.json')))['wild_encounter_groups'][0]['encounters']
    g3 = {e['base_label']: e for e in json.load(open(os.path.join(RIP, 'gen3/data/wild_encounters.json')))
          ['wild_encounter_groups'][0]['encounters']}
    out = ['// Generated by tools/quetzal_port/gen_gen3.py: Johto / Kanto wild tables before Gen 4 opens', '']
    pairs = []
    for e in g4:
        f = g3.get(e['base_label'], {})
        for k, suffix in AREAS:
            if k not in e or k not in f:
                continue
            a, b = e[k]['mons'], f[k]['mons']
            if [m['species'] for m in a] == [m['species'] for m in b]:
                continue
            if k == 'rock_smash_mons' and len(b) == 3:
                b = [b[0], b[1], b[2], b[2], b[2]]   # gen_wild.py: Kai's 5 ROCK SMASH slots
            name = 'sQz3_%s_%s' % (e['base_label'], suffix)
            out.append('extern const struct WildPokemonInfo %s_%sInfo;' % (e['base_label'], suffix))
            out.append('static const struct WildPokemon %s[] = {%s};' % (name, ', '.join(
                '{%d, %d, %s}' % (m['min_level'], m['max_level'], check(m['species'])) for m in b)))
            out.append('static const struct WildPokemonInfo %sInfo = {%d, %s};' % (name, f[k]['encounter_rate'], name))
            pairs.append('    {&%s_%sInfo, &%sInfo},' % (e['base_label'], suffix, name))
    out += ['', 'static const struct {const struct WildPokemonInfo *gen4, *gen3;} sQzGen3Wild[] = {'] + pairs + ['};', '']
    open(os.path.join(REPO, 'src/data/wild_qz_gen3.h'), 'w').write('\n'.join(out))

    # trainers
    t4 = sorted(json.load(open(os.path.join(RIP, 'gen4/data/trainers.json')))['trainers'], key=lambda t: t['id'])
    t3 = {t['id']: t for t in json.load(open(os.path.join(RIP, 'gen3/data/trainers.json')))['trainers']}
    parties, rows = '', ''
    n_tr = 0
    for n, t in enumerate(t4):
        u = t3.get(t['id'])
        if u is None or [m['species'] for m in t['party']] == [m['species'] for m in u['party']]:
            continue
        kind = u['party_type']
        held = kind in (2, 3, 4)
        moves = kind in (1, 3, 4)
        struct = {(False, False): 'NoItemDefaultMoves', (False, True): 'NoItemCustomMoves',
                  (True, False): 'ItemDefaultMoves', (True, True): 'ItemCustomMoves'}[(held, moves)]
        macro = {'NoItemDefaultMoves': 'NO_ITEM_DEFAULT_MOVES', 'NoItemCustomMoves': 'NO_ITEM_CUSTOM_MOVES',
                 'ItemDefaultMoves': 'ITEM_DEFAULT_MOVES', 'ItemCustomMoves': 'ITEM_CUSTOM_MOVES'}[struct]
        mons = ''
        for m in u['party']:
            iv = m.get('iv', 0)
            if kind == 4:
                iv = min(255, iv * 255 // 31) if iv <= 31 else iv
            line = '    {.iv = %d, .lvl = %d, .species = %s' % (iv, m['lvl'], check(m['species']))
            if held:
                line += ', .heldItem = %s' % check(m.get('held_item') or m.get('item') or 'ITEM_NONE')
            if moves:
                line += ', .moves = {%s}' % ', '.join(check(x) for x in (m.get('moves') or ['MOVE_NONE'] * 4))
            mons += line + '},\n'
        name = 'sParty_Qz3_%d' % t['id']
        parties += 'static const struct TrainerMon%s %s[] = {\n%s};\n' % (struct, name, mons)
        rows += '    {%d, %s(%s)},\n' % (FIRST_ID + n, macro, name)
        n_tr += 1
    open(os.path.join(REPO, 'src/data/trainer_parties_qz_gen3.h'), 'w').write(
        '// Generated by tools/quetzal_port/gen_gen3.py: Johto / Kanto trainers\' teams before Gen 4 opens\n' + parties +
        '\nstatic const struct {u16 trainerId; union TrainerMonPtr party; u8 partySize; u8 partyFlags;} sQzGen3Parties[] = {\n'
        + rows + '};\n')
    print('%d wild tables, %d trainers' % (len(pairs), n_tr))
    for b in sorted(bad):
        print('  not in Kai:', b)


if __name__ == '__main__':
    main()
