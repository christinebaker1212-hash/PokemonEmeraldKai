#!/usr/bin/env python3
"""SPROUT TOWER's swaying pillar, as Crystal animates it (pokecrystal data/tileset_anims.asm TilesetTowerAnim,
engine/tilesets/tileset_anims.asm AnimateTowerPillarTile: the pillar's stripes slide a pixel a step, five frames in
the cycle 0 1 2 3 4 3 2 1, one step every 16 frames). Quetzal redrew the pillar as a wooden column (the top layer of
JOHTO's primary metatiles 0x22E and 0x236, tiles 0x38C 0x38D 0x39C 0x39D 0x3AC 0x3AD 0x3BC 0x3BD, used nowhere else
in SPROUT TOWER): its planks slide the same way inside the column, its outline kept still.

    python3 -I tools/quetzal_port/gen_sprout_pillar.py      (writes src/data/tilesets/qz_sprout_pillar.h)
"""
import os
import struct
from PIL import Image

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
SECONDARY = 'data/tilesets/secondary/johto_sprout_tower1_f/tiles.png'
FIRST_SECONDARY = 640   # (FRLG-style tilesets: the secondary's tiles from 640)
ROWS = [(0x38C, 0x38D), (0x39C, 0x39D), (0x3AC, 0x3AD), (0x3BC, 0x3BD)]   # the column, two tiles wide, top down
FRAMES = 5


def main():
    im = Image.open(os.path.join(REPO, SECONDARY))
    w = im.size[0] // 8
    px = im.load()

    def tile(n):
        n -= FIRST_SECONDARY
        return [[px[(n % w) * 8 + x, (n // w) * 8 + y] for x in range(8)] for y in range(8)]

    out = ['// Generated by tools/quetzal_port/gen_sprout_pillar.py. Do not edit.',
           '// SPROUT TOWER\'s pillar (src/tileset_anims.c TilesetAnim_QzSproutPillar): its tiles and their five frames']
    tiles = [t for row in ROWS for t in row]
    out.append('static const u16 sQzSproutPillarTiles[] = {%s};' % ', '.join('0x%X' % t for t in tiles))
    for f in range(FRAMES):
        data = bytearray()
        for left, right in ROWS:
            a, b = tile(left), tile(right)
            rows = [a[y] + b[y] for y in range(8)]   # 16 pixels a row
            moved = []
            for r in rows:
                inner = r[1:15]
                k = f % len(inner)
                inner = inner[-k:] + inner[:-k] if k else inner
                moved.append([r[0]] + inner + [r[15]])
            for half in (0, 8):
                for y in range(8):
                    for x in range(0, 8, 2):
                        data.append(moved[y][half + x] | moved[y][half + x + 1] << 4)
        words = struct.unpack('<%dH' % (len(data) // 2), bytes(data))
        out.append('static const u16 sQzSproutPillar%d[] = {%s};' % (f, ', '.join('0x%04X' % v for v in words)))
    out.append('static const u16 *const sQzSproutPillarFrames[] = {%s};'
               % ', '.join('sQzSproutPillar%d' % f for f in range(FRAMES)))
    open(os.path.join(REPO, 'src/data/tilesets/qz_sprout_pillar.h'), 'w').write('\n'.join(out) + '\n')
    print('src/data/tilesets/qz_sprout_pillar.h: %d tiles, %d frames' % (len(tiles), FRAMES))


if __name__ == '__main__':
    main()
