#!/usr/bin/env python3
"""MEGA EVOLUTION's forms for battle: src/data/mp_megas.h and graphics/moemon/mega/<name>/ (src/battle_gimmick.c).

    python3 tools/moemon_gimmicks/gen_megas.py [--rom QUETZAL.gba] [--expansion EXPANSION_DIR]

A MEGA form isn't a species here: the battle gives the Pokémon the form's types, ability and stats and shows its
picture while it stays its own species (nothing in the save, the POKéDEX or the party changes).
Sources (cached in tools/moemon_gimmicks/megas.json, so a later run needs neither):
  - Moemon Quetzal's ROM: the MOéMON pictures and palettes of its 50 MEGA / primal forms (Quetzal species 899-948,
    quetzal_rip/data/names.json), in the order of tools/moemon_gen59/gen_items.py MEGA (their stones).
  - pokeemerald-expansion: each form's base stats, types and ability.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'tools', 'quetzal_rip'))
sys.path.insert(0, os.path.join(REPO, 'tools', 'moemon_gen59'))

Q_FRONT, Q_BACK, Q_PAL = 0x4FFD80, 0x4E6ED4, 0x4EB38C
Q_SHINY = 0x4EF84C - 8
GEN = '// Generated by tools/moemon_gimmicks/gen_megas.py. Do not edit.\n'


def forms():
    """[(quetzal id, base species const, expansion form const, stone item const)]"""
    from gen_items import MEGA
    qn = json.load(open(os.path.join(REPO, 'quetzal_rip', 'data', 'names.json'), encoding='utf-8'))['species']
    rows = [r for r in qn if 899 <= r[0] <= 948]
    out, stones = [], list(MEGA)
    for r in rows:
        base = re.sub(r'_\d+$', '', r[1])
        n = sum(1 for x in rows if re.sub(r'_\d+$', '', x[1]) == base)
        if base in ('SPECIES_KYOGRE', 'SPECIES_GROUDON'):
            exp = base + '_PRIMAL'
        elif n > 1:
            exp = base + ('_MEGA_X' if r[1].endswith('_2') else '_MEGA_Y')
        else:
            exp = base + '_MEGA'
        if base == 'SPECIES_RAYQUAZA':
            stone = 'ITEM_NONE'   # (DRAGON ASCENT instead of a stone)
        elif base == 'SPECIES_KYOGRE':
            stone = 'ITEM_BLUE_ORB'
        elif base == 'SPECIES_GROUDON':
            stone = 'ITEM_RED_ORB'
        else:
            stone = stones.pop(0)
        out.append((r[0], base, exp, stone))
    return out


def from_expansion(exp, fs):
    src = ''.join(open(os.path.join(exp, 'src/data/pokemon/species_info', f), encoding='utf-8').read()
                  for f in sorted(os.listdir(os.path.join(exp, 'src/data/pokemon/species_info'))) if f.endswith('.h'))
    data = {}
    for q, base, form, stone in fs:
        m = re.search(r'\[%s\] =\s*\{(.*?)\n    \},' % form, src, re.S)
        if not m:
            raise SystemExit('expansion has no %s' % form)
        b = m.group(1)
        b = re.sub(r'P_UPDATED_\w+ >= GEN_\d+ \? (\d+) : \d+', r'\1', b)   # (the newest numbers)
        st = [int(re.search(r'\.%s\s*=\s*(\d+)' % k, b).group(1)) for k in
              ('baseHP', 'baseAttack', 'baseDefense', 'baseSpeed', 'baseSpAttack', 'baseSpDefense')]
        t = re.search(r'\.types = MON_TYPES\((\w+)(?:,\s*(\w+))?\)', b)
        a = re.search(r'\.abilities = \{\s*(\w+)', b)
        data[form] = {'stats': st, 'types': [t.group(1), t.group(2) or t.group(1)], 'ability': a.group(1)}
    return data


def from_quetzal(rom, fs):
    from qrom import Rom
    from trainer_pics import decompress
    from PIL import Image
    r = Rom(rom)

    def pal(base, n):
        d = decompress(r.d, r.u32(base + 8 * n) - 0x8000000)
        return [((v & 31) * 255 // 31, ((v >> 5) & 31) * 255 // 31, ((v >> 10) & 31) * 255 // 31)
                for v in (d[i] | d[i + 1] << 8 for i in range(0, 32, 2))]

    def img(t, colors):
        im = Image.new('P', (64, 64))
        im.putpalette([c for rgb in colors for c in rgb] + [0] * (768 - 48))
        px = im.load()
        for ti in range(64):
            for y in range(8):
                for x in range(8):
                    b = t[ti * 32 + y * 4 + x // 2]
                    px[(ti % 8) * 8 + x, (ti // 8) * 8 + y] = (b >> 4) if x & 1 else b & 15
        return im

    def bottom(t):
        ys = [(ti // 8) * 8 + y for ti in range(64) for y in range(8) for x in range(8)
              if ((t[ti * 32 + y * 4 + x // 2] >> 4) if x & 1 else t[ti * 32 + y * 4 + x // 2] & 15)]
        return max(ys) if ys else 63

    def jasc(path, colors):
        with open(path, 'w', newline='\r\n') as fh:
            fh.write('JASC-PAL\n0100\n16\n' + ''.join('%d %d %d\n' % c for c in colors))

    out = {}
    for q, base, form, stone in fs:
        name = form[len('SPECIES_'):].lower()
        d = os.path.join(REPO, 'graphics', 'moemon', 'mega', name)
        os.makedirs(d, exist_ok=True)
        front = decompress(r.d, r.u32(Q_FRONT + 8 * q) - 0x8000000)[:2048]
        back = decompress(r.d, r.u32(Q_BACK + 8 * q) - 0x8000000)[:2048]
        img(front, pal(Q_PAL, q)).save(os.path.join(d, 'front.png'))
        img(back, pal(Q_PAL, q)).save(os.path.join(d, 'back.png'))
        jasc(os.path.join(d, 'normal.pal'), pal(Q_PAL, q))
        jasc(os.path.join(d, 'shiny.pal'), pal(Q_SHINY, q))
        out[form] = {'dir': 'graphics/moemon/mega/' + name, 'frontY': 63 - bottom(front), 'backY': 63 - bottom(back)}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rom')
    ap.add_argument('--expansion')
    a = ap.parse_args()
    cache_p = os.path.join(HERE, 'megas.json')
    cache = json.load(open(cache_p, encoding='utf-8')) if os.path.exists(cache_p) else {}
    fs = forms()
    if a.expansion:
        cache['data'] = from_expansion(a.expansion, fs)
    if a.rom:
        cache['art'] = from_quetzal(a.rom, fs)
    json.dump(cache, open(cache_p, 'w', encoding='utf-8'), indent=1)
    abil = set(re.findall(r'#define (ABILITY_\w+)', open(os.path.join(REPO, 'include/constants/abilities.h')).read()))
    lines, gfx = [GEN], []
    lines.append('// {base species, stone (NONE: RAYQUAZA knows DRAGON ASCENT), types, ability, ATK DEF SPEED SPATK SPDEF,'
                 ' picture y offsets, front, back, palette, shiny palette}\n')
    rows = []
    for q, base, form, stone in fs:
        d, art = cache['data'][form], cache['art'][form]
        sym = ''.join(w.capitalize() for w in form[len('SPECIES_'):].split('_'))
        for k, f, ext in (('Front', 'front.png', '.4bpp.lz'), ('Back', 'back.png', '.4bpp.lz'),
                          ('Pal', 'normal.pal', '.gbapal.lz'), ('Shiny', 'shiny.pal', '.gbapal.lz')):
            gfx.append('static const u32 sMega%s_%s[] = INCGFX_U32("%s/%s", "%s");\n' % (k, sym, art['dir'], f, ext))
        ab = d['ability'] if d['ability'] in abil else 'ABILITY_NONE'
        hp, at, df, sp, sa, sd = d['stats']
        rows.append('    {%s, %s, {%s, %s}, %s, {%d, %d, %d, %d, %d}, %d, %d, sMegaFront_%s, sMegaBack_%s, sMegaPal_%s, '
                    'sMegaShiny_%s},\n' % (base, stone, d['types'][0], d['types'][1], ab, at, df, sp, sa, sd,
                                           art['frontY'], art['backY'], sym, sym, sym, sym))
        if ab == 'ABILITY_NONE':
            print('  no ability %s for %s' % (d['ability'], form))
    lines += gfx
    lines.append('\nstatic const struct MegaForm sMegaForms[] =\n{\n' + ''.join(rows) + '};\n')
    open(os.path.join(REPO, 'src', 'data', 'mp_megas.h'), 'w', encoding='utf-8').write(''.join(lines))
    print('%d MEGA forms' % len(rows))


if __name__ == '__main__':
    main()
