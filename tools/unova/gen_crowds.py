#!/usr/bin/env python3
"""CASTELIA's crowds (ov055 field_gimmick_crowd.c, started by script command 0x134): archive 0xBA (a/1/8/6), a 0x32-byte
setup a zone (member n for the zone n of member 5's table): s16 frames between spawns by time of day x 6, u8 areas,
u8 looks, u16 object codes x 4, u8 chatter's first message and count (bank 0x9F), u8 frames a step, pad, then two
areas (u16 z min, z max, x min, x max, direction (0 up, 1 down, 2 left, 3 right), steps walked); member 6 the looks'
talk scripts (s32 object code, u16 script x 6). Writes src/unova/u3d_crowds.h (u3d_vm.c). Needs the ROM unpacked."""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import narc  # noqa: E402


def main():
    arc = narc.arc('a/1/8/6')
    zones = struct.unpack('<%di' % (len(arc[5]) // 4), arc[5])
    rows = []
    for i, z in enumerate(zones):
        if z == 0 or i >= 5:
            continue
        d = arc[i]
        iv = struct.unpack_from('<6h', d, 0)
        codes = struct.unpack_from('<4H', d, 14)
        areas = [struct.unpack_from('<6H', d, 26 + 12 * k) for k in range(2)]
        rows.append((z, iv, d[12], d[13], codes, d[22], d[23], d[24], areas))
    looks = [(struct.unpack_from('<i', arc[6], 16 * k)[0], struct.unpack_from('<6H', arc[6], 16 * k + 4))
             for k in range(len(arc[6]) // 16)]
    path = os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_crowds.h')
    with open(path, 'w') as f:
        f.write('// Generated by tools/unova/gen_crowds.py. Do not edit.\n')
        f.write("// CASTELIA's crowds (Black's archive 0xBA): a zone's spawn frames by time of day, areas, looks, chatter, "
                "step\n// frames and its two areas (z min, z max, x min, x max, direction, steps); the looks' talk scripts\n")
        f.write('static const struct { u16 zone; s16 interval[6]; u8 areas, looks; u16 code[4]; u8 chatFirst, chatCount, '
                'stepFrames; u16 area[2][6]; } sCrowds[%d] = {\n' % len(rows))
        for z, iv, ac, lc, codes, cf, cc, wf, areas in rows:
            f.write('    {%d, {%s}, %d, %d, {%s}, %d, %d, %d, {%s}},\n' % (
                z, ', '.join(map(str, iv)), ac, lc, ', '.join(map(str, codes)), cf, cc, wf,
                ', '.join('{%s}' % ', '.join(map(str, a)) for a in areas)))
        f.write('};\n')
        f.write('static const struct { u16 code, script[6]; } sCrowdLooks[%d] = {\n' % len(looks))
        for c, s in looks:
            f.write('    {%d, {%s}},\n' % (c, ', '.join(map(str, s))))
        f.write('};\n')
    print('%s: %d zones, %d looks' % (path, len(rows), len(looks)))


if __name__ == '__main__':
    main()
