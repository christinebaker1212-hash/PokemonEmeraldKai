#!/usr/bin/env python3
"""Small tables Black's script commands read (src/unova/u3d_tables.h, read by src/unova/u3d_vm.c):

- the POKeDEX ratings (ov021 gPokedexRatingTableKind1-3: u16 limit, u16 rating message; limit 0 ends a table),
  for SCRCMD_POKEMON_FLD_GetPokedexRating
- the key / value tables of the item buyers and prize counters (ov021 sScrcmdTableFileIds: archive 0xD0, a/2/0/8;
  u32 key, u32 value), for CheckTableItemInBag / LookupTableValue / RegisterTableValueNumber / AddTableValueToPoints
- ov010 sScrcmdLookupTable, for SCRCMD_PROC_LookupTableValue
- the move tutors' POKeMON: the personal data's tutor bits (archive a/0/1/6, u32 at 0x38: POKE_TOOL_CheckTutorCompat;
  0-2 GRASS / FIRE / WATER PLEDGE, 3-5 FRENZY PLANT / BLAST BURN / HYDRO CANNON, 6 DRACO METEOR), national numbers

    python3 -I tools/unova/gen_tables.py       (run from the repository; safe to run again)
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import narc  # noqa: E402
import scrcmd  # noqa: E402

RATINGS = (0x021D992C, 0x021D9904, 0x021D98DC)   # (kinds 1 national caught, 2 regional seen, 3 regional caught)
TABLE_IDS, TABLE_COUNT, TABLE_ARC = 0x021D99D0, 4, 'a/2/0/8'
LOOKUP, LOOKUP_COUNT = 0x02171170, 8


def main():
    ram, d = scrcmd.ov_image(21)
    out = ['// Generated by tools/unova/gen_tables.py. Do not edit.',
           "// Small tables of Black's script commands (src/unova/u3d_vm.c)"]
    out.append('// POKeDEX ratings: [kind - 1] rows of {limit, message}, a limit of 0 the last row')
    rows = []
    for a in RATINGS:
        r, i = [], 0
        while True:
            lim, val = struct.unpack_from('<HH', d, a - ram + 4 * i)
            r.append((lim, val))
            i += 1
            if lim == 0:
                break
        rows.append(r)
    n = max(len(r) for r in rows)
    out.append('static const u16 sDexRating[3][%d][2] = {' % n)
    for r in rows:
        out.append('    {%s},' % ', '.join('{%d, %d}' % e for e in r))
    out.append('};')
    arc = narc.arc(TABLE_ARC)
    ids = list(d[TABLE_IDS - ram:TABLE_IDS - ram + TABLE_COUNT])
    out.append("// key / value tables (Black's item numbers as keys): [table] = first, count in sKeyValues")
    kv, starts = [], []
    for i in ids:
        f = arc[i]
        pairs = [struct.unpack_from('<II', f, 8 * k) for k in range(len(f) // 8)]
        starts.append((len(kv), len(pairs)))
        kv += pairs
    out.append('static const u32 sKeyValues[][2] = {')
    for k in range(0, len(kv), 6):
        out.append('    %s,' % ', '.join('{%d, %d}' % e for e in kv[k:k + 6]))
    out.append('};')
    out.append('static const u16 sKeyValueTables[%d][2] = {%s};' % (len(starts), ', '.join('{%d, %d}' % s for s in starts)))
    ram0, d0 = scrcmd.ov_image(10)
    out.append('static const u16 sProcLookup[%d] = {%s};' % (
        LOOKUP_COUNT, ', '.join(str(v) for v in struct.unpack_from('<%dH' % LOOKUP_COUNT, d0, LOOKUP - ram0))))
    personal = narc.arc('a/0/1/6')
    tutors = [(n, struct.unpack_from('<I', personal[n], 0x38)[0] & 0x7F) for n in range(1, 650)]
    tutors = [t for t in tutors if t[1]]
    out.append("// the move tutors' POKeMON (national number, tutor bits), by number")
    out.append('static const u16 sTutorCompat[%d][2] = {' % len(tutors))
    for k in range(0, len(tutors), 8):
        out.append('    %s,' % ', '.join('{%d, 0x%02X}' % e for e in tutors[k:k + 8]))
    out.append('};')
    path = 'src/unova/u3d_tables.h'
    open(path, 'w').write('\n'.join(out) + '\n')
    print('%s: %d key / value pairs' % (path, len(kv)))


if __name__ == '__main__':
    main()
