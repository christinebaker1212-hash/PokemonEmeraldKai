def const(ident):
    return 'ITEM_' + re.sub(r'[^A-Z0-9]+', '_', ident.upper()).strip('_')


def camel(ident):
    return ''.join(p.capitalize() for p in ident.split('-'))


def load_csv(d, name):
    return list(csv.DictReader(open(os.path.join(d, name), encoding='utf-8')))


def flatten(t):
    t = t.replace('\xad', '').replace('\f', '\n')
    t = re.sub(r'-\n', '-', t)
    t = re.sub(r'\s*\n\s*', ' ', t)
    return re.sub(r'  +', ' ', t).strip()


def c_string(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def icon(sprites, ident):
    """24 x 24, 15 colours: graphics/items/icons/unova/IDENT.png and its palette"""
    path = os.path.join(sprites, 'sprites', 'items', ident + '.png')
    im = Image.open(path).convert('RGBA')
    box = im.getchannel('A').point(lambda a: 255 if a >= 128 else 0).getbbox()
    if box:
        im = im.crop(box)
    tmp = os.path.join(REPO, 'build', 'unova_item_icon.png')
    os.makedirs(os.path.dirname(tmp), exist_ok=True)
    im.save(tmp)
    px, w, h = icons.load(tmp)
    px, w = icons.narrow(px, w, h)
    if h > icons.SIZE:   # (too tall: the rows most like their neighbours go, as narrow() does the columns)
        cols = [[px[y][x] for y in range(h)] for x in range(w)]
        cols, h = icons.narrow(cols, h, w)
        px = [[cols[x][y] for x in range(w)] for y in range(h)]
    px = icons.reduce_colors(px, w, h)
    out, pal = icons.to_indexed(px, w, h)
    name = ident.replace('-', '_')
    d = os.path.join(REPO, 'graphics', 'items', 'icons', 'unova')
    os.makedirs(d, exist_ok=True)
    os.makedirs(os.path.join(REPO, 'graphics', 'items', 'icon_palettes', 'unova'), exist_ok=True)
    out.save(os.path.join(d, name + '.png'), transparency=0)
    icons.write_pal(os.path.join(REPO, 'graphics', 'items', 'icon_palettes', 'unova', name + '.pal'), pal)
    return 'graphics/items/icons/unova/%s.png' % name, 'graphics/items/icon_palettes/unova/%s.pal' % name


def item_data(c, kind, ident, name, price, desc):
    lines = ['    [%s] =' % c, '    {', '        .name = _("%s"),' % c_string(name), '        .itemId = %s,' % c,
             '        .price = %d,' % price]
    if kind == GEM:
        lines.append('        .holdEffectParam = TYPE_%s,' % GEM_TYPE[ident[:-4]])
    if kind == HEAL:
        lines.append('        .holdEffectParam = 20,')
    lines.append('        .description = %s,' % desc)
    if kind == KEY:
        lines += ['        .importance = 1,', '        .pocket = POCKET_KEY_ITEMS,', '        .type = ITEM_USE_BAG_MENU,',
                  '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,']
    elif kind == FOSSIL:
        lines += ['        .importance = 1,', '        .pocket = POCKET_KEY_ITEMS,', '        .type = ITEM_USE_BAG_MENU,',
                  '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,']
    elif kind in (WING, HEAL):
        lines += ['        .pocket = POCKET_ITEMS,', '        .type = ITEM_USE_PARTY_MENU,',
                  '        .fieldUseFunc = ItemUseOutOfBattle_Medicine,']
        if kind == HEAL:
            lines += ['        .battleUsage = ITEM_B_USE_MEDICINE,', '        .battleUseFunc = ItemUseInBattle_Medicine,']
    elif kind == ESCAPE:
        lines += ['        .pocket = POCKET_ITEMS,', '        .type = ITEM_USE_BAG_MENU,',
                  '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,', '        .battleUsage = ITEM_B_USE_OTHER,',
                  '        .battleUseFunc = ItemUseInBattle_Escape,']
    else:
        lines += ['        .pocket = POCKET_ITEMS,', '        .type = ITEM_USE_BAG_MENU,',
                  '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,']
    return '\n'.join(lines + ['    },', ''])


def replace_block(text, body, anchor):
    if H_BEGIN in text:
        a = text.index(H_BEGIN)
        b = text.index(H_END, a) + len(H_END)
        return text[:a] + H_BEGIN + '\n' + body + H_END + text[b:]
    a = text.index(anchor)
    return text[:a] + H_BEGIN + '\n' + body + H_END + '\n' + text[a:]


def main():
    csv_dir = sys.argv[1]
    sprites = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.expanduser('~'), '.cache', 'moemon',
                                                                 'pokeapi_sprites')
    rows = {r['identifier']: r for r in load_csv(csv_dir, 'items.csv')}
    names = {r['item_id']: r['name'] for r in load_csv(csv_dir, 'item_names.csv') if r['local_language_id'] == ENGLISH}
    texts = {}
    for r in load_csv(csv_dir, 'item_flavor_text.csv'):
        if r['language_id'] == ENGLISH and r['version_group_id'] == BW:
            texts[r['item_id']] = r['flavor_text']
    vocab = {'Reshiram', 'Zekrom'}   # (the names the texts write in the middle of a sentence: in capitals, as the game writes them)
    for ident, _, _ in ITEMS:
        gen_desc.names_in(flatten(texts.get(rows[ident]['id'], '')), vocab)
    consts, data, descs, gfx, ext, table, effects, etable = [], [], [], [], [], [], [], []
    for k, (ident, kind, short) in enumerate(ITEMS):
        row = rows[ident]
        c = const(ident)
        name = short or names[row['id']].upper().replace('POKé', 'POKé').replace('É', 'é')
        if len(name) > 13:
            raise SystemExit('%s: name "%s" longer than 13 letters' % (ident, name))
        consts.append('#define %-24s %d' % (c, FIRST_ID + k))
        desc_sym = 's%sDesc' % camel(ident)
        text = kai_text(gen_desc.game_style(flatten(texts.get(row['id'], '')), vocab))
        descs.append('static const u8 %s[] = _("%s");' % (desc_sym, c_string(text)))
        price = int(row['cost'] or 0) if kind not in (KEY, FOSSIL) else 0
        data.append(item_data(c, kind, ident, name, price, desc_sym))
        png, pal = icon(sprites, ident)
        pic, palsym = 'gItemIcon_Unova%s' % camel(ident), 'gItemIconPalette_Unova%s' % camel(ident)
        gfx.append('const u32 %s[] = INCGFX_U32("%s", ".4bpp.lz");' % (pic, png))
        gfx.append('const u32 %s[] = INCGFX_U32("%s", ".gbapal.lz");' % (palsym, pal))
        ext += ['extern const u32 %s[];' % pic, 'extern const u32 %s[];' % palsym]
        table.append('    [%s] = {%s, %s}, \\' % (c, pic, palsym))
        if kind == WING:
            idx, flag = WING_STAT[ident]
            effects.append('const u8 gItemEffect_Unova%s[7] = {\n    [%s] = %s,\n    [6] = 1,   // (one point: to 255, pokemon.c)\n};'
                           % (camel(ident), idx, flag))
            etable.append('    [%s - ITEM_POTION] = gItemEffect_Unova%s, \\' % (c, camel(ident)))
        elif kind == HEAL:
            effects.append('const u8 gItemEffect_Unova%s[7] = {\n    [4] = ITEM4_HEAL_HP,\n    [6] = 20,\n};' % camel(ident))
            etable.append('    [%s - ITEM_POTION] = gItemEffect_Unova%s, \\' % (c, camel(ident)))
    last = const(ITEMS[-1][0])
    gems = [const(i) for i, kd, _ in ITEMS if kd == GEM]
    wings = [const(i) for i, kd, _ in ITEMS if kd == WING]
    body = '\n'.join(consts) + '\n'
    body += '#define FIRST_UNOVA_ITEM %s\n#define LAST_UNOVA_ITEM %s\n' % (const(ITEMS[0][0]), last)
    body += '#define IS_UNOVA_GEM(item) ((item) >= %s && (item) <= %s)\n' % (gems[0], gems[-1])
    body += '#define IS_UNOVA_WING(item) ((item) >= %s && (item) <= %s)\n' % (wings[0], wings[-1])
    h = os.path.join(REPO, 'include', 'constants', 'items.h')
    text = open(h, encoding='utf-8').read()
    text = replace_block(text, body, '#define ITEMS_COUNT')
    text = re.sub(r'#define ITEMS_COUNT \([A-Z_]+ \+ 1\)', '#define ITEMS_COUNT (LAST_UNOVA_ITEM + 1)', text)
    open(h, 'w', encoding='utf-8').write(text)

    def write(rel, s):
        with open(os.path.join(REPO, rel), 'w', encoding='utf-8') as f:
            f.write(GEN + s)
    write('src/data/items_unova.h', '\n'.join(data))
    write('src/data/text/item_descriptions_unova.h', '\n'.join(descs) + '\n')
    write('src/data/graphics/items_unova.h', '\n'.join(gfx) + '\n')
    write('src/data/item_icons_unova.h', '\n'.join(ext) + '\n\n#define ITEM_ICONS_UNOVA \\\n' + '\n'.join(table) + '\n\n')
    write('src/data/pokemon/item_effects_unova.h', '\n\n'.join(effects) + '\n\n#define ITEM_EFFECTS_UNOVA \\\n'
          + '\n'.join(etable) + '\n\n')
    print('%d UNOVA items, %d-%d' % (len(ITEMS), FIRST_ID, FIRST_ID + len(ITEMS) - 1))


if __name__ == '__main__':
    main()
