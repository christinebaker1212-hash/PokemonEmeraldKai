#!/usr/bin/env python3
"""The gates' electric news boards (ov048 field_gimmick_gate.c, gimmick_obj_elboard.c) and the weather they report.

Boards: archive 0xAE (a/1/7/4), a 0x7C record each: zone, Black / White (0 both, 20 White, 21 Black), tile place
(x, y, z: units), facing, the message ids (date, news, nine daily, seven weekly), four default places, the TV's
animation, shown or not. News: archive 0xA6 (a/1/6/6), 0x24 each: version, event flag, cleared once shown, message,
kind (0 one, 2 a list), four zones (0x1AB any). ov048's tables: the weather labels by weather id (gElboardLabelMsgId),
the places a weather is looked for (gElboardPlaceTable / Kinds), the notice lanes, the TV animations by kind
(gGateBoardAnimeTable). Each zone's place name (bank 89) and weather (its header), and Black's weather calendar
(ov010 calender.c, archive 0x61 = a/0/9/7: member 1 the zones' offsets, member 0 a byte a day of the year, Feb 29
counted). Writes src/unova/u3d_elboard.h (u3d_elboard.c)."""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import narc  # noqa: E402
import zones as zn  # noqa: E402
import gimmicks  # noqa: E402


def main():
    boards = []
    for d in narc.arc('a/1/7/4'):
        v = struct.unpack_from('<6I23I2I', d)
        p = v[6:29]
        boards.append((v[0], v[1], v[2], v[3], v[4], v[5], p[0], p[2], p[3:12], p[12:19], p[19:23], v[29], v[30]))
    news = [struct.unpack_from('<9i', d) for d in narc.arc('a/1/6/6')]
    img = gimmicks.Image(48)
    labels = [img.u32(0x021F5124 + 4 * i) for i in range(15)]
    lanes = [img.u32(0x021F4E84 + 4 * i) for i in range(4)]
    tv = [img.u16(0x021F50D2 + 2 * i) for i in range(13)]   # (kinds 0-12: the records use them all)
    zs = zn.zones()
    cal = narc.arc('a/0/9/7')
    czones = [struct.unpack_from('<HH', cal[1], 2 + 4 * i) for i in range(68)]
    days = cal[0]
    path = os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_elboard.h')
    with open(path, 'w') as f:
        f.write('// Generated by tools/unova/gen_elboard.py. Do not edit.\n')
        f.write("// Black's gate news boards (archive 0xAE): zone, version (0 both, 20 White, 21 Black), x, y, z (units), "
                "facing (0 up,\n// 1 down, 2 left, 3 right), date / news messages, nine daily, seven weekly (Monday "
                "first), four default places,\n// the TV's animation kind, shown\n")
        f.write('static const struct ElBoard { u16 zone; u8 version; s16 x, y, z; u8 facing; u16 date, news, day[9], '
                'week[7], place[4];\n                              u8 tv, shown; } sElBoards[] = {\n')
        for b in boards:
            f.write('    {%d, %d, %d, %d, %d, %d, %d, %d, {%s}, {%s}, {%s}, %d, %d},\n' % (
                b[0], b[1], b[2], b[3], b[4], b[5], b[6], b[7], ', '.join(map(str, b[8])), ', '.join(map(str, b[9])),
                ', '.join(map(str, b[10])), b[11], b[12]))
        f.write('};\n')
        f.write("// the news (archive 0xA6): version, event flag, cleared once shown, message, kind (0 one, 2 a list), "
                "zones (0x1AB any)\n")
        f.write('static const struct ElNews { u8 version; u16 flag; u8 clears; u16 msg; u8 kind; u16 zone[4]; } '
                'sElNews[] = {\n')
        for n in news:
            f.write('    {%d, %d, %d, %d, %d, {%s}},\n' % (n[0], n[1], n[2], n[3], n[4], ', '.join(map(str, n[5:9]))))
        f.write('};\n')
        f.write('static const u16 sElWeatherLabel[%d] = {%s};   // (by weather id, bank 38)\n'
                % (len(labels), ', '.join(map(str, labels))))
        f.write('static const u8 sElNoticeLanes[4] = {%s};\n' % ', '.join(map(str, lanes)))
        f.write('static const u8 sElTvAnim[%d] = {%s};   // (the TV\'s animation by kind: the model\'s)\n'
                % (len(tv), ', '.join(map(str, tv))))
        f.write("// each zone's place name (bank 89) and its header's weather\n")
        f.write('static const u16 sZonePlace[%d] = {\n' % len(zs))
        for k in range(0, len(zs), 16):
            f.write('    %s,\n' % ', '.join(str(z['place']) for z in zs[k:k + 16]))
        f.write('};\n')
        f.write('static const u8 sZoneWeather[%d] = {\n' % len(zs))
        for k in range(0, len(zs), 32):
            f.write('    %s,\n' % ', '.join(str(z['weather']) for z in zs[k:k + 32]))
        f.write('};\n')
        f.write("// Black's weather calendar: the zones that have one, and a weather a day of the year (Jan 1 first, "
                "Feb 29 counted)\n")
        f.write('static const u16 sCalZones[%d] = {%s};\n' % (len(czones), ', '.join(str(z) for z, _ in czones)))
        f.write('static const u8 sCalDays[%d][366] = {\n' % len(czones))
        for z, off in czones:
            row = days[off:off + 366]
            f.write('    {%s},\n' % ','.join(str(b) for b in row))
        f.write('};\n')
    print('%s: %d boards, %d news, %d calendar zones' % (path, len(boards), len(news), len(czones)))


if __name__ == '__main__':
    main()
