#!/usr/bin/env python3
"""Black's scripted camera moves (PROC_FLD_StartCameraMoveFromArchive, script command 0x146: ov021
scrcmd_encount.c): archive 0xA3 (a/1/6/3), a 0x2C-byte record a member: u16 pitch, u16 yaw (65536ths of a turn), u32
distance, the target (3 fx32), then six u32 channels moved (shift, pitch, yaw, distance, fov, target).
Writes src/unova/u3d_cameras.h (u3d_vm.c). Needs the ROM unpacked (tools/unova/make_pack.sh)."""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import narc  # noqa: E402


def main():
    arc = narc.arc('a/1/6/3')
    rows = []
    for d in arc:
        if len(d) < 0x2C:
            rows.append((0, 0, 0, 0, 0, 0, 0))
            continue
        pitch, yaw, dist, x, y, z = struct.unpack_from('<HHI3i', d, 0)
        ch = struct.unpack_from('<6I', d, 0x14)
        mask = sum(1 << k for k in range(6) if ch[k])
        rows.append((pitch, yaw, dist, x, y, z, mask))
    path = os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_cameras.h')
    with open(path, 'w') as f:
        f.write('// Generated by tools/unova/gen_cameras.py. Do not edit.\n')
        f.write("// Black's scripted camera moves (archive 0xA3): pitch, yaw, distance, target x, y, z (fx32), the channels\n"
                "// moved (bit 0 shift, 1 pitch, 2 yaw, 3 distance, 4 fov, 5 target)\n")
        f.write('static const struct { u16 pitch, yaw; u32 dist; s32 x, y, z; u8 mask; } sCameraMoves[%d] = {\n' % len(rows))
        for r in rows:
            f.write('    {%d, %d, %d, %d, %d, %d, 0x%02X},\n' % r)
        f.write('};\n')
    print('%s: %d camera moves' % (path, len(rows)))


if __name__ == '__main__':
    main()
