#!/usr/bin/env python3
"""SKYARROW's and TUBELINE's traffic (ov053 field_gimmick_sound_objs.c, ov054 field_gimmick_sound_objs_b.c): each of
their models (the expansion units sSoundObjsUnitSetup / sSoundObjsBUnitSetup) follows an ICA path (u32 frames, u8 has
scale / rotation / translation, pad, then each frame's scale, rotation in degrees (x, y, z: rotated about x, then y)
and translation in units, as present) once, sits at its start for a random wait between its limits (a pair of u32 in
the archive) and goes again. SKYARROW: archive 0x94 (a/1/4/8), paths 3 / 5 / 8 / 10 / 11, waits 2 / 4 / 7 / 9 / 13
(sSoundObjsWaitMembers), its music's fade by the camera's height member 0 (u16 track mask, two floats: silent up to the
first, full past the second), the 3D sound sources 8 / 9 / 7 (tracks of the song) on models 0 / 2 / 4 with their
reach (members 1 / 6 / 12: units, volume); TUBELINE: archive 0x7F (a/1/2/7), paths 3 / 4, waits 5 / 6, sources 8 / 9
(members 1 / 2). Writes src/unova/u3d_soundobjs.h (u3d_vm.c): every second frame's place (units x 4) and turn (Black's
angle units), the VM taking the frames between halfway."""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import narc  # noqa: E402

SETS = [   # (zone, archive, [(path, wait, source track or -1, reach member or -1)])
    (249, 'a/1/4/8', [(3, 2, 8, 1), (5, 4, -1, -1), (8, 7, 9, 6), (10, 9, -1, -1), (11, 13, 7, 12)]),
    (254, 'a/1/2/7', [(3, 5, 8, 1), (4, 6, 9, 2)]),
]
STEP = 2


def ica(d):
    n = struct.unpack_from('<I', d)[0]
    hs, hr, ht = bool(d[4]), bool(d[5]), bool(d[6])
    k = 3 * (hs + hr + ht)
    out = []
    for f in range(n):
        v = struct.unpack_from('<%df' % k, d, 8 + 4 * k * f)
        i = 3 * hs
        r = v[i:i + 3] if hr else (0.0, 0.0, 0.0)
        i += 3 * hr
        t = v[i:i + 3] if ht else (0.0, 0.0, 0.0)
        out.append((t, r))
    return out


def ang(deg):
    return int(65535 * ((deg % 360.0) / 360.0)) & 0xFFFF


def main():
    pts, objs, zones = [], [], []
    for zone, arc, rows in SETS:
        m = narc.arc(arc)
        first = len(objs)
        for path, wait, src, reach in rows:
            p = ica(m[path])
            lo, hi = struct.unpack_from('<2i', m[wait])
            rr = struct.unpack_from('<2i', m[reach]) if reach >= 0 else (0, 0)
            objs.append((len(pts), len(p), lo, hi, src, rr[0], rr[1]))
            for f in range(0, len(p), STEP):
                (x, y, z), (rx, ry, _) = p[f]
                pts.append((round(x * 4), round(y * 4), round(z * 4), ang(rx), ang(ry)))
        fade = (0, 0.0, 0.0)
        if zone == 249:
            fade = struct.unpack_from('<H2x2f', m[0])
        zones.append((zone, first, len(objs) - first, fade))
    path = os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_soundobjs.h')
    with open(path, 'w') as f:
        f.write('// Generated by tools/unova/gen_soundobjs.py. Do not edit.\n')
        f.write("// SKYARROW's and TUBELINE's traffic: the zones (their models from the first object, the music's fade "
                "by the camera's\n// height: track mask, silent up to, full past)\n")
        f.write('static const struct { u16 zone; u8 first, n; u16 fadeTracks; float fadeLow, fadeHigh; } '
                'sSoundZones[] = {\n')
        for z, a, n, (tr, lo, hi) in zones:
            f.write('    {%d, %d, %d, 0x%X, %.1ff, %.1ff},\n' % (z, a, n, tr, lo, hi))
        f.write('};\n')
        f.write('// each object: its path (first point, frames: a point every %d), its wait (frames: shortest, longest), '
                'its sound\n// source (a track of the song, -1 none) and reach (units, volume)\n' % STEP)
        f.write('static const struct { u16 at, frames, waitMin, waitMax; s8 track; u16 reach, volume; } '
                'sSoundObjs[] = {\n')
        for o in objs:
            f.write('    {%d, %d, %d, %d, %d, %d, %d},\n' % o)
        f.write('};\n')
        f.write('#define SOUND_PATH_STEP %d\n' % STEP)
        f.write("// the paths' points: x, y, z (units x 4), the turn about x, then y (Black's angle units)\n")
        f.write('static const struct { s16 x, y, z; u16 rx, ry; } sSoundPath[%d] = {\n' % len(pts))
        for k in range(0, len(pts), 6):
            f.write('    %s,\n' % ', '.join('{%d, %d, %d, %d, %d}' % p for p in pts[k:k + 6]))
        f.write('};\n')
    print('%s: %d zones, %d objects, %d points' % (path, len(zones), len(objs), len(pts)))


if __name__ == '__main__':
    main()
