#!/usr/bin/env python3
"""The LEAGUE's descent to the CHAMPION (ov010 namein_setup.c NAMEIN_SETUP_RunFallEvent / RunLandEvent, script command
0x1BB; ov049 / ov050 the two rooms' models): the camera's move in the hub (d_02172528: pitch | yaw, distance, target x,
y, z: fx32), and the heights the centre platform and the player take a Black frame, sinking in the hub (archive 0x9D =
a/1/5/7 member 24, an ICA: its translation's y) and coming down into the CHAMPION's room (member 25). Writes
src/unova/u3d_league.h (u3d_vm.c League*)."""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import narc  # noqa: E402
import gimmicks  # noqa: E402


def ica_y(d):
    n = struct.unpack_from('<I', d)[0]
    hs, hr, ht = bool(d[4]), bool(d[5]), bool(d[6])
    k = 3 * (hs + hr + ht)
    return [struct.unpack_from('<f', d, 8 + 4 * (k * f + 3 * hs + 3 * hr + 1))[0] for f in range(n)]


def main():
    m = narc.arc('a/1/5/7')
    fall, land = ica_y(m[24]), ica_y(m[25])
    img = gimmicks.Image(10)
    cam = [img.u32(0x02172528 + 4 * i) for i in range(5)]
    cam = [cam[0] & 0xFFFF, cam[0] >> 16] + [struct.unpack('<i', struct.pack('<I', v))[0] for v in cam[1:]]
    path = os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_league.h')
    with open(path, 'w') as f:
        f.write('// Generated by tools/unova/gen_league.py. Do not edit.\n')
        f.write("// the hub's camera for the descent: pitch, yaw, distance, target x, y, z (fx32)\n")
        f.write('static const s32 sLeagueCam[6] = {%s};\n' % ', '.join(str(v) for v in cam))
        f.write("// the platform's and the player's height a Black frame: sinking in the hub, coming down in the "
                "CHAMPION's room\n")
        for name, ys in (('sLeagueFallY', fall), ('sLeagueLandY', land)):
            f.write('static const s16 %s[%d] = {\n' % (name, len(ys)))
            for k in range(0, len(ys), 16):
                f.write('    %s,\n' % ', '.join(str(round(y)) for y in ys[k:k + 16]))
            f.write('};\n')
    print('%s: %d + %d frames' % (path, len(fall), len(land)))


if __name__ == '__main__':
    main()
