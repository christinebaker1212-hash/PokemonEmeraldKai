#!/usr/bin/env python3
"""Black's 3D cut-ins (ov021 fld3d_ci.c, fld_wipe_3dobj.c SCRCMD_StartFld3dCi*): each sequence's record (archive
0x75: its two models' delays, the particle effect, the field darkened under it), the sounds at its frames (ov021
d_021DA720: Black's numbered sounds as the game's nearest), the key items' cut-ins (gFld3dCiKeyTable: item, sequence)
and the cut-in's camera (d_021DA6E8, up d_021DA6D0, its field of view from d_020A1EB8). The models and their
animations are the pack's gimmicks 1000 + the sequence (tools/unova/gimmicks.py ci_setup). Writes
src/unova/u3d_cutins.h, u3d_cutin_names.h (u3d.c U3D_Ci*) and u3d_cutin_keys.h (u3d_vm.c)."""
import math
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'sinnoh'))
import narc  # noqa: E402
import scrcmd  # noqa: E402
import gimmicks  # noqa: E402

# Black's sounds as the game's nearest (Black's are numbered only: by the moment they mark in the cut-in)
SE = {1930: 'SE_M_TELEPORT', 2010: 'SE_M_SWIFT', 1509: 'SE_M_REFLECT', 2011: 'SE_M_SWIFT', 1941: 'SE_M_HARDEN',
      1402: 'SE_SHINY', 1650: 'SE_M_SWAGGER', 2028: 'SE_M_TELEPORT', 2015: 'SE_M_REFLECT', 1927: 'SE_M_MORNING_SUN',
      1522: 'SE_M_TELEPORT', 1998: 'SE_M_SWIFT', 1895: 'SE_M_COSMIC_POWER', 2006: 'SE_M_TELEPORT', 1990: 'SE_M_GUST',
      1943: 'SE_M_HARDEN', 1976: 'SE_SHINY', 1423: 'SE_M_DOUBLE_TEAM', 1449: 'SE_M_REFLECT', 1975: 'SE_M_SWIFT'}


def fov_half():
    """the perspective camera's half height angle (d_020A1EB8[6], [7]: its sine and cosine, ARM9's)"""
    sys.path.insert(0, os.path.join(scrcmd.ALETHEIA, 'tools'))
    import blz
    d = blz.decompress(open(os.path.join(narc.EXTRACT, 'arm9.bin'), 'rb').read())
    sn, cs = struct.unpack_from('<2h', d, 0x020A1EB8 - 0x02004000 + 12)
    return math.degrees(math.atan2(sn, cs))


def main():
    img = gimmicks.Image(21)
    seqs = [gimmicks.ci_record(i) for i in range(gimmicks.CI_SEQS)]
    cues = []
    first = []
    for s in range(len(seqs)):
        p = img.u32(0x021DA720 + 4 * s)
        first.append(len(cues))
        for k in range(32):
            sid, fr = img.s32(p + 8 * k), img.u32(p + 8 * k + 4)
            if sid == -1:
                break
            cues.append((fr, SE[sid], sid))
    first.append(len(cues))
    keys = [(img.u16(0x021DAAE0 + 4 * i), img.u16(0x021DAAE2 + 4 * i)) for i in range(17)]
    eye, up = img.vec(0x021DA6E8), img.vec(0x021DA6D0)
    half = fov_half()
    path = os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_cutins.h')
    with open(path, 'w') as f:
        f.write('// Generated by tools/unova/gen_cutins.py. Do not edit.\n')
        f.write("// Black's 3D cut-ins (archive 0x75): models, particle effect (0 none), start delays, wait delays, the "
                "field darkened,\n// the first of its sounds in sCiCues (to the next one's)\n")
        f.write('static const struct CiSeq { u8 models, effect; u16 start[2], wait[2]; u8 dark; u16 cue; } '
                'sCiSeqs[%d] = {\n' % len(seqs))
        for i, r in enumerate(seqs):
            f.write('    {%d, %d, {%d, %d}, {%d, %d}, %d, %d},\n' % (
                len(r['models']), 0 if r['effect'] == 0xFFFF else 1, r['start'][0], r['start'][1], r['wait'][0],
                r['wait'][1], 1 if r['dark'] else 0, first[i]))
        f.write('};\n')
        f.write('static const u16 sCiCueEnd = %d;\n' % len(cues))
        f.write("// the sounds: Black's frame, the game's sound (Black's number)\n")
        f.write('static const struct CiCue { u16 frame, se; } sCiCues[%d] = {\n' % max(1, len(cues)))
        for fr, se, sid in cues:
            f.write('    {%d, %s},   // (%d)\n' % (fr, se, sid))
        if not cues:
            f.write('    {0, 0},\n')
        f.write('};\n')
        f.write("// the camera: its eye looking at the origin, up, the half height angle (degrees)\n")
        f.write('static const float sCiEye[3] = {%.4ff, %.4ff, %.4ff}, sCiUp[3] = {%.4ff, %.4ff, %.4ff};\n'
                % (eye + up))
        f.write('static const float sCiFovHalf = %.4ff;\n' % half)
    # the VS name cut-ins (ov073 enceff_name_cutin.c, ov074 g_Fld3dCiNameRows): Black's trainer classes with one (arm9
    # gTpokeDataTrainerKindTable: 7 bits the class; its index picks ov021 d_021DB7F6's encounter effect, kinds 10-30,
    # 32-34, 3, 4 the rows in order), each row's sequence, portrait (archive 0xB4), name (bank 0xB0) and layout (1: the
    # hero's portrait and name below), and the groups of model 0 each texture is drawn on
    sys.path.insert(0, os.path.join(scrcmd.ALETHEIA, 'tools'))
    import blz
    import nitro
    arm9 = blz.decompress(open(os.path.join(narc.EXTRACT, 'arm9.bin'), 'rb').read())
    kinds = struct.unpack_from('<28H', arm9, 0x0209FEE4 - 0x02004000)
    effects = [img.d[0x021DB7F6 - img.ram + i] for i in range(28)]
    rowof = {k: k - 10 for k in range(10, 31)}
    rowof.update({32: 21, 33: 22, 34: 23, 3: 24, 4: 25})
    classes = [(v & 0x7F, rowof[e]) for v, e in zip(kinds, effects) if e in rowof and v != 0]
    img74 = gimmicks.Image(74)
    rows = [struct.unpack_from('<5I', img74.d, 0x021F54F0 - img74.ram + 20 * i) for i in range(26)]
    res = narc.arc('a/1/1/5')
    texnames = ('trwb_face001', 'name_up', 'trwb_hero_ine', 'name_down')
    groups = {}
    for r in rows:
        q = r[0]
        if q in groups:
            continue
        model = nitro.Bmd0(res[seqs[q]['models'][0]]).models[0]
        drawn = sorted(model.draw().keys())
        groups[q] = [[gi for gi, mi in enumerate(drawn) if model.materials[mi].texture == t] for t in texnames]
    with open(os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_cutin_names.h'), 'w') as f:
        f.write("// Generated by tools/unova/gen_cutins.py. Do not edit.\n// Black's VS name cut-ins: a trainer class's row "
                "(ov073 / ov074)\n")
        f.write('static const u8 sCiClassRow[%d][2] = {%s};\n' % (len(classes), ', '.join('{%d, %d}' % c
                                                                                        for c in classes)))
        f.write("// a row: sequence, portrait (archive 0xB4), name (bank 0xB0), layout (1: the hero below)\n")
        f.write('static const struct CiNameRow { u8 seq, portrait; u16 msg; u8 layout; } sCiNameRows[%d] = {\n'
                % len(rows))
        for r in rows:
            f.write('    {%d, %d, %d, %d},\n' % (r[0], r[1], r[3], r[4]))
        f.write('};\n')
        f.write("// model 0's groups drawn with each texture: the portrait, the name, the hero's portrait, the hero's name "
                "(-1 none)\n")
        f.write('static const struct CiNameGroups { u8 seq; s8 g[4][2]; } sCiNameGroups[%d] = {\n' % len(groups))
        for q, gl in sorted(groups.items()):
            f.write('    {%d, {%s}},\n' % (q, ', '.join('{%d, %d}' % (tuple(g[:2]) + (-1, -1))[:2] for g in gl)))
        f.write('};\n')
    with open(os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_cutin_keys.h'), 'w') as f:
        f.write("// Generated by tools/unova/gen_cutins.py. Do not edit.\n// the key items' cut-ins "
                "(SCRCMD_StartFld3dCiByTable, gFld3dCiKeyTable): Black's item, sequence (u3d_vm.c sCiKeyItems)\n")
        f.write('%s\n' % ', '.join('{%d, %d}' % k for k in keys))
    print('%s: %d sequences, %d sounds, camera at %s, half angle %.2f' % (path, len(seqs), len(cues), eye, half))


if __name__ == '__main__':
    main()
