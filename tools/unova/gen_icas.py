#!/usr/bin/env python3
"""People flown along Black's paths (script commands 0x15B-0x15E, ov021 scrcmd_misc.c SCRCMD_MMDL_ICA_*): archive 0xCB
(a/2/0/3), an ICA each: u32 frames, u8 has scale / rotation / translation, pad, then each frame's scale, rotation
(degrees) and translation (units) as present; the path is the person's place from where the player stood, its
rotation's y (0, 90, 180, 270) their facing (down, right, up, left). Writes src/unova/u3d_icas.h (u3d_vm.c)."""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import narc  # noqa: E402


def main():
    paths, pts = [], []
    for d in narc.arc('a/2/0/3'):
        n = struct.unpack_from('<I', d, 0)[0]
        hs, hr, ht = bool(d[4]), bool(d[5]), bool(d[6])
        step = 12 * (hs + hr + ht)
        paths.append((len(pts), n))
        for f in range(n):
            o = 8 + f * step + 12 * hs
            ry = struct.unpack_from('<3f', d, o)[1] if hr else None
            t = struct.unpack_from('<3f', d, o + 12 * hr) if ht else (0.0, 0.0, 0.0)
            face = {0: 1, 90: 3, 180: 0, 270: 2}.get(round(ry) if ry is not None else -1, 255)
            pts.append((round(t[0] * 8), round(t[1] * 8), round(t[2] * 8), face))
    path = os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_icas.h')
    with open(path, 'w') as f:
        f.write('// Generated by tools/unova/gen_icas.py. Do not edit.\n')
        f.write("// Black's people's flight paths (archive 0xCB): first point, points; each point x, y, z (an eighth of a "
                "unit, from\n// the player's place) and the facing Black gives at it (0 up, 1 down, 2 left, 3 right, "
                "255 kept)\n")
        f.write('static const u16 sIcaPaths[%d][2] = {%s};\n' % (len(paths), ', '.join('{%d, %d}' % p for p in paths)))
        f.write('static const s16 sIcaPoints[][4] = {\n')
        for k in range(0, len(pts), 6):
            f.write('    %s,\n' % ', '.join('{%d, %d, %d, %d}' % p for p in pts[k:k + 6]))
        f.write('};\n')
    print('%s: %d paths, %d points' % (path, len(paths), len(pts)))


if __name__ == '__main__':
    main()
