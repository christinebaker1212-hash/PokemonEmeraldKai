#!/usr/bin/env python3
"""The ELITE FOUR rooms' entrance scenes (ov056 field_fk_demo.c, script command 0x1A2 with the room's slot 1-4):
archive 0x96 (a/1/5/0), for each slot six files from 6 * slot: the camera's own (unused), the set with its hero for
a female and her hero's texture frames (BTP), for a male and his, the set's joint animation; then the camera's paths
(files 24-27, ICAs: rotation in degrees about x then y, translation, looking down -z) and the sounds' cues (28-31: an
ICA whose nine channels, translation, scale, rotation, are 1 to play and 2 to stop a sound of gFkSoundAnimeSoundIds).
Everything is placed from gFkDemoOrigin; the player ends at gFkDemoEndTile facing gFkDemoEndDir; slots 3 and 4 also
play the room building's first slot (gFkDemoBuildModelPos). Writes src/unova/u3d_fkdemo.h (u3d_vm.c Fk*); the sets
themselves are pack gimmicks 171-174 (tools/unova/gimmicks.py)."""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import narc  # noqa: E402
import gimmicks  # noqa: E402

# Black's sounds as the game's nearest (by their length and colour: Black's are named by number only)
SE = {0x748: 'SE_WARP_IN', 0x749: 'SE_M_TELEPORT', 0x74A: 'SE_M_GUST', 0x73F: 'SE_M_STRENGTH', 0x740: 'SE_ELEVATOR',
      0x741: 'SE_M_GUST2', 0x757: 'SE_SWITCH', 0x758: 'SE_M_STRENGTH', 0x759: 'SE_M_REFLECT', 0x745: 'SE_M_TELEPORT',
      0x743: 'SE_DOOR'}


def main():
    m = narc.arc('a/1/5/0')
    img = gimmicks.Image(56)
    origin = img.vec(0x021F426C)
    cams, cues, ends = [], [], []
    for v in range(4):
        d = m[24 + v]
        n = struct.unpack_from('<I', d)[0]
        rows = []
        for f in range(n):
            s = struct.unpack_from('<9f', d, 8 + 36 * f)
            rows.append((round(s[6] * 4), round(s[7] * 4), round(s[8] * 4), round(s[3] * 100), round(s[4] * 100)))
        cams.append(rows)
        ids = [img.u16(0x021F43A4 + 18 * v + 2 * c) for c in range(9)]
        d = m[28 + v]
        for f in range(struct.unpack_from('<I', d)[0]):
            s = struct.unpack_from('<9f', d, 8 + 36 * f)
            ch = list(s[6:9]) + list(s[0:3]) + list(s[3:6])
            for c, val in enumerate(ch):
                if val in (1.0, 2.0) and ids[c] != 0xFFFF:
                    cues.append((v, f, SE[ids[c]], 1 if val == 2.0 else 0))
        t = img.vec(0x021F4308 + 12 * v)
        ends.append((round(t[0] * 4096), round(t[2] * 4096), img.u16(0x021F4264 + 2 * v), img.u32(0x021F4290 + 4 * v),
                     tuple(round(c) for c in img.vec(0x021F42D8 + 12 * v))))
    path = os.path.join(HERE, '..', '..', 'src', 'unova', 'u3d_fkdemo.h')
    with open(path, 'w') as f:
        f.write('// Generated by tools/unova/gen_fkdemo.py. Do not edit.\n')
        f.write('static const float sFkOrigin[3] = {%.1ff, %.1ff, %.1ff};\n' % origin)
        f.write("// each slot: the player's tile and facing after (Black's dir: 0 up, 1 down, 2 left, 3 right), the room "
                "building played\n// (x, z units), the camera's path (from sFkCam's frame, its frames)\n")
        at = 0
        f.write('static const struct { u8 x, z, dir, build; s16 bx, bz; u16 cam, frames; } sFkSlots[4] = {\n')
        for v in range(4):
            x, z, dr, b, bp = ends[v]
            f.write('    {%d, %d, %d, %d, %d, %d, %d, %d},\n' % (x, z, dr, b, bp[0], bp[2], at, len(cams[v])))
            at += len(cams[v])
        f.write('};\n')
        f.write("// the camera a Black frame: eye x, y, z (units x 4, from sFkOrigin), turned about x then y (0.01 "
                "degrees)\n")
        f.write('static const s16 sFkCam[%d][5] = {\n' % at)
        for rows in cams:
            for k in range(0, len(rows), 6):
                f.write('    %s,\n' % ', '.join('{%d, %d, %d, %d, %d}' % r for r in rows[k:k + 6]))
        f.write('};\n')
        f.write("// the sounds: slot, Black frame, sound, 1 to stop it\n")
        f.write('static const struct { u8 slot; u16 frame, se; u8 stop; } sFkCues[%d] = {\n' % len(cues))
        for c in cues:
            f.write('    {%d, %d, %s, %d},\n' % c)
        f.write('};\n')
    print('%s: %d camera frames, %d sound cues' % (path, at, len(cues)))


if __name__ == '__main__':
    main()
