def parse_moves():
    moves = {}
    for f in ('battle_moves.h', 'battle_moves_gen4.h', 'battle_moves_gen58.h'):
        text = (ROOT / 'src/data' / f).read_text()
        for m in re.finditer(r'\[MOVE_(\w+)\]\s*=\s*\{(.*?)\n\s*\},', text, re.S):
            body = m.group(2)
            get = lambda k: (re.search(r'\.%s\s*=\s*([^,\n]+)' % k, body) or [None, ''])[1].strip()
            moves[m.group(1)] = {'effect': get('effect'), 'power': int(get('power') or 0),
                                 'type': get('type').replace('TYPE_', ''), 'target': get('target'),
                                 'flags': get('flags')}
    ids = {}
    for line in (ROOT / 'include/constants/moves.h').read_text().splitlines():
        m = re.match(r'#define MOVE_(\w+)\s+(\d+)\b', line)
        if m and m.group(1) in moves:
            ids[m.group(1)] = int(m.group(2))
    flags = {}
    ff = (ROOT / 'src/data/move_flags_gen58.h').read_text()
    for m in re.finditer(r'\[MOVE_(\w+)(?:\s*-\s*\w+)?\]\s*=\s*([^,\n]+)', ff):
        flags[m.group(1)] = m.group(2)
    return moves, ids, flags


def audit():
    out = {}
    if AUDIT.exists():
        for line in AUDIT.read_text().splitlines():
            p = line.split()
            if len(p) >= 4 and p[0].isdigit():
                out[int(p[0])] = (int(p[1]), int(p[2]), int(p[3]))   # frames, first hit, last hit (-1: none)
    return out


def family_of(name, mv, gflags):
    for rx, fam in NAME_RULES:
        if re.search(rx, name):
            return fam, 'name'
    for flag, fam in GEN58_FLAG_FAMILY:
        if flag in gflags.get(name, ''):
            return fam, 'flag'
    if mv['power'] == 0:
        for rx, fam in EFFECT_RULES:
            if re.search(rx, mv['effect']):
                return fam, 'effect'
        if mv['target'] == 'MOVE_TARGET_USER':
            return 'BUFF', 'target'
        return 'STATUS', 'status'
    for rx, fam in EFFECT_RULES:
        if fam in ('DRAIN', 'BLAST', 'QUAKE', 'MULTI', 'CHARGE') and re.search(rx, mv['effect']):
            return fam, 'effect'
    if 'FLAG_MAKES_CONTACT' in mv['flags']:
        return 'RAM', 'contact'
    if mv['type'] in PHYSICAL and mv['type'] not in ('POISON', 'GHOST'):
        return ('FROMSKY' if mv['type'] == 'ROCK' else 'ORB'), 'type'
    return TYPE_FAMILY.get(mv['type'], 'ORB'), 'type'


def variant_of(name, fam, mv):
    if mv['target'] in ('MOVE_TARGET_BOTH', 'MOVE_TARGET_FOES_AND_ALLY') and fam not in ('QUAKE', 'FIELD'):
        return 'SPREAD'
    if mv['power'] >= 120:
        return 'BIG'
    if fam in ('SHADOW',) or mv['type'] in ('DARK', 'GHOST'):
        return 'DARK'
    if re.search(r'(TWIN|DOUBLE|DUAL|FUSION)', name):
        return 'TWIN'
    if re.search(r'(SPIN|WHEEL|ROLL|VORTEX|TWISTER|WHIRL|DRILL)', name):
        return 'SPIRAL'
    if re.search(r'(UPPERCUT|GEYSER|ERUPTION|SPOUT|RISING|ASCENT)', name):
        return 'RISING'
    return 'NONE'


