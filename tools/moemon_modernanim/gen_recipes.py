def main():
    moves, ids, gflags = parse_moves()
    timing = audit()
    rows = []
    why = {}
    for name, mid in sorted(ids.items(), key=lambda kv: kv[1]):
        mv = moves[name]
        fam, src = family_of(name, mv, gflags)
        why[name] = src
        var = variant_of(name, fam, mv)
        rgb = COLORS.get(name, TYPE_RGB.get(mv['type'], (255, 255, 255)))
        fr, first, last = timing.get(mid, (0, -1, -1))
        rows.append((mid, name, fam, var, rgb, fr, first, last, mv))
    if '--report' in sys.argv:
        byfam = {}
        for r in rows:
            byfam.setdefault(r[2], []).append(r[1])
        for f in FAMILIES:
            if f in byfam:
                print('%-8s %3d: %s' % (f, len(byfam[f]), ', '.join(byfam[f])))
        return
    lines = ['// Generated by tools/moemon_modernanim/gen_recipes.py. Do not edit.',
             '// MODERN battle animations: each move\'s family, variant, color, and its Classic animation\'s length and',
             '// first / last hit frames (the audit; 0 / -1 where unknown). Read by src/mp/mp_modernanim.c.',
             'enum {']
    lines += ['    MA_%s,' % f for f in FAMILIES] + ['    MA_FAMILY_COUNT', '};', 'enum {']
    lines += ['    MAV_%s,' % v for v in VARIANT_NAMES] + ['};', '',
              'static const struct MaRecipe { u8 family, variant, r, g, b; u16 frames; s16 firstHit, lastHit; } '
              'sMaRecipes[MOVES_COUNT] = {']
    for mid, name, fam, var, rgb, fr, first, last, mv in rows:
        lines.append('    [MOVE_%s] = {MA_%s, MAV_%s, %d, %d, %d, %d, %d, %d},' % (name, fam, var, rgb[0], rgb[1], rgb[2],
                                                                            fr, first, last))
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n')
    print('wrote %s: %d moves' % (OUT.relative_to(ROOT), len(rows)))


if __name__ == '__main__':
    main()
