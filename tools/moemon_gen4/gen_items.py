def kai_name(name):
    return name.upper().replace('’', "'").replace('É', 'é')


def parse_expansion(exp):
    src = open(os.path.join(exp, 'src', 'data', 'items.h'), encoding='utf-8').read()
    gfx = open(os.path.join(exp, 'src', 'data', 'graphics', 'items.h'), encoding='utf-8').read()
    paths = dict(re.findall(r'const u(?:16|32) (gItemIcon\w*)\[\] = INCGFX_U(?:16|32)\("([^"]+)"', gfx))
    out = {}
    for const, _ in ITEMS:
        m = re.search(r'\n    \[%s\] =\n    \{(.*?)\n    \},' % const, src, re.S)
        if not m:
            raise SystemExit('expansion has no %s' % const)
        body = m.group(1)
        body = re.sub(r'[ \t]*#if[^\n]*\n.*?#else[^\n]*\n(.*?)[ \t]*#endif[^\n]*\n', r'\1', body, flags=re.S)
        body = re.sub(r'[ \t]*#if[^\n]*\n(.*?)[ \t]*#endif[^\n]*\n', r'\1', body, flags=re.S)
        e = {}
        d = re.search(r'\.description = COMPOUND_STRING\((.*?)\),\n', body, re.S)
        e['description'] = ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', d.group(1))) if d else ''
        for f in ('holdEffect', 'holdEffectParam', 'iconPic', 'iconPalette', 'secondaryId'):
            v = re.search(r'\.%s = ([^,\n]+),' % f, body)
            if v:
                e[f] = v.group(1).strip()
        e['icon_png'] = paths.get(e.get('iconPic'))
        e['icon_pal'] = paths.get(e.get('iconPalette'))
        out[const] = e
    return out


def block(rel, start, end, body):
    p = os.path.join(REPO, rel)
    s = open(p, encoding='utf-8').read()
    a = s.index(start)
    b = s.index(end, a)
    s = s[:a] + start + '\n' + body + s[b:]
    open(p, 'w', encoding='utf-8').write(s)


def main():
    g4 = json.load(open(os.path.join(HERE, 'gen4_data.json'), encoding='utf-8'))
    pitems = {x['const']: x for x in g4['items'] if not x.get('missing')}
    cache_p = os.path.join(HERE, 'items_text.json')
    cache = json.load(open(cache_p, encoding='utf-8')) if os.path.exists(cache_p) else {}
    if len(sys.argv) > 1:
        exp = sys.argv[1]
        cache = parse_expansion(exp)
        for const, e in cache.items():
            for k, sub in (('icon_png', 'icons'), ('icon_pal', 'icon_palettes')):
                if e.get(k):
                    dst = os.path.join(REPO, e[k])
                    if not os.path.exists(dst):
                        shutil.copy(os.path.join(exp, e[k]), dst)
        json.dump(cache, open(cache_p, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)

    for const, t in TYPE_BOOST.items():
        cache[const]['holdEffect'] = 'HOLD_EFFECT_%s_POWER' % t
        cache[const]['holdEffectParam'] = '20'
        KAI_HOLD['HOLD_EFFECT_%s_POWER' % t] = 'HOLD_EFFECT_%s_POWER' % t
    holds = []
    for const, _ in ITEMS:
        h = cache[const].get('holdEffect', 'HOLD_EFFECT_NONE')
        if h not in KAI_HOLD and h not in holds:
            holds.append(h)
    block('include/constants/hold_effects.h', '// Moemon Kai: Gen 4 hold effects (tools/moemon_gen4/gen_items.py)',
          '// end of Gen 4 hold effects', ''.join('#define %-30s %d\n' % (h, FIRST_HOLD + i) for i, h in enumerate(holds)))
    ids = {const: FIRST_ID + i for i, (const, _) in enumerate(ITEMS)}
    body = ''.join('#define %s %d\n' % (c, i) for c, i in ids.items())
    body += '#define FIRST_GEN4_ITEM ITEM_X_SP_DEF\n#define LAST_GEN4_ITEM  %s\n' % ITEMS[-1][0]
    body += '#define FIRST_PLATE_ITEM ITEM_FLAME_PLATE\n#define LAST_PLATE_ITEM  ITEM_IRON_PLATE\n'
    body += '\n#define ITEMS_COUNT %d\n' % (FIRST_ID + len(ITEMS))
    block('include/constants/items.h', '// Moemon Kai: Gen 4 items (tools/moemon_gen4/gen_items.py)',
          '// end of Gen 4 items', body)

    data, descs, gfx, icons = [GEN], [GEN], [GEN], []
    for const, kind in ITEMS:
        p, e = pitems[const], cache[const]
        sym = ''.join(w.capitalize() for w in const[5:].split('_'))
        name = kai_name(p['name'])
        if len(name) > 13:
            raise SystemExit('%s: name too long' % name)
        hold = KAI_HOLD.get(e.get('holdEffect', 'HOLD_EFFECT_NONE'), e.get('holdEffect', 'HOLD_EFFECT_NONE'))
        param = {'X_ITEM_STAGES': '0', 'POWER_ITEM_BOOST': '8'}.get(e.get('holdEffectParam', '0'), e.get('holdEffectParam', '0'))
        lines = ['        .name = _("%s"),' % name, '        .itemId = %s,' % const, '        .price = %d,' % p['price']]
        if hold != 'HOLD_EFFECT_NONE':
            lines.append('        .holdEffect = %s,' % hold)
        if param not in ('0', None):
            lines.append('        .holdEffectParam = %s,' % param)
        lines.append('        .description = s%sDesc,' % sym)
        if e.get('secondaryId', '').startswith('STAT_'):       # Power items: the stat they raise
            lines.append('        .secondaryId = %s,' % e['secondaryId'])
        if kind == 'fossil':
            lines += ['        .importance = 1,', '        .pocket = POCKET_KEY_ITEMS,', '        .type = ITEM_USE_BAG_MENU,',
                      '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,']
        elif kind == 'stone':
            lines += ['        .pocket = POCKET_ITEMS,', '        .type = ITEM_USE_PARTY_MENU,',
                      '        .fieldUseFunc = ItemUseOutOfBattle_EvolutionStone,']
        elif kind == 'x':
            lines += ['        .pocket = POCKET_ITEMS,', '        .type = ITEM_USE_BAG_MENU,',
                      '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,', '        .battleUsage = ITEM_B_USE_OTHER,',
                      '        .battleUseFunc = ItemUseInBattle_StatIncrease,']
        else:
            lines += ['        .pocket = POCKET_ITEMS,', '        .type = ITEM_USE_BAG_MENU,',
                      '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,']
        data.append('    [%s] =\n    {\n%s\n    },\n\n' % (const, '\n'.join(lines)))
        d = e.get('description') or p['description']
        d = kai_text(d).split('\\n')
        descs.append('static const u8 s%sDesc[] = _(\n%s);\n\n' % (
            sym, '\n'.join('    "%s%s"' % (l, '\\n' if i < len(d) - 1 else '') for i, l in enumerate(d))))
        if e.get('icon_png'):
            gfx.append('const u32 gItemIcon_%s[] = INCGFX_U32("%s", ".4bpp.lz");\n' % (sym, e['icon_png']))
            gfx.append('const u32 gItemIconPalette_%s[] = INCGFX_U32("%s", ".gbapal.lz");\n' % (sym, e['icon_pal']))
            icons.append('    [%s] = {gItemIcon_%s, gItemIconPalette_%s},' % (const, sym, sym))
        else:
            icons.append('    [%s] = {gItemIcon_QuestionMark, gItemIconPalette_QuestionMark},' % const)
    open(os.path.join(REPO, 'src/data/items_gen4.h'), 'w', encoding='utf-8').write(''.join(data))
    open(os.path.join(REPO, 'src/data/text/item_descriptions_gen4.h'), 'w', encoding='utf-8').write(''.join(descs))
    open(os.path.join(REPO, 'src/data/graphics/items_gen4.h'), 'w', encoding='utf-8').write(''.join(gfx))
    ext = [l.replace('const u32 ', 'extern const u32 ').split(' = ')[0] + ';\n' for l in gfx[1:]]
    open(os.path.join(REPO, 'src/data/item_icons_gen4.h'), 'w', encoding='utf-8').write(
        GEN + ''.join(ext) + '#define ITEM_ICONS_GEN4 \\\n' + ' \\\n'.join(icons) + '\n')
    print('%d items (%d-%d), %d new hold effects' % (len(ITEMS), FIRST_ID, FIRST_ID + len(ITEMS) - 1, len(holds)))


if __name__ == '__main__':
    main()
