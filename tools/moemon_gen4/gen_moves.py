def write(rel, text):
    p = os.path.join(REPO, rel)
    old = open(p, encoding='utf-8').read() if os.path.exists(p) else None
    if old != text:
        open(p, 'w', encoding='utf-8').write(text)


def replace_block(rel, start, end, body):
    p = os.path.join(REPO, rel)
    s = open(p, encoding='utf-8').read()
    if start in s:
        a = s.index(start)
        b = s.index(end, a) + len(end)
        s = s[:a] + start + '\n' + body + end + s[b:]
    else:
        raise SystemExit('%s: no "%s" marker' % (rel, start))
    open(p, 'w', encoding='utf-8').write(s)


def c_string(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def expansion_moves(path):
    src = open(os.path.join(path, 'src', 'data', 'moves_info.h'), encoding='utf-8').read()
    out = {}
    for m in re.finditer(r'\n    \[(MOVE_\w+)\] =\n    \{(.*?)\n    \},', src, re.S):
        body = m.group(2)
        e = {}
        d = re.search(r'\.description = COMPOUND_STRING\((.*?)\),\n', body, re.S)
        if d:
            e['description'] = ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', d.group(1)))
        for f in ('contestEffect', 'contestCategory', 'contestComboStarterId'):
            v = re.search(r'\.%s = ([^,\n]+(?:\?[^,\n]+)?),' % f, body)
            if v:
                val = v.group(1).strip()
                if '?' in val:        # GEN_6 ? newer : older -> the older (Gen 4) one
                    val = val.split(':')[-1].strip()
                e[f] = val
        v = re.search(r'\.contestComboMoves = \{([^}]*)\}', body)
        if v:
            e['contestComboMoves'] = [x.strip() for x in v.group(1).split(',') if x.strip() and x.strip() != '0']
        out[m.group(1)] = e
    return out


def main():
    exp = sys.argv[1] if len(sys.argv) > 1 else None
    g4 = json.load(open(os.path.join(HERE, 'gen4_data.json'), encoding='utf-8'))
    moves = [m for m in g4['moves'] if m['id'] >= 355]
    cache_p = os.path.join(HERE, 'moves_text.json')
    cache = json.load(open(cache_p, encoding='utf-8')) if os.path.exists(cache_p) else {}
    if exp:
        em = expansion_moves(exp)
        for m in moves:
            e = em.get(m['const'], {})
            cache[m['const']] = e
        with open(cache_p, 'w', encoding='utf-8') as fh:
            json.dump(cache, fh, indent=1, ensure_ascii=False)
            fh.write('\n')
    contest_h = open(os.path.join(REPO, 'include', 'constants', 'contest.h')).read()
    contest_h = re.sub(r'// Moemon Kai: Gen 4 combo starters.*?// end of Gen 4 combo starters', '', contest_h, flags=re.S)
    kai_contest = set(re.findall(r'#define (CONTEST_\w+|COMBO_STARTER_\w+)', contest_h))
    new_starters = []
    for m in moves:
        s = cache.get(m['const'], {}).get('contestComboStarterId', '0')
        if s != '0' and s not in kai_contest and s not in new_starters:
            new_starters.append(s)

    # constants
    body = ''.join('#define %s %d\n' % (m['const'], m['id']) for m in moves)
    replace_block('include/constants/moves.h', '// Moemon Kai: Gen 4 moves (tools/moemon_gen4/gen_moves.py)',
                  '// end of Gen 4 moves', body + '\n#define MOVES_COUNT %d\n' % (moves[-1]['id'] + 1))
    new = list(dict.fromkeys(NEW_EFFECTS.values()))
    body = ''.join('#define %s %d\n' % (e, FIRST_NEW_EFFECT + i) for i, e in enumerate(new))
    replace_block('include/constants/battle_move_effects.h', '// Moemon Kai: Gen 4 effects (tools/moemon_gen4/gen_moves.py)',
                  '// end of Gen 4 effects', body + '#define NUM_BATTLE_MOVE_EFFECTS %d\n' % (FIRST_NEW_EFFECT + len(new)))
    if new_starters:
        last = max(int(v) for v in re.findall(r'#define COMBO_STARTER_\w+\s+(\d+)', contest_h))
        body = ''.join('#define %s %d\n' % (s, last + 1 + i) for i, s in enumerate(new_starters))
        replace_block('include/constants/contest.h', '// Moemon Kai: Gen 4 combo starters (tools/moemon_gen4/gen_moves.py)',
                      '// end of Gen 4 combo starters', body)

    # battle data
    out = [GEN]
    for m in moves:
        k = m['const'][5:]
        eff = EFFECTS.get(m['effect'][len('BATTLE_EFFECT_'):]) or NEW_EFFECTS[m['effect'][len('BATTLE_EFFECT_'):]]
        flags = [FLAGS[f[len('MOVE_FLAG_'):]] for f in m['flags'] if f[len('MOVE_FLAG_'):] in FLAGS]
        chance = CHANCES.get(k, m['effect_chance'])
        if eff == 'EFFECT_OVERHEAT':
            chance = 100
        out.append('    [%s] =\n    {\n        .effect = %s,\n        .power = %d,\n        .type = %s,\n'
                   '        .accuracy = %d,\n        .pp = %d,\n        .secondaryEffectChance = %d,\n'
                   '        .target = %s,\n        .priority = %d,\n        .flags = %s,\n    },\n' % (
                       m['const'], eff, m['power'], m['type'], m['accuracy'], m['pp'], chance,
                       TARGETS[m['range'][len('RANGE_'):]], m['priority'], ' | '.join(flags) or '0'))
    write('src/data/battle_moves_gen4.h', ''.join(out))

    # names: Platinum's, in Kai's capitals
    write('src/data/text/move_names_gen4.h', GEN + ''.join(
        '    [%s] = _("%s"),\n' % (m['const'], c_string(m['name'].upper())) for m in moves))

    # descriptions
    text, table = [GEN], []
    for m in moves:
        d = cache.get(m['const'], {}).get('description') or m['description']
        lines = d.replace('Pokémon', 'MOéMON').split('\\n')
        sym = 's%sDescription' % ''.join(w.capitalize() for w in m['const'][5:].split('_'))
        text.append('static const u8 %s[] = _(\n%s);\n\n' % (
            sym, '\n'.join('    "%s%s"' % (l, '\\n' if i < len(lines) - 1 else '') for i, l in enumerate(lines))))
        table.append('    [%s - 1] = %s,\n' % (m['const'], sym))
    write('src/data/text/move_descriptions_gen4.h', ''.join(text) + '#define MOVE_DESCRIPTIONS_GEN4 \\\n' +
          ' \\\n'.join(t.rstrip('\n') for t in table) + '\n')

    # contest
    out = [GEN]
    for m in moves:
        c = cache.get(m['const'], {})
        eff = c.get('contestEffect', 'CONTEST_EFFECT_HIGHLY_APPEALING')
        if eff not in kai_contest:
            eff = 'CONTEST_EFFECT_HIGHLY_APPEALING'
        cat = c.get('contestCategory', 'CONTEST_CATEGORY_COOL')
        combos = [x for x in c.get('contestComboMoves', []) if x in kai_contest or x in new_starters][:4]
        out.append('    [%s] =\n    {\n        .effect = %s,\n        .contestCategory = %s,\n'
                   '        .comboStarterId = %s,\n        .comboMoves = {%s},\n    },\n' % (
                       m['const'], eff, cat, c.get('contestComboStarterId', '0'), ', '.join(combos) or '0'))
    write('src/data/contest_moves_gen4.h', ''.join(out))

    # physical / special / status for every move (Gen 4's split; Platinum's classes)
    cls = {'CLASS_PHYSICAL': 'MOVE_CATEGORY_PHYSICAL', 'CLASS_SPECIAL': 'MOVE_CATEGORY_SPECIAL',
           'CLASS_STATUS': 'MOVE_CATEGORY_STATUS'}
    kai_moves = set(re.findall(r'#define (MOVE_\w+) \d+', open(os.path.join(REPO, 'include', 'constants', 'moves.h')).read()))
    alias = {'MOVE_DOUBLE_SLAP': 'MOVE_DOUBLESLAP'}
    out = [GEN, 'const u8 gMoveCategories[MOVES_COUNT] =\n{\n']
    for m in g4['moves']:
        c = KAI_NAMES.get(m['const'], m['const'])
        if c not in kai_moves:
            c = '%d' % m['id']
            out.append('    [%s] = %s,  // %s\n' % (c, cls[m['class']], m['name']))
        else:
            out.append('    [%s] = %s,\n' % (c, cls[m['class']]))
    out.append('};\n')
    write('src/data/move_categories.h', ''.join(out))

    # animations and effect scripts (pointer tables; the scripts themselves are hand-written files)
    write('data/battle_anim_ptrs_gen4.inc', '@ ' + GEN[3:] + ''.join('\tptrvalue Move_%s\n' % m['const'][5:] for m in moves))
    write('data/battle_effect_ptrs_gen4.inc', '@ ' + GEN[3:] + ''.join(
        '\tptrvalue BattleScript_%s\n' % ''.join(w.capitalize() for w in e.split('_')) for e in new))
    anim_p = os.path.join(REPO, 'data', 'battle_anim_scripts_gen4.inc')
    have = open(anim_p).read() if os.path.exists(anim_p) else '@ Gen 4 move animations (Move_<MOVE>). A move still borrowing a Gen 3 animation\n@ just jumps to it; tools/moemon_gen4/gen_moves.py adds a borrowing stub for any move missing here.\n'
    for m in moves:
        k = m['const'][5:]
        if not re.search(r'^Move_%s:' % k, have, re.M):
            have += '\nMove_%s:\n\tgoto Move_%s\n' % (k, ANIMS[k])
    write('data/battle_anim_scripts_gen4.inc', have)
    eff_p = os.path.join(REPO, 'data', 'battle_scripts_gen4.inc')
    have = open(eff_p).read() if os.path.exists(eff_p) else '@ Battle scripts of the Gen 4 move effects (BattleScript_Effect<Name>). Until an effect\n@ is written, its stub plays the move as a plain hit (damaging) or fails (status).\n'
    status = {NEW_EFFECTS[m['effect'][len('BATTLE_EFFECT_'):]] for m in moves
              if m['class'] == 'CLASS_STATUS' and m['effect'][len('BATTLE_EFFECT_'):] in NEW_EFFECTS}
    for e in new:
        lab = 'BattleScript_%s' % ''.join(w.capitalize() for w in e.split('_'))
        if not re.search(r'^%s::' % lab, have, re.M):
            have += '\n%s::\n\tgoto %s\n' % (lab, 'BattleScript_EffectSplash' if e in status else 'BattleScript_EffectHit')
    write('data/battle_scripts_gen4.inc', have)
