#!/usr/bin/env python3
"""The 107 Gen 4 Pokémon (national 387-493) for Kai: species 412-518 (the EGG moves to 519, Unown's letters follow).

    python3 tools/moemon_gen4/gen_species.py [--rom QUETZAL.gba] [--expansion EXPANSION_DIR]

Sources (each step caches what it takes, so a later run needs neither the ROM nor expansion):
  - tools/moemon_gen4/gen4_data.json (pokeplatinum): stats, types, abilities, items, breeding, learnsets,
    evolutions, POKéDEX category and text. Gen 4's own numbers.
  - Moemon Quetzal's ROM: the MOéMON battle pictures (front, back, normal / shiny palettes) ->
    graphics/moemon/gen4/<name>/. Quetzal has one front frame; the second frame repeats it like Kai's static
    MOéMON animation.
  - pokeemerald-expansion: the original POKéMON pictures, icons, footprints (graphics/pokemon/<name>/), cries
    (sound/direct_sound_samples/cries/<name>.wav) and the layout numbers that go with them (coordinates,
    elevation, front animation, dex scales, height / weight) -> species_gfx.json.
Generated files hold everything; the stock tables include them through "Moemon Kai: Gen 4" hooks.
"""
import argparse
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(REPO, 'tools', 'quetzal_rip'))
from kaitext import kai_text

GEN = '// Generated by tools/moemon_gen4/gen_species.py. Do not edit.\n'
FIRST_ID = 412          # SPECIES_TURTWIG
NAT_FIRST = 387
CRY_FIRST = 388         # gCryTable index of the first Gen 4 cry (Chimecho is 387)

# Quetzal ROM tables (file offsets)
Q_FRONT, Q_BACK, Q_PAL = 0x4FFD80, 0x4E6ED4, 0x4EB38C
Q_SHINY = 0x4EF84C - 8           # its entries are one off: entry n holds species n + 1's shiny palette

GROWTH = {'EXP_RATE_ERRATIC': 'GROWTH_ERRATIC', 'EXP_RATE_FAST': 'GROWTH_FAST', 'EXP_RATE_FLUCTUATING': 'GROWTH_FLUCTUATING',
          'EXP_RATE_MEDIUM_FAST': 'GROWTH_MEDIUM_FAST', 'EXP_RATE_MEDIUM_SLOW': 'GROWTH_MEDIUM_SLOW', 'EXP_RATE_SLOW': 'GROWTH_SLOW'}
GENDER = {'GENDER_RATIO_FEMALE_12_5': 'PERCENT_FEMALE(12.5)', 'GENDER_RATIO_FEMALE_25': 'PERCENT_FEMALE(25)',
          'GENDER_RATIO_FEMALE_50': 'PERCENT_FEMALE(50)', 'GENDER_RATIO_FEMALE_75': 'PERCENT_FEMALE(75)',
          'GENDER_RATIO_FEMALE_ONLY': 'MON_FEMALE', 'GENDER_RATIO_MALE_ONLY': 'MON_MALE', 'GENDER_RATIO_NO_GENDER': 'MON_GENDERLESS'}


def key(s):
    return re.sub(r'[^a-z0-9]', '', re.sub(r'^(SPECIES_|ITEM_|MOVE_|ABILITY_)', '', s).lower())


def camel(const):
    return ''.join(w.capitalize() for w in const.split('_', 1)[1].split('_'))


def write(rel, text):
    p = os.path.join(REPO, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    old = open(p, encoding='utf-8').read() if os.path.exists(p) else None
    if old != text:
        open(p, 'w', encoding='utf-8').write(text)


def block(rel, start, end, body):
    p = os.path.join(REPO, rel)
    s = open(p, encoding='utf-8').read()
    a = s.index(start)
    b = s.index(end, a)
    open(p, 'w', encoding='utf-8').write(s[:a] + start + '\n' + body + s[b:])


# ------------------------------------------------------------------ expansion
def from_expansion(exp, species):
    import glob
    src = ''.join(open(f, encoding='utf-8').read() for f in sorted(glob.glob(
        os.path.join(exp, 'src', 'data', 'pokemon', 'species_info', 'gen_*_families.h'))))
    keys = re.findall(r'^    \[(SPECIES_\w+)\] =', src, re.M)
    gfx = open(os.path.join(exp, 'src', 'data', 'graphics', 'pokemon.h'), encoding='utf-8').read()
    paths = dict(re.findall(r'const u\d+ (g\w+)\[\] = INCGFX_\w+\("([^"]+)"', gfx))
    out = {}
    for s in species:
        c = s['const']
        k = c if c in keys else next(x for x in keys if x.startswith(c + '_') and 'MEGA' not in x)
        body = src.split('[%s] =' % k, 1)[1].split('\n    },\n', 1)[0]
        body = re.sub(r'[ \t]*#if[^\n]*\n.*?#else[^\n]*\n(.*?)[ \t]*#endif[^\n]*\n', r'\1', body, flags=re.S)
        e = {'expansion_key': k}
        for f in ('height', 'weight', 'pokemonScale', 'pokemonOffset', 'trainerScale', 'trainerOffset',
                  'frontPicYOffset', 'backPicYOffset', 'enemyMonElevation', 'iconPalIndex'):
            m = re.search(r'\.%s = (-?\d+),' % f, body)
            if m:
                e[f] = int(m.group(1))
        for f in ('frontPicSize', 'backPicSize'):
            m = re.search(r'\.%s = MON_COORDS_SIZE\((\d+), (\d+)\)' % f, body)
            e[f] = [int(m.group(1)), int(m.group(2))]
        for f in ('frontAnimId', 'backAnimId', 'cryId', 'frontPic', 'backPic', 'palette', 'shinyPalette', 'iconSprite'):
            m = re.search(r'\.%s = (\w+),' % f, body)
            e[f] = m.group(1) if m else None
        m = re.search(r'\.frontAnimFrames = ANIM_FRAMES\((.*?)\),\n', body, re.S)
        e['frontAnimFrames'] = re.findall(r'ANIMCMD_FRAME\((\d+), (\d+)\)', m.group(1)) if m else [('0', '30')]
        m = re.search(r'FOOTPRINT\((\w+)\)', body)
        fp = 'gMonFootprint_' + m.group(1) if m else None
        e['dir'] = paths[e['frontPic']].rsplit('/', 1)[0]
        e['footprint_png'] = paths.get(fp)
        e['icon_png'] = paths.get(e['iconSprite'])
        e['cry_wav'] = 'sound/direct_sound_samples/cries/%s.wav' % e['cryId'][4:].lower()
        out[c] = e
    return out


def copy_expansion_files(exp, info):
    for c, e in info.items():
        d = os.path.join(REPO, e['dir'])
        os.makedirs(d, exist_ok=True)
        for f in ('anim_front.png', 'back.png', 'normal.pal', 'shiny.pal'):
            shutil.copy(os.path.join(exp, e['dir'], f), os.path.join(d, f))
        for k, dst in (('icon_png', 'icon.png'), ('footprint_png', 'footprint.png')):
            if e.get(k):
                shutil.copy(os.path.join(exp, e[k]), os.path.join(d, dst))
        wav = os.path.join(exp, e['cry_wav'])
        if os.path.exists(wav):
            shutil.copy(wav, os.path.join(REPO, e['cry_wav']))


# ------------------------------------------------------------------ Quetzal (MOéMON art)
def from_quetzal(rom_path, species, info):
    from qrom import Rom
    from trainer_pics import decompress
    from PIL import Image
    r = Rom(rom_path)

    def pal(base, n):
        d = decompress(r.d, r.u32(base + 8 * n) - 0x8000000)
        return [((v & 31) * 255 // 31, ((v >> 5) & 31) * 255 // 31, ((v >> 10) & 31) * 255 // 31)
                for v in (d[i] | d[i + 1] << 8 for i in range(0, 32, 2))]

    def tiles_to_img(t, colors, frames=1):
        im = Image.new('P', (64, 64 * frames))
        im.putpalette([c for rgb in colors for c in rgb] + [0] * (768 - 48))
        px = im.load()
        for f in range(frames):
            for ti in range(64):
                for y in range(8):
                    for x in range(8):
                        b = t[ti * 32 + y * 4 + x // 2]
                        px[(ti % 8) * 8 + x, f * 64 + (ti // 8) * 8 + y] = (b >> 4) if x & 1 else b & 15
        return im

    def jasc(path, colors):
        with open(path, 'w', newline='\r\n') as fh:
            fh.write('JASC-PAL\n0100\n16\n' + ''.join('%d %d %d\n' % c for c in colors))

    def bbox(t):
        xs, ys = [], []
        for ti in range(64):
            for y in range(8):
                for x in range(8):
                    b = t[ti * 32 + y * 4 + x // 2]
                    if (b >> 4) if x & 1 else b & 15:
                        xs.append((ti % 8) * 8 + x)
                        ys.append((ti // 8) * 8 + y)
        return min(xs), max(xs), min(ys), max(ys)

    moe = {}
    for s in species:
        n = s['national']
        name = info[s['const']]['dir'].split('/')[-1]
        d = os.path.join(REPO, 'graphics', 'moemon', 'gen4', name)
        os.makedirs(d, exist_ok=True)
        front = decompress(r.d, r.u32(Q_FRONT + 8 * n) - 0x8000000)
        back = decompress(r.d, r.u32(Q_BACK + 8 * n) - 0x8000000)
        normal, shiny = pal(Q_PAL, n), pal(Q_SHINY, n)
        tiles_to_img(front + front, normal, 2).save(os.path.join(d, 'anim_front.png'))
        tiles_to_img(front, normal).save(os.path.join(d, 'front.png'))
        tiles_to_img(back, normal).save(os.path.join(d, 'back.png'))
        jasc(os.path.join(d, 'normal.pal'), normal)
        jasc(os.path.join(d, 'shiny.pal'), shiny)
        coords = {}
        for k, t in (('front', front), ('back', back)):
            x0, x1, y0, y1 = bbox(t)
            w, h = min(64, (x1 - x0 + 8) // 8 * 8), min(64, (y1 - y0 + 8) // 8 * 8)
            coords[k] = [w, h, 63 - y1]
        moe[s['const']] = {'dir': 'graphics/moemon/gen4/' + name, 'coords': coords}
    return moe


# ------------------------------------------------------------------ Kai names
def kai_consts(rel, prefix):
    out = {}
    for name, val in re.findall(r'#define (%s\w+)\s+(\d+)' % prefix, open(os.path.join(REPO, rel)).read()):
        out.setdefault(key(name), name)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rom')
    ap.add_argument('--expansion')
    a = ap.parse_args()
    g4 = json.load(open(os.path.join(HERE, 'gen4_data.json'), encoding='utf-8'))
    species = [s for s in g4['species'] if s['national'] >= NAT_FIRST]
    gfx_p = os.path.join(HERE, 'species_gfx.json')
    cache = json.load(open(gfx_p, encoding='utf-8')) if os.path.exists(gfx_p) else {}
    if a.expansion:
        cache['expansion'] = from_expansion(a.expansion, species)
        copy_expansion_files(a.expansion, cache['expansion'])
    if a.rom:
        cache['moemon'] = from_quetzal(a.rom, species, cache['expansion'])
    with open(gfx_p, 'w', encoding='utf-8') as fh:
        json.dump(cache, fh, indent=1)
    exp, moe = cache['expansion'], cache['moemon']

    kai_items = kai_consts('include/constants/items.h', 'ITEM_')
    kai_moves_by_id = {int(v): n for n, v in re.findall(r'#define (MOVE_\w+) (\d+)', open(os.path.join(REPO, 'include/constants/moves.h')).read())}
    pmoves = {m['const']: m['id'] for m in g4['moves']}
    tm_moves = g4['tm_moves']

    def kmove(c):
        return kai_moves_by_id[pmoves[c]]

    def kitem(c):
        k = key(c)
        k = {'thunderstone': 'thunderstone'}.get(k, k)
        return kai_items.get(k, 'ITEM_NONE')

    ids = {s['const']: FIRST_ID + i for i, s in enumerate(species)}
    consts = [s['const'] for s in species]
    names = [c[8:] for c in consts]

    # ---- constants
    block('include/constants/species.h', '// Moemon Kai: Gen 4 species (tools/moemon_gen4/gen_species.py)',
          '// end of Gen 4 species', ''.join('#define %s %d\n' % (c, ids[c]) for c in consts) +
          '#define FIRST_GEN4_SPECIES SPECIES_TURTWIG\n#define LAST_GEN4_SPECIES  SPECIES_ARCEUS\n'
          '#define IS_GEN4_SPECIES(species) ((species) >= FIRST_GEN4_SPECIES && (species) <= LAST_GEN4_SPECIES)\n'
          '#define SPECIES_EGG %d\n' % (FIRST_ID + len(species)))
    block('include/constants/pokedex.h', '    // Moemon Kai: Gen 4 national dex (tools/moemon_gen4/gen_species.py)',
          '    // end of Gen 4 national dex', ''.join('    NATIONAL_DEX_%s,\n' % n for n in names))
    block('include/constants/pokedex.h', '    // Moemon Kai: Gen 4 (no Hoenn number, tools/moemon_gen4/gen_species.py)',
          '    // end of Gen 4 hoenn', ''.join('    HOENN_DEX_%s,\n' % n for n in names))

    # ---- species info
    out = [GEN]
    for s in species:
        st = s['stats']
        ev = s['ev_yields']
        types = [t for t in s['types']]
        if len(types) == 1:
            types.append(types[0])
        eggs = [g.replace('UNDISCOVERED', 'NO_EGGS_DISCOVERED') for g in s['egg_groups']]
        abil = s['abilities'] + ['ABILITY_NONE'] * (2 - len(s['abilities']))
        out.append('''    [%s] =
    {
        .baseHP        = %d,
        .baseAttack    = %d,
        .baseDefense   = %d,
        .baseSpeed     = %d,
        .baseSpAttack  = %d,
        .baseSpDefense = %d,
        .types = { %s, %s },
        .catchRate = %d,
        .expYield = %d,
        .evYield_HP        = %d,
        .evYield_Attack    = %d,
        .evYield_Defense   = %d,
        .evYield_Speed     = %d,
        .evYield_SpAttack  = %d,
        .evYield_SpDefense = %d,
        .itemCommon = %s,
        .itemRare   = %s,
        .genderRatio = %s,
        .eggCycles = %d,
        .friendship = %d,
        .growthRate = %s,
        .eggGroups = { %s, %s },
        .abilities = {%s, %s},
        .safariZoneFleeRate = %d,
        .bodyColor = %s,
        .noFlip = %s,
    },
''' % (s['const'], st[0], st[1], st[2], st[3], st[4], st[5], types[0], types[1], s['catch_rate'], min(255, s['exp_yield']),
            ev[0], ev[1], ev[2], ev[3], ev[4], ev[5], kitem(s['held_items'][0]), kitem(s['held_items'][1]),
            GENDER[s['gender_ratio']], s['hatch_cycles'], s['friendship'], GROWTH[s['growth']], eggs[0], eggs[-1],
            abil[0], abil[1], s['safari_flee'], s['color'].replace('MON_COLOR', 'BODY_COLOR'),
            'TRUE' if s['flip'] else 'FALSE'))
    write('src/data/pokemon/species_info_gen4.h', ''.join(out))
    write('src/data/text/species_names_gen4.h', GEN + ''.join(
        '    [%s] = _("%s"),\n' % (s['const'], s['name'].upper().replace('♀', '♀')) for s in species))

    # ---- learnsets
    lv, ptr = [GEN], [GEN]
    for s in species:
        sym = 's%sLevelUpLearnset' % camel(s['const'])
        lines = ['    LEVEL_UP_MOVE(%2d, %s),' % (l, kmove(m)) for l, m in s['learnset']['level']]
        lv.append('static const u32 %s[] = {\n%s\n    LEVEL_UP_END\n};\n\n' % (sym, '\n'.join(lines)))
        ptr.append('    [%s] = %s,\n' % (s['const'], sym))
    write('src/data/pokemon/level_up_learnsets_gen4.h', ''.join(lv))
    write('src/data/pokemon/level_up_learnset_pointers_gen4.h', ''.join(ptr))

    tmh = open(os.path.join(REPO, 'src/data/pokemon/tmhm_learnsets.h')).read()
    kai_tm_fields = re.findall(r'\.(\w+) = TRUE', tmh)
    kai_tm_fields = list(dict.fromkeys(kai_tm_fields))
    tut = open(os.path.join(REPO, 'src/data/pokemon/tutor_learnsets.h')).read()
    kai_tutor = list(dict.fromkeys(re.findall(r'TUTOR\((MOVE_\w+)\)', tut)))
    out_tm, out_tu, out_egg = [GEN], [GEN], [GEN]
    for s in species:
        teach = {key(tm_moves[t]) for t in s['learnset']['tm']} | {key(m) for m in s['learnset']['tutor']}
        fields = [f for f in kai_tm_fields if key(f) in teach]
        out_tm.append('    [%s] = { .learnset = {\n%s    } },\n\n' % (s['const'], ''.join('        .%s = TRUE,\n' % f for f in fields)))
        tutors = [m for m in kai_tutor if key(m) in teach]
        out_tu.append('    [%s] = %s,\n' % (s['const'], ' | '.join('TUTOR(%s)' % m for m in tutors) or '0'))
        if s['learnset']['egg']:
            out_egg.append('    egg_moves(%s,\n%s),\n\n' % (s['const'][8:], ',\n'.join('              %s' % kmove(m) for m in s['learnset']['egg'])))
    write('src/data/pokemon/tmhm_learnsets_gen4.h', ''.join(out_tm))
    write('src/data/pokemon/tutor_learnsets_gen4.h', ''.join(out_tu))
    write('src/data/pokemon/egg_moves_gen4.h', ''.join(out_egg))

    # ---- pokedex
    ent, txt = [GEN], [GEN]
    for s in species:
        e = exp[s['const']]
        sym = 'g%sPokedexText' % camel(s['const'])
        words = kai_text(s['dex_text'] or '').split()
        lines, cur = [], ''
        for w in words:
            if len(cur) + len(w) + 1 > 40 and cur:
                lines.append(cur)
                cur = w
            else:
                cur = (cur + ' ' + w).strip()
        if cur:
            lines.append(cur)
        txt.append('const u8 %s[] = _(\n%s);\n\n' % (sym, '\n'.join(
            '    "%s%s"' % (l.replace('"', '\\"'), '\\n' if i < len(lines) - 1 else '') for i, l in enumerate(lines))))
        cat = (s['category'] or '').upper()
        for tail in (' POKéMON', ' POKÉMON', ' POKEMON'):
            if cat.endswith(tail):
                cat = cat[:-len(tail)]
        ent.append('''    [NATIONAL_DEX_%s] =
    {
        .categoryName = _("%s"),
        .height = %d,
        .weight = %d,
        .description = %s,
        .pokemonScale = %d,
        .pokemonOffset = %d,
        .trainerScale = %d,
        .trainerOffset = %d,
    },

''' % (s['const'][8:], cat, e['height'], e['weight'], sym, e['pokemonScale'], e['pokemonOffset'],
            e['trainerScale'], e['trainerOffset']))
    write('src/data/pokemon/pokedex_entries_gen4.h', ''.join(ent))
    write('src/data/pokemon/pokedex_text_gen4.h', ''.join(txt))

    # ---- dex numbers, cries (pokemon.c)
    write('src/data/pokemon/dex_numbers_gen4.h', GEN +
          '#define SPECIES_TO_HOENN_GEN4 \\\n' + ' \\\n'.join('    SPECIES_TO_HOENN(%s),' % n for n in names) + '\n' +
          '#define SPECIES_TO_NATIONAL_GEN4 \\\n' + ' \\\n'.join('    SPECIES_TO_NATIONAL(%s),' % n for n in names) + '\n' +
          '#define HOENN_TO_NATIONAL_GEN4 \\\n' + ' \\\n'.join('    HOENN_TO_NATIONAL(%s),' % n for n in names) + '\n')
    write('src/data/pokemon/cry_ids_gen4.h', GEN + ''.join(
        '    [%s - 277] = %d,\n' % (c, CRY_FIRST + i) for i, c in enumerate(consts)))
    write('sound/cry_tables_gen4.inc', '@ ' + GEN[3:] + ''.join('\tcry Cry_%s\n' % camel(c) for c in consts))
    write('sound/cry_tables_reverse_gen4.inc', '@ ' + GEN[3:] + ''.join('\tcry_reverse Cry_%s\n' % camel(c) for c in consts))
    write('sound/direct_sound_data_gen4.inc', '@ ' + GEN[3:] + ''.join(
        '\n\t.align 2\nCry_%s::\n\t.incbin "%s"\n' % (camel(c), exp[c]['cry_wav'][:-4] + '.bin') for c in consts))

    # ---- graphics: definitions, externs, tables
    defs, ext = [GEN], [GEN]
    tabs = {k: [] for k in ('front', 'back', 'pal', 'shiny', 'still', 'fcoord', 'bcoord', 'elev', 'anims', 'icon',
                            'iconpal', 'footprint', 'unknown', 'unused',
                            'pk_front', 'pk_back', 'pk_pal', 'pk_shiny', 'pk_fcoord', 'pk_bcoord', 'pk_elev', 'pk_anims',
                            'pk_animid')}
    pk_defs = [GEN]
    kai_anims = set(re.findall(r'\b(ANIM_[A-Z0-9_]+)\b', open(os.path.join(REPO, 'include/pokemon_animation.h')).read()))
    for c in consts:
        cm, n, e, m = camel(c), c[8:], exp[c], moe[c]
        for sym, typ, path, ext_ in (('gMonFrontPic_' + cm, 'u32', m['dir'] + '/anim_front.png', '.4bpp.lz'),
                                     ('gMonStillFrontPic_' + cm, 'u32', m['dir'] + '/front.png', '.4bpp.lz'),
                                     ('gMonBackPic_' + cm, 'u32', m['dir'] + '/back.png', '.4bpp.lz'),
                                     ('gMonPalette_' + cm, 'u32', m['dir'] + '/normal.pal', '.gbapal.lz'),
                                     ('gMonShinyPalette_' + cm, 'u32', m['dir'] + '/shiny.pal', '.gbapal.lz'),
                                     ('gMonIcon_' + cm, 'u8', e['dir'] + '/icon.png', '.4bpp'),
                                     ('gMonFootprint_' + cm, 'u8', e['dir'] + '/footprint.png', '.1bpp')):
            defs.append('const %s %s[] = INCGFX_%s("%s", "%s");\n' % (typ, sym, typ.upper(), path, ext_))
            ext.append('extern const %s %s[];\n' % (typ, sym))
        for sym, path, ext_ in (('sPkFrontPic_' + cm, e['dir'] + '/anim_front.png', '.4bpp.lz'),
                                ('sPkBackPic_' + cm, e['dir'] + '/back.png', '.4bpp.lz'),
                                ('sPkPalette_' + cm, e['dir'] + '/normal.pal', '.gbapal.lz'),
                                ('sPkShinyPalette_' + cm, e['dir'] + '/shiny.pal', '.gbapal.lz')):
            pk_defs.append('static const u32 %s[] = INCGFX_U32("%s", "%s");\n' % (sym, path, ext_))
        tabs['front'].append('    SPECIES_SPRITE(%s, gMonFrontPic_%s),' % (n, cm))
        tabs['back'].append('    SPECIES_SPRITE(%s, gMonBackPic_%s),' % (n, cm))
        tabs['still'].append('    SPECIES_SPRITE(%s, gMonStillFrontPic_%s),' % (n, cm))
        tabs['pal'].append('    SPECIES_PAL(%s, gMonPalette_%s),' % (n, cm))
        tabs['shiny'].append('    SPECIES_SHINY_PAL(%s, gMonShinyPalette_%s),' % (n, cm))
        f, b = m['coords']['front'], m['coords']['back']
        tabs['fcoord'].append('    [%s] = { .size = MON_COORDS_SIZE(%d, %d), .y_offset = %d },' % (c, f[0], f[1], f[2]))
        tabs['bcoord'].append('    [%s] = { .size = MON_COORDS_SIZE(%d, %d), .y_offset = %d },' % (c, b[0], b[1], b[2]))
        tabs['anims'].append('    [%s] = sAnims_MoemonStatic,' % c)
