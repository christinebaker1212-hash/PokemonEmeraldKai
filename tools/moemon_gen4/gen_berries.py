#!/usr/bin/env python3
"""Gen 4 BERRIES for Kai: items from 474, berry numbers after the e-Reader Berries (like those: plantable,
Berry Crush, Blender, tags), and their battle hold effects.

    python3 tools/moemon_gen4/gen_berries.py [EXPANSION_DIR]

Which: Platinum's berries Kai doesn't have (OCCA..BABIRI, MICLE, CUSTAP, JABOCA, ROWAP). Kai's own CHILAN BERRY
(an e-Reader Berry, item 381) stays as it is and only gains Gen 4's held effect (a NORMAL move halved): Kai's
systems first. Names, prices, NATURAL GIFT and FLING are Platinum's (gen4_data.json); berry data (size, firmness,
flavors, yields, growth, tag text, Berry Crush), item descriptions, icons and berry pictures pokeemerald-expansion's,
the Gen 3 numbers where it has several (cached in berries.json; pictures copied into graphics/, so EXPANSION_DIR is
only needed to refresh). Trees: a vanilla tree of the berry's color (the e-Reader Berries do the same).

Generated: the "Gen 4 berries" blocks of include/constants/items.h (and ITEMS_COUNT) and
include/constants/hold_effects.h, src/data/items_gen4_berries.h, src/data/text/item_descriptions_gen4_berries.h,
src/data/graphics/items_gen4_berries.h (icons and berry pictures), src/data/berries_gen4.h (every table indexed by
berry number, as macros the stock tables include).
"""
import json
import os
import re
import shutil
import sys

from kaitext import kai_text

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
FIRST_ID = 474
GEN = '// Generated by tools/moemon_gen4/gen_berries.py. Do not edit.\n'

BERRIES = ['OCCA', 'PASSHO', 'WACAN', 'RINDO', 'YACHE', 'CHOPLE', 'KEBIA', 'SHUCA', 'COBA', 'PAYAPA', 'TANGA',
           'CHARTI', 'KASIB', 'HABAN', 'COLBUR', 'BABIRI', 'MICLE', 'CUSTAP', 'JABOCA', 'ROWAP']
# hold effects (gen_items.py's Gen 4 ones end at 98)
HOLDS = ['HOLD_EFFECT_RESIST_BERRY', 'HOLD_EFFECT_MICLE_BERRY', 'HOLD_EFFECT_CUSTAP_BERRY', 'HOLD_EFFECT_JABOCA_BERRY',
         'HOLD_EFFECT_ROWAP_BERRY']
FIRST_HOLD = 99
TYPE_WORDS = r'(?:(?<=\\n)|(?<![A-Za-z]))(Normal|Fire|Water|Electric|Grass|Ice|Fighting|Poison|Ground|Flying|Psychic|Bug|Rock|Ghost|Dragon|Dark|Steel)(?![a-z])'
# a vanilla tree for each berry color
TREE_BY_COLOR = {'RED': 'Cheri', 'BLUE': 'Oran', 'PURPLE': 'Chesto', 'GREEN': 'Rawst', 'YELLOW': 'Aspear',
                 'PINK': 'Pecha', 'BLACK': 'Durin', 'GRAY': 'Spelon', 'BROWN': 'Pomeg', 'WHITE': 'Wepear'}
FIRMNESS = {'VERY_SOFT', 'SOFT', 'HARD', 'VERY_HARD', 'SUPER_HARD'}


def first_arg(v):
    m = re.match(r'\w+\(([^,)]+)', v)
    return m.group(1).strip() if m else v


def parse_expansion(exp):
    src = open(os.path.join(exp, 'src/berry.c'), encoding='utf-8').read()
    items = open(os.path.join(exp, 'src/data/items.h'), encoding='utf-8').read()
    out = {}
    for b in BERRIES + ['CHILAN']:
        m = re.search(r'\[BERRY_ID_%s\] =\s*\{(.*?)\n    \},' % b, src, re.S)
        e = {}
        body = m.group(1)
        for f in ('firmness', 'color', 'size', 'maxYield', 'minYield', 'growthDuration', 'spicy', 'dry', 'sweet',
                  'bitter', 'sour', 'smoothness', 'berryCrushDifficulty', 'berryCrushPowder'):
            fm = re.search(r'\.%s = ([^\n]+?),\n' % f, body)
            e[f] = first_arg(fm.group(1)) if fm else '0'
        for f in ('description1', 'description2'):
            fm = re.search(r'\.%s = COMPOUND_STRING\("(.*?)"\)' % f, body)
            e[f] = fm.group(1)
        m = re.search(r'\[ITEM_%s_BERRY\] =\s*\{(.*?)\n    \},' % b, items, re.S)
        body = m.group(1)
        for f in ('holdEffect', 'holdEffectParam'):
            fm = re.search(r'\.%s = ([^,\n]+),' % f, body)
            e[f] = fm.group(1).strip() if fm else None
        fm = re.search(r'\.description = COMPOUND_STRING\((.*?)\),', body, re.S)
        e['itemDescription'] = ''.join(re.findall(r'"(.*?)"', fm.group(1)))
        out[b] = e
    return out


def sym(b):
    return b.capitalize()


def block(rel, start, end, body):
    p = os.path.join(REPO, rel)
    s = open(p, encoding='utf-8').read()
    a = s.index(start)
    b = s.index(end, a)
    s = s[:a] + start + '\n' + body + s[b:]
    open(p, 'w', encoding='utf-8').write(s)


def c_lines(text):
    lines = text.split('\\n')
    return '\n'.join('    "%s%s"' % (l, '\\n' if i < len(lines) - 1 else '') for i, l in enumerate(lines))


def main():
    g4 = json.load(open(os.path.join(HERE, 'gen4_data.json'), encoding='utf-8'))
    pitems = {x['const']: x for x in g4['items'] if not x.get('missing')}
    cache_p = os.path.join(HERE, 'berries.json')
    if len(sys.argv) > 1:
        exp = sys.argv[1]
        cache = parse_expansion(exp)
        for b in BERRIES:
            low = b.lower()
            for rel in ('graphics/items/icons/%s_berry.png' % low, 'graphics/items/icon_palettes/%s_berry.pal' % low,
                        'graphics/berries/%s.png' % low):
                shutil.copy(os.path.join(exp, rel), os.path.join(REPO, rel))
        json.dump(cache, open(cache_p, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    cache = json.load(open(cache_p, encoding='utf-8'))

    # constants
    body = ''.join('#define ITEM_%s_BERRY %d\n' % (b, FIRST_ID + i) for i, b in enumerate(BERRIES))
    body += '#define FIRST_GEN4_BERRY ITEM_%s_BERRY\n#define LAST_GEN4_BERRY  ITEM_%s_BERRY\n' % (BERRIES[0], BERRIES[-1])
    body += '#define NUM_GEN4_BERRIES (LAST_GEN4_BERRY - FIRST_GEN4_BERRY + 1)\n'
    body += '\n#define ITEMS_COUNT %d\n' % (FIRST_ID + len(BERRIES))
    block('include/constants/items.h', '// Moemon Kai: Gen 4 berries (tools/moemon_gen4/gen_berries.py)',
          '// end of Gen 4 berries', body)
    block('include/constants/hold_effects.h', '// Moemon Kai: Gen 4 berry hold effects (tools/moemon_gen4/gen_berries.py)',
          '// end of Gen 4 berry hold effects', ''.join('#define %-30s %d\n' % (h, FIRST_HOLD + i) for i, h in enumerate(HOLDS)))

    items, descs, gfx, ext = [GEN], [GEN], [GEN], [GEN]
    berries, crush, pics, trees, pals, gfxids, tagtext = [], [], [], [], [], [], []
    for b in BERRIES:
        const, e, p, s = 'ITEM_%s_BERRY' % b, cache[b], pitems['ITEM_%s_BERRY' % b], sym(b)
        name = '%s BERRY' % b
        param = e['holdEffectParam'] or '0'
        if param.startswith('TYPE_'):
            param = param.upper()
        items.append('    [%s] =\n    {\n%s\n    },\n\n' % (const, '\n'.join([
            '        .name = _("%s"),' % name, '        .itemId = %s,' % const, '        .price = %d,' % p['price'],
            '        .holdEffect = %s,' % e['holdEffect'], '        .holdEffectParam = %s,' % param,
            '        .description = s%sBerryDesc,' % s, '        .pocket = POCKET_BERRIES,',
            '        .type = ITEM_USE_BAG_MENU,', '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,'])))
        descs.append('static const u8 s%sBerryDesc[] = _(\n%s);\n\n' % (s, c_lines(re.sub(TYPE_WORDS, lambda m: m.group(1).upper(), kai_text(e['itemDescription'])))))
        gfx.append('const u32 gItemIcon_%sBerry[] = INCGFX_U32("graphics/items/icons/%s_berry.png", ".4bpp.lz");\n' % (s, b.lower()))
        gfx.append('const u32 gItemIconPalette_%sBerry[] = INCGFX_U32("graphics/items/icon_palettes/%s_berry.pal", ".gbapal.lz");\n' % (s, b.lower()))
        gfx.append('const u32 gBerryPic_%s[] = INCGFX_U32("graphics/berries/%s.png", ".4bpp.lz");\n' % (s, b.lower()))
        gfx.append('const u32 gBerryPalette_%s[] = INCGFX_U32("graphics/berries/%s.png", ".gbapal.lz");\n' % (s, b.lower()))
        for n in ('gItemIcon_%sBerry' % s, 'gItemIconPalette_%sBerry' % s, 'gBerryPic_%s' % s, 'gBerryPalette_%s' % s):
            ext.append('extern const u32 %s[];\n' % n)
        firm = e['firmness'].replace('BERRY_FIRMNESS_', '')
        assert firm in FIRMNESS, firm
        stage = max(1, int(e['growthDuration']) // 4)
        tagtext.append('static const u8 sBerryDescriptionPart1_%s[] = _("%s");\n' % (s, kai_text(e['description1'])))
        tagtext.append('static const u8 sBerryDescriptionPart2_%s[] = _("%s");\n' % (s, kai_text(e['description2'])))
        berries.append('    [BERRY_SLOT(%s)] = { .name = _("%s"), .firmness = BERRY_FIRMNESS_%s, .size = %s, .maxYield = %s, '
                       '.minYield = %s, .description1 = sBerryDescriptionPart1_%s, .description2 = sBerryDescriptionPart2_%s, '
                       '.stageDuration = %d, .spicy = %s, .dry = %s, .sweet = %s, .bitter = %s, .sour = %s, .smoothness = %s },'
                       % (const, b, firm, e['size'], e['maxYield'], e['minYield'], s, s, stage, e['spicy'], e['dry'],
                          e['sweet'], e['bitter'], e['sour'], e['smoothness']))
        crush.append('    [BERRY_SLOT(%s)] = {.difficulty = %s, .powder = %s},' % (const, e['berryCrushDifficulty'], e['berryCrushPowder']))
        pics.append('    [BERRY_SLOT(%s)] = {gBerryPic_%s, gBerryPalette_%s},' % (const, s, s))
        color = e['color'].replace('BERRY_COLOR_', '').split(':')[-1].strip()   # "X ? A : B" -> the original B
        tree = TREE_BY_COLOR[color]
        trees.append('    [BERRY_SLOT(%s)] = sPicTable_%sBerryTree,' % (const, tree))
        pals.append('    [BERRY_SLOT(%s)] = gBerryTreePaletteSlotTable_%s,' % (const, tree))
        gfxids.append('    [BERRY_SLOT(%s)] = gBerryTreeObjectEventGraphicsIdTable,' % const)

    def macro(name, lines):
        return '#define %s \\\n%s\n\n' % (name, ' \\\n'.join(lines))

    open(os.path.join(REPO, 'src/data/items_gen4_berries.h'), 'w', encoding='utf-8').write(''.join(items))
    open(os.path.join(REPO, 'src/data/text/item_descriptions_gen4_berries.h'), 'w', encoding='utf-8').write(''.join(descs))
    open(os.path.join(REPO, 'src/data/graphics/items_gen4_berries.h'), 'w', encoding='utf-8').write(''.join(gfx))
    icons = ['    [ITEM_%s_BERRY] = {gItemIcon_%sBerry, gItemIconPalette_%sBerry},' % (b, sym(b), sym(b)) for b in BERRIES]
    open(os.path.join(REPO, 'src/data/berries_gen4.h'), 'w', encoding='utf-8').write(
        GEN + '// Included by the files whose tables are indexed by item or berry number; each takes the macro it needs.\n'
        '#ifndef GUARD_DATA_BERRIES_GEN4_H\n#define GUARD_DATA_BERRIES_GEN4_H\n' + ''.join(ext[1:]) + '\n'
        + macro('ITEM_ICONS_GEN4_BERRIES', icons) + macro('BERRY_TAG_TEXT_GEN4', [l.rstrip('\n') for l in tagtext])
        + macro('BERRIES_GEN4', berries) + macro('BERRY_CRUSH_GEN4', crush) + macro('BERRY_PICS_GEN4', pics)
        + macro('BERRY_TREE_PICS_GEN4', trees) + macro('BERRY_TREE_PALETTES_GEN4', pals)
        + macro('BERRY_TREE_GFX_IDS_GEN4', gfxids) + '#endif\n')
    print('%d berries (%d-%d)' % (len(BERRIES), FIRST_ID, FIRST_ID + len(BERRIES) - 1))


if __name__ == '__main__':
    main()
