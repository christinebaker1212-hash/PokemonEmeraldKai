#!/usr/bin/env python3
"""The Gen 4 abilities (78-123) for Kai: constants, names, descriptions.

    python3 tools/moemon_gen4/gen_abilities.py [EXPANSION_DIR]

Order and names: Platinum's (gen4_data.json). Descriptions: pokeemerald-expansion's src/data/abilities.h (kept in
abilities_text.json, so EXPANSION_DIR is only needed to refresh them). The abilities' effects are written by hand
in the battle code (look for "Gen 4 abilities").
Generated: the include/constants/abilities.h block and src/data/text/abilities_gen4.h.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
FIRST = 78
NAMES = {'ABILITY_FOREWARN': 'FOREWARN', 'ABILITY_LEAF_GUARD': 'LEAF GUARD'}


def main():
    g4 = json.load(open(os.path.join(HERE, 'gen4_data.json'), encoding='utf-8'))
    abil = g4['abilities'][g4['abilities'].index('ABILITY_AIR_LOCK') + 1:]   # Kai keeps CACOPHONY (76), so Kai id = Platinum id + 1
    abil = [a for a in abil if a.startswith('ABILITY_') and a != 'ABILITY_MAX']
    cache_p = os.path.join(HERE, 'abilities_text.json')
    cache = json.load(open(cache_p, encoding='utf-8')) if os.path.exists(cache_p) else {}
    if len(sys.argv) > 1:
        src = open(os.path.join(sys.argv[1], 'src', 'data', 'abilities.h'), encoding='utf-8').read()
        for a in abil:
            blk = re.search(r'\[%s\] =\s*\{(.*?)\n    \},' % a, src, re.S)
            if not blk:
                raise SystemExit('no %s in expansion' % a)
            body = blk.group(1)
            name = re.search(r'\.name = _\("([^"]*)"\)', body)
            # "#if <later gen> ... #else <Gen 4> #endif": keep the #else side
            body = re.sub(r'[ \t]*#if[^\n]*\n.*?#else[^\n]*\n(.*?)[ \t]*#endif[^\n]*\n', r'\1', body, flags=re.S)
            body = re.sub(r'[ \t]*#if[^\n]*\n.*?#endif[^\n]*\n', '', body, flags=re.S)
            desc = re.search(r'\.description = (?:COMPOUND_STRING|_)\((.*?)\),\n', body, re.S)
            if not desc:
                raise SystemExit("no description for %s: %r" % (a, body[:300]))
            m = (name.group(1), desc.group(1))
            cache[a] = {'name': m[0], 'description': ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', m[1]))}
        json.dump(cache, open(cache_p, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    p = os.path.join(REPO, 'include', 'constants', 'abilities.h')
    s = open(p).read()
    body = ''.join('#define %s %d\n' % (a, FIRST + i) for i, a in enumerate(abil))
    s = re.sub(r'(// Moemon Kai: Gen 4 abilities \(tools/moemon_gen4/gen_abilities.py\)\n).*?(// end of Gen 4 abilities\n)',
               lambda m: m.group(1) + body + '\n#define ABILITIES_COUNT %d\n' % (FIRST + len(abil)) + m.group(2), s, flags=re.S)
    open(p, 'w').write(s)
    out = ['// Generated by tools/moemon_gen4/gen_abilities.py. Do not edit.\n']
    for a in abil:
        d = cache[a]['description'].replace('Pokémon', 'MOéMON')
        out.append('static const u8 s%sDescription[] = _("%s");\n' % (''.join(w.capitalize() for w in a[8:].split('_')), d))
    out.append('#define ABILITY_NAMES_GEN4 \\\n' + ' \\\n'.join(
        '    [%s] = _("%s"),' % (a, cache[a]['name'].upper()) for a in abil) + '\n')
    out.append('#define ABILITY_DESCRIPTIONS_GEN4 \\\n' + ' \\\n'.join(
        '    [%s] = s%sDescription,' % (a, ''.join(w.capitalize() for w in a[8:].split('_'))) for a in abil) + '\n')
    open(os.path.join(REPO, 'src', 'data', 'text', 'abilities_gen4.h'), 'w', encoding='utf-8').write(''.join(out))
    print('%d abilities (%d-%d)' % (len(abil), FIRST, FIRST + len(abil) - 1))


if __name__ == '__main__':
    main()
