#!/usr/bin/env python3
"""FLING power and NATURAL GIFT power / type of every Kai item, from Platinum (gen4_data.json), matched by name.

    python3 tools/moemon_gen4/gen_item_battle.py      -> src/data/gen4_item_battle.h
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
ALIAS = {'xdefend': 'xdefense', 'xspecial': 'xspatk', 'paralyzeheal': 'parlyzheal', 'stick': 'stick'}


def key(s):
    return re.sub(r'[^a-z0-9]', '', s.lower())


def main():
    g4 = json.load(open(os.path.join(HERE, 'gen4_data.json'), encoding='utf-8'))
    pl = {}
    for it in g4['items']:
        if it.get('name'):
            pl[key(it['name'])] = it
            pl.setdefault(key(it['const'][5:]), it)
    kai = re.findall(r'#define (ITEM_\w+) (\d+)', open(os.path.join(REPO, 'include/constants/items.h')).read())
    fl, ng = [], []
    for c, v in kai:
        k = key(c[5:])
        it = pl.get(ALIAS.get(k, k))
        if not it:
            continue
        if it.get('fling_power'):
            fl.append('    [%s] = %d,' % (c, it['fling_power']))
        p, t = it.get('natural_gift') or (0, None)
        if p and t:
            ng.append('    [%s] = {%d, %s},' % (c, p, t))
    out = ['// Generated by tools/moemon_gen4/gen_item_battle.py from Platinum. Do not edit.',
           'static const u8 sFlingPower[ITEMS_COUNT] =\n{', *fl, '};', '',
           'static const u8 sNaturalGift[ITEMS_COUNT][2] =   // power, type\n{', *ng, '};', '']
    open(os.path.join(REPO, 'src/data/gen4_item_battle.h'), 'w').write('\n'.join(out))
    print('%d fling powers, %d natural gifts' % (len(fl), len(ng)))


if __name__ == '__main__':
    main()
