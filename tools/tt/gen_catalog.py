#!/usr/bin/env python3
"""Writes src/tt/tt_catalog.c and include/tt/card_ids.h from tools/tt/cards.json (tools/tt/fetch_cards.py).
Card ids are Final Fantasy XIV's own: they never move (saves store them)."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
TYPES = {'': 'TT_TYPE_NONE', 'Primal': 'TT_TYPE_PRIMAL', 'Scion': 'TT_TYPE_SCION', 'Society': 'TT_TYPE_SOCIETY',
         'Garlean': 'TT_TYPE_GARLEAN'}

def plain(s):
    """The game's fonts have no curly quotes, box lines or music notes"""
    for a, b in (('“', '"'), ('”', '"'), ('‘', "'"), ('’', "'"), ('─', '-'), ('–', '-'), ('—', '-'), ('～', '~'),
                 ('æ', 'ae'), ('Æ', 'AE'), ('♪', ''), ('\n', ' '), ('…', '...')):
        s = s.replace(a, b)
    s = re.sub(r'-{2,}', ' - ', s)
    s = re.sub(r'\s+', ' ', s).strip()
    assert all(32 <= ord(c) < 127 for c in s), s
    return s

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def ident(name):
    s = re.sub(r'[^A-Za-z0-9]+', '_', plain(name)).strip('_').upper()
    return s

def main():
    cards = json.load(open(os.path.join(HERE, 'cards.json')))
    top = max(c['id'] for c in cards)
    out = ['// Generated by tools/tt/gen_catalog.py from tools/tt/cards.json (Final Fantasy XIV\'s cards, from xivapi).',
           '// Do not edit: rerun the script.',
           '#include "tt/tt.h"', '',
           'const struct TtCard gTtCards[TT_CARD_MAX + 1] = {']
    for c in cards:
        out.append('    [%d] = {%s, %s, {%d, %d, %d, %d}, %d, %s, %d, %d},' % (
            c['id'], cstr(plain(c['name'])), cstr(plain(c['description'])), c['top'], c['right'], c['bottom'],
            c['left'], c['stars'], TYPES[c['type']], c['sale'], c['order']))
    out.append('};')
    open(os.path.join(ROOT, 'src', 'tt', 'tt_catalog.c'), 'w').write('\n'.join(out) + '\n')
    seen = set()
    ids = ['// Generated by tools/tt/gen_catalog.py. Card ids are Final Fantasy XIV\'s and never move.',
           '#ifndef MOEMON_TT_CARD_IDS_H', '#define MOEMON_TT_CARD_IDS_H',
           '#define TT_CARD_MAX %d' % top, '#define TT_CARD_COUNT %d' % len(cards)]
    for c in cards:
        n = ident(c['name'])
        if n in seen:
            n += '_%d' % c['id']
        seen.add(n)
        ids.append('#define TT_CARD_%s %d' % (n, c['id']))
    ids.append('#endif')
    open(os.path.join(ROOT, 'include', 'tt', 'card_ids.h'), 'w').write('\n'.join(ids) + '\n')
    print(len(cards), 'cards, ids up to', top)

if __name__ == '__main__':
    main()
