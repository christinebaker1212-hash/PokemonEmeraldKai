#!/usr/bin/env python3
"""GB OPTIONS > COLORS (CRYSTAL): Crystal's own colours for each of its 251 POKeMON, normal and shiny.

Reads pret/pokecrystal: data/pokemon/palettes.asm names each species' normal.gbcpal (made from its front.png: the
picture's two middle palette entries) and its shiny.pal. Writes src/mp/mp_gbpal_data.h: sGbCrystalMonPals[252][2][2]
(species 0-251 in national order, which Kai's species 1-251 keep; [normal / shiny][light / dark]) as GBA colours, the
white and black around them being the GBC's own.

    python3 tools/moemon_legacy/gbpal_species.py POKECRYSTAL_DIR [OUT]
"""
import os, re, sys

def rgb5(r, g, b):
    return (r & 31) | ((g & 31) << 5) | ((b & 31) << 10)

def from_png(path):
    from PIL import Image
    im = Image.open(path)
    pal = im.getpalette()
    out = []
    for k in (1, 2):
        r, g, b = pal[k * 3:k * 3 + 3]
        out.append(rgb5(r >> 3, g >> 3, b >> 3))
    return out

def from_pal(path):
    vals = [tuple(int(x) for x in m) for m in re.findall(r'RGB\s+(\d+),\s*(\d+),\s*(\d+)', open(path).read())]
    return [rgb5(*v) for v in vals[:2]]

def main():
    root = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'mp',
                                                               'mp_gbpal_data.h')
    lines = open(os.path.join(root, 'data', 'pokemon', 'palettes.asm')).read().split('\n')
    entries = []   # [(normal, shiny)]
    i = 0
    pending = []
    for l in lines:
        s = l.split(';')[0].strip()
        m = re.match(r'INCBIN "gfx/pokemon/(\w+)/(normal|front)\.gbcpal"', s)
        if m:
            d = os.path.join(root, 'gfx', 'pokemon', m.group(1))
            png = os.path.join(d, 'front.png')
            if not os.path.exists(png):
                png = os.path.join(root, 'gfx', 'pokemon', m.group(1) + '_a', 'front.png')
            pending = [from_png(png)]
            continue
        m = re.match(r'INCLUDE "gfx/pokemon/(\w+)/shiny\.pal"', s)
        if m and pending:
            entries.append((pending[0], from_pal(os.path.join(root, 'gfx', 'pokemon', m.group(1), 'shiny.pal'))))
            pending = []
    entries = entries[:251]
    assert len(entries) == 251, len(entries)
    with open(out, 'w') as f:
        f.write('// Generated by tools/moemon_legacy/gbpal_species.py from pret/pokecrystal: do not edit.\n')
        f.write('// Crystal\'s colours for each POKeMON: [species][normal, shiny][light, dark]\n')
        f.write('static const u16 sGbCrystalMonPals[252][2][2] = {\n    {{0, 0}, {0, 0}},\n')
        for n, s in entries:
            f.write('    {{0x%04X, 0x%04X}, {0x%04X, 0x%04X}},\n' % (n[0], n[1], s[0], s[1]))
        f.write('};\n')
    print('wrote', out, len(entries))

main()
