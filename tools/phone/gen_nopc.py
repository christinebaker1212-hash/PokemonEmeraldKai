#!/usr/bin/env python3
"""Maps where the phone can't move POKeMON between the party and the PC (docs/COMPANION_APP.md "Boxes, party and BAG":
the BATTLE FRONTIERs and the Elite Four in every region; caves and the Underground are left out by their map type,
src/mp/mp_phone.c PcReachable) as src/data/mp_phone_nopc.h, from include/constants/map_groups.h.

    python3 tools/phone/gen_nopc.py     (run from the repository)
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KEEP = re.compile(r'POKEMON_CENTER|POKECENTER|_MART')
OFF = re.compile(r'BATTLE_FRONTIER|^MAP_SINNOH_BATTLE_|^MAP_BATTLE_|TRAINER_HILL|BATTLE_TOWER|BATTLE_PYRAMID|BATTLE_PIKE'
                 r'|EVER_GRANDE_CITY_(SIDNEYS|PHOEBES|GLACIAS|DRAKES|CHAMPIONS)_ROOM|EVER_GRANDE_CITY_HALL\d'
                 r'|EVER_GRANDE_CITY_HALL_OF_FAME|POKEMON_LEAGUE_(AARON|BERTHA|FLINT|LUCIAN|CHAMPION|ELEVATOR|HALL)'
                 r'|POKEMON_LEAGUE_(LORELEIS|BRUNOS|AGATHAS|LANCES|CHAMPIONS)_ROOM|^MAP_JOHTO_(WILLS|KOGAS|BRUNOS|KARENS'
                 r'|LANCES)_ROOM|HALL_OF_FAME')


def main():
    text = open(os.path.join(ROOT, 'include/constants/map_groups.h')).read()
    names = re.findall(r'^\s+(MAP_[A-Z0-9_]+)\s*=', text, re.M)
    off = [n for n in names if OFF.search(n) and not KEEP.search(n)]
    out = ('// Generated by tools/phone/gen_nopc.py from include/constants/map_groups.h. Do not edit.\n'
           '// Maps where the phone can\'t move POKeMON between the party and the PC (src/mp/mp_phone.c PcReachable)\n'
           'static const u16 sPhoneNoPcMaps[] = {\n' + ''.join('    %s,\n' % n for n in off) + '};\n')
    open(os.path.join(ROOT, 'src/data/mp_phone_nopc.h'), 'w').write(out)
    print('src/data/mp_phone_nopc.h: %d maps' % len(off))


if __name__ == '__main__':
    main()
