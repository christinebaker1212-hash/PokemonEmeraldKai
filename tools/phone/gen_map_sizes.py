#!/usr/bin/env python3
"""How many maps each map group holds (data/maps/map_groups.json), for code that walks every map
(src/mp/mp_phone_dev.c: the live map's places). Run by the Makefile (json_data_rules.mk)."""
import json, sys

out, src = sys.argv[1], sys.argv[2]
d = json.load(open(src))
sizes = [len(d[g]) for g in d["group_order"]]
with open(out, "w") as f:
    f.write("// Generated by tools/phone/gen_map_sizes.py from data/maps/map_groups.json: maps in each group\n")
    f.write("static const u8 sMapGroupSizes[MAP_GROUPS_COUNT] = {%s};\n" % ", ".join(map(str, sizes)))
