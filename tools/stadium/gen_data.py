#!/usr/bin/env python3
"""POKéMON STADIUM's trainers, teams and rentals as the game's data (docs/STADIUM.md, docs/stadium/RULES.md).

    python3 tools/stadium/extract.py ROM.z64 /tmp/stadium.json      (the user's ROM, never committed)
    python3 tools/stadium/gen_data.py /tmp/stadium.json src/data/mp_stadium_data.h   (and include/constants/stadium.h)

Everything as the ROM has it: names, nicknames, OT IDs, levels, moves, DVs and stat EXP. The game turns DVs and stat EXP
into IVs, EVs and a nature when it builds a POKéMON (src/mp/mp_stadium.c StadiumMon_Build), where it can read the moves'
categories and the species' base stats. The dup Poké Cup blocks (8, 9, 39, 40) and Battle Now are left out.
"""
import json
import os
import sys

# Stadium's trainer classes -> the game's pictures (KANTO's FireRed pictures: TRAINER_PIC values as trainers_qz.h uses them)
PICS = {
    'COOL\xbe': 169, 'COOL\xa9': 168, 'BEAUTY': 157, 'JR.\xbe': 146, 'JR.\xa9': 145, 'GAMBLER': 156, 'PSYCHIC': 159,
    'OLD MAN': 170, 'JUGGLER': 161, 'CUEBALL': 155, 'LAB MAN': 166, 'LASS': 143, 'ROCKET': 167, 'BURGLAR': 151,
    'PKMNIAC': 147, 'SWIMMER': 154, 'MEDIUM': 172, 'JUDOBOY': 164, 'HIKER': 149, 'SAILOR': 144, 'LAD': 141,
    'BUG BOY': 142, 'BIRDBOY': 163, 'FISHER': 153, 'ROCKER': 160, 'MR.FIX': 152, 'BIKER': 150, 'TAMER': 162,
    'NERD': 148, 'BROCK': 128, 'MISTY': 129, 'SURGE': 130, 'ERIKA': 131, 'KOGA': 132, 'SABRINA': 133, 'BLAINE': 134,
    'GIOVANI': 135, 'LORELEI': 136, 'BRUNO': 137, 'AGATHA': 138, 'LANCE': 139, 'RIVAL': 140, 'MEWTWO': 0,
}

CUPS = [   # (constant, ROM block for Round 1, Round 2 = +31)
    ('STADIUM_PETIT', 0), ('STADIUM_PIKA', 1),
    ('STADIUM_PRIME_POKE', 2), ('STADIUM_PRIME_GREAT', 3), ('STADIUM_PRIME_ULTRA', 4), ('STADIUM_PRIME_MASTER', 5),
    ('STADIUM_POKE_POKE', 6), ('STADIUM_POKE_GREAT', 7), ('STADIUM_POKE_ULTRA', 10), ('STADIUM_POKE_MASTER', 11),
] + [('STADIUM_GYM_%d' % i, 11 + i) for i in range(1, 9)] + [
    ('STADIUM_ELITE_FOUR', 20), ('STADIUM_RIVAL', 21), ('STADIUM_MEWTWO', 22)]
RENTALS = [('STADIUM_RENT_PETIT', 23), ('STADIUM_RENT_PIKA', 24), ('STADIUM_RENT_PRIME', 25), ('STADIUM_RENT_POKE', 26),
           ('STADIUM_RENT_CASTLE', 30)]


def text(s):
    s = s.strip().replace('\xbe', '♀').replace('\xa9', '♂').replace('\n', '')
    return s.replace('"', '\\"')


def main():
    d = json.load(open(sys.argv[1]))
    mons, trainers, cups, rentals = [], [], [], []

    def add_mon(m):
        mons.append(m)
        return len(mons) - 1

    for rnd in range(2):
        for const, blk in CUPS:
            b = d[blk + 31 * rnd]
            first = len(trainers)
            for t in b['trainers']:
                name = t['name'].strip()
                cls = t['class'].strip()
                pic = PICS.get(name, PICS.get(cls))
                if pic is None:
                    sys.exit('no picture for %r / %r' % (name, cls))
                fm = len(mons)
                for m in t['pokemon']:
                    add_mon(m)
                trainers.append((name, pic, t['unknown'][0], fm, len(t['pokemon'])))
            cups.append((const, rnd, first, len(trainers) - first))
        for const, blk in RENTALS:
            b = d[blk + 31 * rnd]
            fm = len(mons)
            for m in b['pokemon']:
                add_mon(m)
            rentals.append((const, rnd, fm, len(b['pokemon'])))
    for m in mons:
        assert 1 <= m['dex'] <= 151 and all(1 <= x <= 165 for x in m['moves']), m

    ids = ['// Generated by tools/stadium/gen_data.py. Do not edit.', '#pragma once', '', 'enum {']
    ids += ['    %s,' % c for c, _ in CUPS]
    ids += ['    STADIUM_DIVISION_COUNT,', '};', 'enum {']
    ids += ['    %s,' % c for c, _ in RENTALS]
    ids += ['    STADIUM_RENTAL_LIST_COUNT,', '};']
    open(os.path.join(os.path.dirname(sys.argv[2]), '..', '..', 'include', 'constants', 'stadium.h'), 'w').write('\n'.join(ids) + '\n')
    o = ['// Generated by tools/stadium/gen_data.py from the user\'s POKéMON STADIUM ROM. Do not edit.', '#pragma once', '']
    o.append('static const struct StadiumMon sStadiumMons[] = {')
    for m in mons:
        mv = (m['moves'] + [0, 0, 0, 0])[:4]
        o.append('    {%d, %d, {%s}, 0x%04X, {%s}, %d, _("%s"), _("%s")},' % (
            m['dex'], m['level'], ', '.join(map(str, mv)), m['dvs'], ', '.join(map(str, m['statexp'])), m['otid'],
            text(m['nickname']), text(m['ot'])))
    o.append('};')
    o.append('')
    o.append('static const struct StadiumTrainer sStadiumTrainers[] = {')
    for name, pic, ai, fm, n in trainers:
        o.append('    {_("%s"), %d, %d, %d, %d},' % (text(name), pic, ai, fm, n))
    o.append('};')
    o.append('')
    o.append('// [round][division]: the first trainer and how many')
    o.append('static const struct StadiumRange sStadiumDivisions[2][STADIUM_DIVISION_COUNT] = {')
    for rnd in range(2):
        o.append('    {' + ', '.join('[%s] = {%d, %d}' % (c, f, n) for c, r, f, n in cups if r == rnd) + '},')
    o.append('};')
    o.append('static const struct StadiumRange sStadiumRentals[2][STADIUM_RENTAL_LIST_COUNT] = {')
    for rnd in range(2):
        o.append('    {' + ', '.join('[%s] = {%d, %d}' % (c, f, n) for c, r, f, n in rentals if r == rnd) + '},')
    o.append('};')
    open(sys.argv[2], 'w').write('\n'.join(o) + '\n')
    print('%d POKéMON, %d trainers' % (len(mons), len(trainers)))


if __name__ == '__main__':
    main()
