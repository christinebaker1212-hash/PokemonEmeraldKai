#!/usr/bin/env python3
"""The CHALLENGE CUP's tables (STADIUM 2's, the user's special case: docs/stadium/RULES.md) from
tools/stadium/challenge_cup.json into src/data/mp_stadium_cc.h.

    python3 tools/stadium/gen_challenge.py tools/stadium/challenge_cup.json src/data/mp_stadium_cc.h
"""
import json
import re
import sys

PICS = {   # STADIUM 2's trainer classes -> TRAINER_PIC values (KANTO's / JOHTO's pictures as trainers_qz.h uses them)
    'CAMPER': 145, 'ROCKET': 167, 'PICNICKER': 146, 'GUITARIST': 'TRAINER_PIC_GUITARIST', 'FISHER': 153, 'MEDIUM': 172,
    'JUGGLER': 161, 'TWINS': 'TRAINER_PIC_TWINS', 'SCHOOLBOY': 'TRAINER_PIC_SCHOOL_KID_M', 'SAILOR': 144,
    'SWIMMER': 158, 'OFFICER': 'TRAINER_PIC_POKEMON_RANGER_M', 'KIMONO GIRL': 55, 'SCIENTIST': 166, 'GENTLEMAN': 170,
}


def move_const(name):
    name = {'POISONPOWDER': 'POISON POWDER', 'SOLARBEAM': 'SOLAR BEAM'}.get(name, name)   # STADIUM 2's spellings
    return 'MOVE_' + re.sub(r'[^A-Z0-9]+', '_', name.upper()).strip('_')


def main():
    d = json.load(open(sys.argv[1]))
    o = ['// Generated by tools/stadium/gen_challenge.py from tools/stadium/challenge_cup.json. Do not edit.', '#pragma once', '']
    o.append('static const struct StadiumCcMon sStadiumCcPool[] = {')
    starts = []
    for c in d['classes']:
        starts.append(len([l for l in o if l.startswith('    {')]))
        for m in c['pool']:
            name = m['name']
            split = len(re.match(r"[A-Z.'\-♂♀ ]*", name).group(0))
            types = ['TYPE_' + t.upper() for t in m['types']]
            o.append('    {%d, %d, %d, %d, {%s, %s}},' % (m['dex'], split, m['bst'], int(m['rate'] * 10),
                                                   types[0], types[-1]))
    count = len([l for l in o if l.startswith('    {')])
    o.append('};')
    o.append('')
    o.append('static const struct StadiumCcClass sStadiumCcClasses[4] = {')
    for i, c in enumerate(d['classes']):
        end = starts[i + 1] if i + 1 < 4 else count
        o.append('    {%d, %d, %d, %d},' % (c['level'], c['bst_target'], starts[i], end - starts[i]))
    o.append('};')
    o.append('')
    o.append('static const struct StadiumCcTrainer sStadiumCcTrainers[4][8] = {')
    for c in d['classes']:
        rows = []
        for t in c['trainers']:
            tmpl = []
            for k, v in t['template'].items():
                tmpl += ['TYPE_NONE' if k == 'ANY' else 'TYPE_' + k] * v
            moves = [move_const(m) for m in t['moves']] + ['MOVE_NONE'] * (7 - len(t['moves']))
            pic = PICS[t['class']]
            name = t['name'].split('/')[0]
            rows.append('        {_("%s"), _("%s"), %s, {%s}, {%s}, {%d, %d}, {%d, %d}},' % (
                t['class'], name, pic, ', '.join(map(str, tmpl)), ', '.join(moves), t['statexp'][0], t['statexp'][1],
                t['speed'][0] or 0, t['speed'][1] or 0))
        o.append('    {\n' + '\n'.join(rows) + '\n    },')
    o.append('};')
    o.append('')
    o.append('static const u8 sStadiumCcPlayerTemplates[6][3] = {')
    for t in d['player_templates']:
        o.append('    {%s},' % ', '.join('TYPE_' + x for x in t))
    o.append('};')
    open(sys.argv[2], 'w').write('\n'.join(o) + '\n')
    print('%d pool entries' % count)


if __name__ == '__main__':
    main()
