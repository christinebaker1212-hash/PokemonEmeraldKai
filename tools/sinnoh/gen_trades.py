#!/usr/bin/env python3
"""Platinum's in-game trades (res/npc_trades/*.json, numbered as include/constants/npc_trades.h: KAZZA's ABRA,
CHARAP's CHATOT, GASPAR's HAUNTER, FOPPA's MAGIKARP) as the game's in-game trade table: src/data/sinnoh_ingame_trades.h
(src/trade.c uses it in SINNOH; Platinum's InitNPCTrade / StartNPCTrade in src/sinnoh/s3d_party.c).

Platinum makes the POKeMON as NPCTrade_CreateMon does: its personality and OT ID, its six IVs, its contest stats,
its held item, its OT's name and gender, its language; the ability is the personality's lowest bit (Gen 4's rule).

    python3 -I tools/sinnoh/gen_trades.py POKEPLATINUM_DIR     (run from the repository)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    root = sys.argv[1]
    ids = re.findall(r'(NPC_TRADE_\w+)', open(os.path.join(root, 'include/constants/npc_trades.h')).read())
    ids = [i for i in ids if i != 'NPC_TRADE_ID' and not i.startswith('NPC_TRADE_ID')]
    rows = []
    for n, tid in enumerate(i for i in ids if i != 'MAX_NPC_TRADES'):
        path = os.path.join(root, 'res/npc_trades', tid[len('NPC_TRADE_'):].lower() + '.json')
        d = json.load(open(path, encoding='utf-8'))
        rows.append(
            '    [%d] = {   // %s\n'
            '        .nickname = _("%s"), .species = %s,\n'
            '        .ivs = {%d, %d, %d, %d, %d, %d}, .abilityNum = %d, .otId = %d,\n'
            '        .conditions = {%d, %d, %d, %d, %d}, .personality = %d, .heldItem = %s, .mailNum = -1,\n'
            '        .otName = _("%s"), .otGender = %s, .sheen = 0, .requestedSpecies = %s, .language = %s,\n'
            '    },' % (n, tid, d['name'], d['species'], d['hpIV'], d['atkIV'], d['defIV'], d['speedIV'], d['spAtkIV'],
                       d['spDefIV'], d['personality'] & 1, d['otID'], d['cool'], d['beauty'], d['cute'], d['smart'],
                       d['tough'], d['personality'], d['heldItem'], d['otName'],
                       'FEMALE' if d['otGender'] == 'GENDER_FEMALE' else 'MALE', d['requestedSpecies'], d['language']))
    out = ('// Generated by tools/sinnoh/gen_trades.py from pret/pokeplatinum res/npc_trades. Do not edit.\n'
           '// SINNOH\'s in-game trades, numbered as Platinum\'s NPC_TRADE_* (src/trade.c InGameTrade)\n'
           'static const struct InGameTrade sSinnohIngameTrades[] =\n{\n' + '\n'.join(rows) + '\n};\n')
    open(os.path.join(ROOT, 'src/data/sinnoh_ingame_trades.h'), 'w').write(out)
    print('src/data/sinnoh_ingame_trades.h: %d trades' % len(rows))


if __name__ == '__main__':
    main()
