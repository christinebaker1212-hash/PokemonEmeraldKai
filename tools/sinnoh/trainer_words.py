def lines(platinum_class, key):
    """(intro, defeat, after) for a trainer of a Platinum class (without TRAINER_CLASS_), the same each time for a key"""
    fam = LINES[FAMILY.get(platinum_class, 'ace')]
    h = 0
    for ch in key:
        h = (h * 31 + ord(ch)) & 0xFFFFFFFF
    return fam[h % len(fam)]
