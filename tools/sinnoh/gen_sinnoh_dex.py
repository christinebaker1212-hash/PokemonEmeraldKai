#!/usr/bin/env python3
"""Platinum's SINNOH POKéDEX (its 210, in its order) as this game's species: src/data/sinnoh_dex.h, for Platinum's
scripts that count it (GetLocalDexSeenCount, CheckLocalDexCompleted: src/sinnoh/s3d_scrcmd.c SINNOH_LOCAL_DEX).

    python3 tools/sinnoh/gen_sinnoh_dex.py CSV_DIR     (PokeAPI's data/v2/csv: pokemon_dex_numbers.csv, pokemon_species.csv)

PokeAPI's pokedex 6 is Platinum's ("extended-sinnoh"). Species by name: a PokeAPI identifier as this game's constant
(mr-mime -> SPECIES_MR_MIME).
"""
import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SPECIAL = {'nidoran-f': 'NIDORAN_F', 'nidoran-m': 'NIDORAN_M', 'mime-jr': 'MIME_JR', 'mr-mime': 'MR_MIME'}


def main():
    d = sys.argv[1]
    names = {r['id']: r['identifier'] for r in csv.DictReader(open(os.path.join(d, 'pokemon_species.csv')))}
    rows = sorted((int(r['pokedex_number']), names[r['species_id']])
                  for r in csv.DictReader(open(os.path.join(d, 'pokemon_dex_numbers.csv'))) if r['pokedex_id'] == '6')
    ours = set(re.findall(r'#define (SPECIES_\w+)\s', open(os.path.join(ROOT, 'include/constants/species.h')).read()))
    out = []
    for n, ident in rows:
        c = 'SPECIES_' + SPECIAL.get(ident, ident.upper().replace('-', '_'))
        if c not in ours:
            sys.exit('no %s here' % c)
        out.append(c)
    text = ('// Generated by tools/sinnoh/gen_sinnoh_dex.py: Platinum\'s SINNOH POKéDEX, in its order. Do not edit.\n'
            'static const u16 sSinnohDex[] = {\n' + ''.join('    %s,\n' % c for c in out) + '};\n')
    open(os.path.join(ROOT, 'src/data/sinnoh_dex.h'), 'w').write(text)
    print('%d species' % len(out))


if __name__ == '__main__':
    main()
