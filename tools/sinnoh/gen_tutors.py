#!/usr/bin/env python3
"""Platinum's move tutors (res/pokemon/move_tutors.json: each move, its RED / BLUE / YELLOW / GREEN SHARD costs and the
tutor who teaches it, ROUTE 212's, the SURVIVAL AREA's or SNOWPOINT's; each species' res/pokemon/<species>/data.json
learnset "by_tutor") as the game's tables: src/data/sinnoh_tutors.h (src/sinnoh/s3d_party.c, Platinum's
CheckHasLearnableTutorMoves / ShowMoveTutorMoveSelectionMenu / CheckCanAffordMove / PayShardCost / ShowShardCost).

    python3 -I tools/sinnoh/gen_tutors.py POKEPLATINUM_DIR     (run from the repository)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    root = sys.argv[1]
    ours_species = set(re.findall(r'#define (SPECIES_\w+)\s', open(os.path.join(ROOT, 'include/constants/species.h')).read()))
    ours_moves = set(re.findall(r'#define (MOVE_\w+)\s', open(os.path.join(ROOT, 'include/constants/moves.h')).read()))
    locations = [x.strip() for x in open(os.path.join(root, 'generated/tutor_locations.txt')) if x.strip()]
    tutors = json.load(open(os.path.join(root, 'res/pokemon/move_tutors.json'), encoding='utf-8'))
    index = {}
    rows = []
    for n, t in enumerate(tutors):
        if t['move'] not in ours_moves:
            sys.exit('%s is not in this game' % t['move'])
        index[t['move']] = n
        rows.append('    {%s, %d, %d, %d, %d, %d},   // %s' % (t['move'], t['redCost'], t['blueCost'], t['yellowCost'],
                                                            t['greenCost'], locations.index(t['location']), t['location']))
    size = (len(tutors) + 7) // 8
    masks, missing = [], []
    pdir = os.path.join(root, 'res/pokemon')
    for name in sorted(os.listdir(pdir)):
        path = os.path.join(pdir, name, 'data.json')
        if not os.path.exists(path):
            continue
        d = json.load(open(path, encoding='utf-8'))
        moves = (d.get('learnset') or {}).get('by_tutor') or []
        if not moves:
            continue
        sp = 'SPECIES_' + name.upper()
        if sp not in ours_species:
            missing.append(sp)
            continue
        bits = [0] * size
        for m in moves:
            if m in index:
                bits[index[m] // 8] |= 1 << (index[m] % 8)
        masks.append('    [%s] = {%s},' % (sp, ', '.join('0x%02X' % b for b in bits)))
    out = ('// Generated by tools/sinnoh/gen_tutors.py from pret/pokeplatinum res/pokemon. Do not edit.\n'
           '// Platinum\'s move tutors: {move, RED, BLUE, YELLOW, GREEN SHARDS, tutor (0 ROUTE 212, 1 SURVIVAL AREA,\n'
           '// 2 SNOWPOINT CITY)}, and which of them each species learns (a bit per move, in this order)\n'
           '#define SINNOH_TUTOR_COUNT %d\n'
           'static const u16 sSinnohTutorMoves[SINNOH_TUTOR_COUNT][6] = {\n%s\n};\n'
           'static const u8 sSinnohTutorMask[NUM_SPECIES][%d] = {\n%s\n};\n'
           % (len(tutors), '\n'.join(rows), size, '\n'.join(masks)))
    open(os.path.join(ROOT, 'src/data/sinnoh_tutors.h'), 'w').write(out)
    print('src/data/sinnoh_tutors.h: %d moves, %d species%s' % (len(tutors), len(masks),
                                                                 ', not here: ' + ' '.join(missing) if missing else ''))


if __name__ == '__main__':
    main()
