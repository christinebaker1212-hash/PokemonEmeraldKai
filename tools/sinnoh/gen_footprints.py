#!/usr/bin/env python3
"""Platinum's footprints (res/pokemon/<species>/data.json "footprint": whether it leaves one, and DR. FOOTSTEP's
type for it: FOOTPRINT_TYPE_CUTE / TOUGH / SCARY / SLOW / SILENT) as the game's table, by this game's species:
src/data/sinnoh_footprints.h (src/sinnoh/s3d_party.c, Platinum's GetPartyMonFootprintType).

    python3 -I tools/sinnoh/gen_footprints.py POKEPLATINUM_DIR     (run from the repository)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TYPES = {'FOOTPRINT_TYPE_NONE': 0, 'FOOTPRINT_TYPE_CUTE': 1, 'FOOTPRINT_TYPE_TOUGH': 2, 'FOOTPRINT_TYPE_SCARY': 3,
         'FOOTPRINT_TYPE_SLOW': 4, 'FOOTPRINT_TYPE_SILENT': 5}


def main():
    root = sys.argv[1]
    ours = set(re.findall(r'#define (SPECIES_\w+)\s', open(os.path.join(ROOT, 'include/constants/species.h')).read()))
    rows, missing = [], []
    pdir = os.path.join(root, 'res/pokemon')
    for name in sorted(os.listdir(pdir)):
        path = os.path.join(pdir, name, 'data.json')
        if not os.path.exists(path):
            continue
        d = json.load(open(path, encoding='utf-8'))
        f = d.get('footprint')
        if not f:
            continue
        sp = 'SPECIES_' + name.upper()
        if sp not in ours:
            missing.append(sp)
            continue
        rows.append('    [%s] = {%d, %d},' % (sp, 1 if f.get('has') else 0, TYPES.get(f.get('type'), 0)))
    out = ('// Generated by tools/sinnoh/gen_footprints.py from pret/pokeplatinum res/pokemon. Do not edit.\n'
           '// Platinum\'s footprints: {leaves one, DR. FOOTSTEP\'s type 1 CUTE, 2 TOUGH, 3 SCARY, 4 SLOW, 5 SILENT}\n'
           'static const u8 sSinnohFootprints[NUM_SPECIES][2] = {\n' + '\n'.join(rows) + '\n};\n')
    open(os.path.join(ROOT, 'src/data/sinnoh_footprints.h'), 'w').write(out)
    print('src/data/sinnoh_footprints.h: %d species%s' % (len(rows), ', not here: ' + ' '.join(missing) if missing else ''))


if __name__ == '__main__':
    main()
