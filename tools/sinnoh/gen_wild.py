#!/usr/bin/env python3
"""SINNOH's wild POKéMON (docs/SINNOH_HANDOFF.md step 3): each kept place's encounter table from pret/pokeplatinum
(res/field/encounters/<wildEncountersArchiveID>.json: species and levels) as the game's own wild tables, entries of
src/data/wild_encounters.json's gWildMonHeaders, as JOHTO's and KANTO's are.

    python3 -I tools/sinnoh/gen_wild.py POKEPLATINUM_DIR     (run from the repository; safe to run again)

Platinum's slots line up with Emerald's: grass has the same 12 slots and rates, surfing the same 5. Fishing: Emerald
has 10 slots (OLD ROD 2, GOOD ROD 3, SUPER ROD 5), Platinum 5 a rod: the first 2 / 3 / 5 of each.

Platinum's grass slots 2 and 3 change by the time of day (the table's are the morning's) and slots 0 and 1 hold the
day's swarm on its route: src/data/sinnoh_wild_extra.h (src/sinnoh/s3d_wild.c), with the swarms' routes and the
HONEY trees' POKéMON and the TROPHY GARDEN's daily ones. (The POKé RADAR's and a GBA game's slots aren't used.)
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from source import open_source  # noqa: E402
from places import places  # noqa: E402
from gen_maps import ident  # noqa: E402

LABEL = 'gSinnoh_'


def table(rate, mons, take=None):
    mons = [m for m in mons if m['species'] != 'SPECIES_NONE']
    if not rate or not mons:
        return None
    return {'encounter_rate': rate, 'mons': mons}


def land(d):
    mons = [{'min_level': e['level'], 'max_level': e['level'], 'species': e['species']} for e in d['land_encounters']]
    if len(mons) != 12 or any(m['species'] == 'SPECIES_NONE' for m in mons):
        return None
    return table(d['land_rate'], mons)


def ranged(e):
    return {'min_level': min(e['level_min'], e['level_max']), 'max_level': max(e['level_min'], e['level_max']),
            'species': e['species']}


def water(d):
    mons = [ranged(e) for e in d['surf_encounters']]
    if len(mons) != 5 or any(m['species'] == 'SPECIES_NONE' for m in mons):
        return None
    return table(d['surf_rate'], mons)


def fishing(d):
    old, good, sup = d['old_rod_encounters'][:2], d['good_rod_encounters'][:3], d['super_rod_encounters'][:5]
    mons = [ranged(e) for e in old + good + sup]
    if len(mons) != 10 or any(m['species'] == 'SPECIES_NONE' for m in mons):
        return None
    return table(max(d['old_rod_rate'], d['good_rod_rate'], d['super_rod_rate']), mons)


# Platinum's swarm routes (src/overlay006/swarm.c sSwarmMapIdTable, its order) and HONEY trees' places
# (src/overlay005/honey_tree.c sHoneyTreeMapHeaderIDs, its order: a tree's number)
SWARMS = ['ROUTE_201', 'ROUTE_202', 'ROUTE_203', 'ROUTE_206', 'ROUTE_207', 'ROUTE_208', 'ROUTE_209', 'ROUTE_214',
          'ROUTE_215', 'ROUTE_217', 'ROUTE_218', 'ROUTE_221', 'ROUTE_222', 'ROUTE_224', 'ROUTE_225', 'ROUTE_226',
          'ROUTE_227', 'ROUTE_228', 'ROUTE_229', 'ROUTE_230', 'VALLEY_WINDWORKS_OUTSIDE', 'ETERNA_FOREST']
HONEY_TREES = ['ROUTE_205_SOUTH', 'ROUTE_205_NORTH', 'ROUTE_206', 'ROUTE_207', 'ROUTE_208', 'ROUTE_209',
               'ROUTE_210_SOUTH', 'ROUTE_210_NORTH', 'ROUTE_211_EAST', 'ROUTE_212_NORTH', 'ROUTE_212_SOUTH', 'ROUTE_213',
               'ROUTE_214', 'ROUTE_215', 'ROUTE_218', 'ROUTE_221', 'ROUTE_222', 'VALLEY_WINDWORKS_OUTSIDE',
               'ETERNA_FOREST_OUTSIDE', 'FUEGO_IRONWORKS_OUTSIDE', 'FLOAROMA_MEADOW']


def map_id(name):
    return 'MAP_SINNOH_' + ident('MAP_HEADER_' + name)[0]


def write_extra(root, timed):
    honey = json.load(open(os.path.join(root, 'res/field/encounters/encounters_honey_tree.json')))
    trophy = json.load(open(os.path.join(root, 'res/field/encounters/encounters_trophy_garden.json')))
    rows = ''.join('    {%s, {%s}, {%s}, {%s}, {%s}},\n' % (m, ', '.join(b), ', '.join(d), ', '.join(n), ', '.join(w))
                   for m, b, d, n, w in timed)
    open('src/data/sinnoh_wild_extra.h', 'w').write(
        '// Generated by tools/sinnoh/gen_wild.py from Platinum\'s encounter tables: grass slots 0-3 as the table has them\n'
        '// (the morning\'s), slots 2-3 by day and by night, slots 0-1 in a swarm (src/sinnoh/s3d_wild.c)\n'
        'static const struct SinnohTimedSlots { u16 map; u16 base[4], day[2], night[2], swarm[2]; } sTimed[] = {\n'
        + rows + '};\n\n// the routes a swarm can come to, in Platinum\'s order\n'
        'static const u16 sSwarmMaps[] = {\n' + ''.join('    %s,\n' % map_id(m) for m in SWARMS) + '};\n\n'
        '// the HONEY trees\' places (a tree\'s number: its place here) and their POKéMON: groups A, B and C (MUNCHLAX)\n'
        'static const u16 sHoneyMaps[] = {\n' + ''.join('    %s,\n' % map_id(m) for m in HONEY_TREES) + '};\n'
        'static const u16 sHoneyMons[3][6] = {\n' + ''.join('    {%s},\n' % ', '.join(honey[k]) for k in
                                                            ('common', 'uncommon', 'rare')) + '};\n\n'
        '// the TROPHY GARDEN: MR. BACKLOT\'s daily POKéMON, in its grass slots 6-7 (the table\'s: sTrophyBase)\n'
        'static const u16 sTrophyBase[2] = {%s};\n' % ', '.join(e['species'] for e in trophy['land_encounters'][6:8]) +
        'static const u16 sTrophyMons[] = {\n' + ''.join('    %s,\n' % m for m in trophy['daily_encounters']) + '};\n')


def main():
    root = sys.argv[1]
    src = open_source(root)
    path = 'src/data/wild_encounters.json'
    data = json.load(open(path))
    headers = data['wild_encounter_groups'][0]
    headers['encounters'] = [e for e in headers['encounters'] if not e.get('base_label', '').startswith(LABEL)]
    added = 0
    timed = []
    for p in sorted(places(src, root), key=lambda p: p['header']):
        name = p['fields'].get('wildEncountersArchiveID')
        file = os.path.join(root, 'res/field/encounters', (name or '') + '.json')
        if not name or not os.path.exists(file):
            continue
        d = json.load(open(file))
        const, camel = ident(p['header'])
        entry = {'map': 'MAP_SINNOH_' + const, 'base_label': LABEL + camel}
        for key, t in (('land_mons', land(d)), ('water_mons', water(d)), ('fishing_mons', fishing(d))):
            if t:
                entry[key] = t
        if 'land_mons' in entry:
            base = [e['species'] for e in d['land_encounters'][:4]]
            day, night, swarm = d.get('day') or base[2:4], d.get('night') or base[2:4], d.get('swarms') or base[:2]
            if day != base[2:4] or night != base[2:4] or swarm != base[:2]:
                timed.append((entry['map'], base, day, night, swarm))
        if len(entry) > 2:
            headers['encounters'].append(entry)
            added += 1
    json.dump(data, open(path, 'w'), indent=2)
    open(path, 'a').write('\n')
    write_extra(root, sorted(timed))
    print('%d SINNOH places with wild POKéMON (%d with timed / swarm slots)' % (added, len(timed)))


if __name__ == '__main__':
    main()
