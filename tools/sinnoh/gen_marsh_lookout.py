#!/usr/bin/env python3
"""The GREAT MARSH lookout's spots (PASTORIA's observatory binoculars, Platinum's great_marsh_lookout.c: five looks at
the marsh, each at one of 36 spots of the ROM's encdata_ex member 11, its coordinates not in the decomp): here six
spots in each of the six areas, on marsh grass (TILE_BEHAVIOR_MUD_WITH_GRASS / MUD_DEEP_WITH_GRASS), picked once with a
fixed seed from matrix 240's land data, in the marsh map's tiles (Sinnoh_GreatMarsh6 holds the whole marsh). Writes
src/data/sinnoh_marsh_lookout.h (src/sinnoh/s3d_binoculars.c).

    python3 -I tools/sinnoh/gen_marsh_lookout.py POKEPLATINUM_DIR
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build_pack as b  # noqa: E402

GRASS = (0xA6, 0xA7)


def main():
    src = b.open_source(sys.argv[1])
    mt = src.matrix(240)
    rng = random.Random(240)
    spots = []
    for cz in range(mt.height):
        for cx in range(mt.width):
            lid, header, _ = mt.cell(cx, cz)
            if not header.startswith('MAP_HEADER_GREAT_MARSH_'):
                continue
            land = b.Land(src.land(lid))
            # (away from the cell's edge, so the view's middle is the area's)
            tiles = [i for i, a in enumerate(land.attrs) if a & 0xFF in GRASS and 4 <= i % 32 < 28 and 4 <= i // 32 < 28]
            for i in sorted(rng.sample(tiles, 6)):
                spots.append((cx * 32 + i % 32, cz * 32 + i // 32, header))
    out = os.path.join(HERE, '..', '..', 'src', 'data', 'sinnoh_marsh_lookout.h')
    with open(out, 'w') as f:
        f.write('// Generated by tools/sinnoh/gen_marsh_lookout.py. Do not edit.\n'
                '// The GREAT MARSH lookout\'s 36 spots: six on marsh grass in each area, the marsh map\'s tiles\n')
        f.write('static const u8 sMarshLookout[%d][2] = {\n' % len(spots))
        for x, y, h in spots:
            f.write('    {%d, %d},   // (%s)\n' % (x, y, h[len('MAP_HEADER_'):]))
        f.write('};\n')
    print('%s: %d spots' % (os.path.relpath(out), len(spots)))


if __name__ == '__main__':
    main()
