#!/usr/bin/env python3
"""SINNOH's shops, as Platinum stocks them (pret/pokeplatinum include/data/mart_items.h; only items and badge counts reach
the repository): the common clerk's list grows with the region's badges (src/data/sinnoh_marts.h, read by shop.c's
`pokemart 0` in SINNOH), each specialty clerk (a town's own goods, the department store's counters, the herb shop)
sells its list (data/scripts/sinnoh_marts.inc). Items the game doesn't have (Platinum's mail) are left out.

    python3 -I tools/sinnoh/gen_marts.py POKEPLATINUM_DIR      (then gen_words.py and gen_maps.py)

gen_words.py roles() gives each vendor its kind: ('mart',) for the common clerk, ('martlist', LABEL) for the others.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import items  # noqa: E402

# Platinum's requiredBadges -> the badge count it means (1: from the start .. 6: all eight)
BADGES = {1: 0, 2: 1, 3: 3, 4: 5, 5: 7, 6: 8}


def our(item):
    item = items.RENAME.get(item, item)
    return item if item in items.own() else None


def lists(root):
    """(common [(item, badges)], {MART_SPECIALTIES_ID_X: [items]})"""
    text = open(os.path.join(root, 'include/data/mart_items.h'), encoding='utf-8').read()
    common = []
    for item, need in re.findall(r'\{ (ITEM_\w+), (0x[0-9A-Fa-f]+|\d+) \}', text.split('const u16')[0]):
        if our(item):
            common.append((our(item), BADGES[int(need, 0)]))
    arrays = {name: re.findall(r'(ITEM_\w+)', body)
              for name, body in re.findall(r'const u16 (\w+)\[\] = \{(.*?)\};', text, re.S)}
    table = dict(re.findall(r'\[(MART_SPECIALTIES_ID_\w+)\] = (\w+)', text))
    special = {}
    for mid, array in table.items():
        special[mid] = [i for i in (our(x) for x in arrays.get(array, [])) if i]
    return common, special


def vendor_kind(root, place_file):
    """{Platinum script entry name: ('mart',) or ('martlist', label)} for one place's vendors"""
    path = os.path.join(root, 'res/field/scripts/scripts_%s.s' % place_file)
    if not os.path.exists(path):
        return {}
    text = open(path, encoding='utf-8', errors='replace').read()
    out = {}
    for name, body in re.findall(r'^(\w+):\s*\n(.*?)(?=^\w+:|\Z)', text, re.S | re.M):
        if re.search(r'PokeMartCommon', body):
            out[name] = ('mart',)
        else:
            m = re.search(r'PokeMartSpecialties\w* (MART_SPECIALTIES_ID_\w+)', body)
            if m:
                out[name] = ('martlist', label(m.group(1)))
    return out


def label(mid):
    return 'Sinnoh_Mart_' + ''.join(p.capitalize() for p in mid[len('MART_SPECIALTIES_ID_'):].split('_'))


def main():
    root = sys.argv[1]
    common, special = lists(root)
    head = '// Generated by tools/sinnoh/gen_marts.py. Do not edit.\n'
    open('src/data/sinnoh_marts.h', 'w').write(
        head + '// SINNOH\'s common clerk: each item and the badges it waits for (Platinum\'s PokeMartCommonItems)\n'
        'static const struct { u16 item; u8 badges; } sSinnohCommonMart[] = {\n' +
        ''.join('    {%s, %d},\n' % (i, b) for i, b in common) + '};\n')
    open('data/scripts/sinnoh_marts.inc', 'w').write(
        head.replace('//', '@') + ''.join('\t.align 2\n%s::\n%s\tpokemartlistend\n\n' % (
            label(mid), ''.join('\t.short %s\n' % i for i in its)) for mid, its in sorted(special.items()) if its))
    print('%d common items, %d specialty lists' % (len(common), sum(1 for v in special.values() if v)))


if __name__ == '__main__':
    main()
