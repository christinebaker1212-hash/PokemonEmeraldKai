#!/usr/bin/env python3
"""Moemon Co-op: the in-game PATCH NOTES (mp_patchnotes.c) from tools/release/notes/v<ver>.md.

usage: gen_patchnotes.py OUT.h NOTES.md...   (the Makefile runs it: src/data/mp_patchnotes.h, generated)

Each notes file's first line is 'Moemon Emerald Kai Co-op <ver> "<Catchy Title!>": <one-line summary>';
the rest becomes the body: "## Heading" -> 'H', "- item" -> 'B', "  - item" -> 'S', other text -> 'P' (one
paragraph per blank-line-separated block, continuation lines joined). The "## Installing" section and the
standard "installs this update by itself" line are left out (they're about the download, not the changes).
"""
import re
import sys

TITLE = re.compile(r'^Moemon Emerald Kai Co-op (\d+\.\d+\.\d+) "([^"]+)": (.*)$')
SKIP_LINES = ("The game installs this update by itself when it starts.",)
SKIP_SECTIONS = ("installing",)


def version_key(v):
    return tuple(int(x) for x in v.split('.'))


def clean(text):
    text = text.replace('**', '').replace('`', '').replace('…', '...')
    text = text.replace('’', "'").replace('‘', "'").replace('“', '"').replace('”', '"')
    text = text.replace('—', '-').replace('–', '-')
    for ch in text:
        if ord(ch) > 127 and ch not in 'éÉ':
            raise SystemExit('gen_patchnotes: character %r (U+%04X) has no game glyph' % (ch, ord(ch)))
    if '{' in text or '}' in text:
        raise SystemExit('gen_patchnotes: braces are button tokens in game text: %r' % text)
    return re.sub(r'\s+', ' ', text).strip()


def parse(path):
    with open(path, encoding='utf-8') as f:
        lines = f.read().split('\n')
    m = TITLE.match(lines[0].strip())
    if not m:
        raise SystemExit('gen_patchnotes: %s: the first line must be \'Moemon Emerald Kai Co-op <ver> "<Title!>": <summary>\'' % path)
    version, title, summary = m.group(1), clean(m.group(2)), clean(m.group(3))
    items = []          # [kind, text]
    skipping = False
    for raw in lines[1:]:
        line = raw.rstrip()
        if not line.strip():
            if items and items[-1][0] == 'P':
                items.append(['', ''])   # ends the paragraph
            continue
        if line.startswith('## '):
            skipping = line[3:].strip().lower() in SKIP_SECTIONS
            if not skipping:
                items.append(['H', line[3:]])
            continue
        if skipping or line.strip().startswith(SKIP_LINES):
            continue
        sub = re.match(r'^ {2,}- (.*)$', line)
        top = re.match(r'^- (.*)$', line)
        if top:
            items.append(['B', top.group(1)])
        elif sub:
            items.append(['S', sub.group(1)])
        elif line.startswith(' ') and items and items[-1][0] in 'BS':
            items[-1][1] += ' ' + line.strip()       # a wrapped list item
        elif items and items[-1][0] == 'P':
            items[-1][1] += ' ' + line.strip()       # a wrapped paragraph
        else:
            items.append(['P', line])
    body = [(k, clean(t)) for k, t in items if k and clean(t)]
    return version, title, summary, body


def c_string(text):
    out = []
    for ch in text:
        if ch == '\\' or ch == '"':
            out.append('\\' + ch)
        elif ch == '\n':
            out.append('\\n')
        elif ord(ch) > 127:
            out.append(''.join('\\%03o' % b for b in ch.encode('utf-8')))
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    notes = [parse(p) for p in sys.argv[2:]]
    seen = set()
    for v, _, _, _ in notes:
        if v in seen:
            raise SystemExit('gen_patchnotes: version %s twice' % v)
        seen.add(v)
    notes.sort(key=lambda n: version_key(n[0]), reverse=True)
    out = ['// Generated by tools/release/gen_patchnotes.py from tools/release/notes/*.md: edit those, not this.',
           '// Newest first. Body: one item per line, its first character the kind (H heading, B item, S sub-item,',
           '// P paragraph).', '']
    out.append('static const struct MpPatchNote sMpPatchNotes[] = {')
    for v, title, summary, body in notes:
        text = '\n'.join(k + t for k, t in body)
        out.append('    {%s, %s, %s,' % (c_string(v), c_string(title), c_string(summary)))
        out.append('     %s},' % c_string(text))
    out.append('};')
    with open(sys.argv[1], 'w', encoding='ascii') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
