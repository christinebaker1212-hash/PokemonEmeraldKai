#!/usr/bin/env python3
"""Every TM the game hands out once and marks with an event flag, read from the maps themselves:
item balls (map.json object events whose script is an item ball: data/scripts/item_ball_scripts.inc), hidden items
(map.json bg_events), and gifts (a script with `giveitem ITEM_TM_*` and a `setflag` in the same script).

Writes src/mp/mp_tm_sources.h: {item, flag} pairs. mp_tmrefund.c uses them for saves from before TMs became
reusable (1.18.1): a TM a flag proves the player got, and that's in neither the BAG nor the PC, was used up.
Gifts that come again (a daily or weekly flag, a variable instead of a flag) prove nothing and are left out;
TMs from shops and prize counters leave no trace at all.

usage: tools/moemon_tms/gen_tm_sources.py  (from the repo root)
"""
import glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(REPO, 'src', 'mp', 'mp_tm_sources.h')

REPEATING = re.compile(r'DAILY|THIS_WEEK|TODAY|FLAG_TEMP_|_TEMP_')

# the TM list: ITEM_TM_<MOVE> is ITEM_TM01 + its place in FOREACH_TM
tms = re.findall(r'F\((\w+)\)', open(os.path.join(REPO, 'include/constants/tms_hms.h')).read().split('FOREACH_HM')[0])
tm_number = {'ITEM_TM_' + name: i + 1 for i, name in enumerate(tms)}


def tm_of(item):
    if item in tm_number:
        return tm_number[item]
    m = re.fullmatch(r'ITEM_TM(\d\d)', item)
    return int(m.group(1)) if m else None


found = {}       # (tm, flag) -> where


def add(tm, flag, where):
    if tm is None or not flag or flag == '0' or REPEATING.search(flag):
        return
    found.setdefault((tm, flag), where)


# item balls: their scripts' items
ball_item = {}
label = None
for line in open(os.path.join(REPO, 'data/scripts/item_ball_scripts.inc')):
    m = re.match(r'(\w+)::', line)
    if m:
        label = m.group(1)
    m = re.match(r'\s+finditem\s+(\w+)', line)
    if m and label:
        ball_item[label] = m.group(1)

for path in sorted(glob.glob(os.path.join(REPO, 'data/maps/*/map.json'))):
    mp = json.load(open(path))
    name = os.path.basename(os.path.dirname(path))
    for o in mp.get('object_events', []):
        item = ball_item.get(o.get('script', ''))
        if item:
            add(tm_of(item), o.get('flag'), name + ' item ball')
    for b in mp.get('bg_events', []):
        if b.get('type') == 'hidden_item':
            add(tm_of(b.get('item', '')), b.get('flag'), name + ' hidden item')

# gifts: each script (from a label to the next) giving a TM, with the flag it sets
unmatched = []
for path in sorted(glob.glob(os.path.join(REPO, 'data/maps/*/scripts.inc')) + glob.glob(os.path.join(REPO, 'data/scripts/*.inc'))):
    if path.endswith('item_ball_scripts.inc'):
        continue
    blocks, cur = [], None
    for line in open(path, errors='replace'):
        m = re.match(r'(\w+)::', line)
        if m:
            cur = [m.group(1), []]
            blocks.append(cur)
        elif cur:
            cur[1].append(line)
    for name, lines in blocks:
        text = ''.join(lines)
        gives = [tm_of(i) for i in re.findall(r'giveitem\s+(ITEM_TM\w+)', text)]
        gives = [g for g in gives if g]
        if not gives:
            continue
        flags = [f for f in re.findall(r'setflag\s+(FLAG_\w+)', text) if not REPEATING.search(f)]
        if not flags:
            unmatched.append('%s %s: TM%s' % (os.path.relpath(path, REPO), name, ','.join('%02d' % g for g in gives)))
            continue
        for g in gives:
            for f in flags:
                add(g, f, '%s %s' % (os.path.basename(os.path.dirname(path)), name))

pairs = sorted(found)
out = ['// Generated by tools/moemon_tms/gen_tm_sources.py from the maps: do not edit.',
       '// TMs handed out once with an event flag: {TM number (1-50), flag}. mp_tmrefund.c gives back the ones a save',
       '// got (the flag) and no longer has (used up before TMs became reusable).',
       'static const struct { u8 tm; u16 flag; } sTmSources[] = {']
for tm, flag in pairs:
    out.append('    {%2d, %s},   // %s' % (tm, flag, found[(tm, flag)]))
out.append('};')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('%s: %d sources, %d TMs' % (os.path.relpath(OUT, REPO), len(pairs), len({t for t, f in pairs})))
for u in unmatched:
    print('  no flag (left out):', u)
