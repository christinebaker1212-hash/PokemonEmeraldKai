#!/usr/bin/env python3
"""TM140 on: Black's TMs (UNOVA, docs/UNOVA_DECISIONS.md) whose moves aren't TMs or HMs here, by the user's rule for
TM93 on (tools/moemon_tms/gen_tm3.py: "a different move on the same number ... gets a new slot after the last TM"):
Black's TM01 HONE CLAWS is not FOCUS PUNCH, so it is TM140. A Black TM whose move is a TM here at another number gets
no slot: its places give that TM (tools/unova/gen_items.py maps Black's TMs by the move they teach). In Black's
number order; items 866 on, after UNOVA's new items (tools/unova/gen_new_items.py); TM/HM index TMHM_INDEX_TM4 on;
who learns them is gTm4Learnsets (bit k = TM(140 + k)).

    python3 -I tools/moemon_tms/gen_tm4.py POKEAPI_CSV_DIR

From PokeAPI's tables (public data, as gen_tm3.py's): Black / White's TM list (machines.csv, version group 11), who
learns each there (pokemon_moves.csv: version group 11, by machine), and the newer species' teachable moves
(tools/moemon_gen59/species.json); descriptions: Black / White's text of the move in the game's style
(tools/moemon_items/gen_desc.py), without line breaks.
"""
import csv
import importlib.util
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FIRST_ITEM = 866
FIRST_NUMBER = 140
BW = '11'
MACHINE = '4'
HEAD = '// Generated by tools/moemon_tms/gen_tm4.py. Do not edit.\n'
SPECIES_ALIAS = {'nidoran-f': 'NIDORAN_F', 'nidoran-m': 'NIDORAN_M', 'farfetchd': 'FARFETCHD', 'mr-mime': 'MR_MIME',
                 'ho-oh': 'HO_OH', 'mime-jr': 'MIME_JR', 'porygon-z': 'PORYGON_Z'}
STATUS = {'HONE_CLAWS', 'TELEKINESIS', 'ALLY_SWITCH', 'QUASH', 'WORK_UP'}


def load_csv(d, name):
    return list(csv.DictReader(open(os.path.join(d, name), encoding='utf-8')))


def write(path, text):
    open(os.path.join(REPO, path), 'w', encoding='utf-8').write(text)


def ours():
    """every move that is a TM or HM here"""
    have = set()
    for f in ('tms_hms.h', 'tms_hms_tm2.h', 'tms_hms_tm3.h'):
        have |= set(re.findall(r'F\((\w+)\)', open(os.path.join(REPO, 'include/constants', f)).read()))
    return have


def gd_module():
    spec = importlib.util.spec_from_file_location('gen_desc', os.path.join(REPO, 'tools/moemon_items/gen_desc.py'))
    gd = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gd)
    return gd


def move_types():
    text = open(os.path.join(REPO, 'src/data/battle_moves.h')).read()
    out = {m: t for m, t in re.findall(r'\[MOVE_(\w+)\]\s*=\s*\{[^}]*?\.type = TYPE_(\w+)', text, re.S)}
    gen59 = os.path.join(REPO, 'src/data/battle_moves_gen58.h')
    if os.path.exists(gen59):
        out.update({m: t for m, t in re.findall(r'\[MOVE_(\w+)\]\s*=\s*\{[^}]*?\.type = TYPE_(\w+)',
                                                 open(gen59).read(), re.S)})
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    d = sys.argv[1]
    moves_by_id = {r['id']: r['identifier'] for r in load_csv(d, 'moves.csv')}
    items_by_id = {r['id']: r['identifier'] for r in load_csv(d, 'items.csv')}
    bw = sorted(((items_by_id[r['item_id']], moves_by_id[r['move_id']]) for r in load_csv(d, 'machines.csv')
                 if r['version_group_id'] == BW), key=lambda x: (x[0][:2] != 'tm', int(x[0][2:])))
    have = ours()
    new = []
    for item, move in bw:
        m = move.upper().replace('-', '_')
        if item.startswith('tm') and m not in have and m not in [x[0] for x in new]:
            new.append((m, int(item[2:])))
    moves = [m for m, _ in new]
    move_ids = {v: k for k, v in moves_by_id.items()}
    wanted = {move_ids[m.lower().replace('_', '-')]: k for k, m in enumerate(moves)}

    # who learns them: Black / White's TM lists, then the newer species' teachable moves
    species = {r['id']: r['identifier'] for r in load_csv(d, 'pokemon_species.csv')}
    known = set(l.split()[1] for l in open(os.path.join(REPO, 'include/constants/species.h'))
                if l.startswith('#define SPECIES_'))
    bits = {}
    for r in load_csv(d, 'pokemon_moves.csv'):
        if r['version_group_id'] != BW or r['pokemon_move_method_id'] != MACHINE or r['move_id'] not in wanted:
            continue
        if int(r['pokemon_id']) > 10000:
            continue   # (a form: its species' default form stands for it)
        ident = species.get(r['pokemon_id'])
        const = 'SPECIES_' + SPECIES_ALIAS.get(ident, ident.upper().replace('-', '_'))
        bits[const] = bits.get(const, 0) | (1 << wanted[r['move_id']])
    g59 = json.load(open(os.path.join(REPO, 'tools/moemon_gen59/species.json')))
    for e in list(g59.values())[0]:
        teach = {x[5:] for x in e['teach']}
        b = sum(1 << k for k, m in enumerate(moves) if m in teach)
        if b:
            bits[e['const']] = bits.get(e['const'], 0) | b
    rows = ''.join('    [%s] = 0x%08X,\n' % (c, b) for c, b in sorted(bits.items()) if c in known)
    missing = sorted(c for c in bits if c not in known)
    write('src/data/pokemon/tm4_learnsets.h', HEAD +
          '// Which species learn TM140 on (bit k = TM(140 + k), TM/HM index TMHM_INDEX_TM4 on): Black\'s TMs whose moves\n'
          '// aren\'t TMs here (pokemon.c CanSpeciesLearnTMHM)\n'
          'const u32 gTm4Learnsets[NUM_SPECIES] =\n{\n' + rows + '};\n')

    # descriptions: Black / White's text of the move
    gd = gd_module()
    texts = {}
    for r in load_csv(d, 'move_flavor_text.csv'):
        if r['language_id'] == gd.ENGLISH and r['version_group_id'] == BW:
            texts[moves_by_id[r['move_id']]] = gd.flatten(r['flavor_text'])
    vocab = set()
    for m in moves:
        gd.names_in(texts[m.lower().replace('_', '-')], vocab)
    vocab -= {'I'}
    descs = {m: gd.game_style(texts[m.lower().replace('_', '-')], vocab).replace('"', '\\"') for m in moves}

    types = move_types()
    write('include/constants/tms_hms_tm4.h', HEAD +
          '// TM140 on: Black\'s TMs whose moves aren\'t TMs here (TM/HM index TMHM_INDEX_TM4 on)\n'
          '#define FOREACH_TM4(F) \\\n' + ' \\\n'.join('    F(%s)' % m for m in moves) + '\n'
          + '#define NUM_TECHNICAL_MACHINES_4 %d\n' % len(moves)
          + ''.join('#define ITEM_TM%d %d   // %s (Black TM%02d)\n' % (FIRST_NUMBER + k, FIRST_ITEM + k, m, num)
                    for k, (m, num) in enumerate(new))
          + '#define LAST_TM4_ITEM ITEM_TM%d\n' % (FIRST_NUMBER + len(new) - 1))
    items, dtext, icons = [HEAD], [HEAD], [HEAD + '#define ITEM_ICONS_TM4 \\\n']
    for k, (m, num) in enumerate(new):
        t = FIRST_NUMBER + k
        price = 2000 if m in STATUS else 3000
        typ = types.get(m, 'NORMAL').capitalize()
        items.append('    [ITEM_TM%d] =\n    {\n        .name = _("TM%d"),\n        .itemId = ITEM_TM%d,\n'
                     '        .price = %d,\n        .description = sTM%dDesc,\n        .pocket = POCKET_TM_HM,\n'
                     '        .type = ITEM_USE_PARTY_MENU,\n        .fieldUseFunc = ItemUseOutOfBattle_TMHM,\n    },\n\n'
                     % (t, t, t, price, t))
        dtext.append('static const u8 sTM%dDesc[] = _(\n    "%s");\n\n' % (t, descs[m]))
        icons.append('    [ITEM_TM%d] = {gItemIcon_TM, gItemIconPalette_%sTMHM}, \\\n' % (t, typ))
    write('src/data/items_tm4.h', ''.join(items))
    write('src/data/text/item_descriptions_tm4.h', ''.join(dtext))
    write('src/data/item_icons_tm4.h', ''.join(icons).rstrip(' \\\n') + '\n')
    print('%d new TMs (TM%d-TM%d), %d species learn at least one; not species here: %s'
          % (len(new), FIRST_NUMBER, FIRST_NUMBER + len(new) - 1, sum(1 for c in bits if c in known), missing[:20]))


if __name__ == '__main__':
    main()
