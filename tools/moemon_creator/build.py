#!/usr/bin/env python3
"""Moemon Co-op trainer creator: builds the game's parts data from the kit.

Usage: build.py KIT_DIR
  KIT_DIR  the "pokemon png" folder of the trainer customization kit
Writes graphics/moemon/creator/parts.bin (every part, every view, at 1x) and
src/mp/mp_creator_data.h (names, styles, colors and where each image is).

Views (all 1x, kit art is drawn at 2x):
  front  80x80               (the game fits it into a 64x64 trainer picture)
  back   4 frames of 87x98   (Emerald's ready, wind-up, throw, standing)
  walk / run / bike  9 frames of 32x32 (Emerald's order: down, up, left, then steps)
Image format: u16 w, u16 h, u8 colors, u8 0, u16 palette[colors] (RGB555),
then runs of (u8 count 1-255, u8 color; 0 = transparent) over the rows.
"""
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
from inventory import Kit, SKINS, HAIR_COLORS  # noqa: E402
from views import rgba, front_frame, back_frames, back_parity, ow_frames  # noqa: E402

VIEWS = ('front', 'back', 'walk', 'run', 'bike')
CATS = ('hair', 'tops', 'bottoms', 'hats', 'bags')
COLOR_WORDS = ['light blue', 'black', 'blue', 'green', 'red', 'white', 'navy', 'pink', 'orange', 'purple', 'yellow',
               'wine', 'beige', 'grey', 'brown', 'aqua', 'gold', 'silver', 'dark', 'light', 'magenta', 'cyan',
               'ginger', 'blonde', 'blond', 'violet', 'bee', 'brownish']
SYNONYM = {'blond': 'blonde', 'violet': 'purple', 'bee': 'yellow', 'brownish': 'beige'}


def clean_color(n):
    for w in COLOR_WORDS:
        if re.search(r'\b%s$' % w, n):
            return SYNONYM.get(w, w)
    return '' if n == 'default' else n


def rgb555(a):
    return ((a[..., 0].astype(np.int32) >> 3) | ((a[..., 1].astype(np.int32) >> 3) << 5)
            | ((a[..., 2].astype(np.int32) >> 3) << 10))


def encode(img):
    """img: (h, w, 4) uint8 -> bytes."""
    h, w = img.shape[:2]
    vis = img[:, :, 3] >= 128
    c = rgb555(img)
    cols = sorted(set(int(v) for v in c[vis]))
    if len(cols) > 255:
        raise ValueError('too many colors')
    lut = {v: i + 1 for i, v in enumerate(cols)}
    idx = np.zeros((h, w), np.uint8)
    for v, i in lut.items():
        idx[vis & (c == v)] = i
    out = bytearray()
    out += w.to_bytes(2, 'little') + h.to_bytes(2, 'little') + bytes((len(cols), 0))
    for v in cols:
        out += v.to_bytes(2, 'little')
    flat = idx.reshape(-1)
    i = 0
    while i < len(flat):
        j = i
        while j < len(flat) and flat[j] == flat[i] and j - i < 255:
            j += 1
        out += bytes((j - i, int(flat[i])))
        i = j
    return bytes(out)


def strip(frames):
    return np.concatenate(frames, axis=1)


class Builder:
    def __init__(self, kit_dir):
        self.kit = Kit(kit_dir)
        self.dir = kit_dir
        self.blob = bytearray()
        self.offsets = []
        self.parity = {}

    def base_path(self, view, g, skin):
        import glob
        d = self.kit.d(view, g)
        if view in ('front', 'back'):
            for f in glob.glob(os.path.join(self.dir, d, 'base', '*.png')):
                if re.sub(r'\s+', ' ', os.path.basename(f)) == 'base %s.png' % skin:
                    return f
            raise FileNotFoundError(skin)
        return os.path.join(self.dir, d, 'bases mf', '%s base %s.png' % (g, skin))

    def image(self, view, g, path):
        a = rgba(path)
        if view == 'front':
            img = front_frame(a)
        elif view == 'back':
            img = strip(back_frames(a, self.parity[g]))
        else:
            img = strip(ow_frames(a))
        self.offsets.append(len(self.blob))
        self.blob += encode(np.ascontiguousarray(img))
        return len(self.offsets) - 1

    def run(self):
        items = self.kit.build()
        for g in 'mf':
            self.parity[g] = back_parity(rgba(self.base_path('back', g, 'light')))
        h = ['// Moemon Co-op: trainer creator parts, generated by tools/moemon_creator/build.py. Do not edit.',
             '// Art: the trainer customization kit (front, back and overworld parts).', '']
        bases = []
        for g in 'mf':
            for skin in SKINS:
                bases.append([self.image(v, g, self.base_path(v, g, skin)) for v in VIEWS])
        styles, colors = [], []
        first = {}
        for g in 'mf':
            for cat in CATS:
                first[(g, cat)] = (len(styles), len(items[g][cat]))
                for style, cols in items[g][cat]:
                    named = [(clean_color(n), p) for n, p in cols]
                    if cat == 'hair':
                        named.sort(key=lambda c: HAIR_COLORS.index(c[0]) if c[0] in HAIR_COLORS else 99)
                    else:
                        named.sort(key=lambda c: c[0])
                    styles.append((style, len(colors), len(named)))
                    for n, paths in named:
                        colors.append((n, [self.image(v, g, paths[v]) if v in paths else 0xFFFF for v in VIEWS]))
        os.makedirs(os.path.join(ROOT, 'graphics/moemon/creator'), exist_ok=True)
        with open(os.path.join(ROOT, 'graphics/moemon/creator/parts.bin'), 'wb') as f:
            f.write(self.blob)
        h.append('#define CR_IMG_COUNT %d' % len(self.offsets))
        h.append('static const u32 sCrImgOffset[CR_IMG_COUNT] = {')
        for i in range(0, len(self.offsets), 12):
            h.append('    ' + ', '.join(str(o) for o in self.offsets[i:i + 12]) + ',')
        h.append('};')
        h.append('')
        h.append('// [gender][skin][view]')
        h.append('static const u16 sCrBase[2][%d][CR_VIEW_COUNT] = {' % len(SKINS))
        for gi in range(2):
            h.append('    {' + ', '.join('{%s}' % ', '.join(map(str, bases[gi * len(SKINS) + s])) for s in range(len(SKINS))) + '},')
        h.append('};')
        h.append('static const char *const sCrSkinNames[%d] = {%s};' % (len(SKINS), ', '.join('"%s"' % s.upper() for s in SKINS)))
        h.append('')
        h.append('static const struct CrStyle sCrStyles[] = {')
        for name, fc, n in styles:
            h.append('    {"%s", %d, %d},' % (name.upper(), fc, n))
        h.append('};')
        h.append('static const struct CrColor sCrColors[] = {')
        for name, imgs in colors:
            h.append('    {"%s", {%s}},' % (name.upper(), ', '.join(map(str, imgs))))
        h.append('};')
        h.append('// First style and number of styles: [gender][category]')
        h.append('static const u16 sCrCatStyles[2][CR_CAT_COUNT][2] = {')
        for g in 'mf':
            h.append('    {' + ', '.join('{%d, %d}' % first[(g, c)] for c in CATS) + '},')
        h.append('};')
        with open(os.path.join(ROOT, 'src/mp/mp_creator_data.h'), 'w') as f:
            f.write('\n'.join(h) + '\n')
        print('%d images, %.1f KB' % (len(self.offsets), len(self.blob) / 1024))


if __name__ == '__main__':
    Builder(sys.argv[1]).run()
