def table():
    """(label, kind, amount, after, extra) for each attack"""
    out = []
    for name, v in E.items():
        kind, amount, extra = v[:3]
        after = v[3] if len(v) > 3 else SINGLE_PHASE.get(kind, 2)
        out.append((name + 'EffectCommands', kind, amount, after, extra))
    return out
