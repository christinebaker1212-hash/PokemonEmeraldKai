#!/usr/bin/env python3
"""Blaine's Quiz #1 guesses a Pokemon's length: the game's own Pokedex heights (src/data/pokemon/pokedex_entries.h,
decimetres) by national number, as src/tcg/tcg_heights.inc (TCG_HEIGHTS[species], 0 unknown).

usage: tools/tcg/regions/gen_heights.py"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
enum = (ROOT / 'include/constants/pokedex.h').read_text()
names = re.findall(r'^\s*(NATIONAL_DEX_[A-Z0-9_]+)\s*,', enum, re.M)
number = {n: i for i, n in enumerate(names)}       # (NATIONAL_DEX_NONE is 0)
entries = (ROOT / 'src/data/pokemon/pokedex_entries.h').read_text()
heights = {}
for name, body in re.findall(r'\[(NATIONAL_DEX_[A-Z0-9_]+)\]\s*=\s*\{(.*?)\}', entries, re.S):
    m = re.search(r'\.height\s*=\s*(\d+)', body)
    if m and name in number:
        heights[number[name]] = int(m.group(1))
top = 386
rows = [heights.get(i, 0) for i in range(top + 1)]
out = ['/* Generated by tools/tcg/regions/gen_heights.py from the game\'s Pokedex: each species\' height in decimetres */',
       f'#define TCG_HEIGHT_SPECIES {top + 1}',
       'static const uint8_t TCG_HEIGHTS[TCG_HEIGHT_SPECIES] = {']
for i in range(0, len(rows), 24):
    out.append('    ' + ', '.join(str(min(v, 255)) for v in rows[i:i + 24]) + ',')
out.append('};')
(ROOT / 'src/tcg/tcg_heights.inc').write_text('\n'.join(out) + '\n')
print(f'src/tcg/tcg_heights.inc: {sum(1 for v in rows if v)} heights')
