"""The regional sets' Poke-Powers, Poke-Bodies and Pokemon Powers (docs/TCG_REGIONS.md): each one the engine plays.

A power is matched to a card by its name and a piece of its words (several cards share a name with different rules:
Pure Body, Fragrance Trap). ID: its TCG_POWER_* name (include/tcg/region_powers.h, generated by
generate_effects.py). USED powers are used during their owner's turn (TCG_USE_POWER); with a script they run the
attack scripts' ops (src/tcg/tcg_script.inc) with "it" the Pokemon using the power, coins first; without one their
rules are C (src/tcg/tcg_powers.c). PASSIVE powers are C hooks named by the ID.

Flags: ONCE once a turn | ACTIVE only as the Active Pokemon | BENCH only on the Bench | ANY works while Asleep,
Confused or Paralyzed (a Poke-Body always does).
"""

