def match(card):
    """The definition of a card's power, or None"""
    ab = card.get('ability')
    if not ab:
        return None
    text = ab['text'].replace(card['name'], 'SELF')
    for d in DEFS:
        if d['name'] == ab['name'] and d['words'] in text:
            return d
    return None
