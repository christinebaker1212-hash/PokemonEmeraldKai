/* CARD SCALING's ratings (tools/tcg/rate_decks.sh writes src/tcg/tcg_ratings.c from this).
 *
 * 1. Every Game Boy deck and every special trainer's own deck play each other (both
 *    orders, ROUNDS times, the game's AI on both sides); a Bradley-Terry fit of the
 *    results, as Elo with the average deck at 1500.
 * 2. Each special trainer variant plays every one of those VARIANT_GAMES times and is
 *    rated against their ratings.
 * 3. The reference decks the game rates a player's deck against: Game Boy decks spread
 *    evenly over the ratings. As a check, every Game Boy deck is rated the way the game
 *    rates a player's (TcgScale_RateDeck) and the difference printed.
 * Everything is seeded, so the same code gives the same table. */
#include "mp_version.h"
#include "tcg/duel.h"
#include "tcg/npc.h"
#include "tcg/scale.h"
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define ROUNDS 8
#define VARIANT_GAMES 6
#define REFERENCES 12
#define MAXD 256

/* The tables this tool makes (the game's are in tcg_ratings.c): filled in before use */
int16_t gTcgDeckRating[MAXD], gTcgSpecialRating[1], gTcgVariantRating[1];
uint8_t gTcgRatingReferences[REFERENCES];
unsigned gTcgRatingReferenceCount;

static const uint16_t *sDeck[MAXD];
static int sGb[MAXD]; /* gTcgDeckDefinitions index, or -1 - special */
static unsigned sCount;

static double sWins[MAXD][MAXD];
static unsigned sGames[MAXD][MAXD];

int main(void)
{
    double strength[MAXD];
    int16_t elo[MAXD];
    unsigned i, j, r, k;
    double mean = 0;
    for (i = 0; i < gTcgDeckDefinitionCount; i++)
        if (strcmp(gTcgDeckDefinitions[i].name, "Unnamed"))
            sDeck[sCount] = gTcgDeckDefinitions[i].cards, sGb[sCount++] = (int)i;
    for (i = 0; i < gTcgSpecialDeckCount; i++)
        sDeck[sCount] = gTcgSpecialDecks[i].cards, sGb[sCount++] = -1 - (int)i;
    for (i = 0; i < sCount; i++)
        for (j = 0; j < sCount; j++)
            if (i != j)
                for (r = 0; r < ROUNDS; r++)
                {
                    int w = TcgScale_Play(sDeck[i], sDeck[j], i * 7919 + j * 104729 + r * 1299709 + 17);
                    if (w < 0)
                        sWins[i][j] += 0.5, sWins[j][i] += 0.5;
                    else
                        sWins[w ? j : i][w ? i : j] += 1;
                    sGames[i][j]++, sGames[j][i]++;
                }
    for (i = 0; i < sCount; i++)
        strength[i] = 1;
    for (r = 0; r < 500; r++)
        for (i = 0; i < sCount; i++)
        {
            double w = 0, d = 0;
            for (j = 0; j < sCount; j++)
                if (sGames[i][j])
                    w += sWins[i][j], d += sGames[i][j] / (strength[i] + strength[j]);
            strength[i] = (w + 0.5) / (d + 1e-9);
        }
    for (i = 0; i < sCount; i++)
        mean += 400 * log10(strength[i]);
    mean /= sCount;
    for (i = 0; i < sCount; i++)
        elo[i] = (int16_t)lround(TCG_SCALE_MEAN + 400 * log10(strength[i]) - mean);

    /* The Game Boy decks' table, and the references spread over it */
    {
        unsigned order[MAXD], n = 0;
        for (i = 0; i < gTcgDeckDefinitionCount; i++)
            gTcgDeckRating[i] = TCG_SCALE_MEAN;
        for (i = 0; i < sCount; i++)
            if (sGb[i] >= 0)
                gTcgDeckRating[sGb[i]] = elo[i], order[n++] = i;
        for (i = 0; i < n; i++)
            for (j = i + 1; j < n; j++)
                if (elo[order[j]] < elo[order[i]])
                    k = order[i], order[i] = order[j], order[j] = k;
        for (k = 0; k < REFERENCES; k++)
            gTcgRatingReferences[k] = (uint8_t)sGb[order[k * (n - 1) / (REFERENCES - 1)]];
        gTcgRatingReferenceCount = REFERENCES;
    }

    printf("/* Generated by tools/tcg/rate_decks.sh: CARD SCALING's deck ratings (include/tcg/scale.h).\n"
           " * Elo from %u AI duels between every Game Boy deck and special deck, the average at %d. */\n"
           "#include \"tcg/scale.h\"\n\n/* By gTcgDeckDefinitions index */\nconst int16_t gTcgDeckRating[] = {\n",
           sCount * (sCount - 1) * ROUNDS, TCG_SCALE_MEAN);
    for (i = 0; i < gTcgDeckDefinitionCount; i++)
        printf("    %d, /* %s */\n", gTcgDeckRating[i], gTcgDeckDefinitions[i].name);
    printf("};\n/* Each special trainer's own deck */\nconst int16_t gTcgSpecialRating[] = {\n");
    for (i = 0; i < sCount; i++)
        if (sGb[i] < 0)
            printf("    %d, /* %s */\n", elo[i], gTcgSpecialDecks[-1 - sGb[i]].name);
    printf("};\n/* Their variants (gTcgSpecialVariants), each against all of the above %u times */\n"
           "const int16_t gTcgVariantRating[] = {\n", VARIANT_GAMES);
    for (k = 0; k < gTcgSpecialVariantCount; k++)
    {
        int16_t ratings[MAXD];
        unsigned games[MAXD], half[MAXD];
        for (i = 0; i < sCount; i++)
        {
            ratings[i] = elo[i];
            games[i] = VARIANT_GAMES;
            half[i] = 0;
            for (r = 0; r < VARIANT_GAMES; r++)
            {
                int w = TcgScale_Play(gTcgSpecialVariants[k].cards, sDeck[i], k * 15485863u + i * 7919 + r * 104729 + 3);
                half[i] += w < 0 ? 1 : w == 0 ? 2 : 0;
            }
        }
        printf("    %d, /* %s */\n", TcgScale_Fit(ratings, games, half, sCount), gTcgSpecialVariants[k].name);
    }
    printf("};\n/* The decks a player's deck is measured against in the game */\nconst uint8_t gTcgRatingReferences[] = {");
    for (k = 0; k < REFERENCES; k++)
        printf("%s%u", k ? ", " : "", gTcgRatingReferences[k]);
    printf("};\nconst unsigned gTcgRatingReferenceCount = %u;\n", REFERENCES);

    /* The check: the game's own way of rating a deck, against the table */
    {
        double err = 0, worst = 0;
        unsigned n = 0;
        for (i = 0; i < sCount; i++)
        {
            double d;
            if (sGb[i] < 0)
                continue;
            d = fabs((double)TcgScale_RateDeck(sDeck[i]) - elo[i]);
            err += d, n++;
            if (d > worst)
                worst = d;
        }
        fprintf(stderr, "in-game rating of the %u Game Boy decks: off by %.0f on average, %.0f at most\n", n, err / n, worst);
    }
    return 0;
}
