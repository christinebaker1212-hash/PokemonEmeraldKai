#!/usr/bin/env python3
"""Produce native immutable card/deck data from the pinned imported catalogue."""
import sys as _sys
_sys.path.insert(0,str(__import__('pathlib').Path(__file__).resolve().parent))
from gb2_effects import TEXT as GB2_TEXT
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[2]
x=json.loads((ROOT/'tools/tcg/catalog.json').read_text())
q=lambda s:json.dumps(s,ensure_ascii=True)
types=['FIRE','GRASS','LIGHTNING','WATER','FIGHTING','PSYCHIC','COLORLESS']
sets=['COLOSSEUM','EVOLUTION','MYSTERY','LABORATORY','PROMOTIONAL','ENERGY']
# Pokemon Card GB2's boosters (tools/tcg/import_poketcg2.py) come after: set 6 + their order
gb2_sets=[p['set'] for p in x.get('gb2_packs',[])]
def set_index(name):
 return sets.index(name) if name in sets else 6+gb2_sets.index(name)
def affinity(s):return types.index(s.removeprefix('WR_')) if s.startswith('WR_') else 255
out=['/* Generated by tools/tcg/generate_catalog.py; poketcg '+x['revision']+(', poketcg2 '+x['gb2_revision'] if 'gb2_revision' in x else '')+' */','#include "mp_version.h"','#include "tcg/tcg.h"','const struct TcgCard gTcgCards[TCG_CARD_COUNT + 1] = {']
ids=['#ifndef TCG_CARD_IDS_H','#define TCG_CARD_IDS_H']
seen=set()
for c in x['cards']:
 n=c['id'];sym=c['symbol']
 if sym in seen:sym=f'{sym}_{n}'
 seen.add(sym);ids.append(f'#define TCG_CARD_{sym} {n}')
 kind={'pokemon':'TCG_POKEMON','energy':'TCG_ENERGY','trainer':'TCG_TRAINER'}[c['kind']]
 typ=next((i for i,t in enumerate(types) if c['type'] in ['TYPE_PKMN_'+t,'TYPE_ENERGY_'+t]),6)
 rarity={'CIRCLE':0,'DIAMOND':1,'STAR':2,'WHITESTAR':2,'PROMOSTAR':3}[c['rarity']]
 cardset=set_index(c['sets'].split(' | ')[0])
 # the GB2 booster that also holds it (a first-game card GB2 sells; 255 none)
 pack2=set_index(c['gb2_set']) if c.get('gb2_set') and c['gb2_set'] in gb2_sets else 255
 # holo (GB2's cards): the holofoil rares of Team Rocket (1-17), and the stars never printed in English
 eng=c.get('english_printing') or ''
 holo=n>228 and rarity==2 and c['kind']!='energy' and ((eng.startswith('base5-') and int(eng.split('-')[1])<=17) or (not eng and c.get('real_set') in ('GB','EXPANSION_SHEET')))
 out.append(f'[{n}] = {{.id={n}, .name={q(c["name"])}, .kind={kind}, .type={typ}, .rarity={rarity}, .set={cardset}, .set2={pack2}, .dark={1 if c.get("dark") else 0}, .holo={1 if holo else 0},')
 if c['kind']=='pokemon':
  stage={'BASIC':0,'STAGE1':1,'STAGE2':2}[c['stage']]
  out.append(f'.hp={c["hp"]}, .stage={stage}, .species={c["species"]}, .level={c["level"]}, .retreat={c["retreat"]}, .weakness={affinity(c["weakness"])}, .resistance={affinity(c["resistance"])}, .evolvesFrom={q(c["evolves_from"])}, .description={q(c["flavor"])}, .attacks={{')
  for a in c['attacks']+[None]*(3-len(c['attacks'])):  # (TCG_ATTACKS)
   if a is None:
    out.append('{.name="",.description="",.effect="NONE",.animation="ATK_ANIM_NONE",.cost={0,0,0,0,0,0,0},.damage=0,.category=TCG_DAMAGE_NORMAL},');continue
   costs=','.join(str(a['energy'].get(t,0)) for t in types)
   desc=GB2_TEXT.get(a['effect'].replace('EffectCommands',''),a['description'])
   out.append(f'{{.name={q(a["name"])},.description={q(desc)},.effect={q(a["effect"])},.animation={q(a["animation"])},.cost={{{costs}}},.damage={a["damage"]},.category=TCG_{a["category"]}}},')
  out.append('}')
 else:out.append(f'.effect={q(c["effect"])},.description={q(c["description"])}')
 out.append('},')
# The regional sets' cards (tools/tcg/regions/cards.json from import_sets.py; docs/TCG_REGIONS.md): after the Game Boy games'
_sys.path.insert(0,str(ROOT/'tools/tcg/regions'))
import effects as REG
REG_TYPES=['Fire','Grass','Lightning','Water','Fighting','Psychic','Colorless','Darkness','Metal']
reg=json.loads((ROOT/'tools/tcg/regions/cards.json').read_text())['cards']
assert reg[0]['id']==len(x['cards'])+1, 'the regional cards follow the Game Boy games\''
def rtype(t):return REG_TYPES.index(t) if t in REG_TYPES else 255
for c in reg:
 n=c['id']
 sym=c['src'].upper().replace('-','_')
 ids.append(f'#define TCG_CARD_{sym} {n}')
 kind={'pokemon':'TCG_POKEMON','energy':'TCG_ENERGY','trainer':'TCG_TRAINER'}[c['kind']]
 holo=c['rarity'] in ('Rare Holo','Rare Shining','Rare Secret')
 rarity={'Common':0,'Uncommon':1}.get(c['rarity'],3 if c['rarity']=='Promo' else 2)
 # boosters: the set's own (13+); promos: TCG_SET_PROMO
 cardset=4 if c['region']=='PROMO' else c['origin']
 flags=[{'STADIUM':'TCG_CF_STADIUM','TOOL':'TCG_CF_TOOL','SUPPORTER':'TCG_CF_SUPPORTER','TM':'TCG_CF_TM','BABY':'TCG_CF_BABY','EX':'TCG_CF_EX','RSM':'TCG_CF_RSM','GAME_CORNER':'TCG_CF_GAME_CORNER','SPECIAL':'TCG_CF_SPECIAL','SHINING':'TCG_CF_SHINING','LIGHT':'TCG_CF_LIGHT','CRYSTAL':'TCG_CF_CRYSTAL','OWNER':'TCG_CF_OWNER'}[f] for f in c['flags'] if f!='DARK']
 if c.get('ability') and c['ability']['kind']=='BODY':flags.append('TCG_CF_BODY')
 if REG.ready(c):flags.append('TCG_CF_READY')
 flagx='|'.join(flags) or '0'
 # (Darkness / Metal Energy provide their own type)
 ctype=c['name'].split()[0] if c['kind']=='energy' and c['name'] in ('Darkness Energy','Metal Energy') else c['type']
 out.append(f'[{n}] = {{.id={n}, .name={q(c["name"])}, .kind={kind}, .type={rtype(ctype)}, .rarity={rarity}, .set={cardset}, .set2=255, .dark={1 if "DARK" in c["flags"] else 0}, .holo={1 if holo else 0}, .flags={flagx}, .origin={c["origin"]},')
 if c['kind']=='pokemon':
  out.append(f'.hp={c["hp"]}, .stage={c["stage"]}, .species={c["species"]}, .level={c["level"]}, .retreat={c["retreat"]}, .weakness={rtype(c["weakness"])}, .resistance={rtype(c["resistance"])}, .evolvesFrom={q(c["evolvesFrom"])}, .description={q(c["flavor"])}, .attacks={{')
  attacks=[]
  if c.get('ability'):
   ab=c['ability'];attacks.append({'name':ab['name'],'text':ab['text'],'effect':ab['effect'],'cost':{},'damage':0,'category':'POKEMON_POWER'})
  attacks+=c['attacks']
  assert len(attacks)<=3,c['src']
  for a in attacks+[None]*(3-len(attacks)):
   if a is None:
    out.append('{.name="",.description="",.effect="NONE",.animation="ATK_ANIM_NONE",.cost={0},.damage=0,.category=TCG_DAMAGE_NORMAL},');continue
   costs=','.join(str(a['cost'].get(t,0)) for t in REG_TYPES)
   out.append(f'{{.name={q(a["name"])},.description={q(a["text"])},.effect={q(a["effect"])},.animation="ATK_ANIM_HIT",.cost={{{costs}}},.damage={a["damage"]},.category=TCG_{a["category"]}}},')
  out.append('}')
 else:out.append(f'.effect={q(c["effect"])},.description={q(c["text"])}')
 out.append('},')
out+=['};','const struct TcgDeckDefinition gTcgDeckDefinitions[] = {']
for d in x['decks']:out.append('{'+q(d['name'])+',{'+','.join(map(str,d['cards']))+'}},')
# GB2's decks: "GB2 " and their name (tcg_field.c deals them to card players alongside the first game's)
for d in x.get('gb2_decks',[]):out.append('{'+q('GB2 '+d['name'])+',{'+','.join(map(str,d['cards']))+'}},')
out+=['};','const unsigned gTcgDeckDefinitionCount = sizeof(gTcgDeckDefinitions)/sizeof(gTcgDeckDefinitions[0]);']
# GB2's boosters: the cards each can hold (first-game cards included)
out+=['const uint16_t gTcgGb2PackCards[TCG_GB2_PACKS][TCG_GB2_PACK_MAX] = {']
for pk in x.get('gb2_packs',[]):out.append('{'+','.join(map(str,pk['cards']))+'},')
out+=['};']
(ROOT/'src/tcg/tcg_catalog.c').write_text('\n'.join(out)+'\n')
(ROOT/'include/tcg/card_ids.h').write_text('\n'.join(ids+['#endif'])+'\n')
print(f'Generated {len(x["cards"])} native cards, {len(reg)} regional ones ({sum(1 for c in reg if REG.ready(c))} finished) and {len(x["decks"])} decks')
