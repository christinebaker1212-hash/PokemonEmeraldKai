#!/usr/bin/env python3
"""Writes the three-region chain tests (tools/test/scenarios/region_chain_<a>_<b>_<c>): one playthrough of all three
regions in a row, the user's region gating check. In each region: its eight BADGES (their flags, as the gym scripts
set them), its HALL OF FAME (the League beaten: the frame script that runs after the CHAMPION), the credits, and the
game going on from the save (no title screen); the GLOBAL PC linked there; then the boat to the next region with the
whole party at customs, keeping only the Lv 70 POKeMON (the others wait in the GLOBAL PC). It is Lv 5 on arrival; in
the new region it's trained to LEVEL2 (below 70 in one chain, above it in the other) and once that League is beaten
it has its best level: 70 again when it stayed below, LEVEL2 when it went past (MP_Region_LeagueLevels). The third
region starts it at Lv 5 again until its own League.

    python3 tools/test/gen_region_chain.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = ['hoenn', 'johto', 'kanto']
BADGES = {0: 0x867, 1: 0x11B2, 2: 0x2100}
# the HALL OF FAME's frame script: how to get there as after the CHAMPION
HOF = {0: ['mp warp 16,11,7,10'], 1: ['mp setvar 0x502A 6', 'mp warp 35,16,6,12'], 2: ['mp warp 36,80,5,11']}
PORT = {
    0: {'warp': '9,9,8,11', 'face': 'up', 'pre': 1},
    1: {'warp': '35,12,8,16', 'face': 'down', 'pre': 0},
    2: {'warp': '37,62,24,34', 'face': 'up', 'pre': 1},
}
ROWS = {0: [2, 1], 1: [2, 0], 2: [1, 0]}   # the region list from each port (QzGetReachableRegionsMask)
FIRST = {0: 'where map 9.9 ', 1: 'where map 35.2 xy 4,4', 2: 'where map 37.120 xy 6,6'}
LEAD = 280   # the Lv 70 POKeMON (slot 0) customs keeps


def badges(r):
    out = ['mp setflag 0x%X' % (BADGES[r] + i) for i in range(8)]
    return out + ['mp regioninfo']


def league(r):
    out = list(HOF[r]) + ['wait 120'] + ['mash A 400 10'] * 4
    return out + ['pressuntil A field 6000', 'wait 60', 'mp where', 'mp regioninfo']


def sail(src, dst, customs):
    p = PORT[src]
    out = ['mp additem 265 1', 'mp setvar 20789 3',   # (S.S. TICKET; KANTO's VERMILION clerk after the S.S. ANNE)
           'mp warp %s' % p['warp'], 'wait 120', 'mp face %s' % p['face'], 'wait 10', 'press A 3', 'wait 20']
    if p['pre']:
        out += ['pressuntil A multichoice 2000', 'wait 20', 'press DOWN 3', 'wait 10', 'press A 3', 'wait 30']
    out += ['pressuntil A multichoice 2000', 'wait 20']
    out += ['press DOWN 3', 'wait 10'] * ROWS[src].index(dst)
    out += ['press A 3', 'wait 30']
    if customs:   # the party screen: the first POKeMON (Lv 70) goes, the rest wait in the GLOBAL PC
        out += ['pressuntil A partymenu 3000', 'wait 60', 'shot customs_%d' % src, 'press A 3']
    out += ['watchlog region: travel %d -> %d' % (src, dst), 'pressuntillog A 3000 region: travel %d -> %d' % (src, dst),
            'pressuntil B field 3000', 'wait 60', 'mp where', 'mp regioninfo']
    return out


def chain(order, level2):
    a, b, c = order
    lines = ['pressuntil A field 5000', 'wait 60', 'mp regioninfo']
    lines += badges(a) + league(a)
    lines += sail(a, b, True)
    lines += badges(b) + ['mp setlevel 0 %d' % level2] + league(b)
    lines += sail(b, c, False)
    lines += badges(c) + league(c)
    lines += ['quit']
    best = max(70, level2)
    expect = [
        # region 1: eight badges, the League, the GLOBAL PC linked
        'badges 8 linked 0', 'region: League of region %d beaten' % a, 'credits: over, the game goes on from the save',
        # customs: only the Lv 70 one sails; Lv 5 on arrival
        'region: travel %d -> %d' % (a, b), FIRST[b], 'party: %d:L5 box1' % LEAD,
        # region 2: its League: its best level
        'region: League of region %d beaten' % b, 'party: %d:L%d box1' % (LEAD, best),
        # region 3: Lv 5 again until its League, then the best level
        'region: travel %d -> %d' % (b, c), 'region: League of region %d beaten' % c,
    ]
    return lines, expect, best


def main():
    for order, level2 in (((0, 1, 2), 40), ((2, 1, 0), 85)):
        name = 'region_chain_' + '_'.join(NAMES[r] for r in order)
        d = os.path.join(HERE, 'scenarios', name)
        os.makedirs(d, exist_ok=True)
        lines, expect, best = chain(order, level2)
        open(os.path.join(d, 'a.txt'), 'w').write('\n'.join(lines) + '\n')
        conf = ['# Generated by tools/test/gen_region_chain.py: one playthrough of %s in a row (badges, League, credits,'
                % ' -> '.join(NAMES[r].upper() for r in order),
                '# customs keeping the Lv 70 POKeMON, Lv 5 on arrival, Lv %d in the second region and its best level, %d, once'
                % (level2, best),
                '# that League is beaten; the GLOBAL PC linked in each cleared region)',
                'MODE=1', 'TMO=900',
                'ENV_A="MOEMON_DEBUG_REGION=%d MOEMON_DEBUG_PARTY=%d:70,255:30,258:20"' % (order[0], LEAD),
                'EXPECT_A=(%s)' % ' '.join('"%s"' % e for e in expect),
                'UNEXPECT_A=("[crash]" "not ported" "Soft Reset called")',
                'CHECK="python3 tools/test/check_region_chain.py %d %d %d %d"' % (order + (best,))]
        open(os.path.join(d, 'conf'), 'w').write('\n'.join(conf) + '\n')
        print(name)


if __name__ == '__main__':
    main()
