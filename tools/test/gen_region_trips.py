#!/usr/bin/env python3
"""Writes the six cross-region trip tests (tools/test/scenarios/region_trip_<from>_<to>): a champion of the starting
region takes its port's boat to the other region (the real clerk scripts and menus, customs keeping the second POKeMON),
arrives (the first town on a first visit, else the port), becomes that region's champion, sails back and checks the
POKeMON are at their own levels in each region and the other one waited in the GLOBAL PC.

    python3 tools/test/gen_region_trips.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = ['hoenn', 'johto', 'kanto']
# the clerk: where to stand, which way to face, menus before the region list ('Other regions' is the second row)
PORT = {
    0: {'warp': '9,9,8,11', 'face': 'up', 'pre': 1, 'arrive': 'where map 9.9 '},
    1: {'warp': '35,12,8,16', 'face': 'down', 'pre': 0, 'arrive': 'where map 35.12 '},
    2: {'warp': '37,62,24,34', 'face': 'up', 'pre': 1, 'arrive': 'where map 37.62 '},
}
FIRST = {1: 'where map 35.2 xy 4,4', 2: 'where map 37.120 xy 6,6'}
# the region list's rows from each region (QzGetReachableRegionsMask: every other region)
ROWS = {0: [2, 1], 1: [2, 0], 2: [1, 0]}


def sail(src, dst, label, customs=True):
    p = PORT[src]
    out = ['mp warp %s' % p['warp'], 'wait 120', 'mp face %s' % p['face'], 'wait 10', 'press A 3', 'wait 20']
    if p['pre']:
        out += ['pressuntil A multichoice 2000', 'wait 20', 'press DOWN 3', 'wait 10', 'press A 3', 'wait 30']
    out += ['pressuntil A multichoice 2000', 'wait 20', 'shot %s_regions' % label]
    out += ['press DOWN 3', 'wait 10'] * ROWS[src].index(dst)
    out += ['press A 3', 'wait 30']
    if customs:   # (with one POKeMON customs asks nothing)
        out += ['pressuntil A partymenu 3000', 'wait 60', 'press DOWN 3', 'wait 10', 'press A 3']
    out += ['watchlog region: travel %d -> %d' % (src, dst), 'pressuntillog A 3000 region: travel %d -> %d' % (src, dst),
            'pressuntil B field 3000', 'wait 60', 'shot %s_arrived' % label, 'mp where', 'mp regioninfo']
    return out


def main():
    for src in range(3):
        for dst in range(3):
            if src == dst:
                continue
            name = 'region_trip_%s_%s' % (NAMES[src], NAMES[dst])
            d = os.path.join(HERE, 'scenarios', name)
            os.makedirs(d, exist_ok=True)
            lines = ['pressuntil A field 5000', 'wait 60', 'mp regionclear %d' % src, 'mp additem 265 1',
                     'mp setvar 20789 3']   # (KANTO's VERMILION clerk sells region trips once the S.S. ANNE has sailed)
            lines += sail(src, dst, 'out')
            lines += ['mp regionclear %d' % dst, 'mp setvar 20789 3']
            lines += sail(dst, src, 'back', customs=False)
            lines += ['quit']
            open(os.path.join(d, 'a.txt'), 'w').write('\n'.join(lines) + '\n')
            first = FIRST.get(dst, PORT[dst]['arrive'])
            back = PORT[src]['arrive']
            conf = ['# Generated by tools/test/gen_region_trips.py: %s -> %s and back by boat (customs keeps TORCHIC, the'
                    % (NAMES[src].upper(), NAMES[dst].upper()),
                    '# first visit lands in the first town; levels per region; MUDKIP waits in the GLOBAL PC)',
                    'MODE=1', 'TMO=300',
                    'ENV_A="MOEMON_DEBUG_REGION=%d MOEMON_DEBUG_PARTY=258:30,255:25"' % src,
                    'EXPECT_A=("region: travel %d -> %d" "%s" "party: 255:L5" "region: travel %d -> %d" "%s" "party: 255:L25")'
                    % (src, dst, first, dst, src, back),
                    'UNEXPECT_A=("[crash]" "not ported")', '']
            open(os.path.join(d, 'conf'), 'w').write('\n'.join(conf))
            print(name)


if __name__ == '__main__':
    main()
