#!/usr/bin/env python3
"""The KANTO / JOHTO starter table's picture (docs/user_images/57.png, the user's mock-up) -> src/mp/mp_startable_gfx.h.

    python3 -I tools/moemon_starters/gen_table.py [--preview OUT.png]

The mock-up shows the table with three POKé BALLS and the hand; the screen (src/mp/mp_startable.c) draws those as
sprites, so they are painted out here: each row of a cut-out box is filled by blending the pixels left and right of
it. The table is symmetric, so its right half is the left half mirrored (the user's correction: the front edge
was a pixel off on the right). Colors as RGB555 with a palette of at most 256.
"""
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'docs', 'user_images', '57.png')
OUT = os.path.join(ROOT, 'src', 'mp', 'mp_startable_gfx.h')
W, H = 240, 160
BALLS_X = (60, 120, 180)
BALL_Y = 64
# boxes cut out (x0, y0, x1, y1), ends excluded: the three balls with their shadows, the hand
CUTS = [(x - 12, BALL_Y - 13, x + 14, BALL_Y + 13) for x in BALLS_X] + [(106, 8, 135, 39)]


def main():
    im = Image.open(SRC).convert('RGB')
    assert im.size == (W, H), im.size
    px = [[im.getpixel((x, y)) for x in range(W)] for y in range(H)]
    # The table top's light is bands of concentric ellipses (center (119.5, 67), three times as wide as high): a
    # pixel under a ball takes the color of the nearest pixel outside the cut-outs on its own ellipse (and of its
    # checker parity, for the bands' dither), so the bands go on behind the balls unbroken.
    def cut(x, y):
        return any(x0 <= x < x1 and y0 <= y < y1 for x0, y0, x1, y1 in CUTS)

    def level(x, y):
        return (((x - 119.5) / 3) ** 2 + (y - 67) ** 2) ** 0.5
    cands = [(x, y, level(x, y)) for y in range(42, 92) for x in range(40, 200) if not cut(x, y) and level(x, y) < 31]
    for x0, y0, x1, y1 in CUTS:
        if y0 < 40:   # the hand: the rows there are flat (the back rim, the wall): the pixel left of the box
            for y in range(y0, y1):
                for x in range(x0, x1):
                    px[y][x] = px[y][x0 - 1]
            continue
        for y in range(y0, y1):
            for x in range(x0, x1):
                d0 = level(x, y)
                best = None
                for tol in (0.3, 0.6, 1.2, 2.5, 5, 10):
                    for cx, cy, d in cands:
                        if abs(d - d0) <= tol and (cx + cy) % 2 == (x + y) % 2:
                            dist = (cx - x) ** 2 + (cy - y) ** 2
                            if best is None or dist < best[0]:
                                best = (dist, cx, cy)
                    if best:
                        break
                px[y][x] = px[best[2]][best[1]]
    for y in range(H):
        for x in range(W // 2, W):
            px[y][x] = px[y][W - 1 - x]
    colors = {}
    idx = []
    for y in range(H):
        row = []
        for x in range(W):
            r, g, b = px[y][x]
            c = (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
            if c not in colors:
                colors[c] = len(colors)
            row.append(colors[c])
        idx.append(row)
    assert len(colors) <= 256, len(colors)
    if '--preview' in sys.argv:
        out = Image.new('RGB', (W, H))
        for y in range(H):
            for x in range(W):
                out.putpixel((x, y), px[y][x])
        out.save(sys.argv[sys.argv.index('--preview') + 1])
    pal = sorted(colors, key=colors.get)
    with open(OUT, 'w') as f:
        f.write('// Generated by tools/moemon_starters/gen_table.py from docs/user_images/57.png: do not edit.\n')
        f.write('static const u8 sStarterTableBallX[3] = {%s};\n' % ', '.join(map(str, BALLS_X)))
        f.write('#define STARTER_TABLE_BALL_Y %d\n' % BALL_Y)
        f.write('static const u16 sStarterTable_Colors[%d] = {\n' % len(pal))
        for i in range(0, len(pal), 12):
            f.write('    ' + ', '.join('0x%04X' % c for c in pal[i:i + 12]) + ',\n')
        f.write('};\n')
        f.write('static const u8 sStarterTable_Bg[%d][%d] = {\n' % (H, W))
        for row in idx:
            f.write('    {' + ','.join(map(str, row)) + '},\n')
        f.write('};\n')
    print('%s: %d colors' % (OUT, len(pal)))


if __name__ == '__main__':
    main()
