#!/usr/bin/env python3
"""FireRed's ELITE FOUR and CHAMPION rematch teams (pokefirered src/data/trainer_parties.h: sParty_EliteFour*2,
sParty_ChampionRematch*) as src/data/mp_frlg_rematch.h, read by mp_region.c once SEVII's network machine is fixed
(audit case 130).

    python3 tools/moemon_starters/frlg_rematch.py [PARTIES_H]

Without a file it fetches the pinned pokefirered copy over HTTPS.
"""
import os
import re
import sys
import urllib.request

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
URL = 'https://raw.githubusercontent.com/pret/pokefirered/master/src/data/trainer_parties.h'
NAMES = ['EliteFourLorelei2', 'EliteFourBruno2', 'EliteFourAgatha2', 'EliteFourLance2',
         'ChampionRematchSquirtle', 'ChampionRematchBulbasaur', 'ChampionRematchCharmander']


def main():
    text = open(sys.argv[1]).read() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read().decode()
    out = ['// Generated by tools/moemon_starters/frlg_rematch.py from pokefirered src/data/trainer_parties.h: FireRed\'s',
           '// ELITE FOUR and CHAMPION rematch teams (mp_region.c, audit case 130). Do not edit by hand.', '']
    for n in NAMES:
        m = re.search(r'static const struct TrainerMonItemCustomMoves sParty_%s\[\] = \{(.*?)\n\};' % n, text, re.S)
        if not m:
            raise SystemExit('no ' + n)
        out.append('static const struct TrainerMonItemCustomMoves sFrParty_%s[] = {%s\n};\n' % (n, m.group(1)))
    open(os.path.join(REPO, 'src/data/mp_frlg_rematch.h'), 'w').write('\n'.join(out))


if __name__ == '__main__':
    main()
