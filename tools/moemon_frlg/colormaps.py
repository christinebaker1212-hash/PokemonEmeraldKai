#!/usr/bin/env python3
"""Moemon Co-op: turns colormaps.txt (hand-mapped sprite colors) into src/mp/mp_color_maps.h.

colormaps.txt lines: `kind cfg MAP`
  kind  ow (overworld sprite), front (trainer picture) or back (back picture)
  cfg   the name the ini file uses (brendan, frlg_lass, hiker, frlg_old_man...)
  MAP   15 letters for palette colors 1-15: S skin, H hair, O outfit, A accent, . keep
The maps were made by looking at highlight sheets (colorsheets.py) of every sprite.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
KINDS = {'ow': 'CMAP_OW', 'front': 'CMAP_FRONT', 'back': 'CMAP_BACK'}


def main():
    src = os.path.join(HERE, 'colormaps.txt')
    out = ['// Moemon Co-op: hand-mapped sprite colors, generated by tools/moemon_frlg/colormaps.py',
           '// from tools/moemon_frlg/colormaps.txt. Do not edit; edit the .txt and run the script.',
           '', 'static const struct MpColorMap sMpColorMaps[] = {']
    seen = set()
    n = 0
    for ln, line in enumerate(open(src).read().split('\n'), 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        parts = line.split()
        if len(parts) != 3 or parts[0] not in KINDS or not re.fullmatch(r'[SHOA.]{15}', parts[2]):
            sys.exit('colormaps.txt:%d: bad line: %s' % (ln, line))
        key = (parts[0], parts[1])
        if key in seen:
            sys.exit('colormaps.txt:%d: %s %s twice' % (ln, parts[0], parts[1]))
        seen.add(key)
        out.append('    {%s, "%s", "%s"},' % (KINDS[parts[0]], parts[1], parts[2]))
        n += 1
    if n == 0:
        out.append('    {0, "", "..............."},')
    out.append('};')
    open(os.path.join(ROOT, 'src/mp/mp_color_maps.h'), 'w').write('\n'.join(out) + '\n')
    print('%d color maps' % n)


if __name__ == '__main__':
    main()
