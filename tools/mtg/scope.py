#!/usr/bin/env python3
"""Writes docs/MTG_SCOPE.md: how much of the pool the C engine plays, what keeps the rest out (each card's first
untranslated piece, from the engine itself: tools/mtg/scope_dump.c), and everything Forge's scripts for the pool
use (effects, triggers, statics, replacements, keywords), so translation can go where it unlocks the most cards.
Rerun after translating anything.

usage: tools/mtg/scope.py"""
import collections, json, os, re, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
PAK = os.path.join(ROOT, "graphics", "mtg", "forge.pak")


def scripts():
    b = open(PAK, "rb").read()
    n = struct.unpack_from("<I", b, 8)[0]
    base = 12 + 12 * n
    for i in range(n):
        no, so, sz = struct.unpack_from("<III", b, 12 + 12 * i)
        yield b[base + no:b.index(b"\0", base + no)].decode(), b[base + so:base + so + sz].decode()


def main():
    exe = "/tmp/mtg-tests/scope_dump"
    os.makedirs(os.path.dirname(exe), exist_ok=True)
    subprocess.run(["gcc", "-std=gnu99", "-O1", "-iquote", "include", "-iquote", "src/mtg", "tools/mtg/scope_dump.c"]
                   + sorted("src/mtg/" + f for f in os.listdir(os.path.join(ROOT, "src/mtg")) if f.endswith(".c"))
                   + ["-o", exe], cwd=ROOT, check=True)
    out = subprocess.run([exe, PAK], capture_output=True, text=True, cwd=ROOT, check=True).stdout
    status = dict(l.split("\t", 1) for l in out.splitlines())
    banned = {c["name"] for c in json.load(open(os.path.join(HERE, "pool.json"))) if c["banned"]}
    translated = set(re.findall(r'\{"(\w+)", MTG_API_', open(os.path.join(ROOT, "src/mtg/mtg_effects.c")).read()))
    playable = [n for n, r in status.items() if not r]
    blockers = collections.Counter(r for r in status.values() if r)
    use = {k: collections.Counter() for k in ("api", "trigger", "static", "replacement", "keyword")}
    cards = {k: collections.defaultdict(set) for k in use}
    for name, t in scripts():
        for line in t.splitlines():
            for m in re.finditer(r"\b(?:SP|AB|DB)\$\s*([A-Za-z]+)", line):
                use["api"][m.group(1)] += 1; cards["api"][m.group(1)].add(name)
            for pre, k in (("T:", "trigger"), ("S:", "static")):
                if line.startswith(pre):
                    m = re.search(r"Mode\$\s*(\w+)", line); x = m.group(1) if m else "?"
                    use[k][x] += 1; cards[k][x].add(name)
            if line.startswith("R:"):
                m = re.search(r"Event\$\s*(\w+)", line); x = m.group(1) if m else "?"
                use["replacement"][x] += 1; cards["replacement"][x].add(name)
            if line.startswith("K:"):
                x = line[2:].split(":")[0].strip()
                use["keyword"][x] += 1; cards["keyword"][x].add(name)
    L = ["# Magic: what the C engine plays",
         "",
         "Generated by `tools/mtg/scope.py` from the engine itself (rerun after translating anything). The pool is",
         "Premodern's (tools/mtg/pool.json); the rules are Forge's, translated into C (docs/MTG_HANDOFF.md).",
         "",
         "**%d of %d cards are playable** (%d of them on Premodern's banned list)." % (
             len(playable), len(status), len([n for n in playable if n in banned])),
         "",
         "## What keeps the rest out",
         "Each unplayable card counted once, by the first thing the engine doesn't translate yet:",
         "", "| first missing piece | cards |", "|---|---|"]
    L += ["| %s | %d |" % (r, n) for r, n in blockers.most_common(40)]
    L += ["", "## What Forge's scripts for the pool use",
          "Uses (lines) and cards for each; **bold** = translated.", ""]
    for k, title in (("api", "Effects (ApiType)"), ("trigger", "Triggers (TriggerType)"),
                     ("static", "Static abilities (StaticAbilityMode)"),
                     ("replacement", "Replacement effects (ReplacementType)"), ("keyword", "Keywords")):
        L += ["### " + title, "", "| | uses | cards |", "|---|---|---|"]
        for x, n in use[k].most_common():
            name = "**%s**" % x if (k == "api" and x in translated) else x
            L.append("| %s | %d | %d |" % (name, n, len(cards[k][x])))
        L.append("")
    open(os.path.join(ROOT, "docs", "MTG_SCOPE.md"), "w").write("\n".join(L))
    print("%d of %d playable -> docs/MTG_SCOPE.md" % (len(playable), len(status)))


if __name__ == "__main__":
    main()
