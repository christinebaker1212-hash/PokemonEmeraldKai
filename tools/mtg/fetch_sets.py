#!/usr/bin/env python3
"""Writes tools/mtg/sets.json and src/mtg/mtg_sets_data.c: the MAGIC booster sets of the Premodern years (Fourth
Edition, 1995, to Scourge, 2003: Scryfall's core sets and expansions) with every pool card printed in each and its
rarity there, from Scryfall (https://api.scryfall.com). The game's boosters (src/mtg/mtg_sets.c) are drawn from them
by rarity, as the real packs were: most sets 15 cards (11 commons, 3 uncommons, a rare), the older smaller ones less.

Scryfall asks for a named User-Agent, an Accept header and a short pause between requests.

usage: fetch_sets.py [--offline]   (--offline: only regenerate the C file from tools/mtg/sets.json)"""
import json, os, sys, time, urllib.parse, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
HEADERS = {"User-Agent": "MoemonKaiCardTool/1.0", "Accept": "application/json"}

# a booster of each: (commons, uncommons, rares); the rest 11 / 3 / 1
LAYOUT = {"hml": (6, 1, 1), "all": (8, 3, 1), "chr": (9, 2, 1)}
# the pack's colors (top, bottom), by the set's look
COLORS = {
    "4ed": (0x6a5a48, 0x2a2018), "ice": (0x80b8e0, 0x203858), "chr": (0xa08050, 0x403018),
    "hml": (0x608050, 0x203018), "all": (0x7090c0, 0x203048), "mir": (0xe0a040, 0x603810),
    "vis": (0xd07030, 0x502010), "5ed": (0x7a6a58, 0x302820), "wth": (0x5888b8, 0x182840),
    "tmp": (0x8050a0, 0x281030), "sth": (0x904060, 0x301020), "exo": (0x506090, 0x182030),
    "usg": (0x50a0a0, 0x103838), "ulg": (0x60a070, 0x183820), "6ed": (0x8a7a60, 0x302a20),
    "uds": (0x907860, 0x302418), "mmq": (0xc09040, 0x503010), "nem": (0x50a050, 0x183018),
    "pcy": (0xc0a060, 0x504018), "inv": (0x5060c0, 0x101848), "pls": (0x8070c0, 0x281848),
    "7ed": (0x9a8a70, 0x383020), "apc": (0xc05050, 0x401010), "ody": (0x70a0b0, 0x203840),
    "tor": (0x705070, 0x201020), "jud": (0xd0c080, 0x605020), "ons": (0x60a040, 0x203010),
    "lgn": (0xa06030, 0x381808), "scg": (0xa03030, 0x300808),
}
# Chronicles (a set of reprints, legal through its cards' first printings); Fourth Edition's foreign black-bordered
# printing (the same set again)
SKIP = ("chr", "4bb")
RARITY = {"common": 0, "uncommon": 1, "rare": 2, "mythic": 2}


def get(url):
    for attempt in range(5):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=60) as r:
                return json.load(r)
        except Exception:
            if attempt == 4:
                raise
            time.sleep(2 ** attempt)


def fetch():
    pool = {c["name"] for c in json.load(open(os.path.join(HERE, "pool.json")))}
    sets = {}
    for s in get("https://api.scryfall.com/sets")["data"]:
        if s["set_type"] in ("core", "expansion") and not s.get("digital") \
                and "1995-04-01" <= s.get("released_at", "") <= "2003-05-26":
            sets[s["code"]] = {"code": s["code"].upper(), "name": s["name"], "released": s["released_at"], "cards": {}}
    for code in SKIP:
        sets.pop(code, None)
    for code, s in sorted(sets.items(), key=lambda kv: kv[1]["released"]):
        url = "https://api.scryfall.com/cards/search?" + urllib.parse.urlencode(
            {"q": "set:%s" % code, "unique": "prints", "order": "set"})
        while url:
            d = get(url)
            for c in d["data"]:
                if c["name"] in pool and "Basic Land" not in c.get("type_line", ""):
                    s["cards"].setdefault(c["name"], RARITY.get(c.get("rarity"), 0))
            url = d.get("next_page")
            time.sleep(0.12)
        print("%s %s: %d cards" % (s["code"], s["name"], len(s["cards"])))
    out = [dict(s, cards=sorted(s["cards"].items())) for s in sorted(sets.values(), key=lambda s: s["released"])]
    json.dump(out, open(os.path.join(HERE, "sets.json"), "w"), indent=0)
    return out


def name_hash(name):   # Mtg_NameHash (mtg_collection.c): FNV-1a of the name's bytes
    h = 2166136261
    for b in name.encode():
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def write_c(sets):
    L = ["// Generated by tools/mtg/fetch_sets.py from Scryfall: MAGIC's booster sets (Fourth Edition to Scourge) and the",
         "// pool's cards in each, by name hash (Mtg_NameHash) and rarity there. Don't edit: rerun the script.",
         '#include "mtg/collection.h"', "", "const MtgSetCard gMtgSetCards[] = {"]
    first = 0
    rows = []
    for s in sets:
        for name, r in s["cards"]:
            L.append("    {0x%08xu, %d},   // %s" % (name_hash(name), r, name.replace("\\", "")))
        n = len(s["cards"])
        c, u, r = LAYOUT.get(s["code"].lower(), (11, 3, 1))
        top, bottom = COLORS.get(s["code"].lower(), (0x707070, 0x202020))
        rows.append('    {"%s", "%s", %s, 0x%06x, 0x%06x, %d, %d, %d, %d, %d},' % (
            s["code"], s["name"].replace('"', ''), s["released"][:4], top, bottom, c, u, r, first, n))
        first += n
    L += ["};", "", "const MtgSet gMtgSets[MTG_SETS] = {"] + rows + ["};", ""]
    open(os.path.join(ROOT, "src", "mtg", "mtg_sets_data.c"), "w").write("\n".join(L))
    h = os.path.join(ROOT, "include", "mtg", "collection.h")
    print("%d sets, %d cards in them (MTG_SETS must be %d in %s)" % (len(sets), first, len(sets), h))


def main():
    if "--offline" in sys.argv:
        sets = [s for s in json.load(open(os.path.join(HERE, "sets.json"))) if s["code"].lower() not in SKIP]
    else:
        sets = fetch()
    write_c(sets)


if __name__ == "__main__":
    main()
