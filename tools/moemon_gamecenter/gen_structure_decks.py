#!/usr/bin/env python3
"""The GAME CENTER CARD SHOP's structure decks: the 1999 Base Set theme decks Overgrowth, Zap! and Brushfire, card
for card (their Base Set numbers), as the game's cards (tools/tcg/printed_art.json "printing" -> card id); then the
English theme decks the cards of both Game Boy games can make, card for card, from theme_decks.json (pokemon-tcg-data's
decks/en, each printing matched to the game's card), priced a bit higher.
Writes src/tcg/tcg_structure_decks.h.  usage: python3 tools/moemon_gamecenter/gen_structure_decks.py
"""
import json, os
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
DECKS = [
    ('Overgrowth', 'GRASS and WATER: BEEDRILL, STARMIE, GYARADOS',
     {44: 4, 30: 2, 69: 4, 33: 2, 17: 1, 65: 4, 64: 3, 35: 2, 6: 1,                   # Pokemon
      91: 2, 93: 2, 95: 2, 90: 2, 94: 1,                                              # Bill, Gust, Switch, Super Potion, Potion
      99: 16, 102: 12}),                                                              # Grass, Water Energy
    ('Zap!', 'LIGHTNING and PSYCHIC: MEWTWO, JYNX, HAUNTER',
     {58: 4, 53: 3, 43: 3, 50: 3, 29: 2, 49: 2, 31: 2, 32: 1, 10: 1,
      91: 2, 93: 2, 95: 2, 71: 1, 80: 1, 94: 1, 88: 1, 90: 1,                         # .. Computer Search, Defender, Prof. Oak
      101: 16, 100: 12}),
    ('Brushfire', 'FIRE and GRASS: NINETALES, ARCANINE, CHARMELEON',
     {46: 4, 24: 2, 12: 1, 68: 2, 28: 2, 23: 1, 69: 4, 55: 4, 66: 2,
      75: 1, 84: 1, 81: 2, 95: 1, 94: 3, 93: 1, 92: 1,
      98: 18, 99: 10}),
]
STARTER_PRICE, THEME_PRICE = 15000, 18000


def main():
    cat = {c['id']: c for c in json.load(open(os.path.join(ROOT, 'tools/tcg/catalog.json')))['cards']}
    pr = json.load(open(os.path.join(ROOT, 'tools/tcg/printed_art.json')))['cards']
    by = {}
    for i, v in pr.items():
        by.setdefault(v['printing'], int(i))
    out = ['// Generated by tools/moemon_gamecenter/gen_structure_decks.py: the GAME CENTER\'s structure decks, the 1999 Base',
           '// Set theme decks and the later English theme decks, card for card (tcg_ui.c, the GAME CENTER CARD SHOP).', '',
           'static const struct { const char *name, *blurb, *set; unsigned price; uint16_t cards[TCG_DECK_SIZE]; } sStructureDecks[] = {']
    decks = []
    for name, blurb, cards in DECKS:
        ids = []
        for num, n in cards.items():
            ids += [by['base1-%d' % num]] * n
        decks.append((name, blurb, '1999 Base Set', STARTER_PRICE, ids))
    TYPES = {'TYPE_ENERGY_FIRE': 'FIRE', 'TYPE_ENERGY_GRASS': 'GRASS', 'TYPE_ENERGY_WATER': 'WATER',
             'TYPE_ENERGY_LIGHTNING': 'LIGHTNING', 'TYPE_ENERGY_FIGHTING': 'FIGHTING', 'TYPE_ENERGY_PSYCHIC': 'PSYCHIC'}
    for d in json.load(open(os.path.join(ROOT, 'tools/moemon_gamecenter/theme_decks.json')))['decks']:
        ids = []
        for c in d['cards']:
            ids += [c['id']] * c['count']
        energy = {}
        for i in ids:
            if i <= 6:
                energy[TYPES[cat[i]['type']]] = energy.get(TYPES[cat[i]['type']], 0) + 1
        kinds = sorted(energy, key=lambda t: -energy[t])
        mons = sorted({i for i in ids if cat[i]['kind'] == 'pokemon'},
                      key=lambda i: (-{'BASIC': 0, 'STAGE1': 1, 'STAGE2': 2}[cat[i]['stage']], -cat[i]['hp'], i))
        names = []
        for i in mons:
            n = cat[i]['name'].upper().replace('POKEMON', 'POKeMON')
            if n not in names:
                names.append(n)
        blurb = '%s: %s' % (' and '.join(kinds), ', '.join(names[:3]))
        # the 1999 Base Set's own deck at the starters' price, the later sets' a bit higher
        decks.append((d['name'], blurb, d['set'], STARTER_PRICE if d['set'] == '1999 Base Set' else THEME_PRICE, ids))
    for name, blurb, setname, price, ids in decks:
        assert len(ids) == 60, name
        out.append('    {"%s", "%s", "%s", %d,' % (name, blurb, setname, price))
        out.append('     {' + ', '.join(str(i) for i in sorted(ids, key=lambda i: (cat[i]['kind'] == 'energy', i))) + '}},')
    out.append('};')
    open(os.path.join(ROOT, 'src/tcg/tcg_structure_decks.h'), 'w').write('\n'.join(out) + '\n')
    print('src/tcg/tcg_structure_decks.h: %d decks' % len(decks))

main()
