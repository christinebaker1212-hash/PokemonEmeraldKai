"""Catalog of the flags / vars the rip uses, and headers that define every QZ symbol it writes,
so the ripped files assemble as they are (values = Quetzal's own numbers).
"""
import json
import os
import re
from collections import defaultdict

from scripts import OPS, SPECIALS, STD

FLAG_OPS = {'setflag': 'set', 'clearflag': 'clear', 'checkflag': 'check'}
VAR_OPS = {'setvar': 'set', 'addvar': 'add', 'subvar': 'sub', 'copyvar': 'copy', 'setorcopyvar': 'set',
           'compare_var_to_value': 'check', 'compare_var_to_var': 'check', 'specialvar': 'special_result'}


def flag_range(v):
    if v < 0x20:
        return 'temp'
    if v <= 0xE97:
        return 'saveblock flags (stock Emerald numbering; Quetzal reuses Emerald\'s unused 0x20-0xBE)'
    if 0x1000 <= v < 0x2000:
        return 'Quetzal block 0x1000-0x1FFF (Johto)'
    if 0x2000 <= v < 0x3000:
        return 'Quetzal block 0x2000-0x2FFF (Kanto)'
    return 'other'


def var_range(v):
    if 0x4000 <= v < 0x4010:
        return 'temp'
    if v < 0x4100:
        return 'stock Emerald var numbering'
    if 0x5000 <= v < 0x5100:
        return 'Quetzal block 0x5000-0x50FF (Johto)'
    if 0x5100 <= v < 0x5200:
        return 'Quetzal block 0x5100-0x51FF (Kanto)'
    return 'other'


def catalog(r):
    """r is the Ripper (after run())."""
    dis = r.dis
    flags = defaultdict(lambda: defaultdict(set))
    vars_ = defaultdict(lambda: defaultdict(set))
    for pc, (name, args, end, op) in dis.insn.items():
        for k, v in args:
            if k == 'F':
                flags[v][FLAG_OPS.get(name, name)].add(pc)
            elif k == 'V' and (0x4010 <= v < 0x4100 or 0x5000 <= v < 0x5200):
                vars_[v][VAR_OPS.get(name, name)].add(pc)
    # map each instruction to the maps that own its block
    pc_owner = {}
    for L, (pcs, nxt) in dis.blocks.items():
        names = sorted(r.by_key[o]['name'] for o in dis.owners.get(L, ()))
        for pc in pcs:
            pc_owner.setdefault(pc, set()).update(names)
    obj_flags = defaultdict(set)
    hidden = defaultdict(set)
    coord_vars = defaultdict(set)
    for m in r.targets:
        for o in m['events']['objects']:
            if o['flag']:
                obj_flags[o['flag']].add(m['name'])
        for b in m['events']['bgs']:
            if b['kind'] == 7:
                hidden[b['flag']].add(m['name'])
        for c in m['events']['coords']:
            if 0x4010 <= c['var'] < 0x4100 or 0x5000 <= c['var'] < 0x5200:
                coord_vars[c['var']].add(m['name'])
        for t, a, table in m['map_scripts']:
            for var, val, s in table or ():
                if 0x4010 <= var < 0x4100 or 0x5000 <= var < 0x5200:
                    coord_vars[var].add(m['name'])

    def uses(d):
        return {op: sorted({n for pc in pcs for n in pc_owner.get(pc, ())}) for op, pcs in d.items()}

    fl = {}
    for v in sorted(set(flags) | set(obj_flags) | set(hidden)):
        e = {'value': '0x%X' % v, 'range': flag_range(v)}
        e.update(uses(flags.get(v, {})))
        if v in obj_flags:
            e['hides_objects_in'] = sorted(obj_flags[v])
        if v in hidden:
            e['hidden_item_in'] = sorted(hidden[v])
        fl['FLAG_QZ_0x%X' % v] = e
    vr = {}
    for v in sorted(set(vars_) | set(coord_vars)):
        e = {'value': '0x%X' % v, 'range': var_range(v)}
        e.update(uses(vars_.get(v, {})))
        if v in coord_vars:
            e['map_triggers_in'] = sorted(coord_vars[v])
        vr['VAR_QZ_0x%04X' % v] = e
    return fl, vr


def write(r):
    fl, vr = catalog(r)
    d = os.path.join(r.out, 'data')
    with open(os.path.join(d, 'flags_vars.json'), 'w') as fh:
        json.dump({'flags': fl, 'vars': vr}, fh, indent=1)
        fh.write('\n')
    inc = os.path.join(r.out, 'include')
    os.makedirs(inc, exist_ok=True)
    # every QZ symbol the rip writes
    text = ''
    for root, _, files in os.walk(r.out):
        for f in files:
            if f.endswith(('.inc', '.json')) and 'include' not in root and 'sound' not in root:
                text += open(os.path.join(root, f), encoding='utf-8').read()
    syms = {}
    for pat in (r'\b(FLAG_QZ_0x([0-9A-F]+))\b', r'\b(VAR_QZ_0x([0-9A-F]+))\b'):
        for m in re.finditer(pat, text):
            syms[m.group(1)] = '0x' + m.group(2)
    for pat, prefix in ((r'\b(TRAINER_QZ_(\d+))\b', ''), (r'\b(OBJ_EVENT_GFX_QZ_(\d+))\b', ''), (r'\b(MUS_QZ_(\d+))\b', ''),
                        (r'\b(MOVEMENT_TYPE_QZ_0x([0-9A-F]+))\b', '0x')):
        for m in re.finditer(pat, text):
            syms[m.group(1)] = prefix + m.group(2)
    lines = ['// Generated by tools/quetzal_rip: Quetzal\'s own numbers for every QZ symbol in quetzal_rip/.',
             '// Porting = replace these with Kai constants (see docs/QUETZAL_RIP.md).', '#ifndef GUARD_QUETZAL_CONSTANTS_H',
             '#define GUARD_QUETZAL_CONSTANTS_H', '']
    for k in sorted(syms, key=lambda s: (s.split('_QZ_')[0], int(syms[s], 0))):
        lines.append('#define %-36s %s' % (k, syms[k]))
    hid = sorted({(m.group(1), int(m.group(2))) for m in re.finditer(r'\bFLAG_QZ_(\w+?)_HIDDEN_ITEM_(\d+)\b', text)})
    lines += ['', '// Hidden items store (flag - FLAG_HIDDEN_ITEMS_START) like Emerald, but Kanto\'s ids restart at 0',
              '// (overlapping Hoenn\'s), so Quetzal resolves them per region. Placeholder values above Kai\'s range:']
    for reg, n in hid:
        lines.append('#define FLAG_QZ_%s_HIDDEN_ITEM_%-6d (FLAG_HIDDEN_ITEMS_START + 0x400 + %d)' % (reg, n, n))
    lines += ['#define TRAINER_BATTLE_QZ_13               13', '', '#endif']
    open(os.path.join(inc, 'quetzal_constants.h'), 'w').write('\n'.join(lines) + '\n')
    # Quetzal's own species / item / move numbering (the rip names them by Quetzal's names)
    ids = ['// Generated by tools/quetzal_rip: Quetzal\'s species / item / move ids under the names the rip uses.',
           '// NOT for Kai\'s build (the names clash with Kai\'s, values differ): check_build.sh includes it to',
           '// verify the rip byte for byte, and a porter can use it as the Quetzal side of an id mapping.',
           '#ifndef GUARD_QUETZAL_IDS_H', '#define GUARD_QUETZAL_IDS_H']
    for tab in (r.names.species_const, r.names.item_const, r.names.move_const):
        for i, n in enumerate(tab):
            ids.append('#undef %s' % n)
            ids.append('#define %s %d' % (n, i))
    ids.append('#endif')
    open(os.path.join(inc, 'quetzal_ids.h'), 'w').write('\n'.join(ids) + '\n')
    # asm side: custom commands, specials, std scripts
    names = {}
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'qz_names.json')
    if os.path.exists(p):
        names = json.load(open(p))
    m = ['@ Generated by tools/quetzal_rip. Quetzal\'s script commands 0xE3-0xF5 as raw bytes, and its new',
         '@ specials / std scripts as numbers, so quetzal_rip/*.inc assembles. They do nothing in Kai until ported.', '']
    sizes = {'b': '.byte', 'V': '.2byte', 'S': '.2byte', 'I': '.2byte'}
    for op in range(0xE3, 0xF6):
        name, kinds = OPS[op]
        args = ['a%d' % i for i in range(len(kinds))]
        info = names.get('commands', {}).get('0x%X' % op, {})
        if info:
            m.append('\t@ %s: %s' % (info.get('name', ''), info.get('args', '')))
        m.append('\t.macro %s %s' % (name, ', '.join(a + ':req' for a in args)))
        m.append('\t.byte 0x%02X' % op)
        for a, k in zip(args, kinds):
            m.append('\t%s \\%s' % (sizes[k], a))
        m.append('\t.endm')
        m.append('')
    used = sorted({(x.group(0), int(x.group(1))) for x in re.finditer(r'\b(?:Qz\w+?|QZ_SPECIAL)_(\d+)\b', text)
                   if not x.group(0).startswith('QZ_SPECIAL') or True}, key=lambda t: t[1])
    m.append('\t@ Quetzal specials by their index in Quetzal\'s gSpecials (see docs/quetzal/SPECIALS.md)')
    for sym, n in used:
        if sym.startswith(('MOVEMENT', 'TRAINER')):
            continue
        m.append('\t.set SPECIAL_%s, %d' % (sym, n))
        m.append('\t.set SPECIAL_WAITSTATE_%s, 0' % sym)
    m += ['', '\tSTD_QZ_11 = 11', '\tSTD_QZ_12 = 12', '',
          '\t@ givemon whose two words / byte stock Emerald leaves 0 (Quetzal uses them; meaning in docs/quetzal/SCRIPT_COMMANDS.md)',
          '\t.macro qz_givemon_ex species:req, level:req, item:req, w1:req, w2:req, b:req',
          '\t.byte SCR_OP_GIVEMON', '\t.short \\species', '\t.byte \\level', '\t.short \\item',
          '\t.int \\w1', '\t.int \\w2', '\t.byte \\b', '\t.endm', '',
          '\t@ trainerbattle type 13 (Quetzal): like TRAINER_BATTLE_SINGLE; see docs/quetzal/SCRIPT_COMMANDS.md',
          '\t.macro qz_trainerbattle_13 trainer:req, local_id:req, intro:req, defeat:req',
          '\t.byte SCR_OP_TRAINERBATTLE', '\t.byte 13', '\t.short \\trainer', '\t.short \\local_id',
          '\tptrvalue \\intro', '\tptrvalue \\defeat', '\t.endm', '']
    open(os.path.join(inc, 'quetzal_macros.inc'), 'w').write('\n'.join(m) + '\n')
    return fl, vr


# modern names -> Kai's Gen 3 names
ALIASES = {'MOVE_VISE_GRIP': 'MOVE_VICE_GRIP', 'MOVE_HIGH_JUMP_KICK': 'MOVE_HI_JUMP_KICK',
           'MOVE_FEINT_ATTACK': 'MOVE_FAINT_ATTACK', 'MOVE_SMELLING_SALTS': 'MOVE_SMELLING_SALT',
           'MOVE_THUNDER_PUNCH': 'MOVE_THUNDERPUNCH', 'MOVE_SOLAR_BEAM': 'MOVE_SOLARBEAM',
           'ITEM_X_SP_ATK': 'ITEM_X_SPECIAL'}


def id_map(r):
    """Every species / item / move the Kanto-Johto rip refers to, with Kai's constant of the same name
    (null = Kai has no such constant: the porter decides what to map it to or adds it)."""
    kai = {}
    for f, pre in (('include/constants/species.h', 'SPECIES_'), ('include/constants/items.h', 'ITEM_'),
                   ('include/constants/moves.h', 'MOVE_')):
        for m in re.finditer(r'#define (%s\w+)' % pre, open(os.path.join(r.out, '..', f)).read()):
            kai[m.group(1)] = True
    text = ''
    for root, _, files in os.walk(r.out):
        if 'include' in root or 'sound' in root:
            continue
        for f in files:
            if f.endswith(('.inc', '.json')):
                text += open(os.path.join(root, f), encoding='utf-8').read()
    from collections import Counter
    uses = Counter(re.findall(r'\b((?:SPECIES|ITEM|MOVE)_[A-Z0-9_]+)\b', text))
    out = {'species': {}, 'items': {}, 'moves': {}}
    tables = (('species', r.names.species_const, r.names.species), ('items', r.names.item_const, r.names.items),
              ('moves', r.names.move_const, r.names.moves))
    for key, consts_, disp in tables:
        for i, c in enumerate(consts_):
            if c in uses:
                k = c if c in kai else ALIASES.get(c) if ALIASES.get(c) in kai else None
                out[key][c] = {'quetzal_id': i, 'name': disp[i], 'uses': uses[c], 'kai': k}
    with open(os.path.join(r.out, 'data', 'id_map.json'), 'w', encoding='utf-8') as fh:
        json.dump(out, fh, indent=1, ensure_ascii=False)
        fh.write('\n')
    return {k: (len(v), sum(1 for x in v.values() if x['kai'] is None)) for k, v in out.items()}
