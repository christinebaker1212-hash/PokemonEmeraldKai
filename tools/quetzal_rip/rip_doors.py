#!/usr/bin/env python3
"""JOHTO's door animations, Moemon Quetzal's own: its door table (FireRed's format: metatile, sound, size, frames,
palette numbers) at ROM 0x952148 (19 one-metatile doors, read by the game next to Emerald's table at 0x951EC0) and
FireRed's tall doors after it at 0x952358 (8). JOHTO's tilesets share FireRed's numbering, so a door is its metatile
number in this table, as in Quetzal: a door tile it doesn't list opens without an animation.

    python3 -I tools/quetzal_rip/rip_doors.py QUETZAL_ROM

Writes quetzal_rip/doors/ (each door's frames as .4bpp, doors.json) and src/data/qz_doors.h for src/mp/mp_frlgdoor.c.
"""
import json
import os
import struct
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
TABLES = ((0x952148, 19), (0x952358, 8))
FRAME_TILES = {0: 12, 1: 24}   # 1x1: three frames of 4 tiles; 1x2: three of 8
SOUND = {0: 'NORMAL', 1: 'SLIDING'}
SIZE = {0: '1x1', 1: '1x2'}


def main():
    rom = open(sys.argv[1], 'rb').read()
    out_dir = os.path.join(REPO, 'quetzal_rip', 'doors')
    os.makedirs(out_dir, exist_ok=True)
    rows, seen = [], {}
    for base, count in TABLES:
        for k in range(count):
            mt, snd, size, tiles, pals = struct.unpack_from('<HBBII', rom, base + 12 * k)
            name = 'door_%07X' % tiles
            if name not in seen:
                data = rom[tiles - 0x08000000:tiles - 0x08000000 + FRAME_TILES[size] * 32]
                open(os.path.join(out_dir, name + '.4bpp'), 'wb').write(data)
                seen[name] = list(rom[pals - 0x08000000:pals - 0x08000000 + 8])
            rows.append({'metatile': mt, 'sound': SOUND[snd], 'size': SIZE[size], 'tiles': name,
                         'palettes': seen[name], 'rom': '0x%X' % (base + 12 * k + 0x08000000)})
    json.dump(rows, open(os.path.join(out_dir, 'doors.json'), 'w'), indent=1)
    out = ['// Generated by tools/quetzal_rip/rip_doors.py from Moemon Quetzal\'s door table. Do not edit.',
           '// JOHTO\'s door animations (src/mp/mp_frlgdoor.c): Quetzal\'s own frames, FireRed\'s format']
    for name, pals in sorted(seen.items()):
        out.append('static const u8 sQzDoorTiles_%s[] = INCBIN_U8("quetzal_rip/doors/%s.4bpp");' % (name[5:], name))
        out.append('static const u8 sQzDoorPals_%s[] = {%s};' % (name[5:], ', '.join(str(p) for p in pals)))
    out.append('static const struct FrlgDoorGraphics sQzDoors[] = {')
    done = set()
    for r in rows:
        if r['metatile'] in done:   # (a metatile in both tables: the first, as the game's search finds it)
            continue
        done.add(r['metatile'])
        out.append('    {0x%03X, FRLG_DOOR_SOUND_%s, FRLG_DOOR_SIZE_%s, sQzDoorTiles_%s, sQzDoorPals_%s},'
                   % (r['metatile'], r['sound'], r['size'], r['tiles'][5:], r['tiles'][5:]))
    out.append('    {0},')
    out.append('};')
    open(os.path.join(REPO, 'src', 'data', 'qz_doors.h'), 'w').write('\n'.join(out) + '\n')
    print('%d doors, %d pictures' % (len(done), len(seen)))


if __name__ == '__main__':
    main()
